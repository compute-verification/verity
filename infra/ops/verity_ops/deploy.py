def git(*args: str, repo: Path = REPO) -> str:
    return subprocess.run(["git", "-C", str(repo), *args], capture_output=True, text=True, check=True).stdout


def manifest_at(ref: str, repo: Path = REPO) -> str | None:
    """REF's own deploy.toml, so a commit deploys what it lists; None when REF has none (then the checkout's is used)."""
    r = subprocess.run(["git", "-C", str(repo), "show", f"{ref}:{MANIFEST.relative_to(SRC)}"], capture_output=True, text=True)
    return r.stdout if r.returncode == 0 else None


def expected(node: Node, commit: str, repo: Path = REPO) -> dict[str, tuple[str, str, int, Entry]]:
    """Installed path -> (repo path, blob, mode, entry) for every file entry and every file of every tree at `commit`; an entry
    whose source `commit` lacks is left out (`absent`)."""
    srcs = [e.src for e in node.entries if e.src]
    tree: dict[str, tuple[str, int]] = {}
    for ln in git("ls-tree", "-r", "--full-tree", commit, "--", *srcs, repo=repo).splitlines() if srcs else []:
        meta, rp = ln.split("\t", 1)
        mode, _, sha = meta.split()
        tree[rp] = (sha, 0o755 if mode == "100755" else 0o644)
    out = {}
    for e in node.entries:
        if e.tree:
            pre = e.src.rstrip("/") + "/"
            for rp, (sha, mode) in tree.items():
                if rp.startswith(pre):
                    out[e.path.rstrip("/") + "/" + rp[len(pre):]] = (rp, sha, mode, e)
        elif e.src in tree:
            out[e.path] = (e.src, *tree[e.src], e)
    return out


def absent(node: Node, want: dict) -> list[Entry]:
    return [e for e in node.entries if e.src and not e.tree and e.path not in want]


PLACE = re.compile(r"\{\{([^{}\s:]+)(?::([A-Za-z_][A-Za-z0-9_]*))?\}\}")      # {{NAME}}, {{NAME:FIELD}}; NAME may be a pattern
