"""The network certifier's transfer rows (CMP-92): every value that crosses a server block's boundary (`blocks`), the
weights' one-time load, the request bytes in and the generated bytes out, and between two servers a wire's bytes,
committed by the network certifier on the server's uplink, never by the prover, and signed with its key. The verifier
pins each value's root from that certificate alone (`blocks.pins`), so every unit's row that crosses the boundary is a
registered read opened against the certifier's signed root by the Lean verifier's registered reads (`flock-verify
--registered`, `Flock.Registered.checkPort`: an input port, or an output port's row), which don't change.

**The commitment** is a registered value's (`one_stage.registered`), as the prover would commit it, under the
certifier's own salts. The value is `rows` rows of `words` u16 words, row r its words in the order the units read them,
each row the `hm96-sha512/row/v2` bit row a unit's port carries:

    b‖c_r  = hm96.SHA512.commit_string(default_key, sha512_row_v2_digest(row r), salt_r)
    leaf_r = row_leaf(D, r, hm96.SHA512.tree_leaf(default_key, b‖c_r), "hm96-sha512/row/v2")
    root   = the frame-v3-sha512 root of the rows' leaves under D = registered.domain(program, value, words, rows)

D leaves the window out, as a value the verifier holds across windows does, so the root is the one
`registration.check` holds a pinned value's entry to (`pinned`) and the one the verifier's `--registered` port opens;
the head and its certificate bind the link-window. `program` is the circuit's program digest (``circuit.json``'s
``program``), public. salt_r is 192 bytes the certifier draws from the operating system for row r and no other row.
The salts are witness, which the certifier hands to the prover alone (`Transfer.witness`); the rows are what the server
sent or received, which the prover holds.

**The signed head** (`TransferHead`) is public, as a hiding root is:

    H = u16be len(link) ‖ link ‖ u8 direction ‖ u64be window ‖ u16be len(kind) ‖ kind ‖ u16be len(value) ‖ value
      ‖ program (64 bytes) ‖ u32be words ‖ u32be rows ‖ domain (64 bytes) ‖ root (64 bytes)
    transfer digest = tagged_sha512(TRANSFER_TAG, H)

and its certificate is `Issuer.sign`'s of the transfer digest: the certifier's message for the link-window in its
session (`certificate.certificate_message`), so it verifies for that link, direction and window alone. The warden's
cells digest and the record digest of a link-window are under other tags, so none verifies as another.

**The kinds** (`KINDS`) and their directions: ``load`` (ingress: the registered parameters' leaves the load connection
carries, once a server session), ``request`` (ingress), ``response`` (egress), and ``wire`` (a value one server sends
another: its egress on the sender's uplink and its ingress on the receiver's, one value under two certifiers). The
receiver's certifier commits the rows it saw under the sender's certifier's salts, handed it with the rows by whoever
relays them (``salts``), so the two roots are one exactly when the rows that arrived are the rows that left under those
salts, which the verifier holds them to (`blocks.certified`), and the root is as hiding as the sender's. This
workload's rows (`request_rows`, `response_rows`): slot j's request is row j, its length and then its prompt's NP bytes,
one u16 each; byte k of slot j's response is row j·O + k, one u16, byte | present << 8.

**The registration** (`registration`) is the head and its certificate as one public JSON object:

    {"format": REGISTRATION, "link", "direction", "window", "kind", "value", "program", "words", "rows", "word_bits",
     "row_schema", "domain", "root", "certificate": {"key", "digest", "signature"}}

`check_registration` is the verifier's read of it for the transfer it expects: every field the verifier's own, the
domain the one it derives, and the certificate over the head's digest verifying under the certifier's key in its session
for the link-window it expects. `port` is the verifier's own `--registered` port of the value at the head's root.
"""

from __future__ import annotations

import re
from collections.abc import Mapping, Sequence
from dataclasses import dataclass
from functools import cached_property
from typing import Any

from verity.ml.commitments import hm96
from verity.ml.commitments.identity import tagged_sha512
from verity.ml.commitments.merkle import CommitmentDomain
from verity.core.protocols.certifier.certificate import DIGEST_BYTES, Certificate, Direction, Issuer, PublicKey, _text, _u
from verity.core.protocols.sampled_proofs.one_stage import produced
from verity.core.protocols.sampled_proofs.one_stage import registered as G

TRANSFER_TAG = "verity-network-certifier/transfer/v1"
REGISTRATION = "verity-network-certifier/transfer-registration/v1"
#: each kind's directions
KINDS = {"load": (Direction.INGRESS,), "request": (Direction.INGRESS,), "response": (Direction.EGRESS,),
         "wire": (Direction.EGRESS, Direction.INGRESS)}
WORD_BITS = 16
SCHEMA = G.SCHEMA_V2
_INST = hm96.SHA512
SALT_BYTES = _INST.salt_bytes
_HEX64 = re.compile("[0-9a-f]{128}")


def _kind(kind: str, direction: Direction) -> None:
    if direction not in KINDS.get(kind, ()):
        allowed = ", ".join(f"{k} {'/'.join(d.value for d in ds)}" for k, ds in KINDS.items())
        raise ValueError(f"a transfer is a {allowed}, not {kind!r} {getattr(direction, 'value', direction)!r}")


def _program(program: str) -> str:
    if not (isinstance(program, str) and _HEX64.fullmatch(program)):
        raise ValueError(f"a program digest is lowercase hex of 64 bytes, not {program!r}")
    return program


def domain(program: str, value: str, words: int, rows: int) -> CommitmentDomain:
    """The frame-v3-sha512 domain of a transfer value's rows: a registered value's held across windows
    (`registered.domain` with no window), the one a pinned value's entry is under."""
    return G.domain(_program(program), value, words, rows)


def bc(words: Sequence[int], salt: bytes) -> bytes:
    """A row's hm96 commitment string `b ‖ c` under its salt: what a statement's table row of it is."""
    return _INST.commit_string(_INST.default_key, G.row_digest(words, WORD_BITS, SCHEMA), salt)


@dataclass(frozen=True, slots=True)
class TransferHead:
    """What the certifier signs for a transfer value: public, since its root is hiding."""

    link: str
    direction: Direction
    window: int
    kind: str
    value: str
    program: bytes
    words: int
    rows: int
    domain: bytes
    root: bytes

    def __post_init__(self) -> None:
        _kind(self.kind, self.direction)
        if any(len(x) != DIGEST_BYTES for x in (self.program, self.domain, self.root)):
            raise ValueError("the program digest, the domain and the root are 64 bytes")

    def encode(self) -> bytes:
        return b"".join([_text(self.link, "link"), _u(self.direction.code, 1, "direction"), _u(self.window, 8, "window"),
                         _text(self.kind, "kind"), _text(self.value, "value"), self.program, _u(self.words, 4, "words"),
                         _u(self.rows, 4, "rows"), self.domain, self.root])

    def digest(self) -> bytes:
        return tagged_sha512(TRANSFER_TAG, self.encode())


@dataclass(frozen=True)
class Transfer:
    """The certifier's opening of one transfer value, witness: the rows and their salts (`committed`), and the link-window
    and kind it crossed in."""

    link: str
    direction: Direction
    window: int
    kind: str
    committed: G.Registered

    @classmethod
    def commit(cls, link: str, direction: Direction, window: int, kind: str, program: str, value: str,
               rows: Sequence[Sequence[int]], salts: Sequence[bytes] | None = None) -> Transfer:
        """`rows`: the value's rows of u16 words, all of one width. `salts`: one a row, drawn once (default: fresh from the
        operating system) and never for another row."""
        _kind(kind, direction)
        return cls(link, direction, window, kind, G.Registered.commit(_program(program), value, rows, salts, WORD_BITS, SCHEMA))

    @property
    def value(self) -> str:
        return self.committed.value

    @property
    def root(self) -> bytes:
        return self.committed.root

    @property
    def salts(self) -> tuple[bytes, ...]:
        return self.committed.salts

    @cached_property
    def head(self) -> TransferHead:
        c = self.committed
        return TransferHead(self.link, self.direction, self.window, self.kind, c.value, bytes.fromhex(c.program), c.words,
                            c.leaves, c.domain.domain_id, c.root)

    @property
    def witness(self) -> bytes:
        """What the certifier hands the prover beside the rows: their salts, in order (`read_witness`)."""
        return b"".join(self.salts)

    def statement(self, positions: Sequence[int]) -> tuple[list[tuple[int, ...]], list[bytes], dict[str, Any]]:
        """What a statement whose port reads the rows at `positions` commits: those rows, their salts (the prover's) and
        its header's `registered` entry, `{"value", "positions", "paths"}`."""
        return self.committed.statement(positions)


def read_witness(blob: bytes) -> list[bytes]:
    """`Transfer.witness` read back: the rows' salts."""
    if not blob or len(blob) % SALT_BYTES:
        raise ValueError(f"a transfer's witness is {SALT_BYTES} bytes a row")
    return [blob[i:i + SALT_BYTES] for i in range(0, len(blob), SALT_BYTES)]


def attest(issuer: Issuer, link: str, direction: Direction, window: int, kind: str, program: str, value: str,
           rows: Sequence[Sequence[int]], salts: Sequence[bytes] | None = None) -> tuple[Transfer, Certificate | None]:
    """The value's rows committed and their head signed by `issuer` for the link-window (None when its signer refuses)."""
    t = Transfer.commit(link, direction, window, kind, program, value, rows, salts)
    return t, issuer.sign(link, direction, window, t.head.digest())


def request_rows(requests: Sequence[bytes], slots: int, prompt_bytes: int) -> list[list[int]]:
    """A window's request value: slot j's row its request's length, then its NP = `prompt_bytes` bytes, one u16 each,
    zero-padded; a slot no request holds all zeros. Refused (ValueError) past S = `slots` requests or a request past NP
    bytes: the certifier admits at most S requests a window, each within the class's prompt cap."""
    if len(requests) > slots:
        raise ValueError(f"{len(requests)} requests in a window of {slots} slots")
    rows = []
    for j in range(slots):
        r = bytes(requests[j]) if j < len(requests) else b""
        if len(r) > prompt_bytes:
            raise ValueError(f"request {j} is {len(r)} bytes, past the class's {prompt_bytes}")
        rows.append([len(r), *r, *[0] * (prompt_bytes - len(r))])
    return rows


def response_rows(responses: Sequence[bytes], slots: int, outputs: int) -> list[list[int]]:
    """A window's response value: byte k of slot j at row j·O + k (O = `outputs`), one u16, byte | 1 << 8, and 0 past the
    response's end or in a slot no response holds. Refused (ValueError) past S = `slots` responses or a response past O
    bytes."""
    if len(responses) > slots:
        raise ValueError(f"{len(responses)} responses in a window of {slots} slots")
    rows = []
    for j in range(slots):
        r = bytes(responses[j]) if j < len(responses) else b""
        if len(r) > outputs:
            raise ValueError(f"response {j} is {len(r)} bytes, past the class's {outputs}")
        rows += [[r[k] | 1 << 8] if k < len(r) else [0] for k in range(outputs)]
    return rows


def registration(head: TransferHead, certificate: Certificate) -> dict[str, Any]:
    """The public record of a transfer value: its head, its rows' format, and the certificate."""
    return {"format": REGISTRATION, "link": head.link, "direction": head.direction.value, "window": head.window,
            "kind": head.kind, "value": head.value, "program": head.program.hex(), "words": head.words, "rows": head.rows,
            "word_bits": WORD_BITS, "row_schema": SCHEMA, "domain": head.domain.hex(), "root": head.root.hex(),
            "certificate": {"key": certificate.key_id.hex(), "digest": certificate.digest.hex(),
                            "signature": certificate.signature.hex()}}


def check_registration(doc: Any, key: PublicKey, session: bytes, *, link: str, direction: Direction, window: int,
                       kind: str, value: str, program: str, words: int, rows: int) -> tuple[TransferHead, CommitmentDomain]:
    """The verifier's read of a transfer registration for the transfer it expects (its link-window, kind, value, the
    circuit's program digest and the value's shape, all from its own record), under the network certifier's key and
    session: the head and the domain the verifier derived, or ValueError naming what fails."""
    _kind(kind, direction)
    dom = domain(program, value, words, rows)
    want = {"format": REGISTRATION, "link": link, "direction": direction.value, "window": window, "kind": kind,
            "value": value, "program": program, "words": words, "rows": rows, "word_bits": WORD_BITS, "row_schema": SCHEMA,
            "domain": dom.domain_id.hex()}
    if not isinstance(doc, Mapping):
        raise ValueError(f"a transfer registration is a JSON object, not {type(doc).__name__}")
    for k, v in want.items():
        if doc.get(k) != v or type(doc.get(k)) is not type(v):
            raise ValueError(f"the transfer registration's {k} is {doc.get(k)!r}, and the verifier's {v!r}")
    if set(doc) != set(want) | {"root", "certificate"}:
        raise ValueError(f"a transfer registration holds the keys {sorted(set(want) | {'root', 'certificate'})} and no other")
    try:
        if not (isinstance(doc["root"], str) and _HEX64.fullmatch(doc["root"])):
            raise ValueError(f"its root is lowercase hex of 64 bytes, not {doc['root']!r}")
        head = TransferHead(link, direction, window, kind, value, bytes.fromhex(program), words, rows, dom.domain_id,
                            bytes.fromhex(doc["root"]))
        c = doc["certificate"]
        if not isinstance(c, Mapping) or set(c) != {"key", "digest", "signature"}:
            raise ValueError("its certificate is {key, digest, signature}")
        cert = Certificate(bytes.fromhex(c["key"]), link, direction, window, bytes.fromhex(c["digest"]),
                           bytes.fromhex(c["signature"]))
    except (KeyError, TypeError, ValueError) as e:
        raise ValueError(f"the transfer registration's root or certificate doesn't read: {e}") from None
    if cert.digest != head.digest():
        raise ValueError("the transfer registration's certificate doesn't sign its head")
    if not cert.verify(key, session):
        raise ValueError(f"the transfer registration's certificate doesn't verify under the network certifier's key in its "
                         f"session for {link} {direction.value} window {window}")
    return head, dom


def port(head: TransferHead, reads: Sequence[int | None], reads_from: int = 0) -> dict[str, Any]:
    """The verifier's own `--registered` port (`verity/registered-reads/v1`) of a unit population that reads the head's
    value: unit `reads_from + i` opens row `reads[i]` (None: it reads none) at the certifier's signed root."""
    if any(r is not None and not (type(r) is int and 0 <= r < head.rows) for r in reads):
        raise ValueError(f"a read is a row of the value's {head.rows}, or None")
    e = {"leaves": head.rows, "words": head.words, "word_bits": WORD_BITS, "domain": head.domain.hex()}
    return produced.port(head.value, e, head.root.hex(), list(reads), SCHEMA) | \
        ({G.READS_FROM: int(reads_from)} if reads_from else {})
