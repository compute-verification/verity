"""Vectors for `Definitions.Pouw.PearlC.RowPrims`: PoUW's primitives in the row units, computed by
`verity.ml.protocols.pouw.circuit.words`, as Lean data.

    python scripts/row_prims_vectors.py [--out DIR]

Writes `Definitions/Pouw/PearlC/RowPrimVectors.lean` (the vectors, `(operands…, word)`) and
`Proofs/Pouw/PearlC/RowPrimChecks.lean` (one `decide +kernel` theorem per part) under DIR (default: the Lean
package). `PouwETilde_v1` is exhaustive on its domain (16 codes × 256 bytes); the others reach every branch:
* `PouwF32SqrtRn_v1`: ±0, ±inf, NaNs, negative words, subnormals, one word per exponent field, exact squares, and
  random words;
* `PouwSqAcc_v1`: every exponent edge of `sq300` and accumulators up to and past `2^576`;
* `PouwSqCeil_v1`: `up48`'s edges (`2^48 − 1`, `2^48`, the carry at `2^49 − 1`), `n` zero, one and past `2^32`, and
  random sums;
* `PouwSqGe_v1`: thresholds at, above and below `up48 (sq300 x)`;
* `PouwBf16Neg_v1`: its edges and random words.

`verity/core/protocols/pouw/tests/test_row_prims_lean.py` checks that this script still writes both files byte for byte.
"""
from __future__ import annotations

import argparse
import random
import struct
from pathlib import Path

from verity.ml.protocols.pouw.circuit import words as W

SEED = 2026100321
HEADER = "/-! Generated by `verity/core/protocols/pouw/lean/scripts/row_prims_vectors.py` (seed {seed}); do not edit. -/"
F32_SPECIAL = [0x00000000, 0x80000000, 0x7F800000, 0xFF800000, 0x7FC00000, 0x7F800001, 0xFFC00000, 0xFFFFFFFF,
               0x00000001, 0x007FFFFF, 0x00800000, 0x7F7FFFFF, 0x3F800000, 0x40000000, 0x40800000, 0x80000001,
               0xBF800000, 0x807FFFFF, 0x00400000, 0x00000002, 0x00000003, 0x3F800001, 0x3FFFFFFF]


def _f32(v: float) -> int:
    return struct.unpack("<I", struct.pack("<f", v))[0]


def f32_words(rng: random.Random, per_field: int, extra: int) -> list[int]:
    out = list(F32_SPECIAL)
    for e in range(256):
        for _ in range(per_field):
            out.append((rng.getrandbits(1) << 31) | (e << 23) | rng.getrandbits(23))
    out += [rng.getrandbits(32) for _ in range(extra)]
    return out


def sqrt_vectors(rng: random.Random) -> list[tuple[int, ...]]:
    xs = f32_words(rng, 1, 300)
    for k in range(1, 64):
        xs.append(_f32(float(k * k)))
    for _ in range(64):
        m = rng.getrandbits(12) | 1
        xs.append(_f32(float(m * m) * 2.0 ** rng.randrange(-60, 60, 2)))
    xs += [x & 0x7FFFFFFF for x in xs[:200]]
    return [(x, W.PouwF32SqrtRn.evaluate(x)) for x in xs]


def sqacc_vectors(rng: random.Random) -> list[tuple[int, ...]]:
    accs = [0, 1, (1 << 576) - 1, (1 << 576) - (1 << 500), (1 << 571) - 1, 1 << 575]
    out = []
    for x in f32_words(rng, 0, 40):
        out.append((rng.choice(accs) if rng.random() < 0.5 else rng.getrandbits(rng.randrange(1, 577)), x))
    for e in (0, 1, 2, 127, 253, 254, 255):
        for _ in range(4):
            x = (rng.getrandbits(1) << 31) | (e << 23) | rng.getrandbits(23)
            out.append((rng.choice(accs), x))
    return [(a, x, W.PouwSqAcc.evaluate(a, x)) for a, x in out]


def sqceil_vectors(rng: random.Random) -> list[tuple[int, ...]]:
    ts = [0, 1, 2, (1 << 48) - 1, 1 << 48, (1 << 48) + 1, (1 << 49) - 1, 1 << 49, (1 << 49) + 1, (1 << 97) - 1,
          (1 << 96) + (1 << 48), (1 << 571) - 1, (1 << 576) - 1]
    out = [(t, 64) for t in ts] + [(t, 1) for t in ts] + [(t, 0) for t in ts[:5]]
    ns = [1, 2, 3, 7, 16, 63, 64, 65, 1024, (1 << 32) - 1, 1 << 32, (1 << 32) + 5, (1 << 40) + 64]
    for _ in range(120):
        out.append((rng.getrandbits(rng.randrange(1, 577)), rng.choice(ns) if rng.random() < 0.5 else
                    rng.getrandbits(rng.randrange(1, 40))))
    return [(t, n, W.PouwSqCeil.evaluate(t, n)) for t, n in out]


def sqge_vectors(rng: random.Random) -> list[tuple[int, ...]]:
    out = []
    for x in f32_words(rng, 0, 30) + [((rng.getrandbits(1) << 31) | (e << 23) | rng.getrandbits(23))
                                      for e in (0, 1, 2, 126, 127, 128, 253, 254, 255)]:
        q = W.up48(W.sq300(x & W.M32))
        for th in {q, q + 1, max(q - 1, 0), 0, (1 << 64) - 1, rng.getrandbits(64)}:
            out.append((x, th))
    return [(x, th, W.PouwSqGe.evaluate(x, th)) for x, th in sorted(out)]


def etilde_vectors() -> list[tuple[int, ...]]:
    return [(e, ae, W.PouwETilde.evaluate(e, ae)) for e in range(16) for ae in range(256)]


def bf16neg_vectors(rng: random.Random) -> list[tuple[int, ...]]:
    xs = [0, 0x8000, 0x7FFF, 0xFFFF, 0x7F80, 0xFF80, 0x7FC0, 0x0001] + [rng.getrandbits(16) for _ in range(56)]
    return [(x, W.PouwBf16Neg.evaluate(x)) for x in xs]


#: (Lean name stem, function, arity, vectors per part, doc)
FAMILIES = [
    ("sqrt", "sqrtWord", 1, 200, "`PouwF32SqrtRn_v1`"),
    ("sqacc", "sqAccWord", 2, 150, "`PouwSqAcc_v1`"),
    ("sqceil", "sqCeilWord", 2, 200, "`PouwSqCeil_v1`"),
    ("sqge", "sqGeWord", 2, 200, "`PouwSqGe_v1`"),
    ("etilde", "eTildeWord", 2, 512, "`PouwETilde_v1`, every code and byte"),
    ("bf16neg", "bf16NegWord", 1, 64, "`PouwBf16Neg_v1`"),
]


def lit(v: int) -> str:
    return f"0x{v:X}"


def render(vectors: dict[str, list[tuple[int, ...]]]) -> tuple[str, str]:
    data = ["import Definitions.Pouw.PearlC.RowPrims", "", HEADER.format(seed=SEED), "",
            "namespace Pouw.PearlC.RowPrimVectors", ""]
    checks = ["import Definitions.Pouw.PearlC.RowPrimVectors", "", HEADER.format(seed=SEED), "",
              "namespace Pouw.PearlC.RowPrimChecks", "", "open Pouw.PearlC.RowCircuit", ""]
    for stem, fn, arity, per, doc in FAMILIES:
        vs = vectors[stem]
        typ = "ℕ × ℕ" if arity == 1 else "ℕ × ℕ × ℕ"
        parts = [vs[i:i + per] for i in range(0, len(vs), per)]
        for j, part in enumerate(parts):
            name = f"{stem}{j}"
            data.append(f"/-- {doc}: {len(vs)} vectors `(operands…, word)` from `verity.ml.protocols.pouw.circuit.words`, part {j}. -/")
            data.append(f"def {name} : List ({typ}) := [")
            body = ", ".join("(" + ", ".join(lit(x) for x in v) + ")" for v in part)
            data.append("  " + body + "]")
            data.append("")
            pat, call = ("(a, w)", f"{fn} a") if arity == 1 else ("(a, b, w)", f"{fn} a b")
            checks.append(f"/-- {doc} holds for `{fn}` on part {j} of its vectors, evaluated by the kernel. -/")
            checks.append(f"theorem {name} : RowPrimVectors.{name}.all (fun {pat} => {call} == w) = true := by")
            checks.append("  decide +kernel")
            checks.append("")
    data.append("end Pouw.PearlC.RowPrimVectors")
    checks.append("end Pouw.PearlC.RowPrimChecks")
    return "\n".join(data) + "\n", "\n".join(checks) + "\n"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", type=Path, default=Path(__file__).resolve().parents[6] / "Security")
    args = ap.parse_args()
    rng = random.Random(SEED)
    vectors = {"sqrt": sqrt_vectors(rng), "sqacc": sqacc_vectors(rng), "sqceil": sqceil_vectors(rng),
               "sqge": sqge_vectors(rng), "etilde": etilde_vectors(), "bf16neg": bf16neg_vectors(rng)}
    data, checks = render(vectors)
    for rel, text in (("Definitions/Pouw/PearlC/RowPrimVectors.lean", data),
                      ("Proofs/Pouw/PearlC/RowPrimChecks.lean", checks)):
        path = args.out / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        tmp = path.with_suffix(".lean.tmp")
        tmp.write_text(text)
        tmp.replace(path)


if __name__ == "__main__":
    main()
