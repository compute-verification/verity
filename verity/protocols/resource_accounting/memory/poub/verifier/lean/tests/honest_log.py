"""The honest one-window period whose log `Properties.Poub.Subprotocol.HonestLogAccepted` says the deployed check
accepts (`security/Properties/Poub/Remote/HonestLog.lean`): its case (`run`), and that case as the Lean module the
premise reads (`lean_module`). `python honest_log.py` writes the module (with
`..`, where `ra_cases.py` is, on `PYTHONPATH`); `test_honest_log.py` holds it to this file and
holds the premise to the compiled check.

The period is `test_protocol.periods`' honest one on node `n0`, at one window and one sample, over a store of one block:
`period_prover.run` on a clock and an entropy source the case fixes, so the case is the same bytes on every run."""

from __future__ import annotations

import hashlib
import json
import sys
from unittest import mock

import ra_cases as M

from verity.protocols.resource_accounting.memory.poub.prover import period_prover
from verity.protocols.resource_accounting.memory.poub.verifier import audit

ROOT = M.PACKAGE.parents[6]
MODULE = ROOT / "security/Properties/Poub/Remote/HonestLog/Case.lean"
NAMESPACE = "Properties.Poub.Subprotocol.HonestLog"
STORE = hashlib.shake_256(b"one block").digest(100)
COINS = hashlib.sha512(b"the period's live coins").digest()


def run():
    """The period's run: its case (`commitment`, `evidence`, `params`) and its live session's answer. The registration's
    nonce, which the verifier draws from the operating system (`audit.register`), comes from the suite's entropy too."""
    c = M.Clock(10 ** 9, 1_000)
    with mock.patch.object(audit.secrets, "token_bytes", M.Entropy(b"nonce")):
        return period_prover.run("n0", STORE, COINS, windows=1, samples=1, clock=c, sleep_until=c.sleep_until,
                                 entropy=M.Entropy(b"salts"))


def _lean(v) -> str:
    if v is None:
        return ".null"
    if isinstance(v, bool):
        return f".bool {'true' if v else 'false'}"
    if isinstance(v, int) and v >= 0:
        return f".num (Lean.JsonNumber.fromNat {v})"
    if isinstance(v, str):
        return ".str " + json.dumps(v)
    if isinstance(v, list):
        return "(.arr #[" + ", ".join(map(_lean, v)) + "])"
    if isinstance(v, dict):
        return "(Lean.Json.mkObj [" + ", ".join(f"({json.dumps(k)}, {_lean(x)})" for k, x in v.items()) + "])"
    raise TypeError(f"no Lean term for {v!r}")


def lean_module(case: dict) -> str:
    """The case as Lean `Json` terms: the parameters, the registration the commitment's bytes hold, and the evidence."""
    reg = json.loads(bytes.fromhex(case["commitment"]))
    ev = json.loads(bytes.fromhex(case["evidence"]))
    p = case["params"]
    events = ",\n".join("    " + _lean(e) for e in ev["events"])
    return f"""module

public import Poub.Protocol

/-! Generated by `verity/protocols/resource_accounting/memory/poub/verifier/lean/tests/honest_log.py`; do not edit. -/

@[expose] public section

namespace {NAMESPACE}

/-- The honest one-window period's parameters. -/
def params : _root_.Poub.Protocol.Params where
  notBeforeNs := {_lean(p["not_before_ns"])}
  params := {_lean(p["params"])}

/-- The registration its commitment's bytes hold. -/
def registration : Lean.Json :=
  {_lean(reg)}

/-- Its evidence: the coins and the verifier's log. -/
def evidence : _root_.Poub.Protocol.Evidence where
  appendCoins := {_lean(ev["append_coins"])}
  coins := {_lean(ev["coins"])}
  events := #[
{events}]

end {NAMESPACE}
"""


if __name__ == "__main__":
    MODULE.parent.mkdir(parents=True, exist_ok=True)
    MODULE.write_text(lean_module(run().case))
    sys.stdout.write(f"wrote {MODULE.relative_to(ROOT)}\n")
