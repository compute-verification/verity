"""The Lean soundness package's data for a verified lowering: a unit's gate circuit and its pinned rows, as
`Security/Proofs/Flock/Soundness/Rope/Gates.lean`, `Pinned.lean`, `Checkpoints.lean` and `Chunks.lean`. The
kernel checks the derivation `FlockSoundness.GateRows.rows` in chunks of `CHUNK` gates (`Chunks.lean`), each from a
checkpoint: the next wire, the next AND's column, and the forms of the wires still read.
`verity/ml/flock/tests/test_lean_rope.py` checks that these files are what this module writes, for the netlist
`rope_head.PINS` pins.

The gate circuit is the committed `Gates.lean` (the Boolean export's gate list when it had one): this module reads it back,
checks on random inputs that it computes the unit's circuit, and writes the other three files from it and the lowering's
rows.

Encodings, one `Nat` literal each, so that Lean elaborates the data quickly:

* a gate is ``op + 3·(a + 2^17·b)`` (op 0 AND, 1 XOR, 2 NOT with b = 0), an operand ``0`` / ``1`` for the constants 0 / 1
  and ``2 + w`` for wire ``w`` (``-1`` / ``-2`` and wire numbers below);
* a list of columns is its runs of consecutive columns, ``(first, length)``, each the base-2^22 digit
  ``first·512 + length + 1``, least significant first.

    python -m verity_flock.lean_rows --out Security/Proofs/Flock/Soundness/Rope
"""
from __future__ import annotations

import argparse
import random
import re
from pathlib import Path

HEAD = "/-! Generated by `python -m verity_flock.lean_rows` (`verity/ml/flock/python/verity_flock/lean_rows.py`); do not edit. -/"
CHUNK = 1000
FILES = ("Gates.lean", "Pinned.lean", "Checkpoints.lean", "Chunks.lean")
ROPE = Path(__file__).resolve().parents[5] / "Security" / "Proofs" / "Flock" / "Soundness" / "Rope"


def _listdef(name: str, items: list[str], ty: str, per: int) -> str:
    if len(items) <= per:
        return f"def {name} : List {ty} := [{', '.join(items)}]"
    parts = [items[i:i + per] for i in range(0, len(items), per)]
    out = [f"def {name}_{k} : List {ty} := [{', '.join(q)}]" for k, q in enumerate(parts)]
    out.append(f"def {name} : List {ty} := " + " ++ ".join(f"{name}_{k}" for k in range(len(parts))))
    return "\n\n".join(out)


def _operand(w: int) -> int:
    return 0 if w == -1 else 1 if w == -2 else w + 2


def _ungate(c: int) -> tuple[int, int, int | None]:
    """`Rope.decGate`, in Python: the op and the operands (``-1`` / ``-2`` for the constants), NOT's second None."""
    src = lambda n: -1 if n == 0 else -2 if n == 1 else n - 2
    return c % 3, src(c // 3 % (1 << 17)), None if c % 3 == 2 else src(c // 3 // (1 << 17))


def _gate_code(op: int, a: int, b: int) -> int:
    x, y = _operand(a), _operand(b) if op != 2 else 0
    assert x < 1 << 17 and y < 1 << 17, f"an operand of ({op}, {a}, {b}) is at or above 2^17, which a gate code cannot hold"
    c = op + 3 * (x + (1 << 17) * y)
    assert _ungate(c) == (op, a, None if op == 2 else b)
    return c


def _unpack(n: int) -> list[int]:
    """`Rope.unpackRuns 512` then `runsList`, in Python."""
    cols: list[int] = []
    for _ in range(512):
        if n == 0:
            break
        d = n % (1 << 22) - 1
        cols.extend(range(d // 512, d // 512 + d % 512))
        n >>= 22
    return cols


def _pack(cols: list[int]) -> int:
    runs: list[list[int]] = []
    for c in cols:
        if runs and c == runs[-1][0] + runs[-1][1]:
            runs[-1][1] += 1
        else:
            runs.append([c, 1])
    assert len(runs) <= 512, f"{len(runs)} runs, more than Rope.unpackRuns' fuel of 512"
    n = 0
    for a, length in reversed(runs):
        d = a * 512 + length + 1
        assert a < 8192 and length < 512 and d < 1 << 22, f"the run ({a}, {length}) does not fit a base-2^22 digit"
        n = (n << 22) + d
    assert _unpack(n) == list(cols)
    return n


def _bits(m: int) -> list[int]:
    return [i for i in range(m.bit_length()) if m >> i & 1]


def _gate_list() -> tuple[list[int], int, list[int]]:
    """The committed gate circuit (`Rope/Gates.lean`): flat ``[op, a, b]`` triples (NOT's ``b`` is ``-1``), the input
    count, and the output operands."""
    text = (ROPE / "Gates.lean").read_text()
    n_in = int(re.search(r"^def nIn : Nat := (\d+)$", text, re.M).group(1))
    gates: list[int] = []
    for body in re.findall(r"^def gatesChunk\d+(?:_\d+)? : List Nat := \[([^\]]*)\]", text, re.M):
        for c in body.split(", "):
            op, a, b = _ungate(int(c))
            gates += [op, a, -1 if b is None else b]
    codes = re.search(r"^def outCodes : List Nat := \[([^\]]*)\]", text, re.M).group(1).split(", ")
    return gates, n_in, [-1 if n == 0 else -2 if n == 1 else n - 2 for n in map(int, codes)]


def _computes(gates: list[int], n_in: int, outs: list[int], C, T: int = 64, seed: int = 0) -> bool:
    """The gate circuit against the unit circuit ``C`` on T random vectors, its inputs in ``C.inputs`` order."""
    rng = random.Random(seed)
    ins = {name: [rng.getrandbits(T) for _ in bits] for name, bits in C.inputs.items()}
    want, _fail = C.evaluate(ins, T)
    mask = (1 << T) - 1
    vals = [x for bits in ins.values() for x in bits]
    if len(vals) != n_in:
        return False
    val = lambda w: 0 if w == -1 else mask if w == -2 else vals[w]  # noqa: E731
    for op, a, b in zip(gates[0::3], gates[1::3], gates[2::3]):
        vals.append(val(a) & val(b) if op == 0 else val(a) ^ val(b) if op == 1 else ~val(a) & mask)
    return [val(o) for o in outs] == [x for bits in want.values() for x in bits]


def rope() -> dict[str, str]:
    """The four files for ``rope-head/neox-bf16/pair`` (the D = 64 lowering; its rows are the same for every D), with
    the netlist's sha256 under ``"sha256"``."""
    from verity_numerical.bench import lowerings, templates as TM

    mod = lowerings.registry("C-Flock").module("rope-head")
    low = mod.lowering(TM.subcircuit("rope-head", D=64))
    lay = low.layout
    # the layout's regions: the input group's words, the ANDs, the output region, the constant last
    AND_BASE = lay.counts["in_words"] * 128
    OUT_BASE = AND_BASE + lay.counts["ands"]
    OUT_LEN = lay.const - OUT_BASE
    k = lay.const
    g, n_in, outs = _gate_list()
    assert _computes(g, n_in, outs, low.units.circuit()), "the committed gate circuit does not compute the unit's circuit"
    ops, A, B = g[0::3], g[1::3], g[2::3]
    G = len(ops)
    codes = [_gate_code(op, a, b) for op, a, b in zip(ops, A, B)]
    # the forms `GateRows.St.steps` gives each wire, in the layout's columns
    forms: list[tuple[int, int]] = [(1 << k, 0) for k in range(n_in)]
    ands = [0]
    for op, a, b in zip(ops, A, B):
        fa = (0, 0) if a == -1 else (0, 1) if a == -2 else forms[a]
        fb = (0, 0) if b == -1 else (0, 1) if b == -2 else forms[b]
        if op == 0:
            forms.append((1 << (AND_BASE + ands[-1]), 0))
            ands.append(ands[-1] + 1)
        else:
            forms.append((fa[0] ^ fb[0], fa[1] ^ fb[1]) if op == 1 else (fa[0], fa[1] ^ 1))
            ands.append(ands[-1])
    last: dict[int, int] = {}
    for i, (op, a, b) in enumerate(zip(ops, A, B)):
        for x in ((a, b) if op != 2 else (a,)):
            if x >= 0:
                last[x] = i
    for x in outs:
        if x >= 0:
            last[x] = G
    cuts = list(range(0, G, CHUNK)) + [G]
    row = lambda r: f"({_pack(lay.rows_a[r])}, {_pack(lay.rows_b[r])})"
    ns, end = "namespace FlockSoundness.Rope\n\n", "\n\nend FlockSoundness.Rope\n"
    gates = [f"{HEAD}\n\n{ns}/-- The unit's inputs. -/\ndef nIn : Nat := {n_in}"]
    pinned = [f"{HEAD}\n\n{ns}" + _listdef("pinIn", [row(r) for r in range(AND_BASE)], "(Nat × Nat)", 256)]
    cps = [f"{HEAD}\n\n{ns}/-! Checkpoints: the next wire, the next AND's column, and `(wire, its form's runs, its constant)`\n"
           "for each wire the rest of the gates or the outputs read. -/"]
    for j, c in enumerate(cuts):
        live = [x for x in range(n_in + c) if last.get(x, -1) >= c]
        ent = ", ".join(f"({x}, {_pack(_bits(forms[x][0]))}, {'true' if forms[x][1] else 'false'})" for x in live)
        cps.append(f"def cpData{j} : Nat × Nat × List (Nat × Nat × Bool) := ({n_in + c}, {AND_BASE + ands[c]}, [{ent}])")
    for j in range(len(cuts) - 1):
        lo, hi = cuts[j], cuts[j + 1]
        gates.append(_listdef(f"gatesChunk{j}", [str(x) for x in codes[lo:hi]], "Nat", 500))
        rs = range(AND_BASE + ands[lo], AND_BASE + ands[hi])
        pinned.append(_listdef(f"pinAnd{j}", [row(r) for r in rs], "(Nat × Nat)", 256))
    K = len(cuts) - 1
    gates.append("def gateCodes : List Nat :=\n  " + " ++ ".join(f"gatesChunk{j}" for j in range(K)))
    gates.append(f"def outCodes : List Nat := [{', '.join(str(_operand(w)) for w in outs)}]")
    pinned.append(_listdef("pinOut", [row(r) for r in range(OUT_BASE, OUT_BASE + OUT_LEN)], "(Nat × Nat)", 256))
    pinned.append(f"def pinConst : Nat × Nat := {row(OUT_BASE + OUT_LEN)}")
    pinned.append("def pinnedCodes : List (Nat × Nat) :=\n  pinIn ++ "
                  + " ++ ".join(f"pinAnd{j}" for j in range(K)) + " ++ pinOut ++ [pinConst]")
    assert OUT_BASE + OUT_LEN + 1 == len(lay.rows_a) and AND_BASE + ands[-1] == OUT_BASE
    chunks = [f"import Proofs.Flock.Soundness.Rope.Defs\n\n{HEAD}\n\n{ns}open GateRows\n",
              "/-- The chunks: each chunk's gates, the checkpoint it reaches, and its AND rows. -/\n"
              "def chunks : List (List Gate × CP × List (ℕ × ℕ)) := [\n"
              + ",\n".join(f"  (gatesChunk{j}.map decGate, decCP cpData{j + 1}, pinAnd{j}.map pinMasks)" for j in range(K))
              + "]"]
    for j in range(K):
        chunks.append(f"theorem chunk{j} : checkChunk {k} (decCP cpData{j}) (gatesChunk{j}.map decGate) (decCP cpData{j + 1})\n"
                      f"    (pinAnd{j}.map pinMasks) = true ∧ pinAnd{j}.all runsBounded = true := by\n  decide +kernel")
    chunks.append(f"theorem chunksOK : ChunksOK {k} (decCP cpData0) chunks := by\n  simp only [chunks, ChunksOK]\n"
                  "  exact ⟨" + ", ".join(f"chunk{j}.1" for j in range(K)) + ", trivial⟩")
    chunks.append("theorem pinnedCodes_bounded (h : pinIn.all runsBounded = true) (h' : pinOut.all runsBounded = true)\n"
                  "    (h'' : runsBounded pinConst = true) : pinnedCodes.all runsBounded = true := by\n"
                  "  simp only [pinnedCodes, List.all_append, List.all_cons, List.all_nil, Bool.and_true, h, h', h'', "
                  + ", ".join(f"chunk{j}.2" for j in range(K)) + "]")
    chunks.append("theorem gates_eq : circ.gates = chunks.flatMap (·.1) := by\n"
                  "  simp only [circ, gateCodes, chunks, List.map_append, List.flatMap_cons, List.flatMap_nil, List.append_nil,\n"
                  "    List.append_assoc]")
    chunks.append("theorem pinned_split : pinnedCodes.map pinMasks =\n"
                  "    pinIn.map pinMasks ++ chunks.flatMap (·.2.2) ++ pinOut.map pinMasks ++ [pinMasks pinConst] := by\n"
                  "  simp only [pinnedCodes, chunks, List.map_append, List.map_cons, List.map_nil, List.flatMap_cons,\n"
                  "    List.flatMap_nil, List.append_nil, List.append_assoc]")
    chunks.append(f"theorem lastCP_chunks : lastCP (decCP cpData0) chunks = decCP cpData{K} := rfl")
    return {"Gates.lean": "\n\n".join(gates) + end, "Pinned.lean": "\n\n".join(pinned) + end,
            "Checkpoints.lean": "\n\n".join(cps) + end, "Chunks.lean": "\n\n".join(chunks) + end, "sha256": low.sha256}


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--out", type=Path, required=True, help="the directory of Security/Proofs/Flock/Soundness/Rope")
    args = ap.parse_args()
    data = rope()
    for name in FILES:
        (args.out / name).write_text(data[name])
    print(f"wrote {', '.join(FILES)} in {args.out} for the netlist {data['sha256']}")


if __name__ == "__main__":
    main()
