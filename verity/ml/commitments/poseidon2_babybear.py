ROLE_X = 1      # activation rows (the ``a`` operand of every unit)
ROLE_W = 2      # weight columns (the ``b`` operand)


def IV(role: int, word_bits: int, n_words: int) -> list[int]:
    """The initial state: rate lanes 0, capacity = (role, word_bits, n_words, 0, ..., 0) -- domain separation of the two
    operand tensors and of the row format inside the permutation."""
    cap = [int(role), int(word_bits), int(n_words)] + [0] * (CAPACITY - 3)
    return [0] * RATE + cap


def pack_words(words, word_bits: int) -> list[int]:
    """``n_words`` words of ``word_bits`` bits (a sequence of ints) -> ``n_words * word_bits / 16`` elements of 16 bits
    each: consecutive words in little-endian order (``w0 + 2^word_bits w1 + ...``).  Pure Python; the vectorised
    committer / witness paths (``archive/direct/ligero/poseidon2.py``) implement the same map on arrays."""
    w = [int(x) for x in words]
    per = LANE_BITS // word_bits
    if LANE_BITS % word_bits or len(w) % per:
        raise ValueError(f"{word_bits}-bit words do not tile 16-bit lanes over {len(w)} words")
    if any(x < 0 or x >= 2**word_bits for x in w):
        raise ValueError("word out of range")
    return [sum(w[i + q] << (word_bits * q) for q in range(per)) for i in range(0, len(w), per)]


def hash_row(words, word_bits: int, role: int) -> list[int]:
    """Scalar reference of the row digest: 8 elements."""
    el = pack_words(words, word_bits)
    if len(el) % RATE:
        raise ValueError("row does not tile the rate")
    s = IV(role, word_bits, len(el) * (LANE_BITS // word_bits))
    for i in range(0, len(el), RATE):
        s = el[i:i + RATE] + s[RATE:]
        s = permute(s)
    return s[:OUT]


def digest_bytes(d) -> bytes:
    """8 elements -> 32 bytes (u32 little-endian each): the Merkle leaf value of ``leaf/v2h``."""
    d = [int(x) for x in d]
    if len(d) != OUT or any(not 0 <= x < P for x in d):
        raise ValueError("digest must be 8 canonical elements")
    return b"".join(x.to_bytes(4, "little") for x in d)


def digest_from_bytes(b: bytes) -> list[int]:
    if len(b) != 4 * OUT:
        raise ValueError("digest bytes must be 32 bytes")
    d = [int.from_bytes(b[4 * i:4 * i + 4], "little") for i in range(OUT)]
    if any(x >= P for x in d):
        raise ValueError("digest element out of the field")
    return d
