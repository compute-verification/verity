# ---------------------------------------------------------------------------------------------------------------------
# Generic evaluation: the state is a list of ring elements supporting + and * by a Python int; ``sbox(x)`` returns x^7
# (materialised as product rows by the gadget), ``reduce(x)`` brings a linear combination back to canonical form.
# ---------------------------------------------------------------------------------------------------------------------

def _external_layer(s: list, reduce) -> list:
    """circ(2 M4, M4, ..., M4): M4 on every 4-lane chunk, then every lane adds the sum of its residue class."""
    t = list(s)
    for c in range(0, WIDTH, 4):
        x = s[c:c + 4]
        for i in range(4):
            acc = x[0] * M4[i][0]
            for j in range(1, 4):
                acc = acc + x[j] * M4[i][j]
            t[c + i] = reduce(acc)
    sums = []
    for k in range(4):
        acc = t[k]
        for c in range(4, WIDTH, 4):
            acc = acc + t[c + k]
        sums.append(acc)
    return [reduce(t[i] + sums[i % 4]) for i in range(WIDTH)]


def _internal_layer(s: list, reduce) -> list:
    """1 + Diag(V): every lane becomes V_i s_i + sum_j s_j."""
    tot = s[0]
    for i in range(1, WIDTH):
        tot = tot + s[i]
    return [reduce(s[i] * DIAG[i] + tot) for i in range(WIDTH)]


def permute_ring(state: list, sbox, reduce) -> list:
    """The permutation on ring elements (Plonky3 order).  ``sbox(x) -> x^7``; ``reduce`` canonicalises sums."""
    if len(state) != WIDTH:
        raise ValueError(f"state has {len(state)} lanes, want {WIDTH}")
    s = _external_layer([reduce(x) for x in state], reduce)
    for rc in RC_EXTERNAL_INITIAL:
        s = [sbox(reduce(s[i] + rc[i])) for i in range(WIDTH)]
        s = _external_layer(s, reduce)
    for rc in RC_INTERNAL:
        s = list(s)
        s[0] = sbox(reduce(s[0] + rc))
        s = _internal_layer(s, reduce)
    for rc in RC_EXTERNAL_FINAL:
        s = [sbox(reduce(s[i] + rc[i])) for i in range(WIDTH)]
        s = _external_layer(s, reduce)
    return s


def _sbox_int(x: int) -> int:
    return pow(x, 7, P)


def permute(state: list[int]) -> list[int]:
    """The scalar reference on canonical integers in [0, p)."""
    return permute_ring([int(x) % P for x in state], _sbox_int, lambda x: x % P)




