"""Each leg against the skeleton's step, as ``{"status": "real" | "fixture" | "not-run", "owner", "issue", ...}``. A leg's
owner makes its real piece run here; until then the entry says what stood in for it, or that nothing did.

Demo A (M1-M3) is PoUW, sampled proofs and network; PoUS, bandwidth and the wipe run in M4 on its P2 store
(``run.py --weights staged``). FIXTURES run here:
* ``pous``: the challenger's spot reads, as reads of random blocks of the store decoded by the P2 reference and compared with
  the registered weights' bytes (no timing, no challenger, no verification root);
* ``wipe``: C written to disk, the in-memory rows zeroed, C reloaded and its digest compared, and the step's root
  recomputed from the reloaded store (no certified fill: memory-accounting's `labels.cu` wipe is the real one);
* ``certifier``: the digests of the requests' bytes in and the generated bytes out that the certifier would sign (network's
  own rehearsal serves its endpoint from this loop, `engine`).
"""
from __future__ import annotations

import hashlib
import tempfile
from pathlib import Path
from typing import Callable

import numpy as np

from .store import PAYLOAD, P2Store, Store, decode_block

OWNERS = {
    "pous": ("memory-accounting", "MEM-67, MEM-69"),
    "bandwidth": ("memory-accounting", "CMP-97"),
    "certifier": ("network-accounting", "NET-72, NET-77"),
    "wipe": ("memory-accounting", "MEM-67 3a.2"),
    "pouw": ("compute-accounting (H200-PERCALL)", "CMP-126"),
    "integrity": ("compute-accounting (ALLP-RUN) and proofs", "PRF-170, CMP-95 item 5"),
}


def _entry(name: str, status: str, **detail) -> dict:
    owner, issue = OWNERS[name]
    return {"status": status, "owner": owner, "issue": issue, **detail}


def pous_spot_reads(store: Store, reads: int, seed: bytes) -> dict:
    if not isinstance(store, P2Store):
        return _entry("pous", "not-run", reason=f"no encoded store ({store.kind})")
    n = store.rows.shape[0]
    rng = np.random.Generator(np.random.PCG64(int.from_bytes(hashlib.sha512(b"pous-spot\0" + seed).digest()[:16], "big")))
    picks = sorted({int(j) for j in rng.integers(0, n, size=reads)})
    wb, bad = store.weights.nbytes, []
    for j in picks:
        lo = j * PAYLOAD
        want = store.weights.stream(lo, min(lo + PAYLOAD, wb)).ljust(PAYLOAD, b"\0")
        if decode_block(store.prefix, j, store.block(j)) != want:
            bad.append(j)
    return _entry("pous", "fixture", reads=len(picks), mismatched_blocks=bad,
                  stands_in_for="the PoUS challenger's timed spot reads on the auditor host")


def wipe_reload(store: Store, recommit: Callable[[], bytes], root: bytes) -> dict:
    if not isinstance(store, P2Store):
        return _entry("wipe", "not-run", reason=f"no encoded store ({store.kind})")
    before = store.digest()
    with tempfile.TemporaryDirectory() as d:
        path = Path(d) / "c.bin"
        store.save(path)
        store.rows[...] = 0
        rows = np.fromfile(path, dtype=np.uint8).reshape(store.rows.shape)
    if isinstance(store.rows, np.ndarray):
        store.rows[...] = rows
    else:
        import torch
        store.rows.copy_(torch.from_numpy(rows))
    after = store.digest()
    again = recommit()
    return _entry("wipe", "fixture", store_digest_equal=before == after, step_root_equal=again == root,
                  stands_in_for="a certified streamed wipe (labels.cu) and the store's reload from disk")


def certifier(prompts: np.ndarray, outputs: np.ndarray) -> dict:
    return _entry("certifier", "fixture",
                  requests_in_sha512=hashlib.sha512(prompts.astype(np.uint8).tobytes()).hexdigest(),
                  bytes_out_sha512=hashlib.sha512(outputs.astype(np.uint8).tobytes()).hexdigest(),
                  stands_in_for="the network certifier's signed records of the requests in and the bytes out (network's "
                                "stand-in serves demo_endpoint from e2e_h200.engine)")


def not_run(name: str, reason: str) -> dict:
    return _entry(name, "not-run", reason=reason)
