"""The decoder's window (`transformer.DecoderLoop`), written for the audit from its records alone, as `serve` writes the MLP's.

    python -m verity_torch_loop.serve_transformer --out DIR [--law L] [--prompt BYTES ...] [--generate G] [--seed S] \\
        [--cap 16] [--workers N] [--run-id ID] [--bf16-dot hopper|ampere] [--tamper]
    python -m verity_torch_loop.serve_transformer --circuit-only [the same shape and --run-id]

The first serves the prompts, commits every unit and writes the window (``circuit.json``, the registration under core's
``one_stage.registration``, the value files) to ``--out``. It prints the circuit record's SHA-512, the run root, the
population by template, the generated bytes, the units whose outputs are not their Definition's (none unless
``--tamper``), and the seconds each stage took. The second prints the circuit record's SHA-512 alone, from the shape and
no value: the circuit the verifier registers before the loop runs."""
from __future__ import annotations

import argparse
import hashlib
import json
import time
from pathlib import Path

from verity.core.protocols.sampled_proofs.one_stage import draw as D, registration as R
from verity.ml.windows import interface as IF

from . import transformer as T

PROMPTS = ("Hello, w", "verity::", "PyTorch!", "decoder.")


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--out")
    ap.add_argument("--circuit-only", action="store_true")
    ap.add_argument("--law", default="subset:2")
    ap.add_argument("--prompt", action="append", help=f"a prompt (UTF-8), once per request; default {list(PROMPTS)}")
    ap.add_argument("--generate", type=int, default=T.CONTEXT - len(PROMPTS[0]))
    ap.add_argument("--seed", type=int, default=0)
    ap.add_argument("--cap", type=int, default=16)
    ap.add_argument("--workers", type=int, default=1, help="processes committing the rows (`Window.close`)")
    ap.add_argument("--run-id", default="", help="the run's name, which its root binds (`DecoderLoop`)")
    ap.add_argument("--bf16-dot", choices=sorted(T.BF16_DOTS), default=T.BF16_DOT, help="the BF16 GEMMs' step")
    ap.add_argument("--tamper", action="store_true")
    a = ap.parse_args(argv)
    if bool(a.out) == a.circuit_only:
        ap.error("--out DIR, or --circuit-only")
    loop = T.DecoderLoop(T.Model(a.seed), [p.encode() for p in (a.prompt or PROMPTS)], a.generate, a.tamper, a.run_id,
                         a.bf16_dot)
    law = D.parse_law(a.law)
    if a.circuit_only:
        empty = IF.Window(loop.circuit(), loop.run_root, law, a.cap)
        print(json.dumps({"circuit": hashlib.sha512(IF.circuit_bytes(empty.circuit_record())).hexdigest()}))
        return 0
    seconds, t = {}, time.perf_counter()
    win = loop.window(law, a.cap)
    seconds["serve"], t = time.perf_counter() - t, time.perf_counter()
    bad = win.mismatches()
    seconds["check"], t = time.perf_counter() - t, time.perf_counter()
    committed = win.close(workers=a.workers)
    seconds["commit"], t = time.perf_counter() - t, time.perf_counter()
    win.write(committed, a.out, {"loop": T.NAME}, registrar=R)
    seconds["write"] = time.perf_counter() - t
    rec = json.loads((Path(a.out) / "registration.json").read_text())
    print(json.dumps({"circuit": rec["window"]["circuit"], "run": loop.run_root, "population": win.window.population,
                      "units": loop.units, "members": len(win.window.members), "generated": [o.hex() for o in loop.outputs],
                      "mismatched": {t: len(v) for t, v in bad.items()}, "registration": R.digest(rec),
                      "seconds": {k: round(v, 2) for k, v in seconds.items()}, "out": str(Path(a.out))}))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
