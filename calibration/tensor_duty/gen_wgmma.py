"""Writes duty.cu's wgmma m64n256k32 wrappers: wgmma_e4m3.cuh (e4m3·e4m3 into f32 accumulators) and wgmma_i8.cuh
(s8·s8, u8·u8 and s8·u8 into s32)."""
from pathlib import Path

N = 256
REGS = N // 2
HEAD = ["// generated by gen_wgmma.py", "#pragma once", "#include <cstdint>", ""]
PAIRS = {"s8s8": ("s8", "s8"), "u8u8": ("u8", "u8"), "s8u8": ("s8", "u8")}


def wrapper(name: str, acc: str, con: str, types: str, scale: str) -> list[str]:
    regs = ",".join(f"%{i}" for i in range(REGS))
    cons = ", ".join(f'"+{con}"(d[{i}])' for i in range(REGS))
    return [
        f"__device__ __forceinline__ void wgmma_{name}_m64n{N}k32({acc}* d, uint64_t da, uint64_t db) {{",
        "  asm volatile(",
        f'    "{{\\n.reg .pred p;\\nsetp.ne.b32 p, %{REGS + 2}, 0;\\n"',
        f'    "wgmma.mma_async.sync.aligned.m64n{N}k32.{types} {{{regs}}}, %{REGS}, %{REGS + 1}, p{scale};\\n}}\\n"',
        f"    : {cons}",
        '    : "l"(da), "l"(db), "r"(1));',
        "}",
        "",
    ]


e4m3 = wrapper("e4m3", "float", "f", "f32.e4m3.e4m3", ", 1, 1")
i8 = [line for name, (a, b) in PAIRS.items() for line in wrapper(name, "uint32_t", "r", f"s32.{a}.{b}", "")]
Path(__file__).with_name("wgmma_e4m3.cuh").write_text("\n".join(HEAD + e4m3))
Path(__file__).with_name("wgmma_i8.cuh").write_text("\n".join(HEAD + i8))
