"""Prover side of genuine selective preparation (workstream C, decision 3; RC 2026-09-07).

    PYTHONPATH=. python -m verity_vllm_adapter.selective_prover --case B1 --checkpoints manifests/checkpoints.json \
        --production <dir> --out <run dir> --handshake <dir> --adapter-revision <sha> [--arena-gb 48] [--weights-format 2]

Phases (the verifier, :mod:`verity_vllm_adapter.selective_verifier`, is a separate process; the two
exchange files under ``--handshake``):

* **phase 0 -- before r_q.**  Build the engine under the replay restrictions and warm it up (no
  capture).  Write the shared, per-run but *not per-request-interior* material: the production
  manifest, the boundary of **every** production request (prompt ids, protected output records,
  sampling params, seed, finish reason; ``steps=[]`` since nothing has been replayed), the weights
  (capture format v2, one leaf per parameter row; the same bytes the checker will open), the
  description regenerated by the verifier's own semantic profile (not observed -- there is nothing
  observed yet) and the required set.  Build the boundary and weights trees ->
  ``commitments_phase0.json``, signal ``READY_PHASE0``.  No RU directory exists at this point.
* **phase 1 -- r_q.**  Wait for ``replay_challenge.json`` (the verifier's ``T_0``, ``r_q`` and the
  selected request ids ``J``).
* **phase 2 -- selected interiors.**  Install the capture and replay ONLY ``J`` (a different replay
  batch from production's; batch invariance is what makes the values identical -- checked by the
  caller against a full-replay control), rewrite the boundaries of ``J`` with the observed steps
  (leaves unchanged -> root unchanged, asserted), build the RU trees of ``J`` -> ``commitments.json``
  (boundary/weights records asserted identical to phase 0), compare the observed description with
  the regenerated one, signal ``READY_PHASE2`` and exit (the GPU is released for the verifier's
  checks).

Everything is timed per phase and written to ``selective_prover.json`` with the byte accounting
(hashed / copied / retained) the report needs.

[A3 contract 2026-09-10] Phase 2 also writes the contract's step-3 response ``exemption_request.json``
(:mod:`verity_vllm_adapter.response_record`): the exemption request ``F`` (RUs of J whose replay could not
reconstruct, whose recomputed outgoing boundary differs from the committed one, or whose recomputed outputs
disagree with the committed output tokens) and, per selected RU, the two R17 fields -- consistency of the
committed I/O (from the unforced sampler argmax at EVERY output position vs the committed tokens; ``unknown``
when not every position is covered or production was not greedy) and ability to supply the response -- plus
the R18 unsupported-check count from ``--expressibility`` / ``--unsupported-kinds`` (A5/A6's set).  A per-RU
failure that used to ABORT the run now requests an exemption for that RU; ``READY_PHASE2`` carries the
request's sha256 and F.  The prover never trims F to the budget.

[E2, EOD 2026-09-11] ``--interior-values <dir>`` (default off) extends phase 2: E1's value rows
(``<dir>/<req>/<step>/<call>.jsonl``) become one interior tree per RU of J (:mod:`e2e.interior.tree`, layout
``interior-layout/chunks-4096/v1``) under ``<out>/interior/<req>/<step>/`` with the root in
``commitments.json#interior_roots``; ``interior_commit.json`` records the per-RU outcome.  Phase-0 records are
asserted unchanged by digest; a refused RU requests exemption.
"""

from __future__ import annotations

import argparse
import json
import os
import shutil
import sys
import time
from pathlib import Path
from typing import Any

from verity_vllm_adapter import profile as prof

ENV_FLAGS = prof.apply_env()

import numpy as np  # noqa: E402
import torch  # noqa: E402
from vllm import LLM  # noqa: E402

from verity_vllm import commit as vcommit  # noqa: E402
from verity_vllm import hashing, selective  # noqa: E402
from verity_vllm import required as vrequired  # noqa: E402
from verity_vllm.capture import WEIGHTS_TREE_ID, Boundary, CaptureReader, RunWriter, boundary_tree_id  # noqa: E402
from verity_vllm.description import Description  # noqa: E402
from verity_vllm.weights_v2 import row_eligible  # noqa: E402
