"""Writes the nine standard outputs of a conformance run (`level.json` and the C0–C5 `ladder.json` beside it) plus the human
`CONFORMANCE.md` and `run.json`."""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from . import OUTPUT_FILES, SCHEMA_RUN
from .level import LEVEL_NAMES


def _dump(path: Path, doc: Any) -> None:
    path.write_text(json.dumps(doc, indent=1, sort_keys=False) + "\n")


def write_outputs(out: Path, *, port_doc: dict, production: dict, replay: dict, program: dict, correspondence: dict,
                  missing: dict, mismatches: list[dict], descriptor: dict, level: dict, inputs: dict, argv: list[str],
                  ladder: dict | None = None) -> list[Path]:
    out.mkdir(parents=True, exist_ok=True)
    _dump(out / "production_repro.json", production)
    _dump(out / "replay_repro.json", replay)
    _dump(out / "program.json", program)
    _dump(out / "correspondence.json", correspondence)
    _dump(out / "missing_values.json", missing)
    (out / "mismatches.jsonl").write_text("".join(json.dumps(m, sort_keys=False) + "\n" for m in mismatches))
    _dump(out / "descriptor_stats.json", descriptor)
    _dump(out / "level.json", level)  # kept: HP/TP read and write it; `ladder.json` is the public C0–C5 verdict beside it
    if ladder is None:
        from .ladder import ladder_from_level  # noqa: PLC0415

        ladder = ladder_from_level(level, axis=port_doc.get("axis"), declared_blockers=(port_doc.get("expectations") or {}).get("blockers"))
    _dump(out / "ladder.json", ladder)
    _dump(out / "run.json", {"schema": SCHEMA_RUN, "port": port_doc["port"], "utc": level["utc"], "argv": argv, "inputs": inputs,
                             "outputs": list(OUTPUT_FILES), "port_snapshot": port_doc})
    (out / "CONFORMANCE.md").write_text(render_markdown(port_doc, production, replay, program, correspondence, missing, mismatches, descriptor, level, inputs, ladder))
    return [out / f for f in OUTPUT_FILES] + [out / "run.json", out / "CONFORMANCE.md"]


def _n(x: Any) -> str:
    return f"{x:,}" if isinstance(x, int) else ("-" if x is None else str(x))


def render_markdown(port_doc: dict, production: dict, replay: dict, program: dict, correspondence: dict, missing: dict,
                    mismatches: list[dict], descriptor: dict, level: dict, inputs: dict, ladder: dict | None = None) -> str:
    cfg = port_doc["vllm_config"]
    headline = ladder["summary"] if ladder else level["summary"]
    L: list[str] = [f"# Conformance: port `{port_doc['port']}` — {headline}", "",
                    f"Generated by `python -m verity_vllm_adapter.conformance run` at {level['utc']}. Do not edit by hand.", "",
                    "## Port", "",
                    f"- axis: {_esc(port_doc.get('axis') or cfg.get('axis'))}",
                    f"- checkpoint: `{cfg['checkpoint']['repo']}` (adapter case `{cfg['checkpoint']['role']}`)",
                    f"- hardware class: {cfg['hardware_class']['gpu_generation']} (CC {', '.join(cfg['hardware_class']['compute_capability'])}"
                    + (f"; {', '.join(cfg['hardware_class']['gpu_names'])}" if cfg['hardware_class'].get('gpu_names') else "") + ")",
                    f"- execution: {cfg['execution_mode']}, CUDA graphs {cfg['cuda_graphs']}; replay exec `{cfg['adapter']['replay_exec']}`",
                    f"- parallelism: TP={cfg['parallelism']['tensor_parallel_size']} PP={cfg['parallelism']['pipeline_parallel_size']}"
                    + (" (per-rank capture)" if cfg['adapter']['capture_per_rank'] else ""),
                    f"- decoding: {cfg['decoding']['mode']}; quantization: {cfg['quantization'] or 'none'}",
                    f"- environment flags: " + ", ".join(f"`{k}={v}`" for k, v in cfg["environment_flags"].items()),
                    f"- known profile ids: {', '.join(f'`{p}`' for p in cfg['known_profile_ids']) or '-'}", ""]
    if ladder:
        L += ["## Verdict (promotion ladder C0–C5)", "",
              f"**{ladder['reached'] or 'no rung met'}**" + (f", gaps: {', '.join(ladder['gaps'])}" if ladder["gaps"] else "")
              + f" — outcome `{ladder.get('outcome')}`"
              + (f": {_esc(ladder['unsupported'].get('detail'))} (at {ladder['unsupported'].get('rung')}; {_esc(ladder['unsupported'].get('source'))})" if ladder.get("unsupported") else ""), ""]
        if ladder.get("blocker"):
            b = ladder["blocker"]
            L += [f"Why not further: **{b['rung']} `{b['class']}`** — {_esc(b.get('detail'))} ({_esc(b.get('source'))}).", ""]
        for h in ladder.get("blocker_history") or []:
            L += [f"History: {h['rung']} was `{h['class']}` — {_esc(h.get('detail'))}" + (f"; resolved: {_esc(h.get('resolved'))}" if h.get("resolved") else "") + ".", ""]
        L += ["| rung | status | blocker | reason |", "|---|---|---|---|"]
        for rung, r in ladder["rungs"].items():
            L.append(f"| {rung} {r['name']} | {'**met**' if r['met'] else r['status']} | {('`' + r['blocker']['class'] + '`') if r.get('blocker') else '—'} | {_esc(r.get('reason'))} |")
        L.append("")
        L += [f"Level spelling (`level.json`, kept for the pre-ladder readers): **Level {level['level']} ({level['level_name']})**"
              + (f", gaps: {', '.join(f'L{g}' for g in level['gaps'])}" if level["gaps"] else "") + "; L1→C1, L2→C2, L3→C3, L4→C4.", ""]
    else:
        L += ["## Verdict", "", f"**Level {level['level']} ({level['level_name']})**" + (f", gaps: {', '.join(f'L{g}' for g in level['gaps'])}" if level["gaps"] else ""), ""]
        L += ["| level | status | reason |", "|---|---|---|"]
        for l in (1, 2, 3, 4):
            r = level["levels"][str(l)]
            L.append(f"| L{l} {LEVEL_NAMES[l]} | {'**met**' if r['met'] else r['status']} | {_esc(r.get('reason'))} |")
        L.append("")
    L += ["## Inputs", ""] + [f"- {k}: {_esc(v)}" for k, v in inputs.items()] + [""]
    # C0
    if ladder:
        c0 = ladder["rungs"]["C0"]
        L += ["## C0 — runs: production reproducible, execution choices recorded", "", f"Status: **{c0['status']}**" + (f" — {_esc(c0.get('reason'))}" if c0.get("reason") else ""), ""]
        mans = [e for e in c0["evidence"] if e["kind"] == "production-manifest"]
        if mans:
            L += ["| production manifest | profile | attention | linear | compile (eager / graphs / mode / custom ops) | dtype | TP/PP | GPU (driver) | vLLM (wheel) | checkpoint (revision) | missing |",
                  "|---|---|---|---|---|---|---|---|---|---|---|"]
            for e in mans:
                c = e.get("execution_choices") or {}
                ws = c.get("model.weights_sha256") or {}
                wd = next(iter(ws.values()))[:12] if isinstance(ws, dict) and ws else "-"
                L.append(f"| `{e['path']}` | {e.get('profile_id')} | {_esc(_tail(c.get('backends.attention')))} | {_esc(_tail(c.get('backends.linear')))} | "
                         f"{c.get('compilation.enforce_eager')} / {c.get('compilation.cudagraph_mode')} / {c.get('compilation.mode')} / {c.get('compilation.custom_ops')} | {c.get('dtype')} | "
                         f"{c.get('parallelism.tensor_parallel_size')}/{c.get('parallelism.pipeline_parallel_size')} | {_esc(c.get('gpu.name'))} ({c.get('gpu.driver')}) | "
                         f"{c.get('vllm.commit')} ({str(c.get('vllm.wheel_sha256'))[:12]}…) | {str(c.get('model.revision'))[:12]} ({wd}…) | {_esc(e.get('missing')) if e.get('missing') else '-'} |")
            L.append("")
        for e in c0["evidence"]:
            if e["kind"] == "kernel-record":
                L.append(f"- kernel-selection record `{e['path']}` (cited, not required)")
        L.append("")
    # Level 1
    L += ["## C1 (Level 1) — production and replay reproducibility", "", f"Production: **{production['status']}** ({_esc(production.get('method'))})", ""]
    if production.get("runs"):
        L += ["| production run | profile | requests | positions | in-process 2nd pass identical |", "|---|---|---|---|---|"]
        L += [f"| `{r['path']}` | {r.get('profile_id')} | {r.get('requests')} | {_n(r.get('generated_positions'))} | {r.get('in_process_second_pass_identical')} |" for r in production["runs"]]
        L.append("")
    if production.get("pairs"):
        L += ["| pair | shared requests | tokens identical | logprobs identical |", "|---|---|---|---|"]
        L += [f"| `{p['a']}` vs `{p['b']}` | {p['requests_shared']} | {p['tokens_identical']} | {p['logprobs_identical']} |" for p in production["pairs"]]
        L.append("")
    L += [f"Replay: **{replay['status']}**", ""]
    if replay.get("replays"):
        L += ["| commit | profile | exec | requests followed | logprobs equal | unforced agree | capture leaves | compare identical / scalars | problems |", "|---|---|---|---|---|---|---|---|---|"]
        for r in replay["replays"]:
            tf, lv, ua, c = r["trajectory_followed"], r["logprobs_vs_production"], r["unforced_sampler_agreement"], r.get("compare") or {}
            L.append(f"| `{r['commit']}` | {r.get('profile_id')} | {r.get('replay_exec')} | {tf.get('followed')}/{tf.get('requests')} | {lv.get('equal')}/{lv.get('requests_compared')} | "
                     f"{ua.get('agree')}/{ua.get('positions')} | {_n(r['capture'].get('leaves'))} | {c.get('identical')} / {_n(c.get('compared_scalars'))} | {_esc('; '.join(r['problems'])) or '-'} |")
        L.append("")
    # Level 2
    L += ["## C2 (Level 2) — typed correspondence", "", f"Status: **{correspondence['status']}**" + (f" — {_esc(correspondence.get('reason'))}" if correspondence.get("reason") else ""), ""]
    if program.get("status") == "constructed":
        L += [f"Program: `{program['function']}` at probe shape {program['probe_shape']}: {_n(program['gates'])} gates, {_n(program['input_gates'])} Input gates, "
              f"descriptor {_n(program['descriptor_bytes'])} bytes, digest `{program['program_digest'][:16]}…`; static configuration digest `{program.get('config_digest')}`.", ""]
    elif program.get("status"):
        L += [f"Program: {program['status']} — {_esc(program.get('reason'))}", ""]
    if correspondence.get("files"):
        L += ["| correspondence | request | positions | layers | program | exact | mismatch | sampled | missing-operand | shape-mismatch | program identity |", "|---|---|---|---|---|---|---|---|---|---|---|"]
        for f in correspondence["files"]:
            s = f["summary"]
            L.append(f"| `{f['path']}` | {str(f.get('request'))[:8]} | {f.get('positions')} | {f.get('layers')} | `{(f.get('program') or {}).get('function')}` | {s.get('exact', 0)} | {s.get('mismatch', 0)} | "
                     f"{s.get('sampled', 0)} | {s.get('missing-operand', 0)} | {s.get('shape_mismatch', 0)} | {(f.get('program_identity') or {}).get('match') or 'n/a'} |")
        L.append("")
        for f in correspondence["files"]:
            note = (f.get("program_identity") or {}).get("note")
            if note:
                L.append(f"- `{f['path']}`: {_esc(note)}")
        if any((f.get("program_identity") or {}).get("note") for f in correspondence["files"]):
            L.append("")
    if mismatches:
        L += [f"Mismatches ({len(mismatches)}, all listed in `mismatches.jsonl`):", ""]
        for m in mismatches:
            fm = (m.get("words") or [{}])[0]
            L.append(f"- `{m['canonical_id']}` → `{m['composite']}` ({m['call']}): {m['status']}, {m.get('mismatches')} of {m.get('words_compared')} words"
                     + (f" (word {fm.get('word')}, gate {fm.get('gate')}: IR {fm.get('ir')} vs captured {fm.get('captured')})" if fm else "")
                     + f"; binding `{(m.get('binding') or {}).get('registered')}` status `{(m.get('binding') or {}).get('status')}`"
                     + (f", divergence recorded: {_esc((m.get('binding') or {}).get('divergence_recorded'))}" if (m.get("binding") or {}).get("divergence_recorded") else "; **not recorded on the binding**"))
        L.append("")
    if correspondence.get("status") not in ("not-claimed",):
        mv = missing
        if mv.get("not_in_program") or mv.get("unconsumed_leaves") or mv.get("derived_inputs"):
            L += ["Values outside the program / inputs not from the checkpoint (`missing_values.json`):", ""]
            for r in mv.get("not_in_program", []):
                L.append(f"- not in program ×{r['count']}: `{r['pattern_of_capture_ids']}` — {r['classification']}" + (f": {_esc(r['port_reason'])}" if r.get("port_reason") else "") + f" (tool: {_esc(r.get('tool_reason'))})")
            for r in mv.get("unconsumed_leaves", []):
                L.append(f"- unconsumed weights leaf `{r['leaf_id']}` — {r['classification']}" + (f": {_esc(r['port_reason'])}" if r.get("port_reason") else ""))
            for d in mv.get("derived_inputs", []):
                cpu = d.get("cpu_rebuild") or {}
                L.append(f"- derived input `{d['leaf_id']}` — {d['classification']}: {_esc(d['provenance'])}; rebuilt sha256 matches the committed leaf: {d['rebuilt_sha256_matches_leaf']}"
                         + (f"; CPU rebuild differs in {cpu.get('differing_words')} words" if cpu else ""))
            L.append("")
        if mv.get("unmaterialised_declared"):
            L += ["Declared unmaterialised values:", ""] + [f"- `{u['canonical']}`: {_esc(u['reason'])}" for u in mv["unmaterialised_declared"]] + [""]
    exp = (correspondence.get("expectations") or {}).get("families") or {}
    if exp:
        L += ["| family | declared | captured nodes | captured relations | correspondence | consistent |", "|---|---|---|---|---|---|"]
        for fam, e in sorted(exp.items()):
            L.append(f"| {fam} | {e.get('declared')}{(' (' + e['kind'] + ')') if e.get('kind') else ''} | {e.get('captured_nodes', 0)} | {', '.join(e.get('captured_relations', []))} | {e.get('correspondence') or '-'} | {e.get('consistent')} |")
        L.append("")
    if descriptor.get("status") == "computed":
        p = descriptor["probe"]
        L += [f"Descriptor (probe shape {p['shape']}): {_n(p['gates'])} gates, {_n(p['input_gates'])} Input gates, {_n(p['descriptor_bytes'])} bytes, "
              f"{p['definitions']} definitions ({p['distinct_specializations']} specializations, {p['distinct_primitives']} primitives), built in {p['build_seconds']}s."]
        for r in descriptor.get("recorded_full_shape", []):
            L.append(f"Recorded full shape (`{r['source']}`): `{r.get('function')}` {_n(r.get('gates'))} gates, {_n(r.get('input_gates'))} Input gates, built in {r.get('build_seconds')}s on the pod.")
        for f in descriptor.get("full_shape") or []:
            L.append(f"Full shape {f['shape']} rebuilt here: `{f['function']}` {_n(f['gates'])} gates, {_n(f['input_gates'])} Input gates in {f['build_seconds']}s; "
                     f"matches recorded: {f['matches_recorded']}.")
        L.append("")
    # Level 3
    l3 = level["levels"]["3"]
    L += ["## C3 (Level 3) — protocol bundle", "", f"Status: **{l3['status']}**" + (f" — {_esc(l3.get('reason'))}" if l3.get("reason") else ""), ""]
    rows = [e for e in l3["evidence"] if e["kind"] == "table1-row"]
    if rows:
        L += ["| table1 | experiment | profile | result | recomputed (§10) | verification evidence |", "|---|---|---|---|---|---|"]
        L += [f"| `{e['path']}` | {e.get('experiment_id')} | {e.get('profile_id')} | {e.get('result')} | {e.get('recomputed_result')} | {_esc(e.get('verification_evidence'))} |" for e in rows]
        L.append("")
    for e in l3["evidence"]:
        if e["kind"] == "verify-report":
            L.append(f"- verifier report `{e['path']}`: profile {e.get('profile_id')}, challenge `{str(e.get('challenge_digest'))[:16]}…`, statuses {e.get('statuses')}, authentication {e.get('authentication')}, negatives {e.get('negatives')}")
        elif e["kind"] == "bundle-digests":
            L.append(f"- bundle digests `{e['path']}`: {e['files_ok']}/{e['files_checked']} local files re-hashed equal" + (f", bad {e['files_bad']}" if e.get("files_bad") else ""))
        elif e["kind"] == "audit":
            L.append(f"- independent audit `{e['path']}`: {e.get('result')} ({e.get('worker')})")
        elif e["kind"] == "bundle-problems":
            L.append(f"- problems for `{e['path']}`: {_esc('; '.join(e['problems']))}")
    L.append("")
    # Level 4
    l4 = level["levels"]["4"]
    L += ["## C4 (Level 4) — proof-backed obligation", "", f"Status: **{l4['status']}**" + (f" — {_esc(l4.get('reason'))}" if l4.get("reason") else ""), ""]
    for e in l4["evidence"]:
        if e["kind"] == "typed-obligation":
            L.append(f"- obligation `{e['path']}` ({e.get('name')}): derives from `{e.get('canonical_id')}` (profile {e.get('profile_id')}, results `{e.get('results')}`), "
                     f"statement `{str(e.get('statement_digest'))[:16]}…`, verdict {e.get('verdict')}, fixture files {e.get('fixture_files')}")
        elif e["kind"] == "proof-record":
            L.append(f"- proof record `{e['path']}`: {e.get('backend')} vk `{str(e.get('vk_hash'))[:18]}…`, ok={e.get('ok')} verdict={e.get('verdict')} statement_match={e.get('statement_match')}, matches obligation: {e['matches_obligation']}")
        elif e["kind"] == "obligation-problems":
            L.append(f"- problems for `{e['path']}`: {_esc('; '.join(e['problems']))}")
    L.append("")
    # C5
    if ladder:
        c5 = ladder["rungs"]["C5"]
        L += ["## C5 — vertical slice (common INT pipeline)", "", f"Status: **{c5['status']}**" + (f" — {_esc(c5.get('reason'))}" if c5.get("reason") else ""), ""]
        for e in c5["evidence"]:
            if e["kind"] == "int-record":
                L.append(f"- INT record `{e['path']}` (case {e.get('case')}): recorded verdict {e.get('recorded_verdict')}, second-process `{e.get('reverify')}` "
                         f"fresh verdict {e.get('fresh_verdict')} (agrees {e.get('agrees')}); stages {_esc(e.get('stages'))}; command `{_esc(e.get('command'))}`"
                         + (f"; problems: {_esc('; '.join(e['problems']))}" if e.get("problems") else ""))
        L.append("")
    L += ["## Claims", ""] + [f"- {_esc(c)}" for c in (ladder["claims"] if ladder else level["claims"])] + [""]
    return "\n".join(L)


def _tail(v: Any) -> str:
    """`vllm.v1.attention.backends.flash_attn.FlashAttentionImpl` -> `FlashAttentionImpl`; anything else as text."""
    if isinstance(v, str) and "." in v and " " not in v:
        return v.rsplit(".", 1)[-1]
    return "-" if v is None else str(v)


def _esc(v: Any) -> str:
    if v is None:
        return "-"
    return str(v).replace("|", "\\|").replace("\n", " ")
