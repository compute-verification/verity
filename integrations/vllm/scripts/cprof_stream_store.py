#!/usr/bin/env python3
"""CPERF 2026-09-17 addendum: the streaming builder over a REAL commit store (all RU trees, production ids, memmap values).

    PYTHONPATH=. python scripts/cprof_stream_store.py --store <commit dir>

Per RU: stream the leaves in production tree order through ``StreamingMerkle`` (O(log n) state), compare the root with
``commitments.json``; then "replay-to-open": stream again with one tracked leaf, build a production ``Opening`` from the
regenerated path and verify it with ``verify_opening``.  Reports wall time for the whole store (1 thread) and the peak
resident builder state.  Nothing from the first pass is kept except (root, leaf_count).
"""

from __future__ import annotations

import argparse
import json
import random
import statistics
import sys
import time
from pathlib import Path

HERE = Path(__file__).resolve().parent
POC = HERE.parent
if str(POC) not in sys.path:
    sys.path.insert(0, str(POC))

import numpy as np  # noqa: E402

from verity_vllm import identity  # noqa: E402
from verity_vllm.capture import CaptureReader  # noqa: E402
from verity_vllm.commit import Opening, verify_opening  # noqa: E402
from verity_vllm.commit_bench import fasttree as ft  # noqa: E402
from verity_vllm.commit_bench.prov import provenance  # noqa: E402
from verity_vllm.commit_bench.stream import StreamingMerkle  # noqa: E402


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--store", required=True)
    ap.add_argument("--reps", type=int, default=3)
    args = ap.parse_args()
    reader = CaptureReader(args.store)
    trees = reader.commitments["trees"]
    rng = random.Random(17)
    # pre-resolve (what a template gives you before any value exists): sorted ids + headers + offsets, per RU
    plans = []
    for rid, step in reader.ru_keys():
        ru = reader.ru(rid, step)
        by = {e.canonical_id: e for e in ru.index.entries}
        ids = identity.tree_sorted(list(by))
        plans.append((ru.tree_id, ru.dir / "values.bin", [(c, by[c].dtype, tuple(by[c].shape), by[c].offset, by[c].nbytes, ft.leaf_header(c, by[c].dtype, by[c].shape)) for c in ids]))

    def pass_commit() -> tuple[dict[str, tuple[bytes, int]], int]:
        kept: dict[str, tuple[bytes, int]] = {}
        peak = 0
        for tid, vpath, rows in plans:
            mm = memoryview(np.memmap(vpath, dtype=np.uint8, mode="r"))
            b = StreamingMerkle()
            for _c, _d, _s, off, n, h in rows:
                b.add(h, mm[off : off + n])
                if b.leaf_count % 64 == 0:
                    peak = max(peak, b.resident_bytes())
            kept[tid] = (b.finish(), b.leaf_count)
        return kept, peak

    walls = []
    for _ in range(args.reps):
        t0 = time.perf_counter()
        kept, peak = pass_commit()
        walls.append(time.perf_counter() - t0)
    match = sum(1 for tid, (root, n) in kept.items() if trees[tid]["root"] == root.hex() and trees[tid]["leaf_count"] == n)

    # replay-to-open: one random leaf per tree, regenerated by streaming the store again with a tracked index
    t0 = time.perf_counter()
    verified = 0
    per_tree = []
    for tid, vpath, rows in plans:
        idx = rng.randrange(len(rows))
        mm = memoryview(np.memmap(vpath, dtype=np.uint8, mode="r"))
        b = StreamingMerkle(track=idx)
        t1 = time.perf_counter()
        for _c, _d, _s, off, n, h in rows:
            b.add(h, mm[off : off + n])
        root = b.finish()
        c, d, s, off, n, _h = rows[idx]
        op = Opening(tree=tid, root=root, leaf_count=len(rows), index=idx, canonical_id=c, dtype=d, shape=s, value=bytes(mm[off : off + n]), path=tuple(b.path))
        ok = verify_opening(kept[tid][0], kept[tid][1], op)  # against the RETAINED root of pass 1
        verified += ok
        per_tree.append({"tree": tid, "leaves": len(rows), "index": idx, "regen_s": time.perf_counter() - t1, "path_bytes": 32 * sum(p is not None for p in b.path), "ok": ok})
    t_open = time.perf_counter() - t0
    dec = [p["regen_s"] for p in per_tree if p["leaves"] < 1000]
    pre = [p["regen_s"] for p in per_tree if p["leaves"] >= 1000]
    out = {"schema": "veritor/cperf/stream-store/v1", "store": args.store, "provenance": {k: provenance()[k] for k in ("host", "cpu", "load_avg_1m", "python")},
           "trees": len(plans), "leaves": sum(len(r) for _, _, r in plans), "roots_match_commitments_json": f"{match}/{len(plans)}",
           "stream_commit_all_trees_s": {"first": walls[0], "median": statistics.median(walls)}, "peak_resident_builder_bytes": peak,
           "replay_to_open": {"trees_opened": len(per_tree), "verified_against_retained_root": verified, "total_s": t_open,
                              "regen_decode_ru_median_s": statistics.median(dec) if dec else None, "regen_prefill_ru_median_s": statistics.median(pre) if pre else None,
                              "path_bytes": sorted({p["path_bytes"] for p in per_tree})}}
    print("CPERF-STREAM-JSON " + json.dumps(out, separators=(",", ":"), default=str))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
