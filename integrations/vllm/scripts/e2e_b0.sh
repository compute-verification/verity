#!/usr/bin/env bash
# One command: INT3's composed B0 verification reproduced CPU-side, plus the Bound + prover-overhead
# record (lane INT-PAD, GUIDANCE §29).  Everything a workstation can check is checked; everything it
# cannot is a stated YELLOW with the reason, never relabelled green.
#
#   scripts/e2e_b0.sh
#
# Stages (each GREEN / YELLOW / RED at the end; exit 1 iff any RED):
#   1 record    the committed record (fixtures/e2e-composed/INT-B0-20260908T0725Z) and, when present,
#               the READ-ONLY archive copy (~/veritor-artifacts/int/INT3/...) cross-checked against it
#               (summary/manifest sha256 equal).  The archive adds bundle/ + adapter/, which the
#               committed fixture omits (adapter 335 MB, bundle 58 MB).
#   2 reverify  e2e.verify_composed over the record: program reconstructed from B0's static
#               configuration (digest equal); plan recorded-mode by default (re-validation measured at
#               3.0 GB RSS -- over the ~2 GB lane budget; REVALIDATE_PLAN=1 opts in); records row =
#               h_O / h_L + coverage (IT-F1) + placement (IT-F2) + relations + witness; proofs row =
#               recorded host verification re-read + binding re-checked (a locally built guest is a
#               different program identity -- see integration-pad.md §proofs; HOST=<exact binary> opts
#               into true re-verification); bundle row (archive only) = staged challenge re-derived +
#               fresh CPU sample over J (PARTIAL accepted exactly as e2e-composed.md §5 defines).
#   3 negatives e2e.artefact_negatives, IT's five artefact edits (a b1 b2 b3 c) applied to a temp copy;
#               each must be refused by the intended records-row check (coverage / placement / relations).
#   4 bound     e2e.bound_record --check against the committed Bound + prover-overhead record
#               (results/INTPAD-bound-b0): every bound-report/v1 re-folded with the frozen fold, the
#               overhead arithmetic re-derived.  REBUILD_BOUND=1 rebuilds the kind tables from the
#               declared plan (measured 6.2 GB RSS, ~140 s -- one-shot, needs ARCHIVE for T_native).
#   5 padded    e2e.u_record: PAD-BOUND's union-over-termination wrapper (veritor.plans.padded) --
#               all committed fixture families re-derived from scratch (exact enumeration + frozen
#               fold on every prefix; ANY bound < exact raises), then the veritor/u-record/v1 U
#               record.  Scope: prefix-decoded, ARCHIVED RESEARCH per GUIDANCE $30 item 9 (the
#               record says so); kept as regression evidence for the committed fixtures.
#   6 tiny      e2e.tiny_serve3: the second pipeline target -- PAD-IMPL's TINY Serve@3 at all three
#               spec-$13 EOS bindings (l in {0,3,8}): program build (gate budget = spec $14.1) ->
#               reference-evaluator replay -> transcript/output digests -> verify (vectorized twin
#               bit-for-bit, interpretation, absorbing suffix) + GUIDANCE $30 W_out anchors (D1 open).
#   7 attn      e2e.attn_relation: PROOF-ATTN's AttnBlock relation -- the veritor.fa2-attn gate set
#               re-derived from the registered prims (family version + digest = the committed pin),
#               the cross-language parity vectors regenerated byte-identical to the file the SP1 side
#               asserts against, cargo test of the Rust half when cargo exists, and the pod's
#               committed 50,760-row composition check re-read (local re-fold impossible on the
#               selective @2 record -- stated in the record).
#   8 reduce    e2e.reduce_relation: PROOF-REDUCE's reduction relations -- veritor.reduce-mufu@1
#               re-derived from the Python mirror (digest = the committed pin), the 67k cross-language
#               vector cases regenerated byte-identical, cargo test of the Rust twin when cargo exists,
#               the committed batch manifest + pod proving records re-read (local re-prove out of
#               scope for a CPU lane -- stated in the record).
#   8b elem     e2e.elem_relation: PROOF-ELEM's elementwise relations -- veritor.elem-bf16@1,
#               veritor.elem-f32@1, veritor.pad-inactive@1 re-derived from the Python mirror
#               (digests = the committed pins), the guest's SiLU LUT regenerated byte-identical,
#               cargo test of the Rust twins when cargo exists, the committed pod proving records
#               re-read (local re-prove out of scope for a CPU lane -- stated in the record).
#   8c cov      e2e.cov_relation: PROOF-COV's coverage families against the FRESH record
#               (RECORD2) -- veritor.embed-gather@1 + veritor.pad-serve@1 re-derived from the
#               Python mirrors (digests = the pins), the record-attached statements/proofs
#               (proofs/proof-cov/, proved on the INT-PAD-3 pod: SP1 CUDA prove + CPU-mode
#               verify) re-bound hash by hash, the prefill prompt-token binding re-derived
#               from the record's own bundle, the inactive/prefill/decode coverage census
#               asserted (local re-prove out of scope for a CPU lane -- stated).
#   8d cert     e2e.certificate --require-coverage regenerated from RECORD2 into $OUT and
#               byte-compared against the committed certificate.json (the certificate is a
#               deterministic function of the record; a drift is a RED).
#   9 tests     pytest: test_e2e_composed.py + PAD-BOUND's test_padded_bound.py + INACT-PUB's
#               test_inact_pub_leaf_study.py + TIGHT's test_tight_model.py + PAD-IMPL's verity.ir
#               suites.  SKIP_TESTS=1 skips.
#               test_verify_composed_on_preserved_artefacts is DESELECTED by default: one parameter
#               alone peaks 4.4 GB RSS -- over this box's ~/.veritor/mem_guardian.py per-process cap
#               (4.0 GB, SIGKILL), so it only survives when the peak slips between guardian polls.
#               HEAVY_TESTS=1 opts in; the stage is YELLOW while deselected (stage 2 runs the same
#               verifier end-to-end on the real B0 record, but the preserved-artefact fixtures are
#               deselected coverage and the stage says so).
#
# Env knobs: RECORD RECORD2 ARCHIVE OUT PY HOST BUNDLE_SAMPLE REVALIDATE_PLAN REBUILD_BOUND BOUND_DIR SKIP_TESTS
set -u
cd "$(dirname "$0")/.."

RECORD="${RECORD:-fixtures/e2e-composed/INT-B0-20260908T0725Z}"
RECORD2="${RECORD2:-results/INT-PAD-2/INTPAD2-B0-20260909T013519Z}"
ARCHIVE="${ARCHIVE:-$HOME/veritor-artifacts/int/INT3/INT-B0-20260908T0725Z}"
OUT="${OUT:-/tmp/int-pad/e2e-b0-$(date -u +%Y%m%dT%H%M%SZ)}"
PY="${PY:-$(cd .. && pwd)/.venv/bin/python}"
HOST="${HOST:-}"
BUNDLE_SAMPLE="${BUNDLE_SAMPLE:-64}"
REVALIDATE_PLAN="${REVALIDATE_PLAN:-0}"
REBUILD_BOUND="${REBUILD_BOUND:-0}"
BOUND_DIR="${BOUND_DIR:-results/INTPAD-bound-b0}"
SKIP_TESTS="${SKIP_TESTS:-0}"
HEAVY_TESTS="${HEAVY_TESTS:-0}"

mkdir -p "$OUT"
STATUS_FILE="$OUT/stages.tsv"
: > "$STATUS_FILE"

say()  { printf '\n=== e2e_b0 stage %s ===\n' "$1"; }
mark() { printf '%s\t%s\t%s\n' "$1" "$2" "$3" >> "$STATUS_FILE"; }

# -- stage 1: record ------------------------------------------------------------------------------------------
say "1 record"
if [ ! -f "$RECORD/summary.json" ]; then
  mark record RED "committed record $RECORD missing"
else
  if [ -d "$ARCHIVE" ] && [ -f "$ARCHIVE/summary.json" ]; then
    if cmp -s "$RECORD/summary.json" "$ARCHIVE/summary.json" && cmp -s "$RECORD/manifest.json" "$ARCHIVE/manifest.json"; then
      mark record GREEN "fixture + archive agree (summary/manifest byte-equal); archive supplies bundle/ + adapter/"
    else
      mark record RED "fixture and archive summary/manifest differ -- which record is this?"
    fi
  else
    ARCHIVE=""
    mark record YELLOW "no archive copy: bundle re-verification and T_native unavailable (fixture omits bundle/ + adapter/)"
  fi
fi
tail -1 "$STATUS_FILE"

# -- stage 2: reverify ----------------------------------------------------------------------------------------
say "2 reverify"
VDIR="${ARCHIVE:-$RECORD}"
VARGS=(--dir "$VDIR" --out "$OUT/reverify" --program rebuild --bundle-sample "$BUNDLE_SAMPLE")
[ "$REVALIDATE_PLAN" = "1" ] && VARGS+=(--plan rebuild) || VARGS+=(--plan recorded)
if [ -n "$HOST" ] && [ -x "$HOST" ]; then VARGS+=(--host "$HOST"); else VARGS+=(--allow-recorded-proofs); fi
[ -z "$ARCHIVE" ] && VARGS+=(--skip-bundle)
# the tarball's fresh weights-opening verification peaks over this box's 4 GB guardian cap even at
# small samples (SIGKILL mid-row, no verdict); SKIP_BUNDLE=1 opts out honestly (stage 2 says so)
[ "${SKIP_BUNDLE:-0}" = "1" ] && VARGS+=(--skip-bundle)
"$PY" -m e2e.verify_composed "${VARGS[@]}" 2>&1 | tee "$OUT/reverify_console.log"; vrc=${PIPESTATUS[0]}
if [ ! -f "$OUT/reverify/reverify.json" ]; then
  if [ "$vrc" -ge 128 ]; then
    mark reverify YELLOW "verify_composed killed by signal $((vrc - 128)) (memory pressure; peaks ~625 MB + system load) -- no verdict reached; rerun when quiet"
  else
    mark reverify RED "verify_composed exited $vrc without writing reverify.json"
  fi
  tail -1 "$STATUS_FILE"
else
"$PY" - "$OUT/reverify/reverify.json" "$REVALIDATE_PLAN" <<'EOF'
import json, sys
d = json.load(open(sys.argv[1])); revalidated = sys.argv[2] == "1"
rows = d["rows"]; quals = []
ok = d["agrees"] and d["fresh_verdict"] == "PASS"
if not revalidated: quals.append("plan recorded-mode (re-validation is 3.0 GB RSS; REVALIDATE_PLAN=1)")
if "NOT re-verified" in rows.get("proofs", {}).get("detail", ""): quals.append("proofs: recorded host verification + binding re-check (exact guest binary not on this machine)")
if rows.get("bundle", {}).get("status") == "skipped": quals.append("bundle skipped (no archive)")
elif "PARTIAL" in rows.get("bundle", {}).get("detail", ""): quals.append("bundle fresh check PARTIAL (same-runtime relations need torch; all else held)")
status = ("GREEN" if not quals else "YELLOW") if ok else "RED"
reason = f"fresh {d['fresh_verdict']} = recorded {d['recorded_verdict']}, agrees" + ("; " + "; ".join(quals) if quals else "")
if not ok: reason = f"fresh {d['fresh_verdict']} vs recorded {d['recorded_verdict']}: " + "; ".join(f"{k}={v['status']}" for k, v in rows.items() if v["status"] not in ("ok", "skipped"))
open(sys.argv[1] + ".mark", "w").write(f"reverify\t{status}\t{reason}\n")
EOF
cat "$OUT/reverify/reverify.json.mark" >> "$STATUS_FILE"; tail -1 "$STATUS_FILE"
fi

# -- stage 3: negatives ---------------------------------------------------------------------------------------
say "3 negatives"
"$PY" -m e2e.artefact_negatives --src "$RECORD" --out "$OUT/negatives"
"$PY" - "$OUT/negatives/artefact_negatives.json" <<'EOF'
import json, sys
d = json.load(open(sys.argv[1])); bad = []
for case, doc in d["cases"].items():
    sp = doc["second_process"]; intended = doc["edit"]["intended_refusal"].split(" ")[0].rstrip(":,")
    if sp["fresh_verdict"] != "FAIL" or sp.get("refused_by", "").split(" ")[0] != intended:
        bad.append(f"{case}: refused_by {sp.get('refused_by')} (intended {intended}), verdict {sp['fresh_verdict']}")
status = "GREEN" if not bad else "RED"
reason = f"{len(d['cases'])}/5 IT edits refused by the intended check" if not bad else "; ".join(bad)
open(sys.argv[1] + ".mark", "w").write(f"negatives\t{status}\t{reason}\n")
EOF
cat "$OUT/negatives/artefact_negatives.json.mark" >> "$STATUS_FILE"; tail -1 "$STATUS_FILE"

# -- stage 4: bound + prover overhead -------------------------------------------------------------------------
say "4 bound"
if [ "$REBUILD_BOUND" = "1" ]; then
  BARGS=(--dir "$RECORD" --out "$BOUND_DIR")
  [ -n "$ARCHIVE" ] && BARGS+=(--adapter "$ARCHIVE/adapter")
  "$PY" -m e2e.bound_record "${BARGS[@]}" && mark bound GREEN "rebuilt: kind tables + bound-report/v1 + overhead record -> $BOUND_DIR" \
    || mark bound RED "bound_record rebuild failed"
elif [ -f "$BOUND_DIR/bound_record.json" ]; then
  if "$PY" -m e2e.bound_record --dir "$RECORD" --out "$BOUND_DIR" --check; then
    mark bound GREEN "committed record re-folds under the frozen fold; overhead arithmetic re-derived ($BOUND_DIR)"
  else
    mark bound RED "committed bound record does not re-fold / re-derive"
  fi
else
  mark bound YELLOW "no committed bound record at $BOUND_DIR (REBUILD_BOUND=1 to build; needs ~6.2 GB RSS + archive)"
fi
tail -1 "$STATUS_FILE"

# -- stage 5: padded (U record) -------------------------------------------------------------------------------
say "5 padded"
if "$PY" -m e2e.u_record --out "$OUT/padded" > "$OUT/padded.log" 2>&1; then
  mark padded GREEN "$(tail -1 "$OUT/padded.log" | sed 's/^u_record: //')"
else
  mark padded RED "u_record failed: $(tail -1 "$OUT/padded.log")"
fi
tail -1 "$STATUS_FILE"

# -- stage 6: tiny (Serve@3 second target) --------------------------------------------------------------------
say "6 tiny"
if "$PY" -m e2e.tiny_serve3 --out "$OUT/tiny" > "$OUT/tiny.log" 2>&1; then
  mark tiny GREEN "$(tail -1 "$OUT/tiny.log" | sed 's/^tiny_serve3: //')"
else
  mark tiny RED "tiny_serve3 failed: $(tail -1 "$OUT/tiny.log")"
fi
tail -1 "$STATUS_FILE"

# -- stage 7: attn (PROOF-ATTN relation) ----------------------------------------------------------------------
say "7 attn"
if "$PY" -m e2e.attn_relation --out "$OUT/attn" > "$OUT/attn.log" 2>&1; then
  ATTN_REASON="$(tail -1 "$OUT/attn.log" | sed 's/^attn_relation: //')"
  if command -v cargo >/dev/null 2>&1; then
    if (cd ../zk/sp1-attn/common && cargo test 2>&1 | grep -qE "test result: ok. 1 passed"); then
      mark attn GREEN "$ATTN_REASON; Rust vector test ok"
    else
      mark attn RED "python side ok but cargo test failed in zk/sp1-attn/common"
    fi
  else
    mark attn YELLOW "$ATTN_REASON; Rust half not run (no cargo on PATH)"
  fi
else
  mark attn RED "attn_relation failed: $(tail -1 "$OUT/attn.log")"
fi
tail -1 "$STATUS_FILE"

# -- stage 8: reduce (PROOF-REDUCE relations) -----------------------------------------------------------------
say "8 reduce"
if "$PY" -m e2e.reduce_relation --out "$OUT/reduce" > "$OUT/reduce.log" 2>&1; then
  REDUCE_REASON="$(tail -1 "$OUT/reduce.log" | sed 's/^reduce_relation: //')"
  if command -v cargo >/dev/null 2>&1; then
    if (cd ../zk/sp1 && cargo test -p veritor-zk-common --test reduce_vectors 2>&1 | grep -qE "test result: ok"); then
      mark reduce GREEN "$REDUCE_REASON; Rust vector test ok"
    else
      mark reduce RED "python side ok but cargo test --test reduce_vectors failed in zk/sp1"
    fi
  else
    mark reduce YELLOW "$REDUCE_REASON; Rust half not run (no cargo on PATH)"
  fi
else
  mark reduce RED "reduce_relation failed: $(tail -1 "$OUT/reduce.log")"
fi
tail -1 "$STATUS_FILE"

# -- stage 8b: elem (PROOF-ELEM relations) --------------------------------------------------------------------
say "8b elem"
if "$PY" -m e2e.elem_relation --out "$OUT/elem" > "$OUT/elem.log" 2>&1; then
  ELEM_REASON="$(tail -1 "$OUT/elem.log" | sed 's/^elem_relation: //')"
  if command -v cargo >/dev/null 2>&1; then
    if (cd ../zk/sp1 && cargo test -p veritor-zk-common elem 2>&1 | grep -qE "test result: ok"); then
      mark elem GREEN "$ELEM_REASON; Rust elem tests ok"
    else
      mark elem RED "python side ok but cargo test -p veritor-zk-common elem failed in zk/sp1"
    fi
  else
    mark elem YELLOW "$ELEM_REASON; Rust half not run (no cargo on PATH)"
  fi
else
  mark elem RED "elem_relation failed: $(tail -1 "$OUT/elem.log")"
fi
tail -1 "$STATUS_FILE"

# -- stage 8c: cov (PROOF-COV coverage families against the fresh record) -------------------------------------
say "8c cov"
if [ ! -f "$RECORD2/proofs/proof-cov/cov_summary.json" ]; then
  mark cov YELLOW "fresh record $RECORD2 has no attached proof-cov proofs (run e2e.cov_attach on the proving pod)"
elif "$PY" -m e2e.cov_relation --record "$RECORD2" --out "$OUT/cov" > "$OUT/cov.log" 2>&1; then
  mark cov GREEN "$(tail -1 "$OUT/cov.log" | sed 's/^cov_relation: //')"
else
  mark cov RED "cov_relation failed: $(tail -1 "$OUT/cov.log")"
fi
tail -1 "$STATUS_FILE"

# -- stage 8d: cert (the whole-program certificate regenerated and byte-compared) ------------------------------
say "8d cert"
if [ ! -f "$RECORD2/certificate.json" ]; then
  mark cert YELLOW "fresh record $RECORD2 has no committed certificate.json"
elif "$PY" -m e2e.certificate --record "$RECORD2" --require-coverage --out "$OUT/certificate.json" > "$OUT/cert.log" 2>&1; then
  if cmp -s "$OUT/certificate.json" "$RECORD2/certificate.json"; then
    mark cert GREEN "certificate regenerated BOUND and byte-equal to the committed one ($(tail -1 "$OUT/cert.log" | sed 's/^\[certificate\] //'))"
  else
    mark cert RED "certificate regenerated BOUND but differs from the committed certificate.json"
  fi
else
  mark cert RED "certificate NOT BOUND: $(grep 'problem:' "$OUT/cert.log" | head -2 | tr '\n' '; ')"
fi
tail -1 "$STATUS_FILE"

# -- stage 9: tests -------------------------------------------------------------------------------------------
say "9 tests"
if [ "$SKIP_TESTS" = "1" ]; then
  mark tests YELLOW "skipped (SKIP_TESTS=1)"
else
  # two processes (one pytest holding everything peaks higher).  the preserved-artefact
  # verify_composed tests each peak ~4.4 GB RSS -- over the box guardian's 4 GB SIGKILL cap --
  # and are deselected unless HEAVY_TESTS=1 (see header)
  KARG=(); [ "$HEAVY_TESTS" = "1" ] || KARG=(-k "not verify_composed_on_preserved_artefacts")
  "$PY" -m pytest tests/test_e2e_composed.py "${KARG[@]}" -q --tb=line > "$OUT/pytest.log" 2>&1; rc1=$?
  "$PY" -m pytest ../tests/veritor/plans/test_padded_bound.py tests/test_inact_pub_leaf_study.py \
        tests/test_output_domain.py \
        ../tests/veritor/plans/test_tight_model.py \
        ../tests/ir/test_serve3.py ../tests/ir/test_pad_prims.py \
        ../tests/ir/test_serve3_authored.py \
        ../tests/veritor/core/test_embed_gates.py \
        ../tests/veritor/protocol/test_embed_statement.py \
        ../tests/veritor/protocol/test_pad_statement.py -q --tb=line >> "$OUT/pytest.log" 2>&1; rc2=$?
  # something in the composed suite swallows pytest's final summary line (rc is authoritative);
  # count the -q progress dots instead: one dot per passed test across both runs
  COUNTS="$(grep -oE '^[.s]+' "$OUT/pytest.log" | tr -d 's\n' | wc -c | tr -d ' ') passed"
  if [ "$rc1" -eq 0 ] && [ "$rc2" -eq 0 ]; then
    if [ "$HEAVY_TESTS" = "1" ]; then
      mark tests GREEN "$COUNTS (e2e_composed incl. preserved-artefact group + padded_bound + inact_pub + tight_model + serve3/pad_prims)"
    else
      mark tests YELLOW "$COUNTS, all passing; 3 preserved-artefact verify_composed tests deselected (4.4 GB RSS > box guardian's 4 GB cap; HEAVY_TESTS=1)"
    fi
  elif ! grep -qE 'FAILED|ERROR' "$OUT/pytest.log" && { [ "$rc1" -ge 128 ] || [ "$rc2" -ge 128 ]; }; then
    mark tests YELLOW "pytest killed by signal (box guardian / memory pressure) -- no test failed; rerun when quiet"
  else
    mark tests RED "pytest failed: $(grep -E 'FAILED|ERROR' "$OUT/pytest.log" | head -2 | tr '\n' '; ')"
  fi
  tail -2 "$OUT/pytest.log"
fi
tail -1 "$STATUS_FILE"

# -- summary --------------------------------------------------------------------------------------------------
# disk hygiene: the extracted bundle is ~570 MB/run and accumulated copies starved the data volume
# below ~3 GB free, at which point long stages started getting terminated (KEEP_BUNDLE=1 keeps it)
[ "${KEEP_BUNDLE:-0}" = "1" ] || rm -rf "$OUT/reverify/bundle"
printf '\n=== e2e_b0 summary (%s) ===\n' "$OUT"
column -t -s $'\t' "$STATUS_FILE"
if grep -q $'\tRED\t' "$STATUS_FILE"; then exit 1; fi
exit 0
