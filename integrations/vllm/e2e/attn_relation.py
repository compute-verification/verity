"""PROOF-ATTN's AttnBlock relation as a proof-verification stage entry (CPU-side).

Three checks against the landed lane artifacts (``zk/bench/attn_gates.py``,
``zk/sp1-attn/``, ``docs/data/proofs/attn-block/``):

1. **Relation identity** — the ``veritor.fa2-attn`` gate set is rebuilt from the
   registered prims and its family version + digest must equal what the committed
   B0 composition check pinned (the digest the SP1 guest refuses to run without).
2. **Cross-language vectors** — ``zk/bench/attn_vectors.py`` regenerates the
   parity vectors (~55k evaluations over special values + seeded encodings) and
   the result must be byte-identical to the committed
   ``zk/sp1-attn/common/tests/vectors.json`` (the file the Rust side asserts
   against; ``cargo test`` in ``zk/sp1-attn/common`` is the Rust half and is run
   by the shell stage when cargo is available).
3. **Committed composition check re-read** — the pod's
   ``b0-composition-check.json`` (50,760 attention rows re-folded through the
   registered gate set against a full-replay B0 record, 0 mismatches) is
   re-read and its counts checked.  A local re-fold is NOT possible against this
   lane's archive: INT-B0-20260908T0725Z is the *selective* (@2) record, whose
   bundle commits only the J-selected rows, and the composition check needs every
   attention row -- stated, not relabelled.

Usage: ``python -m e2e.attn_relation --out <dir>`` from ``vllm-poc/``.
"""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
from datetime import datetime, timezone
from pathlib import Path


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--out", required=True)
    args = ap.parse_args()

    import veritor

    repo = Path(veritor.__file__).resolve().parents[2]
    sys.path.insert(0, str(repo / "zk" / "bench"))
    import attn_gates

    committed_doc = json.loads((repo / "docs/data/proofs/attn-block/b0-composition-check.json").read_text())

    # 1. relation identity
    gs = attn_gates.make_fa2_attn_gate_set()
    version = attn_gates.family_version()
    name_version = f"{gs.name}@{version}"
    if name_version != committed_doc["gate_set"]:
        raise AssertionError(f"gate set {name_version} != committed {committed_doc['gate_set']}")
    if gs.digest != committed_doc["gate_set_digest"]:
        raise AssertionError(f"gate-set digest {gs.digest} != committed {committed_doc['gate_set_digest']}")

    # 2. cross-language vectors: regenerate and require byte-identity with the committed file
    vec_path = repo / "zk/sp1-attn/common/tests/vectors.json"
    committed_bytes = vec_path.read_bytes()
    try:
        subprocess.run([sys.executable, str(repo / "zk/bench/attn_vectors.py")], check=True,
                       capture_output=True, cwd=repo)
        fresh = vec_path.read_bytes()
    finally:
        vec_path.write_bytes(committed_bytes)  # the pipeline never mutates the worktree
    if fresh != committed_bytes:
        raise AssertionError("regenerated cross-language vectors differ from the committed vectors.json")
    n_vectors = sum(len(v) for v in json.loads(fresh)["gates"].values()) if "gates" in json.loads(fresh) \
        else sum(len(v) for v in json.loads(fresh).values() if isinstance(v, list))

    # 3. the committed composition check
    rows, mism = int(committed_doc["rows"]), int(committed_doc["mismatched_rows"])
    if mism != 0 or rows <= 0 or committed_doc["mismatches"]:
        raise AssertionError(f"committed composition check is not clean: rows={rows} mismatched={mism}")

    record = {
        "schema": "veritor/attn-relation-check/v1",
        "generated": datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ"),
        "relation": {"gate_set": name_version, "digest": gs.digest,
                     "status": "re-derived from the registered prims; equals the committed pin"},
        "vectors": {"file": "zk/sp1-attn/common/tests/vectors.json",
                    "status": "regenerated byte-identical",
                    "rust_side": "cargo test in zk/sp1-attn/common (run by the shell stage when cargo exists)"},
        "composition_check": {
            "committed": "docs/data/proofs/attn-block/b0-composition-check.json",
            "record": committed_doc["store"], "rows": rows, "mismatched_rows": mism,
            "bn_sweep": committed_doc.get("bn_sweep"),
            "local_refold": "NOT POSSIBLE on this lane's archive: INT-B0-20260908T0725Z is the selective "
                            "(@2) record (only J-selected rows committed); the check needs every attention "
                            "row and was run on the full-replay record INT-B0-20260908T0235Z on the pod",
        },
    }
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    (out / "attn_relation.json").write_text(json.dumps(record, indent=1) + "\n")
    print(f"attn_relation: gate set {name_version} digest re-derived = committed pin; "
          f"vectors regenerated byte-identical; committed composition check {rows} rows / {mism} mismatches")
    return 0


if __name__ == "__main__":
    sys.exit(main())
