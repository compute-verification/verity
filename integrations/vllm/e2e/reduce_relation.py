"""PROOF-REDUCE's reduction relations as a proof-verification stage entry (CPU-side).

Mirrors ``e2e/attn_relation.py`` for the ``veritor.reduce-mufu@1`` family
(RMSNorm both kernels, RoPE, TokenSelect; MUFU tables in-proof):

1. **Relation identity** — the gate set is rebuilt from the Python mirror
   (``veritor.core.reduce_gates``) and its family + digest must equal the pin in
   the committed cross-language vectors (the digest ``GateSet::resolve`` refuses
   to run without on the SP1 side).
2. **Cross-language vectors** — ``zk/bench/gen_reduce_vectors.py`` regenerates
   the vectors byte-identical to the committed
   ``zk/sp1/common/tests/reduce_vectors.json`` (the Rust twin asserts every word
   and every rejection; ``cargo test`` runs it in the shell stage when cargo is
   available, alongside the attn crate).
3. **Committed batch manifest re-read** — ``docs/data/proofs/reduce-manifest.json``
   (statement/witness digests per batch) checked for structural sanity; the SP1
   proving runs themselves are pod records (``reduce-records.jsonl``) and are
   re-read for accept counts.  Local re-proving needs the SP1 prover and is out
   of scope for a CPU lane -- stated, not relabelled.

Usage: ``python -m e2e.reduce_relation --out <dir>`` from ``vllm-poc/``.
"""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
from datetime import datetime, timezone
from pathlib import Path


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--out", required=True)
    args = ap.parse_args()

    import veritor
    from veritor.core.reduce_gates import make_reduce_mufu_gate_set

    repo = Path(veritor.__file__).resolve().parents[2]
    vec_path = repo / "zk/sp1/common/tests/reduce_vectors.json"
    committed_bytes = vec_path.read_bytes()
    committed = json.loads(committed_bytes)
    manifest = json.loads((repo / "docs/data/proofs/reduce-manifest.json").read_text())

    # 1. relation identity
    gs = make_reduce_mufu_gate_set()
    family = f"{gs.name}@1"
    if family != committed["family"] or family != manifest["gate_set"]:
        raise AssertionError(f"family {family} != vectors {committed['family']} / manifest {manifest['gate_set']}")
    if gs.digest != committed["digest"]:
        raise AssertionError(f"gate-set digest {gs.digest} != committed {committed['digest']}")

    # 2. cross-language vectors regenerate byte-identical
    try:
        subprocess.run([sys.executable, str(repo / "zk/bench/gen_reduce_vectors.py")], check=True,
                       capture_output=True, cwd=repo)
        fresh = vec_path.read_bytes()
    finally:
        vec_path.write_bytes(committed_bytes)  # the pipeline never mutates the worktree
    if fresh != committed_bytes:
        raise AssertionError("regenerated reduce vectors differ from the committed reduce_vectors.json")

    # 3. committed batches + pod proving records
    batches = manifest["batches"]
    if not batches or any(not b.get("statement_digest") or not int(b.get("obligations", 0)) for b in batches):
        raise AssertionError("reduce-manifest has an empty or digestless batch")
    records = [json.loads(l) for l in (repo / "docs/data/proofs/reduce-records.jsonl").read_text().splitlines() if l.strip()]
    bad = [r for r in records if r.get("ok") is False or r.get("verified") is False]
    if bad:
        raise AssertionError(f"{len(bad)} committed reduce proving records not ok: {bad[:2]}")

    record = {
        "schema": "veritor/reduce-relation-check/v1",
        "generated": datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ"),
        "relation": {"gate_set": family, "digest": gs.digest,
                     "status": "re-derived from the Python mirror; equals the committed pin"},
        "vectors": {"file": "zk/sp1/common/tests/reduce_vectors.json", "cases": len(committed["cases"]),
                    "status": "regenerated byte-identical",
                    "rust_side": "cargo test -p veritor-zk-common (run by the shell stage when cargo exists)"},
        "committed_batches": {"manifest": "docs/data/proofs/reduce-manifest.json", "batches": len(batches),
                              "proving_records": len(records),
                              "local_reprove": "out of scope for a CPU lane (SP1 prover); pod records re-read"},
    }
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    (out / "reduce_relation.json").write_text(json.dumps(record, indent=1) + "\n")
    print(f"reduce_relation: gate set {family} digest re-derived = committed pin; "
          f"{len(committed['cases'])} vector cases regenerated byte-identical; "
          f"{len(batches)} committed batches / {len(records)} pod proving records re-read")
    return 0


if __name__ == "__main__":
    sys.exit(main())
