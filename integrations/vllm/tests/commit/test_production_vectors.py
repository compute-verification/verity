"""vLLM's Python commit path reproduces the ``vllm-v1`` conformance vectors byte for byte.

The vectors are generated by the core reference (``verity.ml.commitments.vllm_v1``); every check here computes
the same bytes through the integration's commit path (``scheme``, ``hashing``, ``merkle``, ``hidden_stream``,
``padding_steps``), never by calling the reference directly, then drives whole production commits through both.
The weights root is ``scheme.weights_root`` over ``scheme.names_digest``, exactly as ``register_weights`` calls them.
"""

from __future__ import annotations

import hashlib

import numpy as np
import pytest

from verity.ml.commitments import vllm_v1 as ref
from verity.ml.commitments.vllm_v1 import vectors as V
from verity_vllm.commit import hashing, scheme
from verity_vllm.commit import hidden_stream as hs
from verity_vllm.commit import padding_steps as PS
from verity_vllm.commit.merkle import fold_path, path_shape

VECTORS = V.load()


def _b(text: str) -> bytes:
    return bytes.fromhex(text)


def _path(entries: list[str | None]) -> list[bytes | None]:
    return [None if e is None else _b(e) for e in entries]


class _Digest:
    """A layout / geometry whose digest is the vector's (the integration derives those digests from its own JSON)."""

    def __init__(self, digest: bytes, **fields: int) -> None:
        self._digest = digest
        self.__dict__.update(fields)

    def digest(self) -> bytes:
        return self._digest


def test_vectors_are_current() -> None:
    assert VECTORS == V.build()
    assert VECTORS["scheme"] == ref.NAME == scheme.NAME


@pytest.mark.parametrize("case", VECTORS["hash"], ids=lambda c: c["tag"])
def test_base_hash(case: dict) -> None:
    assert hashing.H(case["tag"], *map(_b, case["parts"])).hex() == case["digest"]


def test_pos_leaf() -> None:
    for case in VECTORS["pos_leaf"]:
        assert scheme.pos_leaf(_b(case["value"])).hex() == case["leaf"]
        assert scheme.pos_leaf(memoryview(_b(case["value"]))).hex() == case["leaf"]


def test_chunk_leaf() -> None:
    for case in VECTORS["chunk_leaf"]:
        f = case["fields"]
        tile = {} if (f["BN"], f["D"]) == (0, 0) else {"BN": f["BN"], "D": f["D"]}
        layout = hs.StreamLayout(f["HB"], f["M"], f["NB"], **tile)
        header = scheme.chunk_header(layout, f["launch_tag"], f["chunk_index"], f["chunk_words"], f["src_mask"])
        assert header.hex() == case["header"]
        assert scheme.chunk_leaf(header, _b(case["chunk"])).hex() == case["leaf"]


def test_thread_leaf() -> None:
    for case in VECTORS["thread_leaf"]:
        f = case["fields"]
        header = scheme.thread_header(f["src_mask"], f["slab"], f["m_block"], f["n_block"], f["tidx"], f["seqlen_q"], f["seqlen_k"],
                                      f["launch_tag"], f["n_block_max"], f["ok0"], f["ok1"])
        assert header.hex() == case["header"]
        assert scheme.thread_leaf(header + _b(case["words"])).hex() == case["leaf"]


@pytest.mark.parametrize("case", VECTORS["trees"], ids=lambda c: f"n={c['leaf_count']}")
def test_tree(case: dict) -> None:
    leaves = [_b(x) for x in case["leaves"]]
    assert scheme.fold(list(leaves)).hex() == case["root"]
    if not leaves:
        assert hashing.empty_root().hex() == scheme.empty_root().hex() == case["root"]
        return
    levels = scheme.fold_levels(list(leaves))
    for index, expected in enumerate(case["paths"]):
        path = scheme.path_in_levels(levels, index)
        assert list(path) == _path(expected)
        assert [p is not None for p in path] == path_shape(case["leaf_count"], index)
        assert fold_path(leaves[index], index, path).hex() == case["root"]


def _integration_accepts(case: dict) -> bool:
    """The integration's own opening check (shape from (N, index), then the fold), as ``verify_position_opening`` does it."""
    path = _path(case["path"])
    try:
        expected = path_shape(case["leaf_count"], case["index"])
    except Exception:  # noqa: BLE001 - the integration raises CommitError for an index outside the tree
        return False
    if len(path) != len(expected) or any((p is None) == has for p, has in zip(path, expected, strict=True)):
        return False
    try:
        return fold_path(_b(case["leaf"]), case["index"], path).hex() == case["root"]
    except ValueError:
        return False


@pytest.mark.parametrize("case", VECTORS["rejections"], ids=lambda c: c["why"])
def test_rejections(case: dict) -> None:
    assert not _integration_accepts(case)


def test_roots() -> None:
    kinds = set()
    for case in VECTORS["roots"]:
        i, kind = case["inputs"], case["kind"]
        kinds.add(kind)
        if kind == "semantic":
            got = scheme.semantic_root(_b(i["program_digest"]), _b(i["query_id"]), _b(i["template_digest"]), _b(i["ctx_digest"]),
                                       i["epoch"], i["n"], _b(i["tree_root"]))
        elif kind == "step":
            got = scheme.step_root(_b(i["program_digest"]), _b(i["ctx_digest"]), _b(i["geo_digest"]), _b(i["layout_digest"]), i["n"],
                                   _b(i["tree_root"]))
        elif kind == "run":
            got = scheme.run_root(_b(i["program_digest"]), _b(i["geo_digest"]), [_b(s) for s in i["step_roots"]])
        elif kind == "stream":
            got = scheme.stream_root(_b(i["layout_digest"]), i["launch_tag"], i["src_mask"], i["chunk_words"], i["leaf_count"],
                                     _b(i["tree_root"]))
        elif kind == "thread":
            got = scheme.thread_root(_b(i["geo_digest"]), i["launch_tag"], i["src_mask"], _b(i["tree_root"]))
        elif kind == "weights":
            got = scheme.weights_root(_b(i["geo_digest"]), _b(i["names_digest"]), [_b(t) for t in i["tensor_roots"]])
        else:
            raise AssertionError(f"unknown root kind {kind!r}")
        assert got.hex() == case["root"], kind
    assert kinds == {"semantic", "step", "run", "stream", "thread", "weights"}


def test_names_digest_is_the_compact_json() -> None:
    names = [["model.embed_tokens.weight", "bfloat16", [128256, 2048], 525336576], ["model.norm.weight", "bfloat16", [2048], 4096]]
    text = b'[["model.embed_tokens.weight","bfloat16",[128256,2048],525336576],["model.norm.weight","bfloat16",[2048],4096]]'
    assert scheme.names_digest(names) == hashlib.sha256(text).digest()


def test_integer_like_fields_are_coerced() -> None:
    f = VECTORS["chunk_leaf"][0]["fields"]
    layout = hs.StreamLayout(np.int64(f["HB"]), np.int32(f["M"]), np.uint16(f["NB"]))
    header = scheme.chunk_header(layout, np.int64(f["launch_tag"]), np.int64(f["chunk_index"]), np.int32(f["chunk_words"]), np.uint8(f["src_mask"]))
    assert header.hex() == VECTORS["chunk_leaf"][0]["header"]
    i = next(c["inputs"] for c in VECTORS["roots"] if c["kind"] == "step")
    got = scheme.step_root(bytearray(_b(i["program_digest"])), memoryview(_b(i["ctx_digest"])), _b(i["geo_digest"]), _b(i["layout_digest"]),
                           np.int64(i["n"]), _b(i["tree_root"]))
    assert got.hex() == next(c["root"] for c in VECTORS["roots"] if c["kind"] == "step")


class _GpuLayout:
    """``native_host._gpu_layout``'s duck-typed block layout: (HB, M, NB) = (step, padded words, block kind)."""

    def __init__(self, HB: int, M: int, NB: int = 0) -> None:
        self.HB, self.M, self.NB = HB, M, NB


def _pre_c1_chunk_header(layout, launch_tag: int, chunk_index: int, chunk_words: int, src_mask: int) -> bytes:
    """The integration's host header before it routed through core: every word masked to u32 by ``pack_words``, as the kernels write it."""
    return hs.pack_words([scheme.FA2H_TAG, (scheme.FA2H_VERSION << 16) | (scheme.FA2H_KIND_CHUNK << 8) | (src_mask & 0xFF), launch_tag,
                          chunk_index, chunk_words, layout.HB, layout.M, layout.NB, 0, 0, 0, 0, 0, 0, 0, 0])


@pytest.mark.parametrize("M", [0, 8, 2**32 - 1, 2**32, 2**32 + 7, 5036944512, 2**40 + 3])
def test_chunk_header_matches_the_pre_c1_u32_header(M: int) -> None:
    layout = _GpuLayout(4, M, 1)
    assert scheme.chunk_header(layout, 4, 17, 64, 3) == _pre_c1_chunk_header(layout, 4, 17, 64, 3)
    if M < 2**32:
        assert scheme.chunk_header(layout, 4, 17, 64, 3) == ref.chunk_header(launch_tag=4, chunk_index=17, chunk_words=64, src_mask=3,
                                                                             HB=4, M=M, NB=1)


def test_chunk_header_of_a_step_past_2_32_words() -> None:
    step, m = 4, 5036944512
    header = scheme.chunk_header(_GpuLayout(step, m), step, 0, 64, 0)
    assert header[24:28] == (m % 2**32).to_bytes(4, "little")
    assert header == ref.chunk_header(launch_tag=step, chunk_index=0, chunk_words=64, src_mask=0, HB=step, M=m - 2**32, NB=0)


def test_id_leaf() -> None:
    *leaves, ids = VECTORS["id_leaf"]
    for case in leaves:
        assert hashing.leaf_hash(case["canonical_id"], case["dtype"], tuple(case["shape"]), _b(case["value"])).hex() == case["leaf"]
    assert hashing.ids_digest(sorted(ids["ids"])).hex() == ids["ids_digest"]


class _Geometry(hs.ThreadGeometry):
    """A real ``ThreadGeometry`` (the integration derives headers and indices from it) with the vector's digest."""

    vector_digest = b""

    def digest(self) -> bytes:
        return self.vector_digest


def _integration_opening(case: dict) -> bool:
    """The integration's own verifier for each domain kind, fed the vector's domain."""
    d, index, value, path = case["domain"], case["index"], _b(case["value"]), _path(case["path"])
    root = _b(case["root"])
    if case["kind"] == "stream":
        layout = _Digest(_b(d["layout_digest"]), HB=d["HB"], M=d["M"], NB=d["NB"], legacy_tile=True)
        return hs.verify_chunk_opening(root, layout, d["launch_tag"], d["src_mask"], d["chunk_words"], d["leaf_count"], index * d["chunk_words"],
                                       hs.ChunkOpening(index, 0, value, tuple(path)))
    if case["kind"] == "thread":
        p = case["position"]
        _Geometry.vector_digest = _b(d["geo_digest"])
        geo = _Geometry(HB=d["HB"], b=1, h=d["HB"], M=64 * d["num_m_block"], NB=d["NB"], num_m_block=d["num_m_block"],
                        seqlens_q=(p["seqlen_q"],), seqlens_k=(p["seqlen_k"],), causal=False)
        assert geo.leaf_index(p["slab"], p["m_block"], p["n_block"], p["tidx"]) == index
        return hs.verify_thread_opening(root, geo, d["launch_tag"], d["src_mask"], 0, p["slab"], p["m_block"], p["n_block"], p["tidx"],
                                        hs.ThreadOpening(index, value, tuple(path)))
    if [p is not None for p in path] != path_shape(d["leaf_count"], index):
        return False
    if case["kind"] == "step" and d["chunk"] is not None:
        c = d["chunk"]
        layout = _Digest(b"", HB=c["HB"], M=c["M"], NB=c["NB"])
        leaf = scheme.chunk_leaf(scheme.chunk_header(layout, c["launch_tag"], index, c["chunk_words"], c["src_mask"]), value)
    else:
        leaf = scheme.pos_leaf(value)
    tree_root = fold_path(leaf, index, path)
    if case["kind"] == "semantic":
        return scheme.semantic_root(_b(d["program_digest"]), _b(d["query_id"]), _b(d["template_digest"]), _b(d["ctx_digest"]), d["epoch"],
                                    d["leaf_count"], tree_root) == root
    return scheme.step_root(_b(d["program_digest"]), _b(d["ctx_digest"]), _b(d["geo_digest"]), _b(d["layout_digest"]), d["leaf_count"],
                            tree_root) == root


@pytest.mark.parametrize("case", VECTORS["openings"], ids=lambda c: f"{c['kind']}-{c['index']}-{'accept' if c['accept'] else 'reject'}")
def test_domain_openings(case: dict) -> None:
    assert _integration_opening(case) is case["accept"]


@pytest.mark.parametrize("case", [c for c in VECTORS["openings"] if c["accept"]], ids=lambda c: c["kind"])
def test_lowering_trace_matches_the_integration_hashes(case: dict) -> None:
    digest, cursor = _b(case["leaf"]), case["index"]
    for step, sibling in zip(case["trace"], _path(case["path"]), strict=True):
        if sibling is None:
            digest = hashing.lift_hash(digest)
        else:
            digest = hashing.node_hash(digest, sibling) if cursor % 2 == 0 else hashing.node_hash(sibling, digest)
        assert digest.hex() == step["digest"]
        cursor //= 2
    assert digest.hex() == case["tree_root"]


# --- whole production commits, recomputed with the reference -------------------------------------------------------

_IDENTITIES = [
    {"op_path": "model.layers.0.input_layernorm", "output_member": "out", "request_id": "r0", "step": 0, "element_range": [0, 300], "dtype": "bf16"},
    {"op_path": "fa2.m1/L0", "output_member": "g", "request_id": "r0", "step": 0, "element_range": [0, 77], "dtype": "u32"},
    {"op_path": "runner.sampler", "output_member": "sampled_token_ids", "request_id": "r0", "step": 0, "element_range": [0, 1], "dtype": "i64"},
]


@pytest.mark.parametrize("layout", ["host-pos-leaf", "chunk-leaf-v1", "chunk-leaf-v2"])
def test_padding_step_commit_matches_reference(layout: str) -> None:
    program, geo = hashlib.sha256(b"program").digest(), hashlib.sha256(b"geo").digest()
    chunk, step = 256, 3
    ps = PS.padding_step_commit(step, _IDENTITIES, program_digest=program, run_id="run-x", geo_digest=geo, chunk=chunk, layout=layout)
    stream = ps.stream
    if layout.startswith("chunk-leaf-v"):
        m = 0 if layout == "chunk-leaf-v2" else len(stream) // 4
        leaves = [ref.chunk_leaf(ref.chunk_header(launch_tag=step, chunk_index=k, chunk_words=chunk // 4, src_mask=0, HB=step, M=m,
                                                  NB=PS.PADDING_BLOCK), stream[k * chunk:(k + 1) * chunk])
                  for k in range(len(stream) // chunk)]
    else:
        leaves = [ref.pos_leaf(stream[o:o + chunk]) for o in range(0, len(stream), chunk)]
    assert len(leaves) == ps.n_leaves
    tree_root = ref.TREE.root(leaves)
    assert tree_root == ps.merkle_root
    ctx = hashlib.sha256(f"run-x/step={step}".encode()).digest()
    assert ref.step_root(program, ctx, geo, PS.layout_digest(ps.metas), len(leaves), tree_root) == ps.root
    for k in range(len(leaves)):
        leaf_bytes, path = PS.opening(ps, k)
        assert tuple(path) == ref.TREE.path(leaves, k)
        assert ref.verify_opening(ps.root, len(leaves), k, PS.leaf_digest_of(ps, leaf_bytes, k), path,
                                  bind=lambda r: ref.step_root(program, ctx, geo, PS.layout_digest(ps.metas), len(leaves), r))
    other = PS.padding_step_commit(step + 1, _IDENTITIES, program_digest=program, run_id="run-x", geo_digest=geo, chunk=chunk, layout=layout)
    assert ref.run_root(program, geo, [ps.root, other.root]) == scheme.run_root(program, geo, [ps.root, other.root])


def test_stream_commit_matches_reference() -> None:
    layout = hs.StreamLayout(HB=2, M=8, NB=1)
    stream = np.frombuffer(V.expand("stream", 4 * layout.total_words), dtype="<u4").copy()
    launch_tag, src_mask, cw = 11, 63, 64
    com = hs.commit_stream(stream, layout, launch_tag, src_mask, chunk_words=cw)
    raw = np.concatenate([stream, np.zeros(layout.padded_words(cw) - stream.size, dtype=np.uint32)]).astype("<u4").tobytes()
    n = len(raw) // (4 * cw)
    leaves = [ref.chunk_leaf(ref.chunk_header(launch_tag=launch_tag, chunk_index=k, chunk_words=cw, src_mask=src_mask, HB=2, M=8, NB=1),
                             raw[4 * cw * k:4 * cw * (k + 1)]) for k in range(n)]
    assert ref.TREE.root(leaves) == com.merkle_root
    ctx = ref.stream_ctx_digest(launch_tag=launch_tag, src_mask=src_mask, chunk_words=cw, leaf_count=n)
    assert ref.stream_root(layout.digest(), ctx, com.merkle_root) == com.root
    word = 5 * cw + 3
    opening = com.open(stream, word)
    assert hs.verify_chunk_opening(com.root, layout, launch_tag, src_mask, cw, n, word, opening)
    assert ref.verify_opening(com.root, n, opening.index, leaves[opening.index], opening.path,
                              bind=lambda r: ref.stream_root(layout.digest(), ctx, r))


def test_thread_commit_matches_reference() -> None:
    geo = hs.ThreadGeometry(HB=1, b=1, h=1, M=64, NB=1, num_m_block=1, seqlens_q=(40,), seqlens_k=(100,), causal=False)
    launch_tag, src_mask = 4, 1
    layout = hs.StreamLayout(HB=1, M=64, NB=1)
    stream = np.frombuffer(V.expand("thread-stream", 4 * layout.total_words), dtype="<u4").copy()
    messages = [hs.thread_message(stream, layout, geo, src_mask, launch_tag, 0, 0, 0, 0, t) for t in range(128)]
    for t in (0, 77):
        w, lane = t // 32, t % 32
        r0 = 16 * w + lane // 4
        assert messages[t][:64] == ref.thread_header(src_mask=src_mask, slab=0, m_block=0, n_block=0, tidx=t, seqlen_q=40, seqlen_k=100,
                                                     launch_tag=launch_tag, n_block_max=geo.n_block_max(0, 0), ok0=r0 < 40, ok1=r0 + 8 < 40)
    leaves = [ref.thread_leaf(m) for m in messages]
    digests = np.frombuffer(b"".join(leaves), dtype=np.uint32)
    com = hs.ThreadLeafCommitment.from_digests(digests, geo, launch_tag, src_mask)
    assert ref.TREE.root(leaves) == com.merkle_root
    ctx = ref.thread_ctx_digest(launch_tag=launch_tag, src_mask=src_mask)
    assert ref.thread_root(geo.digest(), ctx, com.merkle_root) == com.root
    opening = com.open(messages[77], 77)
    assert hs.verify_thread_opening(com.root, geo, launch_tag, src_mask, 0, 0, 0, 0, 77, opening)
    assert ref.verify_opening(com.root, len(leaves), 77, ref.thread_leaf(opening.message), opening.path,
                              bind=lambda r: ref.thread_root(geo.digest(), ctx, r))
