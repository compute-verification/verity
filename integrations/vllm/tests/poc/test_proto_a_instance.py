def test_population_agrees_with_summary_c_agreement_2(tiny_built, tiny_plan, tmp_path):
    """Agreement 2 (SUMMARY-C): the sampler's population must be Summary.sampler_populations() -- same N_V, N_R, same plan digest
    convention (plan-json/v1); every outgoing value of a sampled VU has a committed or interior position in AddressBook."""

    from veritor.plans.summary import AddressBook, summarize

    _, adapted, circuit, digest = tiny_built
    plan, _, verdict = tiny_plan
    s = summarize(circuit, plan, verdict, program_digest=("verity-ir/program_digest", digest))
    sp = s.sampler_populations()
    pop = popmod.population(adapted.program, plan, verdict, digest)
    assert (sp["N_V"], sp["N_R"]) == (pop.vu_count, pop.ru_count)
    assert sp["plan_digest"] == pop.plan_digest and sp["program_digest"] == digest
    assert s.plan["digest_kind"] == popmod.plan_digest_kind(plan) == "plan-json/v1"
    # draft 2 (SUMMARY-C objection 1/3): the partition itself is pinned by partition_digest; the instance may name Summary.digest
    assert s.plan["partition_digest"] == pop.partition_digest and s.plan["partition_digest_kind"] == "partition-intervals/v1"
    popfile = json.loads((P3 / "population.json").read_text())
    art = json.loads((P3 / "compact_validation.json").read_text())
    assert popfile["partition_digest"] == art["partition_digest"] == pop.partition_digest
    inst = pi.load_instance(_tiny_instance(tmp_path, summary_digest=str(s.digest)))
    assert inst.partition.partition_digest == pop.partition_digest and inst.partition.summary_digest == str(s.digest)
    assert pi.validate_instance(inst) == []
    ab = AddressBook(circuit, plan, verdict)
    addr = popmod.Addresser(adapted.program, circuit, plan, verdict)
    a = addr.resolve(17)
    assert ab.vu(17).replay_unit == a.ru
    for run in a.outputs:
        for g in range(run.gate, run.gate + run.count * run.stride, run.stride):
            assert ab.committed_position(a.ru, g) is not None or ab.interior_position(a.ru, g) is not None


def test_p1_coordinate_units_resolve_to_their_own_member(tiny_built):
    """SUMMARY-C objection 2 (bug): a one-member Part(path, k, a, a+1) with a > 0 was resolved to member 0 of its node, so gate_lo/gate_hi/path
    of every batch-member unit (all P1/coordinate units) described the wrong unit.  P1/cu=operator on TINY exposes it (P3/cu=block cannot:
    its units are whole calls); before the fix 35,825 of 53,113 vu_map rows were wrong (MEASURED, 2026-09-09)."""

    from veritor.plans.validate import validate_plan

    _, adapted, circuit, digest = tiny_built
    plan, _ = popmod.make_plan("P1/cu=operator", adapted, circuit)
    verdict = validate_plan(circuit, plan)
    index = json.loads((FIX / "index.json").read_text())["plans"]["P1/cu=operator"]
    pop = popmod.population(adapted.program, plan, verdict, digest)
    # REC-15 (COMPACT-P1): make_plan builds P1 as UnitRuns, so its plan_digest is plan-rule/v1 (fixture `plan_digest_compact`), not the dense
    # plan-json/v1 digest PROTO-A pinned; the partition digest is representation-independent and must still agree.
    assert (pop.vu_count, pop.ru_count, pop.partition_digest) == (index["vus"], index["cus"], index["partition_digest"])
    assert pop.plan_digest in (index["plan_digest"], index["plan_digest_compact"])
    assert index["tables"] is False  # 53,113 VUs: the fixture keeps population.json + headers, not the TSVs
    popfile = json.loads((FIX / "P1_cu-operator" / "population.json").read_text())
    assert popfile["ru_of"] == popmod.ru_membership(verdict) and popfile["partition_digest"] == pop.partition_digest
    addr = popmod.Addresser(adapted.program, circuit, plan, verdict)
    # SUMMARY-C's two witnesses, and every unit's interval must be the unit's own gate span (resolve() now raises otherwise)
    assert addr.resolve(1000).interval == (1000, 1001)
    assert addr.resolve(20000).interval == (20866, 20867)
    member_units = 0
    for i, desc in enumerate(plan.verification_units):
        a = addr.resolve(i)
        span = (desc.intervals.intervals()[0][0], desc.intervals.intervals()[-1][1])
        assert a.interval == span, i
        part = desc.parts[0]
        if part.a > 0:
            member_units += 1
            assert a.path[-1] == (part.node_idx, part.a)
    assert member_units > 30000  # the rows that were wrong before the fix


def test_value_map_covers_every_vu_once_and_positions_are_disjoint(tiny_built, tiny_plan):
    _, adapted, circuit, digest = tiny_built
    plan, _, verdict = tiny_plan
    with (P3 / "value_map.tsv").open() as f:
        rows = list(csv.DictReader(f, delimiter="\t"))
    seen_gates: set[int] = set()
    total = 0
    for r in rows:
        gate, count, stride = int(r["gate"]), int(r["count"]), int(r["stride"])
        pos = {gate + i * stride for i in range(count)}
        assert not (pos & seen_gates), "a program value is addressed by two VUs"
        seen_gates |= pos
        total += count
    maps = json.loads((P3 / "maps.json").read_text())
    assert total == maps["counts"]["program_values"]
    vus = {int(r["vu"]) for r in rows}
    with (P3 / "vu_map.tsv").open() as f:
        vu_rows = list(csv.DictReader(f, delimiter="\t"))
    assert [int(r["vu"]) for r in vu_rows] == list(range(maps["plan"]["vus"]))
    # every VU with outgoing boundary values appears in value_map; VUs whose outputs escape nowhere (dead in the program) have none
    with_values = {int(r["vu"]) for r in vu_rows if int(r["n_output_runs"]) > 0}
    assert vus == with_values and len(with_values) <= maps["plan"]["vus"]
    # address resolution for a sampled index, without per-VU objects for the rest
    addr = popmod.Addresser(adapted.program, circuit, plan, verdict)
    a = addr.resolve(17)
    assert a.index == 17 and 0 <= a.ru < maps["plan"]["cus"]
    assert a.ru == json.loads((P3 / "population.json").read_text())["ru_of"][17]
    with pytest.raises(IndexError):
        addr.resolve(maps["plan"]["vus"])  # out of the population


