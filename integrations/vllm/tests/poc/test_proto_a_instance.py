def _rewrite(rec: Path, name: str, mutate) -> None:
    doc = json.loads((rec / name).read_text())
    mutate(doc)
    (rec / name).write_text(json.dumps(doc))


def _repin_instance(rec: Path) -> None:
    _rewrite(rec, "manifest.json", lambda m: m["inputs"].__setitem__("protocol_instance_sha256", _hash(rec / "protocol_instance.json")))


