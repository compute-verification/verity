def _hash(p: Path) -> str:
    import hashlib

    return hashlib.sha256(p.read_bytes()).hexdigest()


def _tiny_record(tmp_path: Path) -> Path:
    """A minimal record directory carrying the v3 evidence for a completed TINY Bernoulli audit (no proofs/bundle: the
    instance_check layer only)."""

    rec = tmp_path / "record"
    rec.mkdir(parents=True)
    inst_f = _tiny_instance(rec)
    import shutil

    for name in ("compact_validation.json", "population.json"):
        shutil.copy(P3 / name, rec / name)
    ss.stage1(inst_f, rec / "population.json", "11" * 32, rec, "ef" * 32)
    ss.stage2(inst_f, rec / "population.json", "33" * 32, rec)
    ss.reveal(rec)
    (rec / "sampling_policy.json").write_text(json.dumps({"selector": "bernoulli", "q_declared": "1/2", "s_declared": "1/8", "bound_utc": "2026-09-09T00:00:00Z"}))
    art = json.loads((rec / "compact_validation.json").read_text())
    manifest = {"inputs": {"program_digest": art["program_digest"], "protocol_instance_sha256": _hash(inst_f),
                           "sampling_policy_sha256": _hash(rec / "sampling_policy.json")}}
    (rec / "manifest.json").write_text(json.dumps(manifest))
    return rec


def _evidence(rec: Path):
    from e2e.instance_check import check_instance_evidence

    return check_instance_evidence(rec, json.loads((rec / "manifest.json").read_text()))


