def test_negative_out_of_program_sampled_unit(tmp_path):
    rec = _tiny_record(tmp_path)

    def out_of_population(doc):
        rs = next(e for e in doc["events"] if e["name"] == "r_s")
        rs["selection"] = sorted(set(rs["selection"]) | {305})  # one past the validated population

    _rewrite(rec, "chronology.json", out_of_population)
    problems, _ = _evidence(rec)
    assert any("outside the population" in p for p in problems)
    assert any("r_s selection does not re-derive" in p for p in problems)
    # a unit inside the population but outside J (not a retained interior) is equally rejected
    rec2 = _tiny_record(tmp_path / "b")

    def outside_J(doc):
        rq = next(e for e in doc["events"] if e["name"] == "r_q")
        rs = next(e for e in doc["events"] if e["name"] == "r_s")
        ru_of = json.loads((rec2 / "population.json").read_text())["ru_of"]
        vu = next(v for v in range(len(ru_of)) if ru_of[v] not in rq["selection"])
        rs["selection"] = sorted(set(rs["selection"]) | {vu})

    _rewrite(rec2, "chronology.json", outside_J)
    problems, _ = _evidence(rec2)
    assert any("not in J" in p for p in problems)


def test_negative_draft2_partition_digest_first_boundary_proof_steps(tmp_path):
    """Draft-2 rules from the reviewer objections: (SUMMARY-C 1) a population file whose partition_digest is not the instance's is refused
    even when plan/program digests agree; (COST-D 1) a first boundary committed AFTER the first challenge, or a Bound attached over a
    multi-RU partition whose first boundary is 'designated outputs only', is refused; (COST-D 2) a sampled obligation without proof_steps."""

    rec = _tiny_record(tmp_path)
    _rewrite(rec, "population.json", lambda d: d.update({"partition_digest": "f" * 64}))
    problems, _ = _evidence(rec)
    assert any("partition_digest" in p and "population.json" in p for p in problems)
    # the instance itself: partition_digest pair must agree with the validation ref
    doc = json.loads((rec / "protocol_instance.json").read_text())
    doc["partition"]["validation"]["partition_digest"] = "e" * 64
    with pytest.raises(pi.InstanceError, match="validation.partition_digest != instance.partition.partition_digest"):
        pi.load_instance(doc)
    # first boundary committed after r_q (the realised chronology.json is the evidence; the pre-challenge instance has no events yet)
    rec2 = _tiny_record(tmp_path / "b")
    _rewrite(rec2, "protocol_instance.json", lambda d: d["partition"]["first_boundary"].__setitem__("committed_in", "interior"))
    _repin_instance(rec2)
    problems, _ = _evidence(rec2)
    assert any("AFTER the first challenge" in p for p in problems)
    # a first boundary that is the designated outputs only, over a multi-RU partition: refused by the entry point ...
    rec3 = _tiny_record(tmp_path / "c")
    _rewrite(rec3, "protocol_instance.json", lambda d: d["partition"]["first_boundary"].__setitem__("rule", "designated outputs only"))
    _repin_instance(rec3)
    problems, _ = _evidence(rec3)
    assert any("needs every CU's outgoing boundary committed before r_q" in p for p in problems)
    # ... and by the instance validator if a Bound is attached over it
    doc = json.loads((rec / "protocol_instance.json").read_text())
    doc["partition"]["first_boundary"]["rule"] = "designated outputs only"
    doc["partition"]["weight_input_check"]["bound_excludes_weight_family"] = True
    doc["security"].update({"bound_attached": True, "bound_value_bits": {"value": 1, "label": "ANALYTICAL", "source": "test"}})
    assert any("first_boundary.rule != 'outgoing boundary runs of every CU'" in p for p in pi.validate_instance(_load_lenient(doc)))
    # a historical instance claiming V2 without a record check that establishes it
    doc = json.loads(HIST.read_text())
    doc["partition"]["weight_input_check"]["verified_by"] = None
    assert any("claimed, unverified" in p for p in pi.validate_instance(_load_lenient(doc)))
    # a sampled obligation with no proof_steps
    doc = json.loads((rec / "protocol_instance.json").read_text())
    for o in doc["obligations"]["mandatory"]:
        o.pop("proof_steps", None)
    assert any("proof_steps" in p for p in pi.validate_instance(_load_lenient(doc)))
    # unknown proof step
    doc = json.loads((rec / "protocol_instance.json").read_text())
    next(o for o in doc["obligations"]["mandatory"] if o["role"] == "sampled")["proof_steps"] = ["witness", "magic"]
    assert any("proof_steps must be distinct members" in p for p in pi.validate_instance(_load_lenient(doc)))
    # acquisition granularity is a closed vocabulary
    doc = json.loads((rec / "protocol_instance.json").read_text())
    doc["partition"]["acquisition_granularity"] = "layer"
    assert any("acquisition_granularity" in p for p in pi.validate_instance(_load_lenient(doc)))


def _load_lenient(doc):
    """Decode strictly but skip semantic validation (to assert on validate_instance's problem list)."""

    return pi._decode(pi.ProtocolInstance, doc, "instance")


def test_certificate_cli_refuses_without_evidence_and_verify_composed_row_fails(tmp_path):
    """The entry points themselves: certificate.py (v3) is NOT BOUND on a record lacking the instance; the --historical-v2 path
    writes the v2 schema and says it attests no instance."""

    from e2e import certificate

    rec = _tiny_record(tmp_path)
    (rec / "summary.json").write_text(json.dumps({"verdict": "PASS", "scope": {}, "stages": {}}))
    (rec / "proofs").mkdir()
    out = tmp_path / "cert.json"
    rc = certificate.main(["--record", str(rec), "--out", str(out)])
    cert = json.loads(out.read_text())
    assert cert["schema"].endswith("/v3") and cert["protocol_instance"]["attests_protocol_instance"] is True
    assert rc == 1 and any("no proofs" in p for p in cert["binding_problems"])  # the instance held; the (absent) proofs did not
    (rec / "protocol_instance.json").unlink()
    rc = certificate.main(["--record", str(rec), "--out", str(out)])
    cert = json.loads(out.read_text())
    assert rc == 1 and cert["protocol_instance"]["attests_protocol_instance"] is False
    assert any("no protocol instance" in p for p in cert["binding_problems"])
    rc = certificate.main(["--record", str(rec), "--out", str(out), "--historical-v2"])
    cert = json.loads(out.read_text())
    assert cert["schema"].endswith("/v2") and cert["protocol_instance"]["attests_protocol_instance"] is False
    assert not any("instance" in p for p in cert["binding_problems"])


