def test_bernoulli_two_stage_chronology_rederives_and_refuses_rerolls(tmp_path):
    inst_f = _tiny_instance(tmp_path)
    out = tmp_path / "chron"
    seed = "ab" * 32
    doc = ss.stage1(inst_f, P3 / "population.json", "11" * 32, out, seed)
    J = doc["events"][-1]["selection"]
    assert doc["realized"]["J_size"]["value"] == len(J) and all(0 <= r < 95 for r in J)
    assert [e["name"] for e in doc["events"]] == ["protocol_instance", "seed_commitment", "boundary", "r_q"]
    with pytest.raises(ss.ChronologyError, match="reroll"):
        ss.stage1(inst_f, P3 / "population.json", "22" * 32, out, seed)
    doc = ss.stage2(inst_f, P3 / "population.json", "33" * 32, out)
    Q = doc["events"][-1]["selection"]
    ru_of = json.loads((P3 / "population.json").read_text())["ru_of"]
    assert all(ru_of[v] in J for v in Q)
    assert doc["realized"]["Q_size"]["value"] == len(Q)
    assert doc["law"]["q"] == "1/2" and "k" not in doc["law"]  # realized counts never become the law
    with pytest.raises(ss.ChronologyError, match="reroll"):
        ss.stage2(inst_f, P3 / "population.json", "44" * 32, out)
    ss.reveal(out)
    assert ss.verify(inst_f, P3 / "population.json", out) == []
    assert len(doc["challenges_drawn"]) == 2
    # the instance's chronology section is fillable from the file
    ch = ss.chronology_for_instance(json.loads((out / "chronology.json").read_text()))
    assert [e["name"] for e in ch["events"]][-1] == "seed_reveal" and ch["rerolls"] == 0
    # J is exactly bernoulli_subset(seed, ..., N_R, q): the law is the product of independent coins, not a fixed k
    assert list(J) == list(ss.draw_J(bytes.fromhex(seed), doc["events"][3]["phase_digest"], 95, Fraction(1, 2)))


