@pytest.mark.parametrize("which", ["world", "biased_world", "fused_world"])
def test_the_native_commitment_is_the_ir_evaluators_leaf_for_leaf(which, request):
    """Both paths on the small model: each call re-committed from its Program's IR evaluation, and its weight side from
    its own, has the native commit's unit leaves, inputs digest, units root and served y, so the run's calls root is the
    same."""
    w = request.getfixturevalue(which)
    ir = [PC.commit_call_ir(r.index, r.scheme, r.call) for r in w.records]
    for nat, ref in zip(w.records, ir):
        assert nat.units == ref.units and nat.leaves == ref.leaves and nat.inputs == ref.inputs and nat.root == ref.root
        assert (nat.side.leaves, nat.side.inputs, nat.side.root) == (ref.side.leaves, ref.side.inputs, ref.side.root)
        assert np.array_equal(nat.y, ref.y) and PC.call_leaf(nat) == PC.call_leaf(ref)
    assert _recommitted(w, ir) == w.commitment


def test_the_honest_run_is_accepted(world):
    rep, pw, issues = _verdict(world)
    assert rep["result"] is True and rep["grade"] == "complete", rep["why"]
    assert PC.ROW_FAMILY in rep["population"]["by_family"] and rep["sample"]["mismatch_n"] == 0
