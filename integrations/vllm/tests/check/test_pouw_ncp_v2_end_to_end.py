    assert issues == []
    assert pw["proved_by_role"]["tile"] == 3 and set(pw["proved_by_role"]) == {"digest", "node", "key", "form_y", "form_x", "tile", "dequant"}
    assert pw["weights"] == 1 and pw["draw"]["domain"] == CPL.DRAW_DOMAIN and len(bytes.fromhex(pw["draw"]["source"])) == 32


