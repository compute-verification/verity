def _tampered(rec, u, j):
    """The call re-committed by a prover that commits and opens output leaf ``j`` of unit ``u`` with its low bit flipped."""
    return PN.commit_call(rec.index, rec.scheme, rec.call, tamper={(u, j): int(rec.opening(u)[j]) ^ 1}, side=rec.side)


def test_a_wrong_x_strip_is_rejected(world):
    bad = world.records[1]
    rec = _tampered(bad, PN.Native(bad.call, bad.scheme).index("form_x", 0), 5)
    assert rec.leaves != bad.leaves
    records = [world.records[0], rec]
    _rep, pw, _issues = _verdict(world, records, _recommitted(world, records))
    assert pw["result"] is False and any("form_x" in w and "does not hold" in w for w in pw["why"]), pw["why"]


