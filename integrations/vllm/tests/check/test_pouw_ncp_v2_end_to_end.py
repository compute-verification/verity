"""`pouw:ncp-v2` beside sampled proofs, end to end on a small model (CPU).

A two-request Program, lowered at its PoUW site by the Build's `pouw_circuit.lower`:
Embedding → RMSNorm → up_proj (the PoUW linear, 64 → 16) → logits → TokenSelect, over a 16-token prefill and one decode
step. Each step's up_proj batch is one call of the adapter's real `ncp-v2` executor, installed through the composition.
The weight's side is bound to its `NcpWeight_v1` Program's inputs once, each call to its `NcpLinear_v1` Program's, their
units computed natively (`pouw_native`) and committed. The model's module outputs are committed as the collector packs
them.

The verifier then runs the real sampled replay, with the PoUW rows answered by their calls (`pouw_circuit.linked`), and
the circuit replay of the run (`pouw_circuit.replay`: the calls as one window on a sealed receipt, each call's closure
draw under the window's fresh key and #362's work law, each proved unit regenerated by the prover and evaluated from its
template by the IR reference, and each drawn Y strip linked to the weight side).

- Every call and weight side committed natively has the commitment its Program's IR evaluation gives, leaf for leaf.
- The honest run is accepted.
- A wrong X strip, wrong tile words, a wrong Y unit in the weight side, a call reading another Y than its weight side's
  and an A strip that is not the quantized input are each rejected, each committed by a prover that commits and opens its
  wrong values and recomputes its root.
- Without the delegate the PoUW rows are not evaluable, so the run fails closed.
- Every other PoUW scheme stays refused beside sampled proofs.
"""
