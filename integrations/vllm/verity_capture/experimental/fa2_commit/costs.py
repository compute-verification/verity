"""Proof-side / prover-side cost table for the two layouts (measured on the laptop with a hash-call counter + analytic
SP1 coefficients from the earlier studies).

    PYTHONPATH=. python -m verity_capture.experimental.fa2_commit.costs --out out/gen/r8/fa2-commit

Per opened value: hash evaluations (verifier: leaf + one per path level + root wrapper), authentication bytes (leaf or
chunk payload + 32 B per sibling), replay work (values regenerated by the prover to produce the opening), and [C] SP1
cycles with the coefficients of `docs/vllm-poc/commitment-cost-study-2026-09-17.md` §7 (≈ 800 cycles per 64-B SHA block
through `sha2`, 12.26 cycles per witness byte).  Commit side: SHA-256 calls, SHA blocks, wall time on this host.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import platform
import statistics
import subprocess
import time
from pathlib import Path

import numpy as np

from . import engine as E
from .encoding import Geometry, ValueId
from .fixture import AttentionFixture, archived_geometry_fixture
from .layouts import HierCommitment, HierLayout, PackedCommitment, PackedLayout, ValueOpening, verify_value_opening

LEAF_WORDS = (1, 4, 16, 64)
CHUNK_WORDS = (64, 256, 1024, 4096)
SP1_CYCLES_PER_BLOCK = 800.0     # `sha2` over the precompile (CPERF-2 §7); 240 when the precompile is driven directly
SP1_CYCLES_PER_WITNESS_BYTE = 12.26


def sp1_cycles(op: ValueOpening) -> float:
    blocks = E.sha_blocks(E.LEAF_FRAME_BYTES + len(op.leaf))
    for st in op.stages:
        for s in st.path:
            blocks += 2 if s is not None else 1
    return blocks * SP1_CYCLES_PER_BLOCK + op.auth_bytes() * SP1_CYCLES_PER_WITNESS_BYTE


def sample_ids(layout, fx: AttentionFixture, n: int, seed: int = 0) -> list[ValueId]:  # noqa: ANN001
    rng = np.random.default_rng(seed)
    rows = list(fx.ctx.qrows())
    out = []
    for _ in range(n):
        h = int(rng.integers(fx.geo.NH))
        r = int(rng.choice(rows))
        rl = layout.row_layout(h, r)
        out.append(rl.unrank(int(rng.integers(rl.count))))
    return out


def measure(fx: AttentionFixture, kind: str, size: int, n_open: int) -> dict:
    counter = E.CountingHash()
    if kind == "hier":
        L = HierLayout(fx.ctx, fx.geo, size)
        c = HierCommitment(L, new=counter)
    else:
        L = PackedLayout(fx.ctx, fx.geo, size)
        c = PackedCommitment(L, new=counter)
    t0 = time.perf_counter()
    R = c.commit(fx)
    t_commit = time.perf_counter() - t0
    commit = {"sha_calls": counter.calls, "sha_blocks": counter.blocks, "bytes_hashed": counter.bytes, "wall_s": t_commit,
              "retained_bytes": c.retained_bytes(), "n_words": L.n_words, "n_leaves": (counter.calls if False else None)}
    if kind == "hier":
        commit["n_subtrees"] = sum(len(v) for v in c.subtree_roots.values())
        commit["n_tiles"] = len(L.tiles)
    else:
        commit["n_chunks"] = L.n_chunks
    opens = []
    for vid in sample_ids(L, fx, n_open):
        counter.reset()
        t0 = time.perf_counter()
        op = c.open(fx, vid)
        t_open = time.perf_counter() - t0
        assert verify_value_opening(R, L, op)
        opens.append({"stage": vid.stage, "hash_evals": op.hash_evals(), "auth_bytes": op.auth_bytes(), "leaf_bytes": len(op.leaf),
                      "path_levels": sum(len(st.path) for st in op.stages), "replayed_words": op.replayed_words,
                      "prover_sha_calls": counter.calls, "open_wall_s": t_open, "sp1_cycles_C": sp1_cycles(op)})
    agg = {k: statistics.fmean(o[k] for o in opens) for k in ("hash_evals", "auth_bytes", "leaf_bytes", "path_levels", "replayed_words",
                                                              "prover_sha_calls", "open_wall_s", "sp1_cycles_C")}
    agg["auth_bytes_max"] = max(o["auth_bytes"] for o in opens)
    agg["replayed_words_max"] = max(o["replayed_words"] for o in opens)
    return {"layout": kind, "size_words": size, "commit": commit, "open_mean": agg, "n_opened": len(opens)}


def run(out: Path, instances: Path | None, n_open: int) -> dict:
    fixtures = {"prefill_L0_s0_T1..155": archived_geometry_fixture(instances, layer=0, step=0),
                "decode_L0_s5_T160": archived_geometry_fixture(instances, layer=0, step=5)}
    rows = []
    for name, fx in fixtures.items():
        for w in LEAF_WORDS:
            r = measure(fx, "hier", w, n_open)
            r["fixture"] = name
            rows.append(r)
            print(f"[costs] {name} hier leaf={w}: commit {r['commit']['wall_s']:.2f}s, {r['commit']['sha_calls']} sha; "
                  f"open: {r['open_mean']['hash_evals']:.1f} hashes, {r['open_mean']['auth_bytes']:.0f} B, replay {r['open_mean']['replayed_words']:.0f} words", flush=True)
        for cw in CHUNK_WORDS:
            r = measure(fx, "packed", cw, n_open)
            r["fixture"] = name
            rows.append(r)
            print(f"[costs] {name} packed chunk={cw}: commit {r['commit']['wall_s']:.2f}s, {r['commit']['sha_calls']} sha; "
                  f"open: {r['open_mean']['hash_evals']:.1f} hashes, {r['open_mean']['auth_bytes']:.0f} B, replay {r['open_mean']['replayed_words']:.0f} words", flush=True)
    rev = subprocess.run(["git", "rev-parse", "HEAD"], capture_output=True, text=True, cwd=Path(__file__).resolve().parents[3]).stdout.strip()
    doc = {"schema": "verity/fa2c/costs/v0", "utc": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()), "host": platform.platform(),
           "python": platform.python_version(), "git_head": rev, "fixture_values": "synthetic (archived geometry)",
           "fixture_source": {k: v.source for k, v in fixtures.items()},
           "coefficients": {"sp1_cycles_per_sha_block": SP1_CYCLES_PER_BLOCK, "sp1_cycles_per_witness_byte": SP1_CYCLES_PER_WITNESS_BYTE,
                            "source": "docs/vllm-poc/commitment-cost-study-2026-09-17.md §7 [C]"},
           "rows": rows}
    out.mkdir(parents=True, exist_ok=True)
    (out / "cost_table.json").write_text(json.dumps(doc, indent=1) + "\n")
    (out / "cost_table.md").write_text(render_md(doc))
    return doc


def render_md(doc: dict) -> str:
    lines = [f"# fa2-commit cost table — {doc['utc']} (host {doc['host']}, Python {doc['python']}, HEAD `{doc['git_head'][:9]}`)", "",
             "Values synthetic, geometry = accepted record `B0-cov_b0_b1_c256` layer 0 (`fixture_source` in the JSON).  "
             "Commit columns [M] (laptop, hash-call counter); opening columns [M] mean over the opened sample; SP1 cycles [C] with "
             f"{doc['coefficients']['sp1_cycles_per_sha_block']:.0f} cycles/SHA block and {doc['coefficients']['sp1_cycles_per_witness_byte']} cycles/witness byte "
             "(`commitment-cost-study-2026-09-17.md` §7).  `replay` = values regenerated by the prover to produce one opening.  "
             "Hash counts, bytes, levels and replay words are value-independent (layout arithmetic); `commit wall` includes the fast "
             "numpy producer (`reference.replay_row`, mechanics only) — with the Verity-semantics oracle producer (`oracle.oracle_row`, "
             "7–55 ms per row [M]) the producer dominates: ~1 min per prefill layer, so wall is reported for the numpy producer.", ""]
    for fixture in sorted({r["fixture"] for r in doc["rows"]}):
        rows = [r for r in doc["rows"] if r["fixture"] == fixture]
        n_words = rows[0]["commit"]["n_words"]
        lines += [f"## {fixture} — N = {n_words:,} committed words ({4 * n_words / 1e6:.2f} MB), {rows[0]['n_opened']} openings sampled per row", "",
                  "| layout | leaf / chunk (words) | commit SHA calls | commit SHA blocks | commit wall s | retained B | verifier hashes / opened value | auth bytes (mean / max) | path levels | replay words (mean / max) | SP1 cycles [C] |",
                  "|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|"]
        for r in rows:
            c, o = r["commit"], r["open_mean"]
            lines.append(f"| {r['layout']} | {r['size_words']} | {c['sha_calls']:,} | {c['sha_blocks']:,} | {c['wall_s']:.2f} | {c['retained_bytes']:,} | "
                         f"{o['hash_evals']:.1f} | {o['auth_bytes']:.0f} / {o['auth_bytes_max']} | {o['path_levels']:.1f} | "
                         f"{o['replayed_words']:.0f} / {o['replayed_words_max']} | {o['sp1_cycles_C'] / 1e3:.1f} k |")
        lines.append("")
    return "\n".join(lines)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="out/gen/r8/fa2-commit")
    ap.add_argument("--instances", default="/private/tmp/census/B0-cov_b0_b1_c256/instances.jsonl")
    ap.add_argument("--n-open", type=int, default=24)
    a = ap.parse_args()
    inst = Path(a.instances)
    run(Path(a.out), inst if inst.exists() else None, a.n_open)


if __name__ == "__main__":
    main()
