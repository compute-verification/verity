"""Build or check the norm-scale tap's CUDA op, the torch extension `verity_norm_tap`: vLLM's generic `fused_add_rms_norm_kernel` (the
width-0 template of `csrc/libtorch_stable/layernorm_kernels.cu` at d9105ea80, which the installed `_C.fused_add_rms_norm` launches under
`VLLM_BATCH_INVARIANT=1`; `RMSNormFusedCuda_v2`) with one store added.

    verity-vllm norm-tap-build --vllm-src DIR --build-dir DIR     # DIR/csrc/libtorch_stable/: the pinned sources (ops/pod_norm_tap.sh)
    verity-vllm norm-tap-build --check DIR/verity_norm_tap.so

`tapped_kernel(text)` cuts the generic template out of the pinned file and makes three edits, each on exactly one line: a `Tap`
template parameter, a `float* scale_out` argument, and after the `__syncthreads()` that publishes `s_variance`,
`if constexpr (Tap) { if (threadIdx.x == 0) scale_out[blockIdx.x] = s_variance; }`.  With `Tap = false` the kernel is the pinned
text.  `norm_tap.cu` launches it as the installed op does under batch invariance (grid = rows, block = min(hidden, 1024), width 0,
the current stream) and registers `fused_add_rms_norm` (tap off), `fused_add_rms_norm_scale` (tap on) and `tap_version`.  The flags
are those vLLM builds `_C_stable_libtorch` with (torch's nvcc flags, -O3, no --use_fast_math, so the division is IEEE and `rsqrtf`
is `rsqrt.approx.f32`), for this device's architecture.  `build_info.json` beside the .so records the sources' sha256, the flags,
the architecture, nvcc and torch.
"""
from __future__ import annotations

import hashlib
import json
import os
import subprocess
import time
from dataclasses import dataclass
from pathlib import Path

from verity_vllm.config import UsageError, option

NAME = "verity_norm_tap"
TAP_VERSION = 1
PIN = "d9105ea8001e0a6d77a96327d17515bb5791fb36"
KERNEL_FILE = "csrc/libtorch_stable/layernorm_kernels.cu"
#: the pinned vLLM sources the build reads, by path under the vLLM tree -> sha256
PINNED_SOURCES: dict[str, str] = {
    KERNEL_FILE: "2041b5da8fa2e2868c1ef6133a46d4ae85ffdbc599a8a5da0c5e66cb91c573f6",
    "csrc/libtorch_stable/cub_helpers.h": "91bd3c5f862387c475806a13245f0353369439a4e83962d2798e820314c48c31",
    "csrc/libtorch_stable/type_convert.cuh": "9274a7464c53de92976f6b5a19cc548b315f5d85e68b825515a6ff1fd73be4ca",
}
#: sha256 of the generic template as `generic_block` cuts it from the pinned file
BLOCK_SHA256 = "1f643c51b834c24b822fc5c101847fb241be365a7114f2872259822c2590782d"
BLOCK_START = "/* Generic fused_add_rms_norm_kernel\n"
TAP_STORE = "  if constexpr (Tap) {\n    if (threadIdx.x == 0) {\n      scale_out[blockIdx.x] = s_variance;\n    }\n  }\n"
EDITS = (("template <typename scalar_t, int width, bool HasWeight>\n", "template <typename scalar_t, int width, bool HasWeight, bool Tap>\n"),
         ("    const int64_t residual_stride) {\n", "    const int64_t residual_stride, float* __restrict__ scale_out) {\n"),
         ("  __syncthreads();\n", "  __syncthreads();\n" + TAP_STORE))
HERE = Path(__file__).resolve().parent


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def generic_block(text: str) -> str:
    """The generic `fused_add_rms_norm_kernel` template of the pinned file: its comment through the function's closing brace."""
    if text.count(BLOCK_START) != 1:
        raise ValueError(f"{KERNEL_FILE}: the generic fused_add_rms_norm_kernel comment occurs {text.count(BLOCK_START)} times, not once")
    i = text.index(BLOCK_START)
    return text[i: text.index("\n}\n", i) + 3]


def tapped_kernel(text: str) -> str:
    """The tapped kernel header (`norm_tap_kernel.cuh`) from the pinned file's text: refuses any other text."""
    block = generic_block(text)
    if sha256(block.encode()) != BLOCK_SHA256:
        raise ValueError(f"{KERNEL_FILE}: the generic kernel is not the pinned one (sha256 {sha256(block.encode())}, want {BLOCK_SHA256})")
    for old, new in EDITS:
        if block.count(old) != 1:
            raise ValueError(f"{KERNEL_FILE}: {old.strip()!r} occurs {block.count(old)} times in the generic kernel, not once")
        block = block.replace(old, new)
    return (f"// Generated by verity_vllm.acquire.norm_tap_src.build_ext from vLLM {PIN} {KERNEL_FILE}: the generic\n"
            f"// fused_add_rms_norm_kernel with the norm-scale tap (Tap = true stores s_variance per row).  Do not edit.\n"
            f"#pragma once\n#include <type_traits>\n\nnamespace vllm {{\nnamespace verity_norm_tap {{\n\n{block}\n"
            f"}}  // namespace verity_norm_tap\n}}  // namespace vllm\n")


def pinned_sources(vllm_src: str) -> dict[str, bytes]:
    """The pinned files under `vllm_src`, each checked against its sha256."""
    out = {}
    for rel, want in PINNED_SOURCES.items():
        data = (Path(vllm_src) / rel).read_bytes()
        if sha256(data) != want:
            raise ValueError(f"{vllm_src}/{rel}: sha256 {sha256(data)}, not the pinned {want} (vLLM {PIN})")
        out[rel] = data
    return out


def nvcc_flags() -> list[str]:
    return ["-O3", "-DNDEBUG", "-std=c++17", "--expt-relaxed-constexpr", "--expt-extended-lambda", f"-DVERITY_NORM_TAP_VERSION={TAP_VERSION}"]


def build(vllm_src: str, build_dir: str) -> dict:
    import torch
    from torch.utils.cpp_extension import CUDA_HOME, load

    srcs = pinned_sources(vllm_src)
    out = Path(build_dir)
    out.mkdir(parents=True, exist_ok=True)
    header = tapped_kernel(srcs[KERNEL_FILE].decode())
    (out / "norm_tap_kernel.cuh").write_text(header)
    cu = HERE / "norm_tap.cu"
    cc = torch.cuda.get_device_capability(0)
    nvcc = os.path.join(CUDA_HOME or "", "bin", "nvcc")
    info = {"name": NAME, "tap_version": TAP_VERSION, "vllm": PIN, "sources": {k: sha256(v) for k, v in srcs.items()},
            "launcher": {"file": str(cu), "sha256": sha256(cu.read_bytes())}, "kernel_header_sha256": sha256(header.encode()),
            "nvcc_flags": nvcc_flags(), "arch": f"{cc[0]}.{cc[1]}", "device": torch.cuda.get_device_name(0), "torch": torch.__version__,
            "torch_cuda": torch.version.cuda, "cuda_home": CUDA_HOME,
            "nvcc_version": subprocess.run([nvcc, "--version"], capture_output=True, text=True).stdout.strip().splitlines()[-1:]}
    t0 = time.time()
    load(name=NAME, sources=[str(cu)], extra_cuda_cflags=nvcc_flags(), extra_cflags=["-O3", "-DNDEBUG"],
         extra_include_paths=[str(Path(vllm_src) / "csrc" / "libtorch_stable"), str(out)], build_directory=str(out), verbose=True,
         is_python_module=False, with_cuda=True)
    so = out / f"{NAME}.so"
    info.update(compile_seconds=round(time.time() - t0, 1), so=str(so), so_sha256=sha256(so.read_bytes()))
    (out / "build_info.json").write_text(json.dumps(info, indent=1) + "\n")
    return info


def check(so: str) -> dict:
    """Load a build and check its ops and tap version."""
    import torch

    torch.ops.load_library(so)
    ns = getattr(torch.ops, NAME)
    missing = [op for op in ("fused_add_rms_norm", "fused_add_rms_norm_scale", "tap_version") if not hasattr(ns, op)]
    version = int(ns.tap_version()) if not missing else None
    return {"so": so, "sha256": sha256(Path(so).read_bytes()), "missing_ops": missing, "tap_version": version,
            "ok": not missing and version == TAP_VERSION}


@dataclass(frozen=True, kw_only=True)
class Options:
    vllm_src: str | None = option("--vllm-src", default=None, help=f"a vLLM tree holding the pinned sources ({', '.join(PINNED_SOURCES)})")
    build_dir: str | None = option("--build-dir", default=None, help=f"where the build and {NAME}.so go")
    check: str | None = option("--check", default=None, help="check a built .so (its ops and tap version) instead of building")


def main(a: Options) -> int:
    if a.check:
        r = check(a.check)
        print(("NORM-TAP-OK " if r["ok"] else "NORM-TAP-FAIL ") + json.dumps(r), flush=True)
        return 0 if r["ok"] else 1
    if not (a.vllm_src and a.build_dir):
        raise UsageError("give --vllm-src and --build-dir (build) or --check SO")
    info = build(a.vllm_src, a.build_dir)
    print(f"BUILD-OK {info['so']} {info['so_sha256']} arch={info['arch']} ({info['compile_seconds']} s)", flush=True)
    return 0
