"""Batched SHA-256 as ONE Triton launch per batch of equal-length (padded) messages (EXPERIMENTAL, CMT-1).

Why: the torch-op backend (`torch_sha256.py`) is correct but launch-bound (~1600 elementwise kernels per SHA block; a decode step's
14-level tree needs > 40 000 launches).  This kernel is the same FIPS 180-4 compression, generated by a tiny code generator
(runtime loop over blocks, 64 rounds unrolled), one lane per message, int32 two's-complement lanes exactly like the torch version (arithmetic shifts are
masked into logical ones; adds and left shifts wrap).  Verified against hashlib (`test_triton_sha256.py`).  "Trivial" in the
BRIEF's sense: ~120 lines, no new cryptography, same frames as production.

    digests = sha256_padded_triton(padded)     # padded: uint8 [N, L] with L % 64 == 0 (FIPS padding already applied) -> uint8 [N, 32]
"""
from __future__ import annotations

import torch

from .torch_sha256 import _H032, _K32, pad_messages

_KERNELS: dict[int, object] = {}
BLOCK = 128


def _gen_source() -> str:
    """One kernel for any block count: runtime loop over the message blocks, 64 rounds unrolled inside (int32 lanes)."""
    L = []
    L.append("import triton\nimport triton.language as tl\n\n")
    L.append("@triton.jit\ndef sha256_kernel(msg_ptr, out_ptr, n, WPM, NBLK, BLOCK: tl.constexpr):\n")
    L.append("    pid = tl.program_id(0)\n    offs = pid * BLOCK + tl.arange(0, BLOCK)\n    mask = offs < n\n    base = msg_ptr + offs * WPM\n")
    for i, h in enumerate(_H032):
        L.append(f"    H{i} = tl.full([BLOCK], {h}, tl.int32)\n")

    def shr(x, n):
        return f"(({x} >> {n}) & {(1 << (32 - n)) - 1})"

    def rotr(x, n):
        return f"(({x} << {32 - n}) | {shr(x, n)})"

    L.append("    for blk in range(NBLK):\n")
    for i in range(16):
        L.append(f"        x = tl.load(base + blk * 16 + {i}, mask=mask, other=0)\n")
        L.append(f"        w{i} = ((x & 255) << 24) | ((x & 65280) << 8) | ({shr('x', 8)} & 65280) | {shr('x', 24)}\n")
    L.append("        a = H0\n        b = H1\n        c = H2\n        d = H3\n        e = H4\n        f = H5\n        g = H6\n        h = H7\n")
    for t in range(64):
        if t >= 16:
            w15, w2, w7, w16 = f"w{(t - 15) % 16}", f"w{(t - 2) % 16}", f"w{(t - 7) % 16}", f"w{t % 16}"
            L.append(f"        s0 = {rotr(w15, 7)} ^ {rotr(w15, 18)} ^ {shr(w15, 3)}\n")
            L.append(f"        s1 = {rotr(w2, 17)} ^ {rotr(w2, 19)} ^ {shr(w2, 10)}\n")
            L.append(f"        {w16} = {w16} + s0 + {w7} + s1\n")
        L.append(f"        S1 = {rotr('e', 6)} ^ {rotr('e', 11)} ^ {rotr('e', 25)}\n")
        L.append("        ch = (e & f) ^ ((~e) & g)\n")
        L.append(f"        t1 = h + S1 + ch + {_K32[t]} + w{t % 16}\n")
        L.append(f"        S0 = {rotr('a', 2)} ^ {rotr('a', 13)} ^ {rotr('a', 22)}\n")
        L.append("        maj = (a & b) ^ (a & c) ^ (b & c)\n        t2 = S0 + maj\n")
        L.append("        h = g\n        g = f\n        f = e\n        e = d + t1\n        d = c\n        c = b\n        b = a\n        a = t1 + t2\n")
    L.append("        H0 = H0 + a\n        H1 = H1 + b\n        H2 = H2 + c\n        H3 = H3 + d\n        H4 = H4 + e\n        H5 = H5 + f\n        H6 = H6 + g\n        H7 = H7 + h\n")
    L.append("    ob = out_ptr + offs * 8\n")
    for i in range(8):
        x = f"H{i}"
        L.append(f"    y = (({x} & 255) << 24) | (({x} & 65280) << 8) | ({shr(x, 8)} & 65280) | {shr(x, 24)}\n")
        L.append(f"    tl.store(ob + {i}, y, mask=mask)\n")
    return "".join(L)


def kernel_for(n_blocks: int = 0):
    k = _KERNELS.get(0)
    if k is None:                                   # Triton needs the @jit source in a real file: write the generated module to a cache dir
        import hashlib
        import importlib.util
        import os
        import pathlib
        src = _gen_source()
        d = pathlib.Path(os.environ.get("VERITY_CMT_CACHE", pathlib.Path.home() / ".cache" / "verity_cmt"))
        d.mkdir(parents=True, exist_ok=True)
        path = d / f"triton_sha256_{hashlib.sha256(src.encode()).hexdigest()[:12]}.py"
        if not path.exists():
            path.write_text(src)
        spec = importlib.util.spec_from_file_location(path.stem, path)
        mod = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(mod)
        k = _KERNELS[0] = mod.sha256_kernel
    return k


def sha256_padded_triton(padded: torch.Tensor) -> torch.Tensor:
    """padded uint8 [N, L] (L % 64 == 0, FIPS padding applied) -> digests uint8 [N, 32]; one launch."""
    n, L = padded.shape
    assert L % 64 == 0 and padded.is_cuda
    words = padded.contiguous().view(torch.int32)              # [N, L/4] little-endian words (byte-swapped in the kernel)
    out = torch.empty((n, 8), dtype=torch.int32, device=padded.device)
    if n:
        kernel_for()[(triton_cdiv(n, BLOCK),)](words, out, n, L // 4, L // 64, BLOCK=BLOCK)
    return out.view(torch.uint8)


def triton_cdiv(a: int, b: int) -> int:
    return -(-a // b)


def sha256_messages_triton(msgs: torch.Tensor) -> torch.Tensor:
    return sha256_padded_triton(pad_messages(msgs, msgs.shape[1]))


# ----------------------------------------------------------------------------------------------------------------------------------
# Frame kernels: build the (2-block) padded frame IN REGISTERS from constant bytes + source words read straight from the level / stream
# tensors -- no frame buffer, no per-level copies.  One launch per tree level (plus one 1-lane launch for an odd lift node), one launch
# for all leaves of a step.  Same digests as the buffer path (test_triton_sha256.py compares full trees against the eager backend).
# ----------------------------------------------------------------------------------------------------------------------------------
import struct as _struct

from .torch_sha256 import LIFT_PREFIX, NODE_PREFIX, POS_LEAF_TAG, _U64_32

_FRAME_KERNELS: dict[str, object] = {}


def _layout(prefix: bytes, parts: list[tuple[str, int]], mid: dict[int, bytes] | None = None) -> tuple[list, int]:
    """Byte layout of a padded 2-block frame: prefix consts, then variable ranges ('A'/'B', nbytes) optionally separated by const bytes."""
    lay: list = [("c", b) for b in prefix]
    for idx, (src, nb) in enumerate(parts):
        lay += [("v", src, i) for i in range(nb)]
        if mid and idx in mid:
            lay += [("c", b) for b in mid[idx]]
    msg_len = len(lay)
    assert msg_len + 9 <= 128, msg_len
    lay.append(("c", 0x80))
    lay += [("c", 0)] * (120 - len(lay))
    lay += [("c", b) for b in _struct.pack(">Q", msg_len * 8)]
    assert len(lay) == 128
    return lay, msg_len


def _gen_frame_source(lay: list, a_words: int, b_words: int) -> str:
    L = ["import triton\nimport triton.language as tl\n\n"]
    L.append("@triton.jit\ndef frame_kernel(a_ptr, b_ptr, out_ptr, n, A_STRIDE, A_OFF, B_STRIDE, B_OFF, BLOCK: tl.constexpr):\n")
    L.append("    pid = tl.program_id(0)\n    offs = pid * BLOCK + tl.arange(0, BLOCK)\n    mask = offs < n\n")

    def shr(x, n):
        return f"(({x} >> {n}) & {(1 << (32 - n)) - 1})"

    def rotr(x, n):
        return f"(({x} << {32 - n}) | {shr(x, n)})"

    def bswap(x):
        return f"((({x} & 255) << 24) | (({x} & 65280) << 8) | ({shr(x, 8)} & 65280) | {shr(x, 24)})"

    for k in range(a_words):
        L.append(f"    x = tl.load(a_ptr + offs * A_STRIDE + A_OFF + {k}, mask=mask, other=0)\n    A{k} = {bswap('x')}\n")
    for k in range(b_words):
        L.append(f"    x = tl.load(b_ptr + offs * B_STRIDE + B_OFF + {k}, mask=mask, other=0)\n    B{k} = {bswap('x')}\n")
    for j in range(32):
        const = 0
        terms = []
        for p in range(4):
            d = lay[4 * j + p]
            sh = 8 * (3 - p)
            if d[0] == "c":
                const |= d[1] << sh
            else:
                _, src, i = d
                terms.append(f"((({src}{i // 4} >> {8 * (3 - i % 4)}) & 255) << {sh})")
        if const >= 1 << 31:
            const -= 1 << 32
        expr = " | ".join([str(const)] + terms) if terms else str(const)
        L.append(f"    m{j} = {expr}\n")
    for i, h in enumerate(_H032):
        L.append(f"    H{i} = tl.full([BLOCK], {h}, tl.int32)\n")
    for blk in range(2):
        L.append("    a = H0\n    b = H1\n    c = H2\n    d = H3\n    e = H4\n    f = H5\n    g = H6\n    h = H7\n")
        w = lambda t: f"m{blk * 16 + t % 16}"  # noqa: E731
        for t in range(64):
            if t >= 16:
                L.append(f"    s0 = {rotr(w(t - 15), 7)} ^ {rotr(w(t - 15), 18)} ^ {shr(w(t - 15), 3)}\n")
                L.append(f"    s1 = {rotr(w(t - 2), 17)} ^ {rotr(w(t - 2), 19)} ^ {shr(w(t - 2), 10)}\n")
                L.append(f"    {w(t)} = {w(t)} + s0 + {w(t - 7)} + s1\n")
            L.append(f"    S1 = {rotr('e', 6)} ^ {rotr('e', 11)} ^ {rotr('e', 25)}\n    ch = (e & f) ^ ((~e) & g)\n")
            L.append(f"    t1 = h + S1 + ch + {_K32[t]} + {w(t)}\n")
            L.append(f"    S0 = {rotr('a', 2)} ^ {rotr('a', 13)} ^ {rotr('a', 22)}\n    maj = (a & b) ^ (a & c) ^ (b & c)\n    t2 = S0 + maj\n")
            L.append("    h = g\n    g = f\n    f = e\n    e = d + t1\n    d = c\n    c = b\n    b = a\n    a = t1 + t2\n")
        L.append("    H0 = H0 + a\n    H1 = H1 + b\n    H2 = H2 + c\n    H3 = H3 + d\n    H4 = H4 + e\n    H5 = H5 + f\n    H6 = H6 + g\n    H7 = H7 + h\n")
    L.append("    ob = out_ptr + offs * 8\n")
    for i in range(8):
        L.append(f"    y = {bswap(f'H{i}')}\n    tl.store(ob + {i}, y, mask=mask)\n")
    return "".join(L)


def _load_kernel(name: str, src: str):
    import hashlib
    import importlib.util
    import os
    import pathlib
    d = pathlib.Path(os.environ.get("VERITY_CMT_CACHE", pathlib.Path.home() / ".cache" / "verity_cmt"))
    d.mkdir(parents=True, exist_ok=True)
    path = d / f"{name}_{hashlib.sha256(src.encode()).hexdigest()[:12]}.py"
    if not path.exists():
        path.write_text(src)
    spec = importlib.util.spec_from_file_location(path.stem, path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod.frame_kernel


def frame_kernel(kind: str, leaf_bytes: int = 64):
    key = f"{kind}{leaf_bytes if kind == 'leaf' else ''}"
    k = _FRAME_KERNELS.get(key)
    if k is None:
        if kind == "leaf":
            assert leaf_bytes % 4 == 0 and 26 + leaf_bytes + 9 <= 128
            lay, _ = _layout(POS_LEAF_TAG + _struct.pack(">Q", leaf_bytes), [("A", leaf_bytes)])
            src = _gen_frame_source(lay, leaf_bytes // 4, 0)
        elif kind == "node":
            lay, _ = _layout(NODE_PREFIX, [("A", 32), ("B", 32)], {0: _U64_32})
            src = _gen_frame_source(lay, 8, 8)
        elif kind == "lift":
            lay, _ = _layout(LIFT_PREFIX, [("A", 32)])
            src = _gen_frame_source(lay, 8, 0)
        else:
            raise ValueError(kind)
        k = _FRAME_KERNELS[key] = _load_kernel(f"triton_frame_{key}", src)
    return k


def leaf_digests_direct(stream: torch.Tensor, leaf_bytes: int = 64) -> torch.Tensor:
    """uint8 stream (numel % leaf_bytes == 0, CUDA) -> pos_leaf digests uint8 [N, 32]; ONE launch, frame built in registers."""
    n = stream.numel() // leaf_bytes
    words = stream.contiguous().view(torch.int32)
    out = torch.empty((n, 8), dtype=torch.int32, device=stream.device)
    if n:
        frame_kernel("leaf", leaf_bytes)[(triton_cdiv(n, BLOCK),)](words, words, out, n, leaf_bytes // 4, 0, 0, 0, BLOCK=BLOCK)
    return out.view(torch.uint8)


def fold_level_direct(level: torch.Tensor) -> torch.Tensor:
    """One production pairing/lift level from digests uint8 [m, 32]: one launch for the pairs (+ one 1-lane launch for an odd lift)."""
    m = level.shape[0]
    pairs, odd = m // 2, m % 2
    words = level.contiguous().view(torch.int32)              # [m, 8]
    out = torch.empty((pairs + odd, 8), dtype=torch.int32, device=level.device)
    if pairs:
        frame_kernel("node")[(triton_cdiv(pairs, BLOCK),)](words, words, out, pairs, 16, 0, 16, 8, BLOCK=BLOCK)
    if odd:
        frame_kernel("lift")[(1,)](words, words, out[pairs:], 1, 0, (m - 1) * 8, 0, 0, BLOCK=BLOCK)
    return out.view(torch.uint8)
