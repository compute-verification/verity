"""verity_vllm/properties/holdout.py — PROTECTED (gate G7).  Orchestrator-side holdout workload generator and assembler.

    uv run verity-vllm holdout --generate --case B0 --model HuggingFaceTB/SmolLM2-135M --vocab 49152 --n 3 --seed 20260917 --out out/gen/holdouts/B0
    uv run verity-vllm holdout --assemble RUN_DIR/holdouts --out RUN_DIR/holdouts.json

Once an adapter is done, the ORCHESTRATOR (never the adapter's author) generates fresh workloads — new token values, prompt/decode
lengths that straddle kernel-specialization boundaries (the FA2 kBlockN 64/128 rows, the persistent-matmul tile edges),
new request ids and, for batched workloads, new batch arrangements — and reruns the full driver on them.  No adapter that encodes a
development trace (`if rows == 32`, fixture-specific mappings, output-specific hacks) survives this.
Holdouts carry NO expected tokens: the clean control run of the sealed driver is the only reference.

`--assemble` collects `<dir>/<holdout>/gates.json` files (written by `run_config.py` for each holdout run) into the
`holdouts.json` that gate G7 reads: pass iff ≥ 1 holdout and every holdout's G1..G6 pass.
"""
from __future__ import annotations

import datetime as dt
import hashlib
import json
import random
import sys
import uuid
from dataclasses import dataclass
from pathlib import Path
from typing import Any

from verity_vllm.config import VLLM, WORKLOAD_SCHEMA, UsageError, option
from verity_vllm.check.gates import HOLDOUT_GATES
from verity_vllm.properties.record import seal

#: prompt lengths that straddle the kernel-specialization boundaries of the pinned profile (FA2 kBlockN 64 / 128, the
#: persistent matmul's 64/128-row tiles) plus a short and a long one; the generator draws from this pool.
LENGTH_POOL = (7, 31, 33, 63, 64, 65, 96, 127, 128, 129, 200)
DECODE_POOL = (5, 9, 16, 24)


def make_workload(*, case: str, model: str, vocab: int, seed: int, n_requests: int = 1, lengths: list[int] | None = None,
                  max_tokens: list[int] | None = None, tokenizer_revision: str | None = None, sampling: dict | None = None,
                  reserve_low: int = 100, reserve_high: int = 100) -> dict[str, Any]:
    rng = random.Random(seed)
    lo, hi = reserve_low, max(reserve_low + 1, vocab - reserve_high)     # keep away from special / added tokens
    reqs = []
    for i in range(n_requests):
        L = lengths[i] if lengths and i < len(lengths) else rng.choice(LENGTH_POOL)
        M = max_tokens[i] if max_tokens and i < len(max_tokens) else rng.choice(DECODE_POOL)
        rid = str(uuid.uuid5(uuid.NAMESPACE_URL, f"verity-holdout/{case}/{seed}/{i}"))
        reqs.append({"request_id": rid, "prompt_token_ids": [rng.randrange(lo, hi) for _ in range(L)], "max_tokens": int(M)})
    greedy = sampling or {"temperature": 0.0, "top_p": 1.0, "top_k": 0}
    doc = {"schema": WORKLOAD_SCHEMA, "model": model, "case": case, "engine": {"revision": tokenizer_revision, "vllm": VLLM, "args": {}},
           "seed": seed,
           "variants": {"greedy": greedy}, "seeds": [seed],
           "note": f"HOLDOUT generated by verity_vllm.properties.holdout (orchestrator seed {seed}); no accepted tokens by design — the sealed driver's clean control run is the reference",
           "prompt_lengths": [len(r["prompt_token_ids"]) for r in reqs], "requests": reqs,
           "generated_utc": dt.datetime.now(dt.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")}
    doc["sha256"] = hashlib.sha256(json.dumps({k: v for k, v in doc.items() if k != "generated_utc"}, sort_keys=True).encode()).hexdigest()
    return doc


def generate(out_dir: Path, *, case: str, model: str, vocab: int, n: int, seed: int, n_requests: int = 1,
             tokenizer_revision: str | None = None) -> list[Path]:
    out_dir.mkdir(parents=True, exist_ok=True)
    paths = []
    rng = random.Random(seed ^ 0x5EED)
    for k in range(n):
        s = rng.randrange(1, 2**31)
        doc = make_workload(case=case, model=model, vocab=vocab, seed=s, n_requests=n_requests, tokenizer_revision=tokenizer_revision)
        p = out_dir / f"holdout_{case}_{k}_{s}.json"
        p.write_text(json.dumps(doc, indent=1) + "\n")
        paths.append(p)
    return paths


def assemble(holdouts_dir: Path) -> dict[str, Any]:
    out: dict[str, Any] = {"schema": "verity-gen/holdouts/v1", "status": "fail", "holdouts": []}
    for d in sorted(p for p in holdouts_dir.iterdir() if p.is_dir()):
        g = d / "gates.json"
        ent: dict[str, Any] = {"name": d.name, "run_dir": str(d), "workload": None, "gates": {}}
        wl = next(iter(d.glob("*.json")), None)
        if (d / "workload.json").exists():
            ent["workload"] = str(d / "workload.json")
        elif wl is not None:
            ent["workload"] = None
        if not g.exists():
            ent["status"] = "missing gates.json"
        else:
            doc = json.loads(g.read_text())
            gates = doc.get("gates", doc)
            if isinstance(gates, list):
                gates = {x["id"]: x for x in gates}
            ent["gates"] = {k: (v.get("status") if isinstance(v, dict) else v) for k, v in gates.items() if k in HOLDOUT_GATES}
            ent["status"] = "pass" if ent["gates"] and all(v == "pass" for v in ent["gates"].values()) and len(ent["gates"]) == len(HOLDOUT_GATES) else "fail"
        out["holdouts"].append(ent)
    out["n"] = len(out["holdouts"])
    out["status"] = "pass" if out["holdouts"] and all(h["status"] == "pass" for h in out["holdouts"]) else "fail"
    return seal(out, out["status"] == "pass")


@dataclass(frozen=True, kw_only=True)
class Options:
    generate: bool = option("--generate", default=False, action="store_true")
    assemble: str | None = option("--assemble", default=None, metavar="DIR")
    case: str | None = option("--case", default=None)
    model: str | None = option("--model", default=None)
    vocab: int | None = option("--vocab", type=int, default=None)
    tokenizer_revision: str | None = option("--tokenizer-revision", default=None)
    n: int = option("--n", type=int, default=3)
    n_requests: int = option("--n-requests", type=int, default=1)
    seed: int | None = option("--seed", type=int, default=None, help="orchestrator seed (default: from the clock)")
    out: str = option("--out")


def main(a: Options) -> int:
    if a.assemble:
        rep = assemble(Path(a.assemble))
        Path(a.out).write_text(json.dumps(rep, indent=1) + "\n")
        print(f"[holdout] {rep['status']}: {rep['n']} holdouts " + ", ".join(f"{h['name']}={h['status']}" for h in rep["holdouts"]), file=sys.stderr)
        return 0 if rep["status"] == "pass" else 1
    if a.generate:
        if not (a.case and a.model and a.vocab):
            raise UsageError("--generate needs --case, --model, --vocab")
        seed = a.seed if a.seed is not None else int(dt.datetime.now().timestamp()) % (2**31)
        paths = generate(Path(a.out), case=a.case, model=a.model, vocab=a.vocab, n=a.n, seed=seed, n_requests=a.n_requests,
                         tokenizer_revision=a.tokenizer_revision)
        for p in paths:
            d = json.loads(p.read_text())
            print(f"{p}  lengths={d['prompt_lengths']} max_tokens={[r['max_tokens'] for r in d['requests']]}")
        print(f"[holdout] seed {seed}: {len(paths)} workloads", file=sys.stderr)
        return 0
    raise UsageError("one of --generate / --assemble")
    return 2
