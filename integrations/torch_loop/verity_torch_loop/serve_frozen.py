"""The frozen H200 shape's decode step (`frozen.FrozenStep`), one window per template, written for the audit from its records
alone, as `serve` writes the MLP's.

    python -m verity_torch_loop.serve_frozen --out DIR [--law L] [--cap N] [--cap-of TAG=N ...] [--layers 1] [--position 7] \\
        [--prompt TEXT] [--tags s8-width,s8-mlp,bf16-dot] [--keep N] [--seed S] [--workers N] [--run-id ID] [--tamper] [--small]
    python -m verity_torch_loop.serve_frozen --circuit-only [the same shape and --run-id]

The first runs the step, commits every unit and writes each template's window (``circuit.json``, the registration under core's
``one_stage.registration``, the value files) to ``DIR/<tag>``. It prints, per tag, the circuit record's SHA-512, the run root,
the population and the members, beside the generated bytes, the sampled units whose outputs are not their Definition's (none
unless ``--tamper``) and the seconds each stage took. The second prints each tag's circuit SHA-512 alone, from the shape and
no value: the circuits the verifier registers before the loop runs. ``--small``: a tiny shape of the same code, for tests."""
from __future__ import annotations

import argparse
import hashlib
import json
import time
from pathlib import Path

from verity.core.protocols.sampled_proofs.one_stage import draw as D, registration as R
from verity.ml.windows import interface as IF

from . import frozen as F

PROMPT = "Hello, w"
SMALL = F.Shape(width=128, heads=2, head_dim=64, mlp=256, vocab=256, context=32, layers=2)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--out")
    ap.add_argument("--circuit-only", action="store_true")
    ap.add_argument("--law", default="subset:64")
    ap.add_argument("--cap", type=int, default=16384, help="units a member at most")
    ap.add_argument("--cap-of", action="append", default=[], metavar="TAG=N",
                    help="a tag's own cap: C-Flock refuses a member past m = log2(blocks) + k_log = 35")
    ap.add_argument("--layers", type=int, default=1)
    ap.add_argument("--position", type=int, default=len(PROMPT) - 1)
    ap.add_argument("--prompt", default=PROMPT)
    ap.add_argument("--tags", default=",".join(F.TAGS))
    ap.add_argument("--keep", type=int, help="record only the first N units of each op (a smoke run at the shape's K)")
    ap.add_argument("--seed", type=int, default=0)
    ap.add_argument("--workers", type=int, default=1, help="processes committing the rows (`Window.close`)")
    ap.add_argument("--run-id", default="", help="the run's name, which every window's root binds (`FrozenStep.run_root`)")
    ap.add_argument("--tamper", action="store_true")
    ap.add_argument("--small", action="store_true", help="a tiny shape of the same code (tests)")
    a = ap.parse_args(argv)
    if bool(a.out) == a.circuit_only:
        ap.error("--out DIR, or --circuit-only")
    shape, law, tags = SMALL if a.small else F.FROZEN, D.parse_law(a.law), tuple(a.tags.split(","))
    caps = {tag: int(n) for tag, n in (c.split("=", 1) for c in a.cap_of)}
    seconds, t = {}, time.perf_counter()
    model = F.Model(shape, a.layers, a.seed) if not a.circuit_only else None
    step = F.FrozenStep(model or _Shapeless(shape, a.layers, a.seed), a.prompt.encode(), a.position, tags, a.tamper, a.keep,
                        a.run_id)
    if a.circuit_only:
        print(json.dumps({tag: hashlib.sha512(IF.circuit_bytes(IF.Window(step.circuit(tag), step.run_root(tag), law, caps.get(tag, a.cap))
                                                                .circuit_record())).hexdigest() for tag in tags}))
        return 0
    seconds["weights"], t = time.perf_counter() - t, time.perf_counter()
    wins = step.windows(law, a.cap, caps)
    seconds["serve"] = time.perf_counter() - t
    out = {"generated": bytes(step.generated).hex(), "checked": step.checked, "mismatched": step.mismatched, "windows": {}}
    for tag, win in wins.items():
        t = time.perf_counter()
        committed = win.close(workers=a.workers)
        seconds[f"commit:{tag}"], t = time.perf_counter() - t, time.perf_counter()
        d = Path(a.out) / tag
        win.write(committed, d, {"loop": F.NAME, "tag": tag}, registrar=R)
        seconds[f"write:{tag}"] = time.perf_counter() - t
        rec = json.loads((d / "registration.json").read_text())
        out["windows"][tag] = {"circuit": rec["window"]["circuit"], "run": step.run_root(tag), "template": step.templates[tag].id,
                               "population": win.window.population, "members": len(win.window.members),
                               "registration": R.digest(rec), "out": str(d)}
        del committed
    out["seconds"] = {k: round(v, 2) for k, v in seconds.items()}
    print(json.dumps(out))
    return 0


class _Shapeless:
    """A model's shape, layer count and seed without its weights: all the circuit and the run roots read."""

    def __init__(self, shape: F.Shape, layers: int, seed: int) -> None:
        self.shape, self.seed, self.layers = shape, seed, [None] * layers


if __name__ == "__main__":
    raise SystemExit(main())
