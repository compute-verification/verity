"""The certifier's `arith_encode` vectors (`verity/core/protocols/certifier/tests/fixtures/arith_encode_vectors.json`) are
what `code.py`, advice v1 and `code_v1` code now: regenerated by `arith_vectors.py --steps`, they are the committed file,
so the certifier's difftest can't drift from the coder it holds the circuit to."""

from __future__ import annotations

import importlib.util
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parents[1]


def _load(name: str):
    key = f"enc_{name}"
    if key not in sys.modules:
        spec = importlib.util.spec_from_file_location(key, HERE / f"{name}.py")
        sys.modules[key] = mod = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(mod)
    return sys.modules[key]


AV = _load("arith_vectors")


def test_the_certifiers_vectors_are_the_coders():
    streams = [{"source": name, **make()} for name, make in AV.sources((), True, (128001,), 600)]
    got = json.loads(json.dumps({"K": AV.K, "streams": streams}))
    assert got == json.loads(AV.FIXTURE.read_text()), \
        "regenerate: python3 benchmarks/network_e2e/encodings/arith_vectors.py --steps --fixture " + str(AV.FIXTURE)
    tags = {sym[0] for s in streams for win in s["windows"] for sym in win["symbols"]}
    assert tags == {0, 1}
    assert all(AV.check(s, circuit=False)["reference_mismatches"] == 0 for s in streams)
