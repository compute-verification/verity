#!/usr/bin/env python3
"""Exact rank-metric Steiner lengths of the peeled low-rank P-noise prefix targets over F_2 (RS-D2F round 2, CMP-13).

Serve (P + U W^T)(V + F) with stride-L prefix commitments. At one (U-bit, F-bit) pair with W fixed, prefix t of cell
(i, l) projects to M_t placed in cell (i, l), with M_t = [W_1^T ... W_t^T 0] (rows a, columns k) and W read mod 2.
This takes a set of cells (rows (i, a), columns (k, l)) and finds the exact length of the shortest Steiner tree
spanning 0 and every target, by Dreyfus-Wagner on the Cayley graph of F_2^{m x n} generated by the rank-1 matrices
(its graph metric is the rank metric). It compares that length with the spider (each cell's prefix chain, cost
sum_t rank W_t a cell) and with Theorem 1's bound (a column map Q that sends the chain to a direct sum, maximized over
coordinate restrictions of the U index).

W modes: full (each block of rank min(r, L) mod 2), uniform ({0, 1} entries), ones (W = J, i.e. W in {+-1} read mod 2).

Usage: peel_cell.py R L S CELLS MODE TRIALS SEED
  CELLS: one (one cell), row2 (two cells sharing rows), col2 (two cells sharing columns), grid (2 x 2 cells).
Prints one JSON line per instance and a summary line.
"""

import itertools
import json
import sys

import numpy as np

CELLS = {"one": [(0, 0)], "row2": [(0, 0), (0, 1)], "col2": [(0, 0), (1, 0)], "grid": [(0, 0), (0, 1), (1, 0), (1, 1)]}
BIG = 10000


def rank2(a):
    a = np.array(a, dtype=np.uint8) % 2
    rows, cols = a.shape
    rk = 0
    for c in range(cols):
        piv = next((i for i in range(rk, rows) if a[i, c]), None)
        if piv is None:
            continue
        a[[rk, piv]] = a[[piv, rk]]
        for i in range(rows):
            if i != rk and a[i, c]:
                a[i] ^= a[rk]
        rk += 1
    return rk


def colspace_basis(a):
    """Reduced basis (as rows) of the column space of a over F_2."""
    return reduced_rows(np.array(a, dtype=np.uint8).T % 2)


def reduced_rows(a):
    a = a.copy()
    rows, cols = a.shape
    rk = 0
    for c in range(cols):
        piv = next((i for i in range(rk, rows) if a[i, c]), None)
        if piv is None:
            continue
        a[[rk, piv]] = a[[piv, rk]]
        for i in range(rows):
            if i != rk and a[i, c]:
                a[i] ^= a[rk]
        rk += 1
    return a[:rk]


def intersect_dim(b1, b2):
    if len(b1) == 0 or len(b2) == 0:
        return 0
    return len(b1) + len(b2) - rank2(np.vstack([b1, b2]))


def thm1_bound(w, r, L, S):
    """Theorem 1's per-cell bound with a singular column map: sum_{t<S} dim(col W_t^T cap col W_{t+1}^T) + rank W_S,
    maximized over coordinate restrictions A of the U index (rows a)."""
    best = 0
    for size in range(1, r + 1):
        for A in itertools.combinations(range(r), size):
            blocks = [w[t * L:(t + 1) * L][:, list(A)] for t in range(S)]
            bases = [colspace_basis(b.T) for b in blocks]  # column space of W_t^T = row space of W_t
            val = sum(intersect_dim(bases[t], bases[t + 1]) for t in range(S - 1)) + len(bases[S - 1])
            best = max(best, val)
    return best


def common_subset(w, r, L, S):
    """For r > L: whether one L-subset A of [r] has W_t[:, A] invertible mod 2 for every block t (Theorem 1's
    hypothesis there); for r <= L, whether every block has full column rank r."""
    if r <= L:
        return all(rank2(w[t * L:(t + 1) * L]) == r for t in range(S))
    return any(all(rank2(w[t * L:(t + 1) * L][:, list(A)]) == L for t in range(S))
               for A in itertools.combinations(range(r), L))


def draw_w(r, L, S, mode, rng):
    s = S * L
    if mode == "ones":
        return np.ones((s, r), dtype=np.uint8)
    if mode == "uniform":
        return rng.integers(0, 2, size=(s, r)).astype(np.uint8)
    blocks = []
    for _ in range(S):
        while True:
            b = rng.integers(0, 2, size=(L, r)).astype(np.uint8)
            if rank2(b) == min(r, L):
                blocks.append(b)
                break
    return np.vstack(blocks)


def targets_of(w, r, L, S, cells):
    s = S * L
    ni = 1 + max(c[0] for c in cells)
    nl = 1 + max(c[1] for c in cells)
    m, n = ni * r, nl * s
    out = []
    for (ii, ll) in cells:
        for t in range(1, S + 1):
            code = 0
            for a in range(r):
                for k in range(t * L):
                    if w[k, a]:
                        code |= 1 << ((ii * r + a) * n + ll * s + k)
            out.append(code)
    return m, n, out


def generators(m, n):
    gens = set()
    for c in range(1, 1 << m):
        for d in range(1, 1 << n):
            code = 0
            for row in range(m):
                if (c >> row) & 1:
                    code |= d << (row * n)
            gens.add(code)
    return np.array(sorted(gens), dtype=np.int64)


def relax(f, gens, chunk=2048):
    """g(v) = min_u f(u) + rank(v - u), by Dial's algorithm on the unit-weight Cayley graph (XOR neighbours)."""
    g = f.copy()
    d = int(g.min())
    while True:
        frontier = np.nonzero(g == d)[0]
        if frontier.size == 0:
            if not np.any((g > d) & (g < BIG)):
                break
            d += 1
            continue
        for lo in range(0, frontier.size, chunk):
            nbrs = (frontier[lo:lo + chunk, None] ^ gens[None, :]).ravel()
            nbrs = nbrs[g[nbrs] > d + 1]
            g[nbrs] = d + 1
        d += 1
    return g


def steiner(targets, size, gens):
    k = len(targets)
    dp = {}
    idx = np.arange(size, dtype=np.int64)
    for i, t in enumerate(targets):
        f = np.full(size, BIG, dtype=np.int16)
        f[t] = 0
        dp[1 << i] = relax(f, gens)
    full = (1 << k) - 1
    for mask in sorted(range(1, full + 1), key=lambda x: bin(x).count("1")):
        if mask in dp:
            continue
        low = mask & -mask
        best = None
        sub = (mask - 1) & mask
        while sub:
            if sub & low:
                cand = dp[sub] + dp[mask ^ sub]
                best = cand if best is None else np.minimum(best, cand)
            sub = (sub - 1) & mask
        dp[mask] = relax(np.minimum(best, BIG).astype(np.int16), gens)
    del idx
    return int(dp[full][0])


def main():
    r, L, S = (int(x) for x in sys.argv[1:4])
    cells_name, mode = sys.argv[4], sys.argv[5]
    trials, seed = int(sys.argv[6]), int(sys.argv[7])
    cells = CELLS[cells_name]
    rng = np.random.default_rng(seed)
    w0 = draw_w(r, L, S, "ones", rng)
    m, n, _ = targets_of(w0, r, L, S, cells)
    if m * n > 20:
        raise SystemExit(f"matrix space {m}x{n} too large")
    gens = generators(m, n)
    size = 1 << (m * n)
    results = []
    for _ in range(trials):
        w = draw_w(r, L, S, mode, rng)
        _, _, codes = targets_of(w, r, L, S, cells)
        uniq = sorted(set(c for c in codes if c != 0))
        st = steiner(uniq, size, gens) if uniq else 0
        block_ranks = [rank2(w[t * L:(t + 1) * L]) for t in range(S)]
        spider = len(cells) * sum(block_ranks)
        bound = len(cells) * thm1_bound(w, r, L, S)
        rec = {"r": r, "L": L, "S": S, "cells": cells_name, "mode": mode, "m": m, "n": n, "steiner": st,
               "spider": spider, "thm1_bound": bound, "floor": len(cells) * S * min(r, L),
               "thm1_hyp": common_subset(w, r, L, S), "block_ranks": block_ranks, "W": w.tolist()}
        results.append(rec)
        print(json.dumps(rec), flush=True)
    print(json.dumps({"summary": True, "r": r, "L": L, "S": S, "cells": cells_name, "mode": mode, "trials": trials,
                      "floor": len(cells) * S * min(r, L),
                      "steiner_min": min(x["steiner"] for x in results),
                      "steiner_eq_spider": sum(1 for x in results if x["steiner"] == x["spider"]),
                      "steiner_below_spider": sum(1 for x in results if x["steiner"] < x["spider"]),
                      "thm1_hyp": sum(1 for x in results if x["thm1_hyp"]),
                      "steiner_eq_floor": sum(1 for x in results if x["steiner"] == x["floor"]),
                      "bound_le_steiner": sum(1 for x in results if x["thm1_bound"] <= x["steiner"]),
                      "bound_eq_steiner": sum(1 for x in results if x["thm1_bound"] == x["steiner"])}), flush=True)


if __name__ == "__main__":
    main()
