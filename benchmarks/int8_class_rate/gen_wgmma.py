"""Writes wgmma_i8.cuh: wgmma m64n256k32 into s32 accumulators, one wrapper per operand type pair (s8·s8, u8·u8, s8·u8)."""
from pathlib import Path

N = 256
REGS = N // 2
PAIRS = {"s8s8": ("s8", "s8"), "u8u8": ("u8", "u8"), "s8u8": ("s8", "u8")}

out = ["// generated by gen_wgmma.py", "#pragma once", "#include <cstdint>", ""]
for name, (a, b) in PAIRS.items():
    regs = ",".join(f"%{i}" for i in range(REGS))
    cons = ", ".join(f'"+r"(d[{i}])' for i in range(REGS))
    out += [
        f"__device__ __forceinline__ void wgmma_{name}_m64n{N}k32(uint32_t* d, uint64_t da, uint64_t db) {{",
        "  asm volatile(",
        f'    "{{\\n.reg .pred p;\\nsetp.ne.b32 p, %{REGS + 2}, 0;\\n"',
        f'    "wgmma.mma_async.sync.aligned.m64n{N}k32.s32.{a}.{b} {{{regs}}}, %{REGS}, %{REGS + 1}, p;\\n}}\\n"',
        f"    : {cons}",
        '    : "l"(da), "l"(db), "r"(1));',
        "}",
        "",
    ]
Path(__file__).with_name("wgmma_i8.cuh").write_text("\n".join(out))
