"""Sequence slots and the MQA KV cache of the step driver for the frozen H200 decoder (CMP-105), and a stand-in for the per-slot
commit call (CMP-95 item 3) until kernels' (HASH-13) lands.

The frozen shape decodes one position a step per sequence: a request is exactly ``prompt`` bytes, its slot runs positions
``0 .. steps - 1`` (``steps = prompt + generate - 1 <= ctx``), the input at position p is prompt byte p while p < prompt and
the previous step's output after, and the output at position p >= prompt - 1 is generated byte p - (prompt - 1).
:class:`SlotKV` holds ``slots`` fixed sequence slots and, for each, one KV head of ``head_dim`` per layer and position (MQA).

A step, as `driver.Driver.serve` runs it (through `driver.Driver.step_slots`)::

    plan = kv.begin()                         # admit into the lowest free slots, FIFO; plan.slots ascending
    for layer in range(shape.layers):
        kv.write(layer, k, v, rows=(lo, hi))  # this step's K and V rows, [hi - lo, head_dim] bf16, a micro-batch of the
                                              # plan's rows at a time (all of them by default)
        k_all, v_all, mask = kv.read(layer)   # [n, ctx, head_dim]; mask[i, j] is j <= plan.positions[i]
    ...                                       # the step's tables committed, a row a slot keyed (slot, position)
    finished = kv.end(tokens, base=base)      # each slot's output byte; frees the slots whose last position this was

The driver's table-major commit holds the KV rows as the ``wk`` and ``wv`` tables' rows, which replay reads
(`units.Replayer.kv`). For the
per-slot subtree (CMP-95 item 3), ``rows()`` gives the rows written this step per slot, the commit call lays each slot's
subtree out with the KV rows at ``[base, base + R)``, and ``end`` takes that base.

Exactness: rows are stored and returned as the bits the step computed. ``write`` refuses any dtype but bf16 rather than
convert, a slot's rows are zeroed when a request is admitted to it, and ``rows`` and ``end`` refuse a step in which some
layer wasn't written. A row's words are its bf16 values' bits as int16, little-endian in the commitment.

Rows for the commitment (``row_words`` words a row, default 1: one row per unit output under the 16-bit rule): slot i's KV
rows at a step are ``R = layers * 2 * head_dim / row_words`` rows in the order (layer, K then V, the head's words), so the K
row of layer l is rows ``[(2 l) * head_dim / row_words, (2 l + 1) * head_dim / row_words)`` after the step's ``base``.
:meth:`SlotKV.refs` turns (sequence, layer, position) into the (step, slot, index) of every K and V row the attention at
that position reads, which is what the replay bundle (CMP-95 item 5) opens.

:func:`commit_step` is the stand-in commit call: one ``frame-v3-sha512`` subtree per slot over ``hm96-sha512/row/v2`` hiding
leaves of the slot's rows (each row the bit row of its 16-bit words, salted by ChaCha20 under the step's salt key), and the
step's root the tree over every slot's subtree root (an idle slot's is its empty root). Its domains are bound by
``STANDIN_TAG``, and kernels' call replaces them.
"""
from __future__ import annotations

import os
from collections import deque
from collections.abc import Iterable, Sequence
from dataclasses import dataclass, field

import numpy as np
import torch

from verity.ml.commitments import hm96
from verity.ml.commitments.identity import identity_digest_sha512
from verity.ml.commitments.indexed import RangeIndexedDomain
from verity.ml.commitments.merkle import CommitmentDomain, merkle_depth, tree_levels
from verity.ml.commitments.row_table import ROOTS_SCHEMA
from verity.ml.commitments.rowleaf import SCHEMA_HM96_SHA512_ROW_V2, sha512_row_v2_digest
from verity.ml.windows.hiding import HidingLeaves
from verity.ml.windows.rows import chacha20

K, V = 0, 1
STANDIN_TAG = "verity/h200-slots/stand-in-commit/v1"
INST = hm96.SHA512


@dataclass(frozen=True)
class SlotShape:
    """The frozen decoder's KV shape and request class (CMP-92: MQA, one KV head of 64, context 32, 8 + 24 bytes)."""

    slots: int
    layers: int = 52
    ctx: int = 32
    head_dim: int = 64
    prompt: int = 8
    generate: int = 24
    row_words: int = 1

    def __post_init__(self) -> None:
        if min(self.slots, self.layers, self.ctx, self.head_dim, self.prompt, self.generate, self.row_words) < 1:
            raise ValueError(f"every size of {self} is positive")
        if self.steps > self.ctx:
            raise ValueError(f"a request runs {self.steps} positions, past the context of {self.ctx}")
        if self.head_dim % self.row_words:
            raise ValueError(f"row_words {self.row_words} doesn't divide head_dim {self.head_dim}")

    @property
    def steps(self) -> int:
        """Positions a request holds its slot: prompt + generate - 1 (the last output isn't fed back)."""
        return self.prompt + self.generate - 1

    @property
    def head_rows(self) -> int:
        return self.head_dim // self.row_words

    @property
    def rows(self) -> int:
        """KV rows a slot writes a step: K and V of every layer at its position."""
        return self.layers * 2 * self.head_rows


@dataclass(frozen=True)
class Request:
    seq: int
    prompt: bytes


@dataclass(frozen=True)
class StepPlan:
    """One step's active slots, ascending, and what each one runs. Tensors are on the cache's device."""

    step: int
    slots: torch.Tensor
    seqs: tuple[int, ...]
    positions: torch.Tensor
    tokens: torch.Tensor
    admitted: tuple[int, ...]

    @property
    def n(self) -> int:
        return len(self.seqs)

    def doc(self) -> dict:
        """The plan as the replay bundle and the block record carry it."""
        return {"step": self.step, "slots": self.slots.tolist(), "seqs": list(self.seqs),
                "positions": self.positions.tolist(), "admitted": list(self.admitted)}


@dataclass(frozen=True)
class StepRows:
    """The KV rows written at ``step``: ``words[i]`` is slot ``slots[i]``'s ``[R, row_words]`` int16 rows."""

    step: int
    slots: torch.Tensor
    seqs: tuple[int, ...]
    positions: torch.Tensor
    words: torch.Tensor


@dataclass(frozen=True)
class KVRowRef:
    """Where one K or V row (``rows`` rows of ``row_words``) of ``seq`` at ``position`` is committed."""

    seq: int
    slot: int
    step: int
    layer: int
    kind: int
    position: int
    index: int
    rows: int


@dataclass(frozen=True)
class Finished:
    seq: int
    slot: int
    admitted: int
    finished: int
    generated: bytes


@dataclass
class _Seq:
    request: Request
    slot: int
    admitted: int
    generated: bytearray = field(default_factory=bytearray)
    finished: int = -1


class SlotKV:
    """Fixed sequence slots (admission, finish, reuse) and their KV rows, in plain PyTorch on any device.

    ``admit`` caps admissions a step (default ``slots // steps``: 1,024 slots over a 31-step request admit 33 a step)."""

    def __init__(self, shape: SlotShape, device: str | torch.device = "cpu", admit: int | None = None) -> None:
        self.shape, self.device = shape, torch.device(device)
        self.admit = max(1, shape.slots // shape.steps) if admit is None else admit
        if self.admit < 1:
            raise ValueError("admit is at least 1")
        size = (shape.layers, shape.slots, shape.ctx, shape.head_dim)
        self.k = torch.zeros(size, dtype=torch.bfloat16, device=self.device)
        self.v = torch.zeros(size, dtype=torch.bfloat16, device=self.device)
        self.step = -1
        self._queue: deque[Request] = deque()
        self._submitted: set[int] = set()
        self._slot_seq: list[int] = [-1] * shape.slots
        self._next: list[int] = [0] * shape.slots
        self._seqs: dict[int, _Seq] = {}
        self._bases: dict[int, torch.Tensor] = {}
        self._plan: StepPlan | None = None
        self._written = torch.zeros(shape.layers, dtype=torch.bool)
        self._filled = [0] * shape.layers

    # --- the scheduler ---------------------------------------------------------------------------------------------------

    def submit(self, requests: Iterable[Request]) -> None:
        for r in requests:
            if len(r.prompt) != self.shape.prompt:
                raise ValueError(f"request {r.seq}'s prompt is {len(r.prompt)} bytes, not the class's {self.shape.prompt}")
            if r.seq in self._submitted:
                raise ValueError(f"request {r.seq} was already submitted")
            self._submitted.add(r.seq)
            self._queue.append(r)

    @property
    def active(self) -> int:
        return sum(s >= 0 for s in self._slot_seq)

    @property
    def idle(self) -> bool:
        return not self._queue and not self.active

    def begin(self) -> StepPlan:
        if self._plan is not None:
            raise RuntimeError(f"step {self.step} hasn't ended")
        self.step += 1
        free = [j for j, s in enumerate(self._slot_seq) if s < 0]
        admitted = []
        for j in free[:min(self.admit, len(self._queue))]:
            r = self._queue.popleft()
            self._seqs[r.seq] = _Seq(r, j, self.step)
            self._slot_seq[j], self._next[j] = r.seq, r.prompt[0]
            admitted.append(j)
        if admitted:
            idx = torch.tensor(admitted, dtype=torch.long, device=self.device)
            self.k[:, idx] = 0
            self.v[:, idx] = 0
        slots = [j for j, s in enumerate(self._slot_seq) if s >= 0]
        seqs = tuple(self._slot_seq[j] for j in slots)
        positions = [self.step - self._seqs[s].admitted for s in seqs]
        self._written.zero_()
        self._filled = [0] * self.shape.layers
        self._plan = StepPlan(self.step, torch.tensor(slots, dtype=torch.long, device=self.device), seqs,
                              torch.tensor(positions, dtype=torch.long, device=self.device),
                              torch.tensor([self._next[j] for j in slots], dtype=torch.long, device=self.device),
                              tuple(admitted))
        return self._plan

    def end(self, tokens: torch.Tensor | Sequence[int], base: int | torch.Tensor | Sequence[int] = 0) -> list[Finished]:
        """Close the step: ``tokens[i]`` is slot ``plan.slots[i]``'s output byte (read only at positions >= prompt - 1),
        ``base`` the index its KV rows start at in the slot's subtree (one for every slot, or one each in plan order).
        Returns the requests that finished."""
        plan = self._require_all_layers()
        toks = torch.as_tensor(tokens).to("cpu", torch.long).reshape(-1).tolist()
        if len(toks) != plan.n or any(not 0 <= t < 256 for t in toks):
            raise ValueError(f"step {plan.step} takes {plan.n} output bytes")
        b = torch.as_tensor(base, dtype=torch.long).to("cpu").reshape(-1)
        b = b.expand(plan.n) if b.numel() == 1 else b
        if b.numel() != plan.n or (plan.n and int(b.min()) < 0):
            raise ValueError(f"base is one index or {plan.n}, each nonnegative")
        bases = torch.full((self.shape.slots,), -1, dtype=torch.long)
        bases[plan.slots.cpu()] = b
        self._bases[plan.step] = bases
        done = []
        for j, seq, p, t in zip(plan.slots.tolist(), plan.seqs, plan.positions.tolist(), toks):
            s = self._seqs[seq]
            if p >= self.shape.prompt - 1:
                s.generated.append(t)
            if p == self.shape.steps - 1:
                s.finished, self._slot_seq[j] = plan.step, -1
                done.append(Finished(seq, j, s.admitted, plan.step, bytes(s.generated)))
            else:
                self._next[j] = s.request.prompt[p + 1] if p + 1 < self.shape.prompt else t
        self._plan = None
        return done

    # --- the KV cache ----------------------------------------------------------------------------------------------------

    def write(self, layer: int, k: torch.Tensor, v: torch.Tensor, rows: tuple[int, int] | None = None) -> None:
        """The plan's rows ``rows = (lo, hi)`` (all by default; the driver writes a micro-batch at a time): the layer is
        written once every row of the plan is."""
        plan = self._current()
        lo, hi = (0, plan.n) if rows is None else rows
        if not 0 <= lo <= hi <= plan.n:
            raise ValueError(f"rows {lo} .. {hi} aren't the plan's {plan.n}")
        want = (hi - lo, self.shape.head_dim)
        for name, x in (("k", k), ("v", v)):
            if x.dtype != torch.bfloat16 or tuple(x.shape) != want:
                raise TypeError(f"{name} is a {want} bf16 tensor, not {tuple(x.shape)} {x.dtype}: no conversion is exact")
        self.k[layer, plan.slots[lo:hi], plan.positions[lo:hi]] = k.to(self.device)
        self.v[layer, plan.slots[lo:hi], plan.positions[lo:hi]] = v.to(self.device)
        self._filled[layer] += hi - lo
        self._written[layer] = self._filled[layer] >= plan.n

    def read(self, layer: int) -> tuple[torch.Tensor, torch.Tensor, torch.Tensor]:
        """Every active slot's K and V rows of ``layer``, ``[n, ctx, head_dim]``, and which positions it reads."""
        plan = self._current()
        mask = torch.arange(self.shape.ctx, device=self.device)[None, :] <= plan.positions[:, None]
        return self.k[layer, plan.slots], self.v[layer, plan.slots], mask

    def rows(self) -> StepRows:
        plan = self._require_all_layers()
        sh = self.shape
        kv = torch.stack([self.k[:, plan.slots, plan.positions], self.v[:, plan.slots, plan.positions]], dim=1)
        words = kv.permute(2, 0, 1, 3).contiguous().view(torch.int16).reshape(plan.n, sh.rows, sh.row_words)
        return StepRows(plan.step, plan.slots, plan.seqs, plan.positions, words)

    def refs(self, seq: int, layer: int, position: int) -> list[KVRowRef]:
        """The K and V rows of positions ``0 .. position`` that ``seq``'s attention at ``layer`` and ``position`` reads, K
        then V for each position, with the step and subtree index each was committed at."""
        s = self._seqs[seq]
        if not 0 <= position < self.shape.steps or not 0 <= layer < self.shape.layers:
            raise ValueError(f"no layer {layer} at position {position}")
        hr = self.shape.head_rows
        out = []
        for j in range(position + 1):
            step = s.admitted + j
            if step not in self._bases:
                raise KeyError(f"request {seq}'s position {j} (step {step}) hasn't been committed")
            base = int(self._bases[step][s.slot])
            out += [KVRowRef(seq, s.slot, step, layer, kind, j, base + (2 * layer + kind) * hr, hr) for kind in (K, V)]
        return out

    def _current(self) -> StepPlan:
        if self._plan is None:
            raise RuntimeError("no step is running: call begin()")
        return self._plan

    def _require_all_layers(self) -> StepPlan:
        plan = self._current()
        if plan.n and not bool(self._written.all()):
            missing = (~self._written).nonzero().reshape(-1).tolist()
            raise RuntimeError(f"step {plan.step} wrote no KV rows for layers {missing[:8]}")
        return plan


# --- the stand-in commit call --------------------------------------------------------------------------------------------

def _slot_domain(run: str, step: int, slot: int, rows: int, row_bits: int) -> CommitmentDomain:
    binding = identity_digest_sha512(STANDIN_TAG, {"run": run, "step": step, "slot": slot, "rows": rows, "row_bits": row_bits,
                                                   "schema": SCHEMA_HM96_SHA512_ROW_V2})
    return CommitmentDomain(binding, -1, RangeIndexedDomain(0, rows), hash="sha512")


def _step_domain(run: str, step: int, slots: int) -> CommitmentDomain:
    binding = identity_digest_sha512(STANDIN_TAG, {"run": run, "step": step, "slots": slots, "schema": ROOTS_SCHEMA})
    return CommitmentDomain(binding, -1, RangeIndexedDomain(0, slots), hash="sha512")


def _path(levels: Sequence[Sequence[bytes]], rank: int) -> tuple[bytes, ...]:
    out = []
    for level in levels[:-1]:
        out.append(level[rank ^ 1])
        rank >>= 1
    return tuple(out)


def _fold(domain: CommitmentDomain, leaf: bytes, rank: int, path: Sequence[bytes]) -> bytes:
    for level, sib in enumerate(path):
        leaf = domain.node(level, rank >> 1, *((leaf, sib) if rank % 2 == 0 else (sib, leaf)))
        rank >>= 1
    return leaf


@dataclass(frozen=True)
class RowOpening:
    step: int
    slot: int
    index: int
    rows: int
    row: bytes
    salt: bytes
    path: tuple[bytes, ...]
    slot_root: bytes
    step_path: tuple[bytes, ...]

    @property
    def words(self) -> np.ndarray:
        return np.frombuffer(self.row, dtype="<i2")


@dataclass(frozen=True)
class StepCommitment:
    """A step's root over one subtree per slot, and (prover side) each active slot's rows, salts and tree levels."""

    run: str
    step: int
    slots: int
    row_bits: int
    root: bytes
    slot_roots: tuple[bytes, ...]
    _rows: dict = field(repr=False)
    _levels: tuple = field(repr=False)

    def open(self, slot: int, index: int) -> RowOpening:
        rows, salts, levels = self._rows[slot]
        n, rb = len(rows) // (self.row_bits // 8), self.row_bits // 8
        if not 0 <= index < n:
            raise IndexError(f"slot {slot} committed {n} rows at step {self.step}")
        return RowOpening(self.step, slot, index, n, rows[index * rb:(index + 1) * rb],
                          salts[index * INST.salt_bytes:(index + 1) * INST.salt_bytes], _path(levels, index),
                          self.slot_roots[slot], _path(self._levels, slot))


def commit_step(step: int, rows: StepRows | tuple[torch.Tensor, torch.Tensor], *, slots: int, run: str = "stand-in",
                salt_key: bytes | None = None) -> StepCommitment:
    """Commit each slot's rows (``[n, R, w]`` int16 words, slot ``slot_ids[i]``'s rows ``words[i]``) as one subtree per slot
    of ``slots``, under the step's root. ``salt_key`` (32 bytes, fresh per step when omitted) expands every row's salt."""
    slot_ids, words = (rows.slots, rows.words) if isinstance(rows, StepRows) else rows
    ids = slot_ids.to("cpu").tolist()
    w = words.to("cpu").numpy()
    if w.dtype != np.int16 or w.ndim != 3 or w.shape[0] != len(ids) or len(set(ids)) != len(ids) \
            or not all(0 <= j < slots for j in ids):
        raise ValueError("rows are [n, R, w] int16 words of n distinct slots")
    key = os.urandom(32) if salt_key is None else salt_key
    n_rows, row_bits = w.shape[1], 16 * w.shape[2]
    hiding = HidingLeaves(instance=INST)
    roots, kept = [], {}
    by_slot = dict(zip(ids, range(len(ids))))
    for j in range(slots):
        if j not in by_slot:
            roots.append(_slot_domain(run, step, j, 0, row_bits).empty_root())
            continue
        dom = _slot_domain(run, step, j, n_rows, row_bits)
        data = w[by_slot[j]].astype("<i2").tobytes()
        rb = row_bits // 8
        inner = [sha512_row_v2_digest(data[r * rb:(r + 1) * rb], row_bits) for r in range(n_rows)]
        salts = chacha20(key, step.to_bytes(4, "little") + j.to_bytes(8, "little"), n_rows * INST.salt_bytes)
        values = hiding.leaves_with(inner, salts)
        levels = tree_levels(dom, [dom.leaf(r, r, SCHEMA_HM96_SHA512_ROW_V2, values[r]) for r in range(n_rows)])
        roots.append(levels[-1][0] if levels else dom.empty_root())
        kept[j] = (data, salts, levels)
    sdom = _step_domain(run, step, slots)
    top = tree_levels(sdom, [sdom.leaf(j, j, ROOTS_SCHEMA, r) for j, r in enumerate(roots)])
    return StepCommitment(run, step, slots, row_bits, top[-1][0], tuple(roots), kept, top)


def verify_row(o: RowOpening, root: bytes, *, slots: int, row_bits: int, run: str = "stand-in") -> bool:
    """Whether ``o`` opens row ``o.index`` of slot ``o.slot``'s subtree under the step root ``root``, through core's
    references (``hm96``, ``rowleaf``, ``merkle``), not the batched path ``commit_step`` takes."""
    if len(o.row) * 8 != row_bits or not 0 <= o.slot < slots or not 0 <= o.index < o.rows:
        return False
    if len(o.path) != merkle_depth(o.rows) or len(o.step_path) != merkle_depth(slots):
        return False
    dom = _slot_domain(run, o.step, o.slot, o.rows, row_bits)
    key = INST.default_key
    value = INST.tree_leaf(key, INST.commit_string(key, sha512_row_v2_digest(o.row, row_bits), o.salt))
    leaf = dom.leaf(o.index, o.index, SCHEMA_HM96_SHA512_ROW_V2, value)
    if _fold(dom, leaf, o.index, o.path) != o.slot_root:
        return False
    sdom = _step_domain(run, o.step, slots)
    return _fold(sdom, sdom.leaf(o.slot, o.slot, ROOTS_SCHEMA, o.slot_root), o.slot, o.step_path) == root


