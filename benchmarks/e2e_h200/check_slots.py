"""Check :mod:`e2e_h200.slots` on a device at the frozen KV shape against a per-request reference, with an exact integer
stand-in for the decoder.

The stand-in model computes in int64 only, so its result is independent of batch, order and device: a step's state for a
slot starts from its input byte and position, and each layer writes K and V rows (a mix of the state, as raw bf16 bits, NaN
and subnormal patterns included), then folds every row it reads at positions <= its own into the state. The output byte is
the state mod 256. A row read from another request, a stale row or a converted bit would change the outputs and the rows.

    python check_slots.py --device cuda --out "$OUT"     # 1,024 slots, 52 layers, ctx 32, head 64; writes slots-check.json

It runs the batched path on the device and on the CPU, compares every finished request's bytes and every step's rows
(SHA-512 of each step's ``rows().words``), and compares a sample of requests' rows with the per-request reference.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import sys
import time
from collections.abc import Callable, Sequence
from pathlib import Path

import torch

sys.path.insert(0, str(Path(__file__).resolve().parent))

from e2e_h200.slots import Finished, Request, SlotKV, SlotShape, StepPlan, StepRows  # noqa: E402

P = 2**31 - 1
A = 1103515245


def mix(h: torch.Tensor, layer: int, kind: int, head_dim: int) -> torch.Tensor:
    """``[n, head_dim]`` int16 bits from the ``[n]`` states ``h`` (each < P)."""
    c = layer * 131 + torch.arange(head_dim, device=h.device) * 7 + kind * 3 + 1
    x = (h[:, None] * A + c[None, :] * 12345) % 65536
    return (x - 65536 * (x >= 32768).long()).to(torch.int16)


def fold(h: torch.Tensor, k: torch.Tensor, v: torch.Tensor, mask: torch.Tensor) -> torch.Tensor:
    """The states after reading ``[n, ctx, head_dim]`` bf16 rows ``k`` and ``v`` at the positions ``mask`` keeps."""
    kb = k.view(torch.int16).long() & 0xFFFF
    vb = v.view(torch.int16).long() & 0xFFFF
    dw = torch.arange(1, k.shape[-1] + 1, device=h.device)
    cw = torch.arange(1, k.shape[-2] + 1, device=h.device)
    acc = (((kb * dw).sum(-1) + vb.sum(-1) * cw) * mask.long()).sum(-1)
    return (h + acc) % P


def start(tokens: torch.Tensor, positions: torch.Tensor) -> torch.Tensor:
    return (tokens * 1000003 + positions * 7919 + 1) % P


def toy_step(kv: SlotKV, plan: StepPlan) -> torch.Tensor:
    """One step of the stand-in model through ``kv``: the output byte of every slot in ``plan``."""
    sh = kv.shape
    h = start(plan.tokens, plan.positions)
    for layer in range(sh.layers):
        kv.write(layer, mix(h, layer, 0, sh.head_dim).view(torch.bfloat16), mix(h, layer, 1, sh.head_dim).view(torch.bfloat16))
        h = fold(h, *kv.read(layer))
    return h % 256


def reference(shape: SlotShape, request: Request) -> tuple[torch.Tensor, bytes]:
    """One request alone, on its own cache: its rows ``[steps, layers, 2, head_dim]`` int16 and its generated bytes."""
    L, C, D = shape.layers, shape.ctx, shape.head_dim
    kc = torch.zeros(L, C, D, dtype=torch.int16)
    vc = torch.zeros(L, C, D, dtype=torch.int16)
    rows = torch.zeros(shape.steps, L, 2, D, dtype=torch.int16)
    out, token = bytearray(), request.prompt[0]
    for p in range(shape.steps):
        h = start(torch.tensor([token]), torch.tensor([p]))
        mask = (torch.arange(C) <= p)[None, :]
        for layer in range(L):
            kc[layer, p], vc[layer, p] = mix(h, layer, 0, D)[0], mix(h, layer, 1, D)[0]
            rows[p, layer, 0], rows[p, layer, 1] = kc[layer, p], vc[layer, p]
            h = fold(h, kc[layer][None].view(torch.bfloat16), vc[layer][None].view(torch.bfloat16), mask)
        t = int(h[0]) % 256
        if p >= shape.prompt - 1:
            out.append(t)
        token = request.prompt[p + 1] if p + 1 < shape.prompt else t
    return rows, bytes(out)


def requests(shape: SlotShape, n: int, seed: int = 0) -> list[Request]:
    g = torch.Generator().manual_seed(seed)
    data = torch.randint(0, 256, (n, shape.prompt), generator=g, dtype=torch.uint8)
    return [Request(1000 + i, bytes(data[i].tolist())) for i in range(n)]


def run(kv: SlotKV, reqs: Sequence[Request], on_step: Callable[[StepPlan, StepRows], None] | None = None,
        on_begin: Callable[[SlotKV, StepPlan], None] | None = None) -> dict[int, Finished]:
    """Serve ``reqs`` through ``kv`` until idle. ``on_step`` sees each step's rows."""
    kv.submit(reqs)
    done: dict[int, Finished] = {}
    while not kv.idle:
        plan = kv.begin()
        if on_begin:
            on_begin(kv, plan)
        tokens = toy_step(kv, plan)
        if on_step:
            on_step(plan, kv.rows())
        done.update((f.seq, f) for f in kv.end(tokens))
    return done


def main(argv: Sequence[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--device", default="cuda" if torch.cuda.is_available() else "cpu")
    ap.add_argument("--slots", type=int, default=1024)
    ap.add_argument("--layers", type=int, default=52)
    ap.add_argument("--requests", type=int, default=3 * 1024)
    ap.add_argument("--sample", type=int, default=48, help="requests checked row by row against the per-request reference")
    ap.add_argument("--out", type=Path, default=None)
    a = ap.parse_args(argv)
    shape = SlotShape(slots=a.slots, layers=a.layers)
    reqs = requests(shape, a.requests)
    result: dict = {"shape": shape.__dict__ | {"steps": shape.steps}, "device": a.device, "torch": torch.__version__,
                    "requests": len(reqs)}
    if a.device.startswith("cuda"):
        result["gpu"] = torch.cuda.get_device_name(0)

    def serve(device: str, keep: set[int]) -> tuple[SlotKV, dict[int, Finished], list[str], dict, float]:
        kv = SlotKV(shape, device)
        digests: list[str] = []
        kept: dict[tuple[int, int], torch.Tensor] = {}

        def on_step(plan: StepPlan, rows: StepRows) -> None:
            w = rows.words.cpu()
            digests.append(hashlib.sha512(w.numpy().tobytes() + rows.slots.cpu().numpy().tobytes()).hexdigest())
            for i, (seq, p) in enumerate(zip(rows.seqs, rows.positions.tolist())):
                if seq in keep:
                    kept[seq, p] = w[i]

        if device.startswith("cuda"):
            torch.cuda.synchronize()
        t0 = time.perf_counter()
        done = run(kv, reqs, on_step)
        if device.startswith("cuda"):
            torch.cuda.synchronize()
        return kv, done, digests, kept, time.perf_counter() - t0

    sample = {r.seq for r in reqs[:: max(1, len(reqs) // a.sample)][: a.sample]}
    kv, done, digests, kept, secs = serve(a.device, sample)
    reused = sorted({f.slot for f in done.values()})
    hosts = {j: sum(f.slot == j for f in done.values()) for j in reused}
    result["device_run"] = {"steps": kv.step + 1, "seconds": round(secs, 3), "finished": len(done),
                            "max_requests_per_slot": max(hosts.values()), "slots_reused": sum(v > 1 for v in hosts.values()),
                            "admitted_per_step_max": kv.admit}
    ok = len(done) == len(reqs)

    if a.device != "cpu":
        _, cdone, cdigests, _, csecs = serve("cpu", set())
        same_bytes = all(cdone[s].generated == done[s].generated and cdone[s].slot == done[s].slot for s in done)
        result["cpu_run"] = {"seconds": round(csecs, 3), "same_generated_and_slots": same_bytes,
                             "same_step_row_digests": cdigests == digests, "steps": len(cdigests)}
        ok &= same_bytes and cdigests == digests

    by_seq = {r.seq: r for r in reqs}
    bad = []
    for seq in sorted(sample):
        rows, gen = reference(shape, by_seq[seq])
        got = torch.stack([kept[seq, p] for p in range(shape.steps)])
        if not torch.equal(got, rows) or gen != done[seq].generated:
            bad.append(seq)
    result["reference"] = {"requests": len(sample), "mismatched": bad}
    ok &= not bad
    result["ok"] = bool(ok)
    text = json.dumps(result, indent=2)
    print(text)
    if a.out:
        a.out.mkdir(parents=True, exist_ok=True)
        (a.out / "slots-check.json").write_text(text + "\n")
    return 0 if ok else 1


if __name__ == "__main__":
    raise SystemExit(main())
