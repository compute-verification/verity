"""demo-stub: a stand-in for the H200 demo's serving endpoint, the network certifier's upstream on the demo card's
loopback: the shape of the demo's class (a prompt of exactly 8 byte ids, exactly 24 generated byte ids, a vocabulary
of 256) in the id form the warden frames, so that the gate's `warden-rehearse --scan --prompts --tokens 24` runs
against it as against the demo's loop, and the loop's endpoint builds against it.

    python demo_stub.py serve [--host 127.0.0.1] [--port 0] [--prompt-ids 8] [--tokens 24] [--vocab 256] [--id-payload 503]
    python demo_stub.py prompts [--count 4] [--prompt-ids 8] [--vocab 256]

`serve` prints ``{"listening": URL, "model": NAME}`` once it listens, then serves until it is stopped, one request a
connection, each answered whole and the connection closed:

- ``GET /v1/models``: its one model, ``demo-stub/p{prompt_ids}-g{tokens}-v{vocab}``, which the rehearsal names in
  every request (`certifier_serve.served_model`).
- **A warden's id request of the class** (`warden_request`): the warden's copy of the client's bytes, its release
  headers right after the request line (`release.with_release`: ``x-verity-release: N`` and
  ``x-verity-release-run: HEX``), around exactly `active.id_request` of its own fields in the scan's B = P + 9-byte
  cells from their first byte (``offset`` 0), as `warden_serve.py rehearse --ids` sends one. The class (`refusal`): the
  model above, greedy (temperature 0, top_p 1), a prompt of exactly ``--prompt-ids`` ids each below ``--vocab`` (the
  prompt's bytes), and ``max_tokens`` exactly ``--tokens``. It is answered id-form with no HTTP head (`answer`): each
  generated id (`outputs`, below ``--vocab``) as an `io_tie.id_event` of P = ``--id-payload`` bytes, then
  `io_tie.TRAILER`, the bytes the warden puts in its egress cells as they come and the scan reads.
- **Anything else**, a request off the class among them, is answered HTTP 400 with ``{"error": why}``. The warden
  frames those bytes like any others, and its check refuses a response that isn't id-form, so a request the loop can't
  serve is a visible failure, never a silent stand-in's answer.

Its generated ids are SHA-512's, not a model's: byte k of the counter-mode stream (`_stream`) of
``verity/demo-stub/v1/outputs``, 0x00, then the prompt's bytes, mod ``--vocab``. `prompts` prints ``--count`` prompts of
the class (`prompts`), the JSON array the gate's `--prompts` reads off its stdin:

    python demo_stub.py prompts --count 4 | ssh -i KEY research@vy-challenger-1 warden-rehearse --peer PEER \
        --port PORT --minutes 4 --requests 8 --height 10 --scan --prompts --tokens 24
"""
from __future__ import annotations

import argparse
import asyncio
import dataclasses
import hashlib
import json
import re

from verity.core.protocols.certifier import active as A, io_tie as IT, release as REL

#: the demo's class: a prompt of 8 byte ids in, 24 generated byte ids out, a vocabulary of 256
PROMPT_IDS, TOKENS, VOCAB = 8, 24, 256
#: the scan's cell payload, P = B − 9 at its B = 512-byte cells (`auditor.SCAN_SCHEDULE`)
ID_PAYLOAD = 503
#: the fields of `active.id_request`, every one of which a warden's id request carries
FIELDS = ("model", "user", "prompt", "max_tokens", "temperature", "top_p", "seed")
DOMAIN = b"verity/demo-stub/v1"


@dataclasses.dataclass(frozen=True)
class Shape:
    """The class a stand-in serves, and its id events' P bytes."""
    prompt_ids: int = PROMPT_IDS
    tokens: int = TOKENS
    vocab: int = VOCAB
    payload: int = ID_PAYLOAD

    def __post_init__(self) -> None:
        if not (self.prompt_ids >= 1 and self.tokens >= 1 and 2 <= self.vocab <= 256):
            raise ValueError(f"a class of at least one prompt id and one token, its vocabulary 2 to 256, not {self}")
        IT.id_event(0, self.payload)

    @property
    def name(self) -> str:
        return f"demo-stub/p{self.prompt_ids}-g{self.tokens}-v{self.vocab}"


def _stream(label: bytes, n: int) -> bytes:
    """The first `n` bytes of SHA-512's counter-mode stream of `label`: SHA-512(label ‖ u32be i) for i = 0, 1, …"""
    blocks = -(-n // 64)
    return b"".join(hashlib.sha512(label + i.to_bytes(4, "big")).digest() for i in range(blocks))[:n]


def outputs(prompt: list[int], shape: Shape = Shape()) -> list[int]:
    """The generated ids of `prompt`: `shape.tokens` bytes of the stream of the prompt's bytes, mod the vocabulary."""
    return [b % shape.vocab for b in _stream(DOMAIN + b"/outputs\x00" + bytes(prompt), shape.tokens)]


def prompts(count: int, shape: Shape = Shape()) -> list[list[int]]:
    """`count` prompts of the class, prompt j `shape.prompt_ids` bytes of the stream of j, mod the vocabulary."""
    return [[b % shape.vocab for b in _stream(DOMAIN + b"/prompts\x00" + j.to_bytes(4, "big"), shape.prompt_ids)]
            for j in range(count)]


def warden_request(request: bytes, payload: int = ID_PAYLOAD) -> dict | None:
    """A warden's id request's fields (`request`: its head and body as the server reads them), or None: exactly
    `active.id_request` of its own fields in B = `payload` + 9-byte cells from their first byte, with the release
    headers the warden puts on the server's copy when it has them (`release.release_of`, `release.with_release`)."""
    head, blank, raw = request.partition(b"\r\n\r\n")
    try:
        body = json.loads(raw)
        fields = {k: body[k] for k in FIELDS}
        canonical = A.id_request(**fields, frame_bytes=payload + A.HEADER.size, offset=0)
    except (ValueError, KeyError, TypeError):
        return None
    released = REL.release_of(head + blank)
    return fields if request == (canonical if released is None else REL.with_release(canonical, *released)) else None


def refusal(fields: dict, shape: Shape = Shape()) -> str | None:
    """Why a warden's id request is off the class (None: the stand-in serves it)."""
    if fields["model"] != shape.name:
        return f"the model {shape.name}"
    if fields["temperature"] != 0 or fields["top_p"] != 1:
        return "greedy (temperature 0, top_p 1)"
    prompt = fields["prompt"]
    if len(prompt) != shape.prompt_ids or not all(0 <= t < shape.vocab for t in prompt):
        return f"a prompt of exactly {shape.prompt_ids} ids below {shape.vocab}"
    if fields["max_tokens"] != shape.tokens:
        return f"max_tokens exactly {shape.tokens}"
    return None


def answer(prompt: list[int], shape: Shape = Shape()) -> bytes:
    """The id-form answer to a request of the class: each generated id's `io_tie.id_event`, then `io_tie.TRAILER`."""
    return b"".join(IT.id_event(t, shape.payload) for t in outputs(prompt, shape)) + IT.TRAILER


class Endpoint:
    def __init__(self, shape: Shape = Shape()) -> None:
        self.shape = shape

    async def __call__(self, reader: asyncio.StreamReader, writer: asyncio.StreamWriter) -> None:
        try:
            writer.write(await self.respond(reader))
            await writer.drain()
        except (asyncio.IncompleteReadError, asyncio.LimitOverrunError, ConnectionError):
            pass
        finally:
            writer.close()

    async def respond(self, reader: asyncio.StreamReader) -> bytes:
        """The whole answer to the connection's one request."""
        head = await reader.readuntil(b"\r\n\r\n")
        if head.startswith(b"GET /v1/models "):
            return http(200, {"object": "list", "data": [{"id": self.shape.name, "object": "model"}]})
        n = re.search(rb"(?im)^content-length:\s*(\d+)", head)
        raw = await reader.readexactly(int(n.group(1))) if n else b""
        fields = warden_request(head + raw, self.shape.payload) if head.startswith(b"POST /v1/completions ") else None
        if fields is None:
            return http(400, {"error": f"a warden's id request (active.id_request in {self.shape.payload + 9}-byte "
                                       "cells from their first byte) to POST /v1/completions"})
        if (why := refusal(fields, self.shape)) is not None:
            return http(400, {"error": why})
        return answer(fields["prompt"], self.shape)


def http(status: int, doc: dict) -> bytes:
    data = json.dumps(doc).encode()
    reason = b"OK" if status == 200 else b"Bad Request"
    return b"HTTP/1.1 %d %s\r\ncontent-type: application/json\r\nconnection: close\r\ncontent-length: %d\r\n\r\n%s" % (
        status, reason, len(data), data)


async def serve(host: str, port: int, endpoint: Endpoint) -> None:
    server = await asyncio.start_server(endpoint, host, port)
    h, p = server.sockets[0].getsockname()[:2]
    print(json.dumps({"listening": f"http://{h}:{p}", "model": endpoint.shape.name}), flush=True)
    async with server:
        await server.serve_forever()


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    sub = ap.add_subparsers(dest="cmd", required=True)
    s, p = sub.add_parser("serve", help="serve the class on HOST:PORT"), sub.add_parser("prompts", help="print prompts")
    for q in (s, p):
        q.add_argument("--prompt-ids", type=int, default=PROMPT_IDS, help="a prompt's ids, exactly")
        q.add_argument("--vocab", type=int, default=VOCAB, help="every id is below it (at most 256: a byte)")
    s.add_argument("--host", default="127.0.0.1")
    s.add_argument("--port", type=int, default=0)
    s.add_argument("--tokens", type=int, default=TOKENS, help="a response's generated ids, exactly (max_tokens)")
    s.add_argument("--id-payload", type=int, default=ID_PAYLOAD, help="P: an id event's bytes, the cells' B - 9")
    p.add_argument("--count", type=int, default=4)
    a = ap.parse_args(argv)
    if a.cmd == "prompts":
        print(json.dumps(prompts(a.count, Shape(a.prompt_ids, vocab=a.vocab)), separators=(",", ":")))
        return 0
    asyncio.run(serve(a.host, a.port, Endpoint(Shape(a.prompt_ids, a.tokens, a.vocab, a.id_payload))))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
