"""``bench-instances/v1``: the frozen, hash-pinned input set every A-GKR/B-Ligero number at K=1536 is measured on.

Why: two proof backends are compared at the decision workload (K=1536 ``GemmCoordinate`` dot products, B=4096).  Without
a shared input set each would benchmark on its own inputs -- the quiet non-comparability ``contract.py`` exists to
prevent.  This module owns the dataset's byte layout, its loader, the build that regenerates it from the recipe in
:mod:`verity_numerical.bench.instances_gen`, its verification against the pinned digests in ``manifest.json``, and the
sensitivity statistic of the negatives.  The relation is not restated here: expected words are ``silicon.tc_dot_chain``
+ ``cast.f32_to_bf16_word`` (``verity.ml.circuits.targets.target.FIRST``), cross-checked against ``hawkeye_close``.

Tiers (``fixtures/bench-instances/v1/``; the byte layout is in that directory's ``README.md``)::

    vu-k1536       4,096 valid VU instances, K=1536, ids 0..4095.  B=1 / 64 / 4096 are the prefixes [0:1], [0:64],
                   [0:4096]; sub-batches are contiguous id ranges.  Every 64-block holds 54 real and 10 corner instances.
                   id 0 is seed qkv_proj_decode_0.
    tu-k16         4,096 transition units: (c, a[16], b[16]) -> out, c an arbitrary finite FP32 word; 2,816 real chain
                   states of vu-k1536, 512 corner-chain states, 768 designed corners.
    vu-k1536-neg   claimed-wrong instances derived from vu-k1536 positives, each tagged with the implementation mistake
                   whose output the claimed word equals, plus out-of-domain instances that must be REJECTED.

Files per tier: ``<tier>.<array>.<u16|u32>`` flat little-endian arrays, instance-major, plus ``<tier>.index.json``.  The
25 MB operand arrays (``vu-k1536.{x,w}.u16``, ``vu-k1536.acc.u32``, ``tu-k16.{a,b}.u16``, ``tu-k16.c.u32``) are *built*,
not committed; ``build`` regenerates them byte-identically and ``verify`` checks every array against ``manifest.json``.

    python -m verity_numerical.bench.instances build  [--out DIR] [--procs N]
    python -m verity_numerical.bench.instances verify [--root DIR] [--full]
    python -m verity_numerical.bench.instances stats  [--root DIR]
    python -m verity_numerical.bench.instances import-seeds --from CAPTURE_DIR [--out DIR/seeds]
"""

