def import_seeds(src: Path, out: Path, repo_copy: Path | None = None) -> dict:
    """Copy the 24 K=1536 seeds (``x.u16``, ``w_row.u16``, ``fixture.json``; not ``openings.json``) from a capture directory
    and write ``seeds.json`` with the experiment id and every sha256 -- ``out_row.u16`` included, although the file itself
    is not copied (the lm_head rows are 303 KB each): its word ``j`` is ``fixture.json``'s ``committed_word`` and the full
    row stays at the repository's copy of the capture, which is checked bitwise here when ``repo_copy`` is given."""

    out.mkdir(parents=True, exist_ok=True)
    doc: dict[str, Any] = {"schema": f"{DATASET}/seeds", "experiment_id": G.EXPERIMENT_ID, "source": str(src),
                           "repo_copy": None if repo_copy is None else str(repo_copy.relative_to(REPO)) if repo_copy.is_relative_to(REPO) else str(repo_copy),
                           "model": {"hf_repo": G.HF_REPO, "hf_revision": G.HF_REVISION, "hidden": 1536, "intermediate": 8960, "fused_qkv_N": 2048, "gate_up_N": 17920, "vocab": 151936},
                           "files_copied": ["x.u16", "w_row.u16", "fixture.json"], "out_row": "not copied; sha256 recorded, word j = committed_word; full row at repo_copy/<name>/out_row.u16",
                           "seeds": {}}
    for name in G.SEED_NAMES:
        d = src / name
        fx = json.loads((d / "fixture.json").read_text())
        if fx["K"] != K:
            raise ValueError(f"{name}: K={fx['K']}")
        dest = out / name
        dest.mkdir(exist_ok=True)
        sha = {}
        for f in ("x.u16", "w_row.u16", "fixture.json"):
            shutil.copyfile(d / f, dest / f)
            sha[f] = sha256_file(dest / f)
        sha["out_row.u16"] = sha256_file(d / "out_row.u16")
        for f in ("x.u16", "w_row.u16", "out_row.u16"):
            if sha[f] != fx["files"][f]["sha256"]:
                raise ValueError(f"{name}/{f}: sha256 differs from fixture.json")
        out_words = G.read_u16(d / "out_row.u16")
        if out_words[fx["j"]] != fx["committed_word"]:
            raise ValueError(f"{name}: out_row[j] != committed_word")
        if repo_copy is not None:
            for f in ("x.u16", "w_row.u16", "out_row.u16", "fixture.json"):
                if sha256_file(repo_copy / name / f) != sha[f]:
                    raise ValueError(f"{name}/{f}: the repository copy differs from the capture")
        doc["seeds"][name] = {"family": fx["family"], "phase": fx["phase"], "layer": str(fx["layer"]), "op": fx["op"], "j": fx["j"], "N": fx["N"], "K": fx["K"],
                              "weight_param": fx["weight_param"], "canonical_id": fx["canonical_id"], "out_row_word_j": fx["committed_word"],
                              "hf_tensor": list(G.tensor_of(fx["family"], str(fx["layer"]), fx["j"])), "sha256": sha}
    _write_json(out / "seeds.json", doc)
    return doc


