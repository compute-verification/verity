def verify(root: Path | str = DEFAULT_ROOT, full: bool = False, sample: int = 64, seeds_dir: Path | str | None = None, log=print) -> dict:
    """Digests of every array against ``manifest.json`` (built arrays: reported missing rather than failed), the seed
    checks, a ``silicon`` recheck of ``sample`` VU and TU instances (every instance with ``full``), and the negatives'
    claims.  Returns a report with ``ok``."""

    root = Path(root)
    seeds_dir = Path(seeds_dir) if seeds_dir else root / "seeds"
    manifest = json.loads((root / "manifest.json").read_text())
    rep: dict[str, Any] = {"root": str(root), "manifest_sha256": sha256_file(root / "manifest.json"), "digests": {"ok": [], "bad": [], "missing": []},
                           "problems": []}
    for files in manifest["tiers"].values():
        for name, rec in files["files"].items():
            p = root / name
            if not p.is_file():
                rep["digests"]["missing"].append(name)
                if rec["committed"]:
                    rep["problems"].append(f"{name} (committed) is missing")
            elif sha256_file(p) != rec["sha256"]:
                rep["digests"]["bad"].append(name)
                rep["problems"].append(f"{name}: sha256 differs from the manifest")
            else:
                rep["digests"]["ok"].append(name)
    seeds = G.load_seeds(seeds_dir)
    rep["seeds"] = _check_seeds(seeds, seeds_dir, json.loads((seeds_dir / "seeds.json").read_text()))
    if rep["seeds"]["sha256_ok"] != 24 or rep["seeds"]["silicon_vs_out_row_j"] != 24:
        rep["problems"].append(f"seed checks: {rep['seeds']}")
    built_present = not any(n in rep["digests"]["missing"] for t in TIERS for n in BUILT_FILES[t])
    if built_present:
        vu = load("vu-k1536", root)
        ids = range(vu.n) if full else range(0, vu.n, max(1, vu.n // sample))
        bad = []
        for i in ids:
            xi, wi, yi = vu.instance(i)
            accs = G.chain_accs(xi, wi)
            if accs != vu.accs(i) or G.epilogue(accs[-1]) != yi:
                bad.append(i)
        rep["vu_recheck"] = {"instances": len(ids), "mismatches": bad[:20], "full": full}
        if bad:
            rep["problems"].append(f"vu-k1536: silicon disagrees with the recorded words on {len(bad)} of {len(ids)} rechecked instances")
        tu = load("tu-k16", root)
        ids = range(tu.n) if full else range(0, tu.n, max(1, tu.n // sample))
        bad = [i for i in ids if S.tc_dot(G.PIPELINE, *tu.instance(i)[:3]) != tu.instance(i)[3]]
        rep["tu_recheck"] = {"instances": len(ids), "mismatches": bad[:20], "full": full}
        if bad:
            rep["problems"].append(f"tu-k16: silicon disagrees on {len(bad)} of {len(ids)} rechecked instances")
    else:
        rep["vu_recheck"] = rep["tu_recheck"] = "skipped: built arrays absent"
    # the negatives, always (they are committed and small)
    neg = load("vu-k1536-neg", root)
    neg_bad = []
    for i in range(neg.n):
        xi, wi, claimed = neg.instance(i)
        row = neg.index[i]
        verdict, correct = row[5], row[4]
        try:
            accs = G.chain_accs(xi, wi)
        except InvalidArtifact:
            if verdict != "reject":
                neg_bad.append((i, "rejected but tagged wrong"))
            continue
        if verdict == "reject":
            neg_bad.append((i, "accepted but tagged reject"))
        elif G.epilogue(accs[-1]) != correct or claimed == correct:
            neg_bad.append((i, "claimed/correct words inconsistent with silicon"))
    rep["negatives"] = {"instances": neg.n, "problems": neg_bad}
    if neg_bad:
        rep["problems"].append(f"negatives: {len(neg_bad)} inconsistent")
    rep["ok"] = not rep["problems"]
    for line in _render_verify(rep):
        log(line)
    return rep


def _render_verify(rep: dict) -> list[str]:
    d = rep["digests"]
    lines = [f"digests: {len(d['ok'])} ok, {len(d['bad'])} bad, {len(d['missing'])} missing" + (f" ({', '.join(d['missing'])})" if d["missing"] else ""),
             f"seeds: {rep['seeds']}", f"vu recheck: {rep['vu_recheck']}", f"tu recheck: {rep['tu_recheck']}",
             f"negatives: {rep['negatives']['instances']} instances, {len(rep['negatives']['problems'])} problems"]
    lines.append("OK" if rep["ok"] else "PROBLEMS: " + "; ".join(rep["problems"]))
    return lines


