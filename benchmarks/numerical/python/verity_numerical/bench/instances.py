def _check_seeds(seeds: Sequence[G.Seed], seeds_dir: Path, seeds_doc: dict) -> dict:
    sha_ok = 0
    sil_ok = 0
    for s in seeds:
        rec = seeds_doc["seeds"][s.name]
        d = seeds_dir / s.name
        ok = all(sha256_file(d / f) == rec["sha256"][f] for f in ("x.u16", "w_row.u16", "fixture.json"))
        ok = ok and rec["sha256"]["x.u16"] == s.sha256["x.u16"] and rec["sha256"]["w_row.u16"] == s.sha256["w_row.u16"]
        sha_ok += ok
        acc = S.tc_dot_chain(G.PIPELINE, 0, s.x, s.w)
        sil_ok += G.epilogue(acc) == s.committed_word == rec["out_row_word_j"]
    return {"sha256_ok": sha_ok, "silicon_vs_out_row_j": sil_ok}


def _sensitivity(results: list[dict], kinds: list[str]) -> dict:
    table: dict[str, dict] = {}
    for m in G.MISTAKES:
        applicable = y_diff = acc_diff = acc_applicable = 0
        by_kind = {"real": 0, "corner": 0}
        for r, kind in zip(results, kinds, strict=True):
            v = r["mistakes"][m.name]
            if v["y"] is not None:
                applicable += 1
                if v["y"] != r["y"]:
                    y_diff += 1
                    by_kind[kind] += 1
            if v["acc_differs"] is not None:
                acc_applicable += 1
                acc_diff += bool(v["acc_differs"])
        table[m.name] = {"description": m.description, "level": m.level, "applicable": applicable, "y_differs": y_diff,
                         "y_differs_real": by_kind["real"], "y_differs_corner": by_kind["corner"],
                         "acc_applicable": acc_applicable if m.level == "chain" else None, "acc_differs": acc_diff if m.level == "chain" else None}
    for name in G.REJECT_CLASSES:
        table[name] = {"description": "outside the supported domain: REJECT, not a computed word", "level": "domain", "applicable": None, "y_differs": None}
    return table


def _plan_tu(kinds: list[str], x: array, w: array, accs: list[list[int]], seeds: Sequence[G.Seed]) -> tuple[list[int], array, array, list[list]]:
    real_ids = [i for i, k in enumerate(kinds) if k == "real"]
    corner_ids = [i for i, k in enumerate(kinds) if k == "corner"]
    n_blocks = N_TU // BLOCK
    rng_r, rng_c = G.Rng("tu-real"), G.Rng("tu-corner")
    real_states = _draw_states(rng_r, real_ids, accs, TU_REAL_PER_BLOCK * n_blocks)
    corner_states = _draw_states(rng_c, corner_ids, accs, TU_CORNER_CHAIN_PER_BLOCK * n_blocks)
    fams = list(G.TU_FAMILIES)
    designed = [(fam, i) for i in range(G.TU_PER_FAMILY) for fam in fams]  # round-robin over the families
    if len(designed) != TU_DESIGNED_PER_BLOCK * n_blocks:
        raise ValueError("tu designed composition")
    c_all: list[int] = []
    a_all, b_all = array("H"), array("H")
    rows: list[list] = []
    ri = ci = di = 0
    for _ in range(n_blocks):
        for pos in range(BLOCK):
            i = len(rows)
            if pos % 16 in (2, 7, 12):  # 12 designed per block
                fam, fi = designed[di]
                di += 1
                t = G.generate_tu_corner(fam, fi, seeds)
                c_all.append(t.c)
                a_all.extend(t.a)
                b_all.extend(t.b)
                rows.append([i, t.tags, None, t.params])
            elif pos % 8 == 5:  # 8 corner-chain states per block (disjoint from the designed slots)
                vid, s = corner_states[ci]
                ci += 1
                _push_state(c_all, a_all, b_all, x, w, accs, vid, s)
                rows.append([i, ["corner-chain"], [vid, s], None])
            else:
                vid, s = real_states[ri]
                ri += 1
                _push_state(c_all, a_all, b_all, x, w, accs, vid, s)
                rows.append([i, ["real-chain"], [vid, s], None])
    if not (ri == len(real_states) and ci == len(corner_states) and di == len(designed) and len(rows) == N_TU):
        raise ValueError(f"tu composition mismatch: {ri} {ci} {di} {len(rows)}")
    return c_all, a_all, b_all, rows


def _draw_states(rng: G.Rng, ids: list[int], accs: list[list[int]], n: int) -> list[tuple[int, int]]:
    """``n`` distinct (instance, step >= 1) pairs over ``ids``, drawn uniformly; the incoming accumulator is finite by
    construction (only a chain's last accumulator can be infinite)."""

    seen: set[tuple[int, int]] = set()
    out: list[tuple[int, int]] = []
    while len(out) < n:
        vid = ids[rng.below(len(ids))]
        s = 1 + rng.below(STEPS - 1)
        if (vid, s) in seen or not G.is_finite_f32(accs[vid][s - 1]):
            continue
        seen.add((vid, s))
        out.append((vid, s))
    return out


def _push_state(c_all, a_all, b_all, x, w, accs, vid, s) -> None:
    c_all.append(accs[vid][s - 1])
    a_all.extend(x[vid * K + s * STEP : vid * K + (s + 1) * STEP])
    b_all.extend(w[vid * K + s * STEP : vid * K + (s + 1) * STEP])


def _spread(candidates: list[int], n: int) -> list[int]:
    if len(candidates) <= n:
        return list(candidates)
    return sorted({candidates[(len(candidates) * q) // n] for q in range(n)})


def _build_negatives(results: list[dict], kinds: list[str], x: array, w: array, rows_index: list[list]) -> dict:
    neg_x, neg_w, neg_y = array("H"), array("H"), array("H")
    rows: list[list] = []
    composition: dict[str, int] = {}

    def push(mistake: str, base: int, xi: Sequence[int], wi: Sequence[int], claimed: int, correct: int | None, verdict: str, note: str) -> None:
        rows.append([len(rows), mistake, base, claimed, correct, verdict, note])
        neg_x.extend(xi)
        neg_w.extend(wi)
        neg_y.append(claimed)
        composition[mistake] = composition.get(mistake, 0) + 1

    for m in G.MISTAKES:
        cands = [r["i"] for r in results if r["mistakes"][m.name]["y"] is not None and r["mistakes"][m.name]["y"] != r["y"]]
        for i in _spread(cands, NEG_PER_MISTAKE):
            r = results[i]
            xi, wi = x[i * K : (i + 1) * K], w[i * K : (i + 1) * K]
            push(m.name, i, xi, wi, r["mistakes"][m.name]["y"], r["y"], "wrong", f"{kinds[i]}: {'/'.join(rows_index[i][1])}")
    # non-finite operands: the checker must reject (D1); the claimed word is what IEEE arithmetic would print
    seeds_ids = [i for i, row in enumerate(rows_index) if "seed" in row[1]][:4]
    for n, (i, where, word, claimed) in enumerate(zip(seeds_ids, ("x", "w", "x", "w"), (0x7F80, 0xFF80, 0x7FC0, 0xFFC0), (0x7F80, 0xFF80, 0x7FC0, 0x7FC0), strict=True)):
        xi, wi = list(x[i * K : (i + 1) * K]), list(w[i * K : (i + 1) * K])
        k = G.Rng("neg-nonfinite", n).below(K)
        (xi if where == "x" else wi)[k] = word
        try:
            G.chain_accs(xi, wi)
        except InvalidArtifact:
            pass
        else:
            raise RuntimeError("a non-finite operand was not rejected by silicon")
        kind = "inf" if word & 0x7F == 0 else "nan"
        push("nonfinite-operand", i, xi, wi, claimed, None, "reject", f"{where}[{k}] = {word:#06x} ({'-' if word >> 15 else '+'}{kind}); claimed the IEEE word")
    # intermediate saturation: a sat-final corner with its saturating block moved from step 95 to step 94 (D8: rejected at step 95)
    sat = [i for i, row in enumerate(rows_index) if row[1][:2] == ["corner", "sat-final"]][:4]
    for i in sat:
        xi, wi = list(x[i * K : (i + 1) * K]), list(w[i * K : (i + 1) * K])
        a, b = (K - STEP), (K - 2 * STEP)
        xi[a : a + STEP], xi[b : b + STEP] = xi[b : b + STEP], xi[a : a + STEP]
        wi[a : a + STEP], wi[b : b + STEP] = wi[b : b + STEP], wi[a : a + STEP]
        try:
            G.chain_accs(xi, wi)
        except InvalidArtifact:
            pass
        else:
            raise RuntimeError("an intermediate saturation was not rejected by silicon")
        push("sat-intermediate", i, xi, wi, results[i]["y"], None, "reject", "steps 94 and 95 of a sat-final corner swapped: acc_94 is +-inf, step 95 is out of the domain; claimed the sticky infinity")
    return {"x": neg_x, "w": neg_w, "y": neg_y, "rows": rows, "composition": composition}


