def _research_result(out: Path, ok: bool, detail: str, fingerprint: dict, measurements: list[dict]) -> None:
    run_id = os.environ.get("RESEARCH_RUN_ID")
    run_dir = os.environ.get("RESEARCH_RUN_DIR")
    if not run_id or not run_dir:
        return
    result = {"schema": "research/result/v0.1", "run_id": run_id, "workload_fingerprint": fingerprint,
              "validation": {"status": "passed" if ok else "failed", "checker": "verity_numerical.bench.instances", "detail": detail, "evidence": []},
              "measurements": measurements, "measurement_files": [], "artifacts": []}
    _write_json(Path(run_dir) / "result.json", result)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="python -m verity_numerical.bench.instances", description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    b = sub.add_parser("build", help="regenerate every array and manifest.json (needs network access to Hugging Face)")
    b.add_argument("--out", default=str(DEFAULT_ROOT))
    b.add_argument("--seeds", default=None, help="seeds directory (default <out>/seeds)")
    b.add_argument("--cache", default=None, help="weight-row cache (default <out>/.cache/hf)")
    b.add_argument("--procs", type=int, default=1)
    v = sub.add_parser("verify", help="digests, seeds, a silicon recheck (sample or --full), the negatives")
    v.add_argument("--root", default=str(DEFAULT_ROOT))
    v.add_argument("--seeds", default=None, help="seeds directory (default <root>/seeds)")
    v.add_argument("--full", action="store_true")
    v.add_argument("--sample", type=int, default=64)
    s = sub.add_parser("stats", help="composition and the sensitivity table")
    s.add_argument("--root", default=str(DEFAULT_ROOT))
    i = sub.add_parser("import-seeds", help="copy the 24 K=1536 seeds from a capture directory")
    i.add_argument("--from", dest="src", required=True)
    i.add_argument("--out", default=str(DEFAULT_ROOT / "seeds"))
    i.add_argument("--repo-copy", default=str(REPO / G.REPO_FIXTURE_DIR))
    h = sub.add_parser("record-hardware", help="append a tc_probe --replay-instances run (probe_results.json) to manifest.json")
    h.add_argument("--root", default=str(DEFAULT_ROOT))
    h.add_argument("--run-id", required=True)
    h.add_argument("--report", required=True, help="the run's probe_results.json")
    h.add_argument("--note", default=None)
    h.add_argument("--build-commit", default=None, help="commit the build's source archive was made from (fills generated.git_head)")
    a = ap.parse_args(argv)

    if a.cmd == "build":
        t0 = time.time()
        try:
            manifest = build(a.out, procs=a.procs, seeds_dir=a.seeds, cache=a.cache)
        except Exception as e:
            _research_result(Path(a.out), False, f"{type(e).__name__}: {e}", {"workload": "bench-instances/build", "dataset": DATASET}, [])
            raise
        rep = verify(a.out, full=False, seeds_dir=a.seeds)
        vu = manifest["tiers"]["vu-k1536"]
        _research_result(Path(a.out), rep["ok"], "built; digests and sample recheck " + ("ok" if rep["ok"] else "; ".join(rep["problems"])),
                         {"workload": "bench-instances/build", "dataset": DATASET, "manifest_sha256": rep["manifest_sha256"],
                          "hf_revision": G.HF_REVISION, "vu_hawkeye_disagreements": vu["cross_check"]["hawkeye_close"]["disagreements"]},
                         [{"name": "build_seconds", "value": round(time.time() - t0, 1), "unit": "s"}])
        return 0 if rep["ok"] else 1
    if a.cmd == "verify":
        rep = verify(a.root, full=a.full, sample=a.sample, seeds_dir=a.seeds)
        return 0 if rep["ok"] else 1
    if a.cmd == "stats":
        for line in _render_stats(Path(a.root)):
            print(line)
        return 0
    if a.cmd == "import-seeds":
        doc = import_seeds(Path(a.src), Path(a.out), Path(a.repo_copy) if a.repo_copy else None)
        print(f"{len(doc['seeds'])} seeds imported to {a.out}")
        return 0
    if a.cmd == "record-hardware":
        entry = record_hardware(a.root, a.run_id, a.report, a.note, a.build_commit)
        print(json.dumps(entry, indent=1))
        return 0
    return 2


if __name__ == "__main__":
    sys.exit(main())
