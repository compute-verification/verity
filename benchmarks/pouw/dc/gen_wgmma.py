"""Writes wgmma.cuh: sm_90a wgmma wrappers whose operand lists (up to 128 accumulator registers) are too long to type.

  python gen_wgmma.py        # rewrites wgmma.cuh beside it; tests/test_dc.py checks the file is current
"""
from __future__ import annotations

import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent

#: (name, shape, PTX types, accumulator C type and constraint, extra immediates after scale-d, A from registers[, 2:4
#: sparse A: wgmma.mma_async.sp with a metadata register and sparsity selector 0, K the logical depth]). An "f16" ctype
#: is an f16x2 accumulator (uint32_t holding two outputs), so a thread writes half the registers of an f32 accumulate.
FORMS = [
    *[(f"s8_n{n}", f"m64n{n}k32", "s32.s8.s8", "int", "r", "", False) for n in (8, 16, 32, 64, 128, 192, 256)],
    ("s8_n256_rs", "m64n256k32", "s32.s8.s8", "int", "r", "", True),
    ("u8s8_n256", "m64n256k32", "s32.u8.s8", "int", "r", "", False),
    # the integer step's eight forms (s8 or u8 operands, .satfinite or not) at the N the s8 GEMMs issue (probes/s8_mma.cu)
    *[(f"i8_{a}{b}_{m}_n{n}", f"m64n{n}k32", f"s32.{a}.{b}" + (".satfinite" if m == "sat" else ""), "int", "r", "", False)
      for n in (64, 128, 256) for m in ("sat", "wrap") for a in ("s8", "u8") for b in ("s8", "u8")],
    ("e4m3_n128", "m64n128k32", "f32.e4m3.e4m3", "float", "f", ", 1, 1", False),
    ("e4m3_n256", "m64n256k32", "f32.e4m3.e4m3", "float", "f", ", 1, 1", False),
    ("e5m2_n256", "m64n256k32", "f32.e5m2.e5m2", "float", "f", ", 1, 1", False),
    ("f16_n256", "m64n256k16", "f32.f16.f16", "float", "f", ", 1, 1, 0, 0", False),
    ("bf16_n256", "m64n256k16", "f32.bf16.bf16", "float", "f", ", 1, 1, 0, 0", False),
    ("bf16_n128", "m64n128k16", "f32.bf16.bf16", "float", "f", ", 1, 1, 0, 0", False),
    ("tf32_n256", "m64n256k8", "f32.tf32.tf32", "float", "f", ", 1, 1", False),
    ("b1_n256", "m64n256k256", "s32.b1.b1.and.popc", "int", "r", "", False),
    ("s8_n256_sp", "m64n256k64", "s32.s8.s8", "int", "r", "", False, True),
    ("e4m3_n256_sp", "m64n256k64", "f32.e4m3.e4m3", "float", "f", ", 1, 1", False, True),
    ("f16_n256_sp", "m64n256k32", "f32.f16.f16", "float", "f", ", 1, 1, 0, 0", False, True),
    ("s8_n256_rs_sp", "m64n256k64", "s32.s8.s8", "int", "r", "", True, True),
    # H32's coverage (probes/sm90_h32_tc.cu): the FP kinds at small N, b1 at small N, and FP16 accumulate
    *[(f"e4m3_n{n}", f"m64n{n}k32", "f32.e4m3.e4m3", "float", "f", ", 1, 1", False) for n in (8, 16, 32, 64)],
    *[(f"f16_n{n}", f"m64n{n}k16", "f32.f16.f16", "float", "f", ", 1, 1, 0, 0", False) for n in (8, 64, 128)],
    *[(f"bf16_n{n}", f"m64n{n}k16", "f32.bf16.bf16", "float", "f", ", 1, 1, 0, 0", False) for n in (8, 64)],
    *[(f"tf32_n{n}", f"m64n{n}k8", "f32.tf32.tf32", "float", "f", ", 1, 1", False) for n in (8, 64, 128)],
    *[(f"b1_n{n}", f"m64n{n}k256", "s32.b1.b1.and.popc", "int", "r", "", False) for n in (8, 64, 128)],
    *[(f"f16f16_n{n}", f"m64n{n}k16", "f16.f16.f16", "f16", "r", ", 1, 1, 0, 0", False) for n in (8, 256)],
    *[(f"e4m3f16_n{n}", f"m64n{n}k32", "f16.e4m3.e4m3", "f16", "r", ", 1, 1", False) for n in (8, 256)],
    ("e5m2f16_n256", "m64n256k32", "f16.e5m2.e5m2", "f16", "r", ", 1, 1", False),
]


def n_of(shape: str) -> int:
    return int(shape.split("n")[1].split("k")[0])


def form(name, shape, types, ctype, con, extra, rs, sp=False) -> str:
    nacc = 64 * n_of(shape) // 128 // (2 if ctype == "f16" else 1)
    ctype = "uint32_t" if ctype == "f16" else ctype
    regs = ", ".join(f"%{i}" for i in range(nacc))
    outs = ", ".join(f'"+{con}"(d[{i}])' for i in range(nacc))
    if rs:
        na = 4
        a_op = "{" + ", ".join(f"%{nacc + i}" for i in range(na)) + "}"
        a_in, a_sig = ", ".join(f'"r"(a[{i}])' for i in range(na)), "const uint32_t (&a)[4]"
    else:
        na, a_op, a_in, a_sig = 1, f"%{nacc}", '"l"(da)', "uint64_t da"
    b_op = f"%{nacc + na}"
    meta, e_in, e_sig = (f"%{nacc + na + 1}, 0, ", ', "r"(e)', ", uint32_t e") if sp else ("", "", "")
    sd = f"%{nacc + na + 1 + sp}"
    ins = f'{a_in}, "l"(db){e_in}, "r"(scale_d)'
    sig = f"{ctype} (&d)[{nacc}], {a_sig}, uint64_t db{e_sig}, int scale_d"
    note = {(True, False): " (A from registers)", (False, True): " (2:4 sparse A, metadata e, selector 0)",
            (True, True): " (2:4 sparse A from registers, metadata e, selector 0)"}.get((rs, sp), "")
    return (f"// {shape}.{types}{note}: {nacc} accumulator registers a thread\n"
            f"__device__ __forceinline__ void wgmma_{name}({sig}) {{\n"
            f'  asm volatile(\n'
            f'      "{{\\n.reg .pred p;\\nsetp.ne.b32 p, {sd}, 0;\\n"\n'
            f'      "wgmma.mma_async{".sp" if sp else ""}.sync.aligned.{shape}.{types} {{{regs}}}, {a_op}, {b_op}, '
            f'{meta}p{extra};\\n}}\\n"\n'
            f"      : {outs}\n"
            f"      : {ins});\n"
            f"}}\n")


def render() -> str:
    head = ("// Generated by gen_wgmma.py; edit that, not this. sm_90a wgmma wrappers: accumulators in registers, B (and A,\n"
            "// unless _rs) from shared-memory matrix descriptors (wgmma_desc), scale_d 0 overwrites D and 1 accumulates.\n"
            "#pragma once\n#include <cstdint>\n\n"
            "__device__ __forceinline__ void wgmma_fence() { asm volatile(\"wgmma.fence.sync.aligned;\" ::: \"memory\"); }\n"
            "__device__ __forceinline__ void wgmma_commit() { asm volatile(\"wgmma.commit_group.sync.aligned;\" ::: \"memory\"); }\n"
            "template <int N> __device__ __forceinline__ void wgmma_wait() {\n"
            "  asm volatile(\"wgmma.wait_group.sync.aligned %0;\" ::\"n\"(N) : \"memory\");\n}\n"
            "// Pins an accumulator array across a wgmma wait, so ptxas reads it only after the wait (CUTLASS's warpgroup_fence_operand).\n"
            "template <class T, int N> __device__ __forceinline__ void wgmma_hold(T (&d)[N]) {\n"
            "#pragma unroll\n  for (int i = 0; i < N; i++) {\n"
            "    if constexpr (sizeof(T) == 4 && T(0.5) != T(0)) asm volatile(\"\" : \"+f\"(d[i])::\"memory\");\n"
            "    else asm volatile(\"\" : \"+r\"(d[i])::\"memory\");\n  }\n}\n\n")
    return head + "\n".join(form(*f) for f in FORMS)


def main() -> int:
    (HERE / "wgmma.cuh").write_text(render())
    return 0


if __name__ == "__main__":
    sys.exit(main())
