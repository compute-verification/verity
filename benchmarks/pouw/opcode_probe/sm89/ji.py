"""FACET-BREAK r3's joint-issue schedule on the L40S (EPS1 ADA r3): the grid `ji.cuh` runs, its pins, and every
program's load on every sm_89 row.

  python ji.py emit K [--pins GATE.json] > jiK.cu  # IMMA.168{K}'s grid (K 16 or 32), pinned from the unpinned build's gate
  python ji.py loads OUT...                         # each timed program's load on every row ADA-89 holds, heaviest first

The grid (each program `j<K>_<lane>_q<Q>_a<NA>u<U>_w<W>`: Q lane ops a 8 MMAs, NA accumulators, U groups of 8 MMAs an
iteration, W warps a SMSP, one block a SM): FMUL by an immediate at 2-8 accumulators, Q 16-160, 1, 2 or 4 warps a SMSP;
every other lane (FADD/FFMA by an immediate, FFMA, IADD3, add/xor by an immediate, LOP3, IMAD, IMAD by an immediate) at
2, 3 and 8 accumulators; unroll 2 and 4; 3, 6 and 8 warps a SMSP. A program keeps its pins only when its loop holds 8U
MMAs, QU lane ops of its lane and nothing but loop overhead (IADD3, ISETP, the uniform counter, MOV) beside them: `emit
--pins` drops the rest (unroll 4 at Q 64 and 112, which ptxas splits with a CALL), so every timed loop is exactly the
schedule its name says.

A load is Σ_k u_kr·x_k over the census classes whose opcodes the loop holds (x_k: warp instructions a SMSP-cycle). MOV has
no class and is left out, so a load is a lower bound; a rate row's coefficients carry the 2% margin, so a load > 1 beats
it.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parents[1] / "machine_model"))

LANES = {  # lane -> (enum, its SASS opcodes)
    "fmuli": ("L_FMULI", ("FMUL",)), "faddi": ("L_FADDI", ("FADD",)), "ffmai": ("L_FFMAI", ("FFMA",)),
    # ptxas puts some of a long add stream on the IMAD pipe (IMAD.IADD): a mix the load prices as IMAD
    "ffma": ("L_FFMA", ("FFMA",)), "iadd3": ("L_IADD3", ("IADD3", "IMAD.IADD")),
    "axi": ("L_AXI", ("IADD3", "IMAD.IADD", "LOP3.LUT")),
    "lop3": ("L_LOP3", ("LOP3.LUT",)), "imad": ("L_IMAD", ("IMAD",)), "imadi": ("L_IMADI", ("IMAD",)),
}
MMA = {16: "IMMA.16816.S8.S8", 32: "IMMA.16832.S8.S8"}
OVERHEAD = re.compile(r"IADD3|ISETP\..*|UIADD3|UISETP\..*|MOV|IMAD\.MOV\.U32|NOP|BRA")


def grid(k: int) -> list[tuple[str, int, int, str, int, int]]:
    """(name, NA, U, lane, Q, W) for IMMA.168{k}."""
    pts = set()
    for na in (2, 3, 4, 6, 8):
        for q in (16, 32, 48, 64, 80, 96, 112, 128, 160):
            for w in (1, 2, 4):
                pts.add((na, 1, "fmuli", q, w))
    for lane in LANES:
        for na in (2, 3, 8):
            for q in (32, 64, 112):
                pts.add((na, 1, lane, q, 2))
    for na in (2, 3, 8):
        for u in (2, 4):
            for q in (16, 32, 48, 64, 112):
                pts.add((na, u, "fmuli", q, 2))
    for na in (2, 3):
        for q in (64, 112):
            for w in (3, 6, 8):
                pts.add((na, 1, "fmuli", q, w))
    return sorted((f"j{k}_{lane}_q{q}_a{na}u{u}_w{w}", na, u, lane, q, w) for na, u, lane, q, w in pts)


def name_of(name: str) -> tuple[int, str, int, int, int, int]:
    k, lane, q, au, w = name.split("_")
    na, u = au[1:].split("u")
    return int(k[1:]), lane, int(q[1:]), int(na), int(u), int(w[1:])


def exact(name: str, top: dict[str, int]) -> bool:
    """The loop is the schedule `name` says: 8U MMAs, QU lane ops, and only loop overhead beside them."""
    k, lane, q, _, u, _ = name_of(name)
    ops = LANES[lane][1]
    if top.get(MMA[k]) != 8 * u:
        return False
    lane_n = sum(n for op, n in top.items() if op in ops)
    if not q * u <= lane_n <= q * u + ("IADD3" in ops):
        return False
    return all(op == MMA[k] or op in ops or OVERHEAD.fullmatch(op) for op in top)


def emit(k: int, pins: Path | None) -> str:
    tops = {}
    if pins:
        for v in json.loads(pins.read_text())["verdicts"]:
            loops = (v.get("verdict") or {}).get("loops") or []
            if len(loops) == 1 and exact(v["probe"], loops[0]["top"]):
                tops[v["probe"]] = loops[0]["top"]
    pts = [p for p in grid(k) if not pins or p[0] in tops]
    out = [f"// generated by ji.py emit {k}{' --pins' if pins else ''}: FACET-BREAK r3's schedule beside IMMA.168{k}",
           '#include "ji.cuh"', ""]
    out += [f"JM({n}, {k}, {na}, {u}, {LANES[lane][0]}, {q}, {128 * w})" for n, na, u, lane, q, w in pts]
    out += ["", "static const OpProbe PROBES[] = {"]
    for n, na, u, lane, q, w in pts:
        ex = ",".join(f"{op}={c}" for op, c in tops[n].items()) if pins else f"{MMA[k]}={8 * u}"
        out.append(f'    {{.name = "{n}", .kernel = (const void*){n}, .tpb = {128 * w}, .expect = "{ex}", '
                   f'.counted = "{MMA[k]}", .iters = 2048}},')
    out += ["};", "", "int main(int argc, char** argv) { return op_main(argc, argv, PROBES); }", ""]
    return "\n".join(out)


def class_of(op: str) -> str | None:
    """The sm_89 census class of a loop opcode (None: no class, left out of the load)."""
    if op.startswith("IMMA.16816"):
        return "IMMA16816"
    if op.startswith("IMMA.16832"):
        return "IMMA16832"
    if op.startswith("U"):
        return "UNI"
    base = op.split(".")[0]
    return {"FMUL": "FFMA", "FADD": "FFMA", "FFMA": "FFMA", "IADD3": "ALU", "LOP3": "ALU", "IMAD": "IMAD",
            "ISETP": "ALU"}.get(base)


def loads(outs: list[Path]) -> list[dict]:
    from verity_machine_model.model import census, device, model

    d = device("sm_89")
    m = model(d)
    cen = census(m, m.epochs[-1], d)
    res = []
    for out in outs:
        for line in (out / "rows.jsonl").read_text().splitlines():
            r = json.loads(line)
            x: dict[str, float] = {}
            unpriced = {}
            for key, rate in r["rates"].items():
                op = key.split(":", 1)[1]
                k = class_of(op)
                if k is None:
                    unpriced[op] = rate / 4
                else:
                    x[k] = x.get(k, 0) + rate / 4
            ld = {}
            for k, xk in x.items():
                for row, u in cen.get(k, {}).items():
                    ld[row] = ld.get(row, 0) + u * xk
            res.append({"probe": r["probe"], "run": r.get("run"), "x": x, "unpriced": unpriced,
                        "loads": dict(sorted(ld.items(), key=lambda t: -t[1]))})
    return res


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    e = sub.add_parser("emit")
    e.add_argument("k", type=int, choices=(16, 32))
    e.add_argument("--pins", type=Path)
    lo = sub.add_parser("loads")
    lo.add_argument("outs", nargs="+", type=Path)
    a = ap.parse_args()
    if a.cmd == "emit":
        sys.stdout.write(emit(a.k, a.pins))
    else:
        for r in loads(a.outs):
            print(json.dumps(r))


if __name__ == "__main__":
    main()
