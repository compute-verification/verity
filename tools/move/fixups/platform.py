#: Lean packages whose `TRUSTED.sha256` the move's rewrites leave stale (the grader's pins, the trusted layer's Lake files):
#: regenerated by their README's command, which must name the files the old one did, in its order
REPIN = ["verity/experimental/protocols/pous/lean"]

#: lean-audit.json records whose `reads` keys still name a module rename.py renamed (it leaves a lock's records standing): the
#: keys renamed, re-sorted and written with the Lean check's own `text()`; `--update` on the result prints no statement change
RENAMED_READS = {"Security/lean-audit.json": ("Specs.", "Models.")}

#: (path, first line, the line it stops before): the text from one to the other goes.
CUTS = [
    # the .pth tests: the catalog, the kernels and experimental have no .pth of their own any more
    ("integrations/vllm/tests/ops/test_pod_bootstrap.py",
     "def test_bootstrap_writes_the_experimental_pth_and_readiness_checks_it() -> None:\n",
     "def test_gpu_mode_record_shape_is_unchanged() -> None:\n"),
]


def sha256(p: Path) -> str:
    return hashlib.sha256(p.read_bytes()).hexdigest()


def main(root: Path) -> int:
    problems, changed = [], set()
    texts: dict[str, str] = {}

    def text(path: str) -> str | None:
        if path not in texts:
            p = root / path
            texts[path] = p.read_text(encoding="utf-8") if p.is_file() else None
        return texts[path]

    def resolve(path: str) -> str:
        """A glob names the one file it matches outside a Lake build directory (Lean files, wherever the move put them)."""
        if "*" not in path:
            return path
        found = sorted(q.relative_to(root).as_posix() for q in root.glob(path) if ".lake" not in q.parts)
        if len(found) != 1:
            problems.append(f"{path}: matches {found or 'nothing'}, not one file")
            return path
        return found[0]

    for path, old, new in EDITS:
        assert old not in new, (path, old)
        path = resolve(path)
        t = text(path)
        if t is None:
            problems.append(f"{path}: missing")
        elif old in t:
            texts[path] = t.replace(old, new)
            changed.add(path)
        elif new not in t:
            problems.append(f"{path}: neither the generated text nor its fix: {old.splitlines()[0][:100]!r}")
    for path, start, stop in CUTS:
        t = text(path)
        if t is None:
            problems.append(f"{path}: missing")
        elif start in t and stop in t and t.index(start) < t.index(stop):
            texts[path] = t[:t.index(start)] + t[t.index(stop):]
            changed.add(path)
        elif start in t or stop not in t:
            problems.append(f"{path}: can't cut from {start.strip()!r} to {stop.strip()!r}")
    whole = []
    for path, (generated, source) in WHOLE.items():
        p = root / path
        if p.is_file() and p.read_bytes() == source.read_bytes():
            continue
        if not p.is_file() or sha256(p) != generated:
            problems.append(f"{path}: not the generated file {generated[:12]} this replaces; merge {source.name} by hand")
        else:
            whole.append((p, source))
    if problems:
        print("\n".join(problems), file=sys.stderr)
        return 1
    for p, source in whole:
        p.write_bytes(source.read_bytes())
        print(f"wrote {p.relative_to(root)}")
    for path in sorted(changed):
        (root / path).write_text(texts[path], encoding="utf-8")
        print(f"fixed {path}")
    for pkg in REPIN:
        d = root / pkg
        m = re.search(r"^(sha256sum [^\n]*) > TRUSTED\.sha256$", re.sub(r"\\\n\s*", "", (d / "README.md").read_text()), re.M)
        if not m:
            problems.append(f"{pkg}/README.md: no `sha256sum ... > TRUSTED.sha256` command")
            continue
        r = subprocess.run(["sh", "-c", m.group(1)], cwd=d, capture_output=True, text=True)
        old = (d / "TRUSTED.sha256").read_text()
        if r.returncode or [ln.split("  ", 1)[1] for ln in r.stdout.splitlines()] != [ln.split("  ", 1)[1] for ln in old.splitlines()]:
            problems.append(f"{pkg}/TRUSTED.sha256: the README's command fails or names other files: {r.stderr.strip()[:200]}")
        elif r.stdout != old:
            (d / "TRUSTED.sha256").write_text(r.stdout)
            print(f"repinned {pkg}/TRUSTED.sha256")
    if RENAMED_READS:
        spec = importlib.util.spec_from_file_location("lean_check_for_fixups", root / "tools" / "verity" / "lean" / "check.py")
        check = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(check)
    for path, (old, new) in RENAMED_READS.items():
        doc = json.loads((root / path).read_text())
        reads = dict(sorted((new + k[len(old):] if k.startswith(old) else k, v) for k, v in doc["reads"].items()))
        if len(reads) != len(doc["reads"]):
            problems.append(f"{path}: renaming its `reads` from {old} to {new} would merge two records")
            continue
        text = check.text({**doc, "reads": reads})
        if text != (root / path).read_text():
            (root / path).write_text(text)
            print(f"renamed {path}'s `reads` from {old} to {new}")
    if problems:
        print("\n".join(problems), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(Path.cwd()))
