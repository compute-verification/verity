SWEEP_EXEMPT = ("tools/move/", "tools/research/src/research/store/moves.json", "uv.lock", "integrations/vllm/tools/migrate/",
                "integrations/vllm/tests/migrate/")
SWEEP = re.compile(r"verity[./]experimental\b")


def sha256(b: bytes) -> str:
    return hashlib.sha256(b).hexdigest()


def git(root: Path, *args: str) -> str:
    return subprocess.run(["git", *args], cwd=root, check=True, capture_output=True, text=True).stdout


def main(root: Path) -> int:
    problems, changed = [], set()
    texts: dict[str, str] = {}

    def text(path: str) -> str | None:
        if path not in texts:
            p = root / path
            texts[path] = p.read_text(encoding="utf-8") if p.is_file() else None
        return texts[path]

    for path, old, new in EDITS:
        assert old not in new, (path, old)
        t = text(path)
        if t is None:
            problems.append(f"{path}: missing")
        elif old in t:
            texts[path] = t.replace(old, new)
            changed.add(path)
        elif new not in t:
            problems.append(f"{path}: neither the generated text nor its fix: {old.splitlines()[0][:100]!r}")
    if problems:
        print("\n".join(problems), file=sys.stderr)
        return 1
    tracked = git(root, "ls-files", "-z").split("\0")
    for path in (p for p in tracked if p.endswith(".lean")):
        t = text(path)
        if t is None:
            continue
        fixed = t
        for old, new in LEAN_PATHS:
            fixed = fixed.replace(old, new)
        if fixed != t:
            texts[path] = fixed
            changed.add(path)
    for path in sorted(changed):
        (root / path).write_text(texts[path], encoding="utf-8")
        print(f"fixed {path}")
    for pkg in REPIN:
        d = root / pkg
        m = re.search(r"^(sha256sum [^\n]*) > TRUSTED\.sha256$", re.sub(r"\\\n\s*", "", (d / "README.md").read_text()), re.M)
        if not m:
            problems.append(f"{pkg}/README.md: no `sha256sum ... > TRUSTED.sha256` command")
            continue
        r = subprocess.run(["sh", "-c", m.group(1)], cwd=d, capture_output=True, text=True)
        old = (d / "TRUSTED.sha256").read_text()
        if r.returncode or [ln.split("  ", 1)[1] for ln in r.stdout.splitlines()] != [ln.split("  ", 1)[1] for ln in old.splitlines()]:
            problems.append(f"{pkg}/TRUSTED.sha256: the README's command fails or names other files: {r.stderr.strip()[:200]}")
        elif r.stdout != old:
            (d / "TRUSTED.sha256").write_text(r.stdout)
            print(f"repinned {pkg}/TRUSTED.sha256")
    for manifest, records in REDIGEST.items():
        now = (root / manifest).read_bytes()
        before = git(root, "show", f"HEAD^:{manifest}").encode()

        def fetched(raw: bytes) -> list:
            return [{k: v for k, v in p.items() if not (p.get("type") == "path" and k == "dir")}
                    for p in json.loads(raw).get("packages", [])]

        if fetched(now) != fetched(before) or {k: v for k, v in json.loads(now).items() if k != "packages"} != {
                k: v for k, v in json.loads(before).items() if k != "packages"}:
            problems.append(f"{manifest}: changed in more than its path requirements' directories; regenerate {records}")
            continue
        for rec in records:
            t = (root / rec).read_text(encoding="utf-8")
            fixed = re.sub(rf'("{re.escape(manifest)}": ")[0-9a-f]{{64}}"', rf'\g<1>{sha256(now)}"', t)
            if fixed == t and f'"{manifest}": "{sha256(now)}"' not in t:
                problems.append(f"{rec}: records no digest of {manifest}")
            elif fixed != t:
                (root / rec).write_text(fixed, encoding="utf-8")
                print(f"redigested {manifest} in {rec}")
    stale = []
    for path in tracked:
        if not path or path.startswith(SWEEP_EXEMPT) or "/CHANGELOG.md" in f"/{path}":
            continue
        p = root / path
        if p.is_file() and SWEEP.search(p.read_text(encoding="utf-8", errors="replace")):
            stale.append(path)
    if stale:
        problems.append(f"still naming verity/experimental: {stale}")
    if problems:
        print("\n".join(problems), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(Path.cwd()))
