#!/usr/bin/env python3
"""The Security layout move (`Security/` as three trees), whole: `python3 tools/move/security_layout.py`, at the root of
a clean checkout of the tree before the move.

`tools/move/rename.py --map tools/move/security_map.toml`, then the three edits rename.py doesn't make:
- the Slack registry: an `owns` entry the words made a repeat of the one before it goes;
- the property proofs' roots (`Proofs.Properties.*`) leave `security_properties`' lakefile and lock for `security_proofs'`;
- PoUS's `TRUSTED.sha256`, regenerated by its README's command.

One script, so that `tools/move/restack.py BRANCH --move-commit M --script tools/move/security_layout.py` carries an open
branch across the move by rerunning all of it.
"""
import json
import re
import subprocess
import sys
from pathlib import Path

PREFIX = "Proofs.Properties."
ROOTS = re.compile(r'(\[\[lean_lib\]\]\nname = "(?P<lib>\w+)"\nroots = )\[(?P<items>[^\]]*)\]')


def dedupe_registry(p=Path(".agents/skills/using-slack/registry.json")):
    lines, out = p.read_text().splitlines(keepends=True), []
    for line in lines:
        if out and re.fullmatch(r'\s*"[^"\n]*",\s*', line) and line == out[-1]:
            continue
        out.append(line)
    p.write_text("".join(out))
    return len(lines) - len(out)


def wrap(items):
    out, line = [], "roots = ["
    for i, it in enumerate(items):
        piece = f'"{it}"' + (", " if i < len(items) - 1 else "]")
        if len(line) + len(piece.rstrip()) > 120:
            out.append(line.rstrip())
            line = "  "
        line += piece
    out.append(line)
    return "\n".join(out)


def lakefile_roots(path, lib, edit):
    p = Path(path)
    s = p.read_text()
    m = next(m for m in ROOTS.finditer(s) if m.group("lib") == lib)
    items = re.findall(r'"([^"]+)"', m.group("items"))
    p.write_text(s[:m.start()] + m.group(1).removesuffix("roots = ") + wrap(edit(items)) + s[m.end():])
    return items


def move_roots(check):
    moved = []

    def take(items):
        moved.extend(i for i in items if i.startswith(PREFIX))
        return [i for i in items if not i.startswith(PREFIX)]
    lakefile_roots("Security/Properties/lakefile.toml", "Properties", take)
    lakefile_roots("Security/Proofs/lakefile.toml", "Proofs", lambda items: items + [m for m in moved if m not in items])
    pl, ql = Path("Security/Properties/lean-audit.json"), Path("Security/Proofs/lean-audit.json")
    props, proofs = json.loads(pl.read_text()), json.loads(ql.read_text())
    lock_moved = [r for r in props["roots"] if r.startswith(PREFIX)]
    props["roots"] = [r for r in props["roots"] if not r.startswith(PREFIX)]
    proofs["roots"] = proofs["roots"] + [r for r in lock_moved if r not in proofs["roots"]]
    check.dump(pl.parent, props)
    check.dump(ql.parent, proofs)
    return moved, lock_moved


def repin_pous(d=Path("verity/core/protocols/pous/lean")):
    text = re.sub(r"\\\n\s*", "", (d / "README.md").read_text())
    cmd = re.search(r"^(sha256sum [^\n]*> TRUSTED\.sha256)$", text, re.M).group(1)
    subprocess.run(["bash", "-c", cmd], cwd=d, check=True)


if __name__ == "__main__":
    subprocess.run([sys.executable, "tools/move/rename.py", "--map", "tools/move/security_map.toml"], check=True)
    sys.path.insert(0, "tools/verity/lean")
    import check  # noqa: E402
    print("registry repeats dropped:", dedupe_registry())
    moved, lock_moved = move_roots(check)
    print(f"roots moved: lakefile {len(moved)}, lock {len(lock_moved)}")
    repin_pous()
    print("PoUS repinned")
    subprocess.run(["git", "add", "-A"], check=True)
