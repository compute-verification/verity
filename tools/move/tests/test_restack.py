def test_a_branch_editing_a_moved_file(repo):
    on(repo, "pr", ("edit util", {"app/util.py": edit(UTIL, "return 5", "return 50")}))
    r = RS.restack("pr", "move", cwd=str(repo))
    assert r["status"] == "clean", r
    assert [s["step"] for s in r["steps"]] == ["base", "script", "moved"]
    assert "app/util.py" not in paths(repo, r["result"])
