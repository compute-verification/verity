def test_restacking_is_idempotent(repo):
    on(repo, "pr", ("edit util", {"app/util.py": edit(UTIL, "return 5", "return 50")}),
       ("add extra", {"app/extra.py": "import app.util\n"}))
    first = RS.restack("pr", "move", cwd=str(repo))
    again = RS.restack("pr", "move", cwd=str(repo))
    assert first["status"] == again["status"] == "clean"
    assert RS.tree_of(first["result"], str(repo)) == RS.tree_of(again["result"], str(repo))
    git(repo, "branch", "restacked", first["result"])
    assert RS.restack("restacked", "move", cwd=str(repo))["status"] == "up-to-date"
    # Rerunning the script on the moved tree changes nothing: the codemod is a fixed point.
    git(repo, "checkout", "-q", "restacked")
    subprocess.run(["python3", "tools/move/layout.py"], cwd=repo, check=True)
    assert git(repo, "status", "--porcelain") == ""


