def test_the_command_a_skipped_crossing_prints_names_its_moves_skips_none_and_builds_the_same_result_commit(
        late, dated, monkeypatch, capsys):
    """The printed command is how the owner says the skip is right: it names each move the crossing crossed, and what it
    merged last, so it skips nothing, is `clean`, and its result is the very commit the skipped crossing built (the commits'
    dates are fixed here, so the same tree, parents and messages are the same id)."""
    repo, first, second = late["repo"], late["first"], late["second"]
