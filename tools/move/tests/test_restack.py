def git(repo: Path, *args: str) -> str:
    return subprocess.run(["git", "-c", "commit.gpgsign=false", *args], cwd=repo, check=True, capture_output=True,
                          text=True).stdout.strip()


def commit(repo: Path, msg: str, files: dict[str, str | None] = {}) -> str:
    for path, text in files.items():
        p = repo / path
        if text is None:
            p.unlink()
        else:
            p.parent.mkdir(parents=True, exist_ok=True)
            p.write_text(text)
    git(repo, "add", "-A")
    git(repo, "commit", "-q", "--allow-empty", "-m", msg)
    return git(repo, "rev-parse", "HEAD")


def edit(text: str, needle: str, new: str) -> str:
    assert needle in text
    return text.replace(needle, new, 1)


def on(repo: Path, branch: str, *steps: tuple[str, dict]) -> str:
    git(repo, "checkout", "-q", branch)
    for msg, files in steps:
        sha = commit(repo, msg, files)
    git(repo, "checkout", "-q", "main")
    return sha


def generate(repo: Path, line: str = "") -> str:
    """The move commit: the toy script run at the root of main's checkout, committed (with ``line``, its move line)."""
    subprocess.run(["python3", "tools/move/layout.py"], cwd=repo, check=True)
    return commit(repo, "layout: generated by tools/move/layout.py" + line)


