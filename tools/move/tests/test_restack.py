def _reports(path: Path, python: str, version: str) -> str:
    """An interpreter at ``path`` that is ``python`` but for the version it reports."""
    path.write_text(f'#!/bin/sh\ncase "$2" in *sys.version*) echo "{version}";; *) exec {python} "$@";; esac\n')
    path.chmod(0o755)
    return str(path)


