def show(repo: Path, rev: str, path: str) -> str:
    return subprocess.run(["git", "show", f"{rev}:{path}"], cwd=repo, check=True, capture_output=True, text=True).stdout


def paths(repo: Path, rev: str) -> set[str]:
    return set(git(repo, "ls-tree", "-r", "--name-only", rev).splitlines())


def test_the_move_commit_itself(repo):
    assert "app/util.py" not in paths(repo, "move")
    assert show(repo, "move", "app/main.py").startswith("from app.core.util import f1\nimport app.core.util\n")


def test_a_branch_editing_a_moved_file(repo):
    on(repo, "pr", ("edit util", {"app/util.py": edit(UTIL, "return 5", "return 50")}))
    r = RS.restack("pr", "move", cwd=str(repo))
    assert r["status"] == "clean", r
    assert [s["step"] for s in r["steps"]] == ["base", "script", "moved"]
    assert "app/util.py" not in paths(repo, r["result"])
    assert "return 50" in show(repo, r["result"], "app/core/util.py")
    assert show(repo, r["result"], "app/core/util.py") == edit(UTIL, "return 5", "return 50")
    assert git(repo, "rev-list", "--parents", "-n", "1", r["result"]).split()[1:] == [r["steps"][1]["commit"], RS.rev("move", str(repo))]
    assert RS.TRAILER_MOVE in git(repo, "log", "-1", "--format=%B", r["steps"][1]["commit"])


def test_a_branch_adding_a_file_that_imports_a_moved_module(repo):
    extra = "from app.util import f3\nfrom app import util  # a from-import of the package is not renamed\n\nX = app.util.f4\n"
