def show(repo: Path, rev: str, path: str) -> str:
    return subprocess.run(["git", "show", f"{rev}:{path}"], cwd=repo, check=True, capture_output=True, text=True).stdout


def paths(repo: Path, rev: str) -> set[str]:
    return set(git(repo, "ls-tree", "-r", "--name-only", rev).splitlines())


