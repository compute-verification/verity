def test_a_branch_adding_a_file_under_a_moved_directory(repo, tmp_path):
    """A directory move carries the branch's new file along, which rename detection only guesses at."""
    r2 = tmp_path / "dirs"
    shutil.copytree(repo, r2)
    git(r2, "checkout", "-q", "base")
    git(r2, "checkout", "-q", "-B", "main")
    commit(r2, "map a directory", {"tools/move/layout_map.toml": '[paths]\n"app" = "lib/app"\n\n[modules]\n"app" = "lib.app"\n'})
    git(r2, "tag", "-f", "move", generate(r2))
    on(r2, "pr", ("add", {"app/new.py": "import app.util\n"}))
    r = RS.restack("pr", "move", cwd=str(r2))
    assert r["status"] == "clean", r
    assert show(r2, r["result"], "lib/app/new.py") == "import lib.app.util\n"
    assert not any(p.startswith("app/") for p in paths(r2, r["result"]))


