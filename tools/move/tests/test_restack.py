def test_a_move_found_on_main_that_a_branch_is_based_after_is_skipped_and_named_where_a_later_moves_base_has_it(
        late, monkeypatch, capsys):
    """A branch merged with main beside a move that landed later is based after that move, and a restack across it would
    double main's commits. Found on main with a later move whose base contains it, it is skipped and named: the later
    move's base merge brings it in, as the owner's merge of main would, and the result is the tree that later move gives
    when it alone is named. The skipped move's script has not run on the branch's own lines, which the output says, and
    the crossing is `clean-skipped`, never `clean`."""
    repo, first, second = late["repo"], late["first"], late["second"]
    moves = RS.moves_on("main", "pr", str(repo))
    assert [m for m, _, _ in moves] == [first, second]
    assert RS.restack("pr", first, cwd=str(repo), main="main")["status"] == "based-after"
    monkeypatch.chdir(repo)
    assert RS.main(["pr", "--main", "main", "--dry-run", "--json"]) == 1
    [found] = json.loads(capsys.readouterr().out)
    assert (found["status"], found["crossed"]) == ("clean-skipped", [second])
    assert found["skipped"] == [{"move": first, "script": "tools/move/layout.py",
                                 "args": ["--map", "tools/move/layout_map.toml"]}]
    assert RS.main(["pr", "--move-commit", second, "--main", "main", "--dry-run", "--json"]) == 0
    [named] = json.loads(capsys.readouterr().out)
    assert (named["status"], named["skipped"]) == ("clean", [])
    assert RS.tree_of(found["result"], str(repo)) == RS.tree_of(named["result"], str(repo))
    assert RS.contains(first, found["result"], str(repo)) and RS.contains(second, found["result"], str(repo))
    assert show(repo, found["result"], "app/core/util.py") == edit(UTIL, "return 5", "return 50")
    assert show(repo, found["result"], "app/extra.py") == "import app.util\nimport app.run\n", "the first map's name stands"
    assert RS.main(["pr", "--main", "main", "--dry-run"]) == 1
    said = capsys.readouterr().out
    assert said.startswith("pr: clean-skipped ")
    assert f"\n    skipped the move {first[:12]} (tools/move/layout.py --map tools/move/layout_map.toml): " in said
    assert "NOT run on the branch's own lines" in said and "that map's old names" in said


def test_a_carry_that_skipped_a_move_is_clean_skipped_where_it_would_be_clean_or_up_to_date(late, monkeypatch):
    """The status is `carry`'s, whoever calls it: with a move skipped it is never `clean` or `up-to-date`, and with none
    skipped it is what it was."""
    repo, first, second = late["repo"], late["first"], late["second"]
    moves, real = RS.moves_on("main", "pr", str(repo)), RS.restack
    found = RS.carry("pr", moves, "main", cwd=str(repo), main="main", found=True)
    assert (found["status"], [s["move"] for s in found["skipped"]], found["crossed"]) == ("clean-skipped", [first], [second])
    assert RS.contains(second, found["result"], str(repo))
    named = RS.carry("pr", moves[1:], "main", cwd=str(repo), main="main")
    assert (named["status"], named["skipped"], named["crossed"]) == ("clean", [], [second])

    def up_to_date(*a, **k):
        r = real(*a, **k)
        return {**r, "status": "up-to-date"} if r["status"] == "clean" else r

    monkeypatch.setattr(RS, "restack", up_to_date)
    assert RS.carry("pr", moves, "main", cwd=str(repo), main="main", found=True)["status"] == "clean-skipped"
    assert RS.carry("pr", moves[1:], "main", cwd=str(repo), main="main")["status"] == "up-to-date"


