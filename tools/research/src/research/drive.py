def failed_suites(run_dir: Path) -> list[dict]:
    """Each failed suite's record: from `suites.json` and `suites-lean.json` once the check ended, else from what it has written
    of its failures so far (`PROGRESS`)."""
    done = [s for s in _docs(run_dir, "suites.json", "suites-lean.json") if s.get("status") == "failed"]
    return done or _docs(run_dir, *PROGRESS[1:])


def _fetch(repo: Path, rid: str, names: list[str]) -> Path | None:
    from .merge import fetch_run

    got = fetch_run(rid, names, repo)
    return got[0] if got else None


def evidence(repo: Path, ids: list[str]) -> list[Path]:
    """The local run dirs of ``ids`` with their steps, live records, spans, suite reports and failed suites' logs fetched
    (`research status --also`)."""
    def one(rid: str) -> Path | None:
        if (d := _fetch(repo, rid, [*PROGRESS, SPANS, LIVE, "suites.json", "suites-lean.json"])) is None:
            return None
        logs = [f"suites/{Path(s['log']).name}" for s in failed_suites(d) if s.get("log")]
        logs += [Path(st["log"]).name for st in failed_steps(d) if st.get("log") and st.get("step") not in ("pytest", "lean-suites")]
        if logs:
            _fetch(repo, rid, logs)
        return d

    return [d for d in _each(one, ids) if d is not None]


def failed_steps(run_dir: Path) -> list[dict]:
    out = []
    with contextlib.suppress(OSError):
        for line in (run_dir / PROGRESS[0]).read_text().splitlines():
            with contextlib.suppress(ValueError):
                if (rec := json.loads(line)).get("status") == "failed":
                    out.append(rec)
    return out


def suite_pyproject(repo: Path, commit: str, suite: str) -> dict:
    """Suite ``suite``'s (its directory's) pyproject.toml at ``commit``; {} when it has none or it isn't TOML."""
    import tomllib

    own = "pyproject.toml" if suite.strip("/") in ("", ".") else f"{suite.strip('/')}/pyproject.toml"
    r = _git(repo, "show", f"{commit}:{own}", check=False)
    try:
        return tomllib.loads(r.stdout) if not r.returncode else {}
    except tomllib.TOMLDecodeError:
        return {}


def suite_inputs(repo: Path, commit: str, suite: str) -> list[str]:
    """The paths suite ``suite`` (its directory) reads at ``commit``: its directory and its `[tool.verity.tests] inputs`; the
    repository's own suite (``.``) only its inputs."""
    inputs = suite_pyproject(repo, commit, suite).get("tool", {}).get("verity", {}).get("tests", {}).get("inputs", [])
    return [i for i in ([] if suite in ("", ".") else [suite]) + [str(x) for x in inputs] if i]


def suite_name(repo: Path, commit: str, suite: str) -> str:
    """The name `suites.py` gives the suite in directory ``suite`` at ``commit`` (its `discover`): `repository` for the root,
    else its pyproject.toml's project name, normalized, else its path."""
    if suite.strip("/") in ("", "."):
        return "repository"
    name = suite_pyproject(repo, commit, suite).get("project", {}).get("name")
    return re.sub(r"[-_.]+", "-", name).lower() if isinstance(name, str) else suite


def task_error(tid: str, result: dict, suite: str | None = None) -> str:
    """What a ring quotes of a failed graph/v2 task: its failed tests (a test-file's, or of a lean-suites task's its failed
    suite ``suite``'s), its new failures (a circuit-binding's), or the error its runner gave."""
    d = result.get("detail") or {}
    if suite is not None:
        d = next((r for r in d.get("failed") or () if isinstance(r, dict) and r.get("name") == suite), d)
    named = [str(x) for x in d.get("failed_tests") or d.get("failures") or ()]
    what = (f"failed {', '.join(named[:3])}" + (f" and {len(named) - 3} more" if len(named) > 3 else "") if named
            else f"outlived its {d['timed_out']:g} s timeout" if isinstance(d.get("timed_out"), int | float)
            else str(d.get("error") or "failed")[:240])
    return f"{tid}: {what}" if suite is None else f"{tid}: suite {suite} {what}"


def task_files(graph: dict, ids: Iterable[str]) -> set[str]:
    """The files graph/v2 tasks ``ids`` depend on: each one's inputs and its env's spec files, and those of each task it reads,
    transitively (a Lean module's are its imports')."""
    tasks, envs = {t["id"]: t for t in graph["tasks"]}, graph.get("envs") or {}
    seen, todo, out = set(), list(ids), set()
    while todo:
        if (i := todo.pop()) in seen or i not in tasks:
            continue
        seen.add(i)
        t = tasks[i]
        out |= {*t["inputs"], *((envs.get(t["env"]) or {}).get("spec") or ())}
        todo += [r["task"] for r in t["reads"]]
    return out


def under(f: str, paths: list[str]) -> bool:
    return any(f == p or f.startswith(p.rstrip("/") + "/") for p in paths)


def lean_errors(log: str) -> set[str]:
    """The repository paths of the Lean files lean-audit's ``log`` reports errors in: each `error: FILE.lean:LINE`, each
    `orphan: FILE.lean` and the module of each `layers: MODULE imports ...` after an `AUDIT .../PKG: FAIL` line, FILE relative to
    PKG."""
    out, pkg, failures = set(), None, False
    for line in log.splitlines():
        if m := LEAN_AUDIT_RE.match(line):
            pkg, failures = m[1], False
        elif pkg and ((m := LEAN_ERROR_RE.match(line)) or (m := LEAN_ORPHAN_RE.match(line))):
            out.add(os.path.normpath(os.path.join(pkg, m[1])))
        elif pkg and (m := LEAN_LAYERS_RE.match(line)):
            parts = m[1].split(".")
            root = os.path.dirname(pkg) if parts[0] == os.path.basename(pkg) else pkg
            out.add(os.path.normpath(os.path.join(root, *parts) + ".lean"))
        elif pkg and "Some required targets logged failures:" in line:
            failures = True                                 # lake's own list: the step's log keeps it when the errors scroll by
        elif pkg and failures and (m := re.match(r"^\s*- ([A-Za-z][\w.]*)\s*$", line)):
            parts = m[1].split(".")                         # a module of a package rooted at its own name sits beside it
            root = os.path.dirname(pkg) if parts[0] == os.path.basename(pkg) else pkg
            out.add(os.path.normpath(os.path.join(root, *parts) + ".lean"))
        elif failures and not line.strip().startswith("-"):
            failures = False
    return out


def killed(run_dir: Path, why: str = "") -> bool:
    """Whether a check failed by being killed rather than by what it checked: a failed step that exited by a signal or 128+N,
    or the run's own exit (``why``, the verdict's `rc=N`) one of those."""
    steps = failed_steps(run_dir)
    if any(isinstance(rc, int) and (rc < 0 or rc in KILLED_RC) for rc in (st.get("rc") for st in steps)):
        return True
    for st in steps:                                     # a step that says one of its own processes was killed (the
        if st.get("log"):                                # Lean check's kernel replay, exit 137)
            with contextlib.suppress(OSError):
                if KILLED_SAYS in (run_dir / Path(st["log"]).name).read_text(errors="replace"):
                    return True
    # circuit-check alone failed, and only on targets whose process died (out of memory, say): the machine's fault, not a
    # landing's
    if len(steps) == 1 and steps[0].get("step") == "circuit-check" and steps[0].get("log"):
        with contextlib.suppress(OSError):
            fails = CIRCUIT_FAIL_RE.findall((run_dir / Path(steps[0]["log"]).name).read_text(errors="replace"))
            if fails and all(f == CIRCUIT_KILLED for f in fails):
                return True
    return any(f"rc={rc}" in why for rc in (*KILLED_RC, -9, -15))


def _named(log: str, base: str) -> set[str]:
    """The files a pytest log's failures name: its tracebacks' frames, and the repository paths in its failure report."""
    rel = lambda p: p if p.startswith("/") else os.path.normpath(os.path.join(base, p))  # noqa: E731
    paths = {rel(m[1] or m[2]) for m in TRACE_RE.finditer(log)}
    report = log.partition("= FAILURES =")[2].partition("short test summary info")[0]
    return paths | {rel(m[1]) for m in NAMED_RE.finditer(report)}


def _step_log(run_dir: Path, st: dict) -> str:
    try:
        return (run_dir / Path(st.get("log") or "").name).read_text(errors="replace") if st.get("log") else ""
    except OSError:
        return ""


def _suite_log(run_dir: Path, s: dict) -> str:
    if s.get("log"):
        with contextlib.suppress(OSError):
            return (run_dir / "suites" / Path(s["log"]).name).read_text(errors="replace")
    return ""


def step_paths(run_dir: Path, st: dict) -> set[str] | None:
    """The paths one failed step other than pytest and lean-suites points at (`implicated`), None when its log names none."""
    log = _step_log(run_dir, st)
    if st.get("step") == "lean-audit" and (lean := lean_errors(log)):
        return lean
    if not (tests := FAILED_RE.findall(log)):
        return None
    return {os.path.normpath(t) for t in tests} | _named(log, "")


def ratchet_failures(run_dir: Path, st: dict) -> list[tuple[str, str, str]]:
    """(name, top commit's first 12 digits, why) of each change a ratchet-gate step's log says the gate failed."""
    return RATCHET_FAILED_RE.findall(_step_log(run_dir, st))


def suite_paths(run_dir: Path, s: dict) -> set[str] | None:
    """The paths one failed suite's record points at (`implicated`), None when it names no failing test and no outside read."""
    base, tests = s.get("suite") or "", s.get("failed_tests") or []
    log = _suite_log(run_dir, s)
    if not tests and (errors := ERROR_RE.findall(log)):     # a collection error names no failing test, only its module,
        tests = errors                                       # and blaming the suite's inputs would take every landing
    if not tests:
        out, child = s.get("outside") or {}, s.get("child_outside") or {}
        modules = list(out.values() if isinstance(out, dict) else ()) + list(child)
        files = list(out) + [f for fs in child.values() for f in fs]
        if not files:
            return None
        return {os.path.normpath(p) for p in files} | {os.path.normpath(m) for m in modules if m and m != "*"}
    paths = {os.path.normpath(os.path.join(base, t.split("::")[0])) for t in tests}
    return paths | (_named(log, base) if log else set())


def implicated(run_dir: Path) -> set[str] | None:
    """The paths a failed check's failure points at: each failed suite's failing test files and the files its log's failures
    name (`_named`: relative to the repository, or absolute as the log wrote them), and the same of a failed step that runs
    pytest on the repository's own tests (`preflight-lints`). A suite the read guard failed with no failing test names the
    files its tests (or their children, `child_outside`) read outside its inputs and the test modules that read them (its
    record's `outside`, path -> module), so the PR that added the reading test, or changed the file read, is implicated.
    None when another step failed, or a failed suite or step names no failing test and no outside read (a timeout, a kill),
    so no file says what broke it."""
    paths: set[str] = set()
    for st in failed_steps(run_dir):
        if st.get("step") in ("pytest", "lean-suites"):
            continue
        if (got := step_paths(run_dir, st)) is None:
            return None
        paths |= got
    suites = failed_suites(run_dir)
    if not suites and not paths:
        return None
    for s in suites:
        if (got := suite_paths(run_dir, s)) is None:
            return None
        paths |= got
    return paths


#: the step whose suites each report of a check holds, which a suite's red record keeps as its `step`
SUITE_REPORTS = {"suites.failed.json": "pytest", "suites-lean.failed.json": "lean-suites", "suites.json": "pytest",
                 "suites-lean.json": "lean-suites"}
#: pytest's failure line, and a tool's error line, in a log: what a ring quotes of it
ERROR_LINE_RE = re.compile(r"^(?:E\s{2,}\S.*|\s*(?:error|Error|ERROR)\b.*|FAIL\b.*)$", re.M)


def suite_rows(run_dir: Path) -> dict[str, dict]:
    """{name: record} of each suite a check's reports name, with the step that ran it (`SUITE_REPORTS`): its failures so far,
    and once the check ended, every suite with its status."""
    out: dict[str, dict] = {}
    for name, step in SUITE_REPORTS.items():
        for s in _docs(run_dir, name):
            if n := s.get("name") or s.get("suite"):
                out[n] = {**out.get(n, {}), **s, "step": step, "status": s.get("status") or "failed"}
    return out


def step_records(run_dir: Path) -> list[dict]:
    out = []
    with contextlib.suppress(OSError):
        for line in (run_dir / PROGRESS[0]).read_text().splitlines():
            with contextlib.suppress(ValueError):
                out.append(json.loads(line))
    return out


def live_steps(run_dir: Path) -> list[dict]:
    """The steps a check's live record (`LIVE`) names, each with its `state`: `stopped` for one still pending or running in the
    record of a check that ended (a group that stopped on a failure never starts the rest); none without one."""
    doc = next(iter(_docs(run_dir, LIVE)), {})
    over, steps = doc.get("state") in ("passed", "failed", "stopped"), doc.get("steps")
    return [{**s, "state": "stopped"} if over and s.get("state") in ("pending", "running") else s
            for s in steps if isinstance(s, dict)] if isinstance(steps, list) else []


#: what a shard's twin says of a step against its other twin, for the shard both run (`shard_steps`): a pass answers for the
#: shard, a step one still has to run may yet pass, and a stop (a cancel's, or a step its ended check never started) says least
RANK = {"passed": 4, None: 3, "failed": 2, "skipped": 1, "stopped": 0}


def shard_steps(groups: list[list[Path]], done: list[bool]) -> list[dict[str, str | None]] | None:
    """Each shard's steps, from its twins' run dirs (``groups``): {step: the status its twins give it, the highest by `RANK`, None
    while one has it pending or running and none passed it}, a twin's by its steps.jsonl (`stopped` for a step a cancel stopped,
    `not_run`), else its live record (`live_steps`), which names every step the check planned.  None, of more than one shard,
    while a shard's plan isn't known: no twin's live record names a step past the preflight, and none exited 0 (``done``), as a
    check does only once every step it planned ended."""
    out = []
    for dirs, known in zip(groups, done):
        got: dict[str, str | None] = {}
        for d in dirs:
            live = live_steps(d)
            known = known or any(s.get("step") not in PREFLIGHT for s in live)
            mine = {s.get("step") or "": s.get("state") for s in live}
            mine.update({st.get("step") or "": "stopped" if not_run(st) else st.get("status") or "failed" for st in step_records(d)})
            for step, v in mine.items():
                v = None if v in ("pending", "running", None) else v
                if step not in got or RANK.get(v, RANK["failed"]) > RANK.get(got[step], RANK["failed"]):
                    got[step] = v
        if len(groups) > 1 and not known:
            return None
        out.append(got)
    return out


def shard_passed(view: list[dict[str, str | None]] | None, allowed: set[str] = frozenset()) -> set[str]:
    """The steps a run passed (``view``, `shard_steps`'): passed in a shard, or failed there only on what an allowance covers
    (``allowed``, `Driver._allowed_steps`), and so, or skipped, in every shard that holds them."""
    def ok(s: str, x: str | None) -> bool:
        return x == "passed" or (x == "failed" and s in allowed)
    return {s for v in view or () for s, x in v.items() if ok(s, x) and all(ok(s, w[s]) or w[s] == "skipped" for w in view if s in w)}


def shard_ended(view: list[dict[str, str | None]] | None) -> set[str]:
    """The steps every shard that holds them has ended (``view``, `shard_steps`')."""
    return {s for v in view or () for s in v if all(w[s] is not None for w in view if s in w)}


def suite_passed(rows: list[dict]) -> bool:
    """Whether a suite's rows from a run's dirs (`suite_rows`') make its pass: none failed, and one passed whole or the passed ones
    are every part of one partition (`part`: parts `ks` of `m`, of the partition `digest`), as a sharded run's shards run a suite
    that declares parts (`suites.py SUITE:K/M`)."""
    if any(r.get("status") == "failed" for r in rows):
        return False
    ok = [r for r in rows if r.get("status") == "passed"]
    if any(not isinstance(r.get("part"), dict) for r in ok):
        return True
    of = {(r["part"].get("m"), r["part"].get("digest")) for r in ok}
    m = next(iter(of))[0] if len(of) == 1 else None
    return isinstance(m, int) and {k for r in ok for k in r["part"].get("ks") or ()} == set(range(1, m + 1))


def not_run(st: dict) -> bool:
    """A step that found nothing: stopped (check.py's `stopped`, a cancel's), or killed by a SIGTERM before check.py marked it
    so (it reads `failed` with an empty log)."""
    return st.get("status") == "stopped" or (st.get("status") == "failed" and st.get("rc") in (-15, SIGTERM_RC))


def named_failure(run_dir: Path, rec: dict) -> str:
    """What a failed suite or step names of its failure: its failed test ids, or the paths the read guard caught it reading
    outside its inputs, and its log's first error line; "" when it names none of them."""
    tests = rec.get("failed_tests") or []
    reads = sorted({*(rec.get("outside") or {}), *(f for fs in (rec.get("child_outside") or {}).values() for f in fs)})
    what = (f"failed {', '.join(tests[:3])}" + (f" and {len(tests) - 3} more" if len(tests) > 3 else "") if tests else
            f"read outside its declared inputs: {', '.join(reads[:3])}" + (f" and {len(reads) - 3} more" if len(reads) > 3 else "")
            if reads else "")
    log = _suite_log(run_dir, rec) if "suite" in rec or "name" in rec else _step_log(run_dir, rec)
    line = m[0].strip()[:240] if (m := ERROR_LINE_RE.search(log)) else ""
    return "; ".join(x for x in (what, f"`{line}`" if line else "") if x)


def first_error(run_dir: Path, rec: dict) -> str:
    """What a ring quotes of a failed suite or step: what it names of its failure (`named_failure`), else its record's detail."""
    return named_failure(run_dir, rec) or rec.get("detail") or "its log has no error line"


def touches(files: set[str], paths: set[str]) -> set[str]:
    """The ``files`` (repository paths) among ``paths``, an absolute path matching the file it ends in when that file is under a
    directory (a bare `conftest.py` would match every conftest an installed package has)."""
    return {f for f in files for p in paths if p == f or ("/" in f and p.startswith("/") and p.endswith("/" + f))}


def py_errors(repo: Path, base: str, top: str) -> list[tuple[str, str]]:
    """Each .py file ``base``..``top`` changes that doesn't compile at ``top``, as `python -m py_compile` compiles it, with why."""
    bad = []
    for f in sorted(changed(repo, base, top)):
        if not f.endswith(".py") or (r := _git(repo, "show", f"{top}:{f}", check=False)).returncode:
            continue
        try:
            compile(r.stdout, f, "exec", dont_inherit=True)
        except (SyntaxError, ValueError) as e:
            bad.append((f, f"{type(e).__name__}: {e}"))
    return bad


def landed_carriers(repo: Path, ref: str, prs: Iterable[PR], n: int = LANDED_WINDOW) -> dict[int, Member]:
    """{number: the landing that carries it} of each of ``prs`` whose head the head of a PR of the same owner (`PR.owner`)
    contains, where that PR landed on ``ref``: its queue commit (`queue_commit`) is one of ``ref``'s last ``n`` first-parent
    commits, and no revert among them undid it.  The lowest such landing, and none when that is the PR's own (it landed at
    that head).  One `log` of ``ref``, one `rev-list --parents` of that window, and one walk of it per owner (`_brought`)."""
    prs = [p for p in prs if p.owner]
    recs = [x.strip() for x in _out(repo, "log", "--first-parent", f"-n{n}", "--format=%H%x00%P%x00%B%x1e", ref).split("\x1e")
            if x.strip()] if prs else []
    if not recs:
        return {}
    landed, undone = [], set()
    for rec in reversed(recs):
        commit, parents, body = rec.split("\x00", 2)
        undone |= set(REVERTS_RE.findall(body))
        if m := queue_commit(commit, parents, body):
            landed.append(m)
    bottom = recs[-1].split("\x00", 1)[0]
    window = {c: ps for c, *ps in map(str.split, _out(repo, "rev-list", "--parents", ref, f"^{bottom}").splitlines())}
    out: dict[int, Member] = {}
    for who in {_who(p.owner) for p in prs if p.head in window}:
        mine = [m for m in landed if m.commit not in undone and _who(m.owner) == who]
        at = _brought(window, enumerate(m.head for m in mine))
        for p in prs:
            if _who(p.owner) == who and p.head in at and (m := mine[at[p.head]]).pr != p.number:
                out[p.number] = m
    return out


def applied_on(repo: Path, ref: str, prs: Iterable[PR]) -> dict[int, tuple[list[str], str | None]]:
    """{number: (the files its change touches, the commit of ``ref``'s first-parent line since which each is there, as `#N's
    landing COMMIT` when the queue made it, else `COMMIT (subject)`)} of each of ``prs`` whose change ``ref`` has already,
    though not its head: each file one of its own commits changes (those its head has and ``ref`` doesn't, a merge's by its
    combined diff), one at least, is on ``ref`` as its head has it, and merging the head onto ``ref`` (`git merge-tree`, no
    renames) changes nothing.  One `rev-list --parents` of every head (`queue.above`), two `log`s of their own commits, and
    one `cat-file` that stops at a PR's first file ``ref`` has otherwise."""
    from .queue import above

    prs, env = list(prs), git_env(GIT_TERMINAL_PROMPT="0")
    reach = above(repo, ref, (p.head for p in prs))
    own = {p.number: reach[p.head][0] for p in prs if reach[p.head][0]}
    if not own:
        return {}
    files: dict[str, list[str]] = {}
    tops = "".join(f"{p.head}\n" for p in prs if p.number in own) + f"^{ref}\n"
    for how in (("--no-merges",), ("--merges", "--cc")):
        r = subprocess.run(["git", "log", "--stdin", "-z", "--no-renames", "--format=%x01%H", "--name-only", *how], cwd=repo,
                           input=tops, capture_output=True, text=True, errors="surrogateescape", env=env)
        if r.returncode:
            raise QueueError(f"git log --name-only {' '.join(how)} ^{ref}: {(r.stderr or r.stdout).strip()[-400:]}")
        for rec in r.stdout.split("\x01")[1:]:
            sha, _, rest = rec.partition("\0")
            files[sha] = [x for x in rest.lstrip("\0\n").split("\0") if x]
    on_ref = {path: meta.split()[2] for meta, _, path in (x.partition("\t") for x in _out(repo, "ls-tree", "-r", "-z", ref).split("\0")
                                                          if x)}
    tree = _out(repo, "rev-parse", f"{ref}^{{tree}}")
    out: dict[int, tuple[list[str], str | None]] = {}
    cat = subprocess.Popen(["git", "cat-file", "--batch-check=%(objectname)"], cwd=repo, stdin=subprocess.PIPE,
                           stdout=subprocess.PIPE, text=True, errors="surrogateescape", env=env)
    try:
        for p in prs:
            if p.number not in own:
                continue
            touched = list(dict.fromkeys(f for c in own[p.number] for f in files.get(c, ())))
            same = bool(touched)
            for f in touched:
                if "\n" in f:
                    same = False
                else:
                    cat.stdin.write(f"{p.head}:{f}\n")
                    cat.stdin.flush()
                    got = cat.stdout.readline().strip()
                    same = (None if got.endswith(" missing") else got) == on_ref.get(f)
                if not same:
                    break
            r = _git(repo, "merge-tree", "--write-tree", "--no-messages", "-Xno-renames", ref, p.head, check=False) if same else None
            if r is not None and not r.returncode and r.stdout.split()[:1] == [tree]:
                out[p.number] = (touched, None)
    finally:
        cat.stdin.close()
        cat.wait()
    for n, (touched, _) in out.items():
        r = subprocess.run(["git", "--literal-pathspecs", "log", "--stdin", "--first-parent", "-1", "--format=%H%x00%P%x00%B"],
                           cwd=repo, input="".join(f"{x}\n" for x in [ref, "--", *touched]), capture_output=True, text=True,
                           errors="surrogateescape", env=env)
        if not r.returncode and (rec := r.stdout.strip()):
            commit, parents, body = rec.split("\x00", 2)
            m, subject = queue_commit(commit, parents, body), body.partition("\n")[0]
            out[n] = (touched, f"#{m.pr}'s landing {commit[:12]}" if m else f"{commit[:12]} ({subject})")
    return out


