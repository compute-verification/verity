MANIFEST = Path(__file__).resolve().parent / "pods" / "nebius" / "deploy.toml"
REPO = Path(__file__).resolve().parents[4]
PROJECT = "verity"
HISTORY = 400                  # REF's commits searched for a stale file's version
AHEAD_DAYS = 21                # origin's branches searched for an unrecorded file's commit

# Runs on the node (stdlib): each path's git blob, mtime and the oldest start of a process whose argv names it, the files the
# managed patterns and trees hold, and the record's last line per path.
PROBE = r'''
import glob, hashlib, json, os, sys
req = json.loads(sys.argv[1])
def blob(p):
    with open(p, "rb") as f:
        d = f.read()
    return hashlib.sha1(b"blob %d\0" % len(d) + d).hexdigest()
files = {}
for p in req["paths"]:
    try:
        st = os.stat(p)
        files[p] = {"blob": blob(p), "mtime": st.st_mtime}
    except FileNotFoundError:
        files[p] = None
    except OSError as e:
        files[p] = {"error": f"{type(e).__name__}: {e}"}
found = set()
for pat in req["globs"]:
    found.update(p for p in glob.glob(pat) if os.path.isfile(p))
for t in req["trees"]:
    for d, dirs, names in os.walk(t):
        dirs[:] = [x for x in dirs if x not in ("__pycache__", ".deploy-prev")]
        found.update(os.path.join(d, n) for n in names if not n.endswith(".pyc"))
btime = next(int(ln.split()[1]) for ln in open("/proc/stat") if ln.startswith("btime"))
hz, want, procs = os.sysconf("SC_CLK_TCK"), set(req["paths"]), {}
for pid in filter(str.isdigit, os.listdir("/proc")):
    try:
        argv = [a.decode(errors="replace") for a in open(f"/proc/{pid}/cmdline", "rb").read().split(b"\0") if a]
        start = btime + int(open(f"/proc/{pid}/stat").read().rsplit(")", 1)[1].split()[19]) / hz
    except (OSError, IndexError, ValueError):
        continue
    try:
        cwd = os.readlink(f"/proc/{pid}/cwd")
    except OSError:
        cwd = None                     # another user's process (root's, under sudo): its absolute arguments still count
    for a in argv:
        if cwd is None and not a.startswith("/"):
            continue
        p = os.path.normpath(os.path.join(cwd or "/", a))
        if p in want:
            procs[p] = min(procs.get(p, start), start)
record = {}
try:
    for ln in open(req["record"]):
        try:
            r = json.loads(ln)
            record[r["path"]] = r
        except (ValueError, KeyError, TypeError):
            pass
except OSError:
    pass
print(json.dumps({"files": files, "found": sorted(found), "procs": procs, "record": record}))
'''

# On the node as root: append lines to the record, owned as the directory above the record's.
APPEND = r'''
import json, os, sys, time
def append(rec, lines):
    os.makedirs(os.path.dirname(rec), exist_ok=True)
    with open(rec, "a") as fh:
        for ln in lines:
            fh.write(json.dumps(ln) + "\n")
    top = os.stat(os.path.dirname(os.path.dirname(rec)))
    os.chown(os.path.dirname(rec), top.st_uid, top.st_gid)
    os.chown(rec, top.st_uid, top.st_gid)
'''

# Runs on the node as root: write each file beside its target, keep the old one's owner, link the old one under .deploy-prev/,
# rename over it, and append the record.
INSTALL = APPEND + r'''
import base64
req = json.load(sys.stdin)
stamp = time.strftime("%Y%m%dT%H%M%SZ", time.gmtime())
out = []
for f in req["files"]:
    p, data = f["path"], base64.b64decode(f["data"])
    try:
        st, cur = os.stat(p), open(p, "rb").read()
    except FileNotFoundError:
        st, cur = None, None
    mode = f["mode"] if f["mode"] is not None else st.st_mode & 0o777 if st else f["git_mode"]
    if cur == data and st.st_mode & 0o777 == mode:
        out.append(False)
        continue
    d = os.path.dirname(p)
    os.makedirs(d, exist_ok=True)
    own = st or os.stat(d)
    tmp = os.path.join(d, f".{os.path.basename(p)}.deploy-tmp")
    with open(tmp, "wb") as fh:
        fh.write(data)
    os.chmod(tmp, mode)
    os.chown(tmp, own.st_uid, own.st_gid)
    if st is not None:
        prev = os.path.join(d, ".deploy-prev")
        os.makedirs(prev, exist_ok=True)
        os.chown(prev, own.st_uid, own.st_gid)
        try:
            os.link(p, os.path.join(prev, f"{os.path.basename(p)}.{stamp}"))
        except FileExistsError:
            pass
    os.replace(tmp, p)
    out.append(True)
append(req["record"], [{"at": stamp, "path": f["path"], "blob": f["blob"], "commit": req["commit"], "ref": req["ref"], "by": req["by"]}
                       for f, changed in zip(req["files"], out) if changed])
print(json.dumps(out))
'''

# Runs on the node as root: move each stray to <record's directory>/attic/<stamp>/<its path>, and append the record.
ATTIC = APPEND + r'''
import re, shutil
req = json.load(sys.stdin)
stamp = time.strftime("%Y%m%dT%H%M%SZ", time.gmtime())
root = os.path.join(os.path.dirname(req["record"]), "attic", stamp)
out = []
for p in req["paths"]:
    dest = root + p
    os.makedirs(os.path.dirname(dest), exist_ok=True)
    shutil.move(p, dest)
    out.append(dest)
    d = os.path.dirname(p)
    while re.search(req["backup"], os.path.basename(d)) and not os.listdir(d):
        os.rmdir(d)
        d = os.path.dirname(d)
append(req["record"], [{"at": stamp, "path": p, "attic": d, "by": req["by"]} for p, d in zip(req["paths"], out)])
print(json.dumps(out))
'''
BACKUP = re.compile(r"\.(bak|prev|orig)([-.\d_]|$)")       # a hand deploy's copy: x.py.bak-20261001T0611Z, x.sh.prev, x.orig

Runner = Callable[[str, list[str], "bytes | None"], subprocess.CompletedProcess]


@dataclass
class Entry:
    path: str
    src: str | None = None             # a file of the repository, or (a tree) a directory of it
    by: str | None = None
    run: list[str] = field(default_factory=list)
    tree: bool = False
    mode: int | None = None            # else an installed file keeps its mode, and a new one gets the repository's


@dataclass
class Node:
    name: str
    record: str
    managed: list[str]
    entries: list[Entry]


def load(manifest: Path = MANIFEST, text: str | None = None) -> dict[str, Node]:
    m = tomllib.loads(manifest.read_text() if text is None else text)
    nodes = {n: Node(n, c["record"], list(c.get("managed", [])), []) for n, c in m.get("nodes", {}).items()}
    for kind in ("file", "tree"):
        for e in m.get(kind, []):
            if bool(e.get("src")) == bool(e.get("by")) or (kind == "tree" and not e.get("src")):
                raise ValueError(f"deploy.toml: {e.get('path')!r} needs exactly one of src and by (a tree, src)")
            for n in e["nodes"]:
                if n not in nodes:
                    raise ValueError(f"deploy.toml: {e['path']!r} names node {n!r}, which has no [nodes.{n}]")
                mode = int(e["mode"], 8) if e.get("mode") else None
                nodes[n].entries.append(Entry(e["path"], e.get("src"), e.get("by"), list(e.get("run", [])), kind == "tree", mode))
    for node in nodes.values():
        seen = set()
        for e in node.entries:
            if e.path in seen:
                raise ValueError(f"deploy.toml: {node.name} lists {e.path} twice")
            seen.add(e.path)
    return nodes


def git(*args: str, repo: Path = REPO) -> str:
    return subprocess.run(["git", "-C", str(repo), *args], capture_output=True, text=True, check=True).stdout


def manifest_at(ref: str, repo: Path = REPO) -> str | None:
    """REF's own deploy.toml, so a commit deploys what it lists; None when REF has none (then the checkout's is used)."""
    r = subprocess.run(["git", "-C", str(repo), "show", f"{ref}:{MANIFEST.relative_to(REPO)}"], capture_output=True, text=True)
    return r.stdout if r.returncode == 0 else None


def expected(node: Node, commit: str, repo: Path = REPO) -> dict[str, tuple[str, str, int, Entry]]:
    """Installed path -> (repo path, blob, mode, entry) for every file entry and every file of every tree at `commit`; an entry
    whose source `commit` lacks is left out (`absent`)."""
    srcs = [e.src for e in node.entries if e.src]
    tree: dict[str, tuple[str, int]] = {}
    for ln in git("ls-tree", "-r", "--full-tree", commit, "--", *srcs, repo=repo).splitlines() if srcs else []:
        meta, rp = ln.split("\t", 1)
        mode, _, sha = meta.split()
        tree[rp] = (sha, 0o755 if mode == "100755" else 0o644)
    out = {}
    for e in node.entries:
        if e.tree:
            pre = e.src.rstrip("/") + "/"
            for rp, (sha, mode) in tree.items():
                if rp.startswith(pre):
                    out[e.path.rstrip("/") + "/" + rp[len(pre):]] = (rp, sha, mode, e)
        elif e.src in tree:
            out[e.path] = (e.src, *tree[e.src], e)
    return out


def absent(node: Node, want: dict) -> list[Entry]:
    return [e for e in node.entries if e.src and not e.tree and e.path not in want]


def versions(srcs: list[str], *revs: str, since: str | None = None, limit: int | None = None,
             repo: Path = REPO) -> dict[tuple[str, str], tuple[str, str]]:
    """(repo path, blob) -> (commit, date) for each version of `srcs` the history of `revs` holds; the newest commit wins."""
    args = ["log", "--format=C %H %cs", "--raw", "--no-abbrev", "--no-renames", "-c"]
    args += [f"--since={since}"] if since else []
    args += [f"-n{limit}"] if limit else []
    out: dict[tuple[str, str], tuple[str, str]] = {}
    commit = date = ""
    for ln in git(*args, *revs, "--", *srcs, repo=repo).splitlines():
        if ln.startswith("C "):
            _, commit, date = ln.split()
        elif ln.startswith(":"):
            meta, rp = ln.split("\t", 1)
            out.setdefault((rp.split("\t")[-1], meta.split()[-2]), (commit, date))
    return out


def origin_branches(commit: str, repo: Path = REPO, most: int = 3) -> list[str]:
    r = subprocess.run(["git", "-C", str(repo), "branch", "-r", "--contains", commit, "--format=%(refname:short)"],
                       capture_output=True, text=True)
    return [b for b in r.stdout.split() if b.startswith("origin/") and b != "origin/HEAD"][:most] if r.returncode == 0 else []


def ssh_runner(project: str = PROJECT) -> Runner:
    from . import remote

    def run(node: str, argv: list[str], stdin: bytes | None) -> subprocess.CompletedProcess:
        t = remote.ssh_host_target(remote.resolve_machine(node, project))
        return remote.ssh_run(remote.ssh_argv(t["host"], t["port"] or 22, user=t["user"]), argv, stdin=stdin, timeout=300)
    return run


def probe(node: Node, paths: list[str], run: Runner) -> dict:
    req = {"paths": paths, "globs": node.managed, "trees": [e.path for e in node.entries if e.tree], "record": node.record}
    r = run(node.name, ["python3", "-c", PROBE, json.dumps(req)], None)
    if r.returncode != 0:
        raise RuntimeError(f"{node.name}: probe failed (exit {r.returncode}): {r.stderr.decode(errors='replace').strip()[-400:]}")
    return json.loads(r.stdout)


def drift(node: Node, ref: str, run: Runner, repo: Path = REPO) -> dict:
    """One node's report: {"commit", "entries": [{path, src, state, detail, restart}], "strays": [...]}."""
    commit = git("rev-parse", f"{ref}^{{commit}}", repo=repo).strip()
    want = expected(node, commit, repo)
    generated = [e.path for e in node.entries if e.by]
    seen = probe(node, sorted({*want, *generated}), run)
    srcs = sorted({v[0] for v in want.values()})
    old = versions(srcs, commit, limit=HISTORY, repo=repo) if srcs else {}
    recent: dict | None = None
    entries = []
    for path in sorted({*want, *generated}):
        got = seen["files"].get(path)
        if path in generated:
            e = next(x for x in node.entries if x.path == path)
            state, detail = ("ok", f"by {e.by}") if got and "blob" in got else ("missing", f"by {e.by}: re-run it")
            entries.append({"path": path, "src": None, "state": state, "detail": detail, "restart": None})
            continue
        rp, sha, _, e = want[path]
        if e.tree and got is None:
            entries.append({"path": path, "src": rp, "state": "missing", "detail": "in the tree, not installed", "restart": None,
                            "tree": e.path})
            continue
        rec = seen["record"].get(path) or {}
        if got is None:
            state, detail = "missing", "install it"
        elif "error" in got:
            state, detail = "unknown", got["error"]
        elif got["blob"] == sha:
            state, detail = "ok", ""
        elif (rp, got["blob"]) in old:
            c, d = old[(rp, got["blob"])]
            state, detail = "stale", f"{ref}'s version of {c[:12]} ({d}); {ref} has changed it since: install it"
        elif rec.get("blob") == got["blob"] and rec.get("commit"):
            state = "ahead"
            detail = f"installed {rec.get('at')} by {rec.get('by')} from {rec.get('ref')} @ {rec['commit'][:12]}, which {ref} lacks"
        else:
            if recent is None:
                recent = versions(srcs, "--remotes=origin", since=f"{AHEAD_DAYS}.days", repo=repo)
            hit = recent.get((rp, got["blob"]))
            if hit:
                state = "ahead"
                detail = f"commit {hit[0][:12]} ({hit[1]}) on {', '.join(origin_branches(hit[0], repo)) or 'a branch'}, not in {ref}"
            else:
                state, detail = "unknown", "no commit holds it: edited in place or never committed"
        restart = None
        started = seen["procs"].get(path)
        if got and "mtime" in got and started is not None and started < got["mtime"] - 1:
            restart = (f"a process started {time.strftime('%m-%d %H:%MZ', time.gmtime(started))}, before the file "
                       f"({time.strftime('%m-%d %H:%MZ', time.gmtime(got['mtime']))})" + (f"; restart {', '.join(e.run)}" if e.run else ""))
        entries.append({"path": path, "src": rp, "state": state, "detail": detail, "restart": restart, **({"tree": e.path} if e.tree else {})})
    for e in absent(node, want):
        entries.append({"path": e.path, "src": e.src, "state": "absent", "detail": f"{ref} lacks {e.src}", "restart": None})
    listed = {*want, *generated, *(e.path for e in absent(node, want))}
    strays = [p for p in seen["found"] if p not in listed and "/.deploy-prev/" not in p and "/__pycache__/" not in p]
    in_tree = {p: (t, f"{t.src}/{os.path.relpath(p, t.path)}") for p in strays
               for t in node.entries if t.tree and p.startswith(t.path.rstrip("/") + "/")}
    if in_tree:
        got = probe(node, sorted(in_tree), run)["files"]
        recent = versions(sorted({rp for _, rp in in_tree.values()}), "--remotes=origin", since=f"{AHEAD_DAYS}.days", repo=repo)
        for p, (t, rp) in sorted(in_tree.items()):
            hit = recent.get((rp, (got.get(p) or {}).get("blob")))
            if hit:
                strays.remove(p)
                entries.append({"path": p, "src": rp, "state": "ahead", "restart": None, "tree": t.path, "detail":
                                f"commit {hit[0][:12]} ({hit[1]}) on {', '.join(origin_branches(hit[0], repo)) or 'a branch'}, not in {ref}"})
    return {"commit": commit, "entries": entries, "strays": strays}


def render(node: str, ref: str, rep: dict) -> str:
    lines = [f"{node} against {ref} ({rep['commit'][:12]})"]
    es = rep["entries"]
    ok = [e for e in es if e["state"] == "ok" and not e["restart"]]
    tree_missing: dict[str, int] = {}
    for e in es:
        if e["state"] == "missing" and e.get("tree"):
            tree_missing[e["tree"]] = tree_missing.get(e["tree"], 0) + 1
    lines.append(f"  ok       {len(ok)} of {len(es)}")
    for e in es:
        if (e["state"] == "ok" and not e["restart"]) or (e["state"] == "missing" and e.get("tree")):
            continue
        lines.append(f"  {e['state']:8} {e['path']}" + (f"  ({e['detail']})" if e["detail"] else ""))
        if e["restart"]:
            lines.append(f"  restart  {e['path']}  ({e['restart']})")
    for t, n in tree_missing.items():
        lines.append(f"  missing  {n} files of the tree {t} (an install of the tree adds them)")
    for p in rep["strays"]:
        lines.append(f"  stray    {p}")
    return "\n".join(lines)


def clean(rep: dict) -> bool:
    return not rep["strays"] and all(e["state"] == "ok" and not e["restart"] for e in rep["entries"] if not
                                     (e["state"] == "missing" and e.get("tree")))


def install(node: Node, ref: str, by: str, only: list[str], run: Runner, dry: bool = False, repo: Path = REPO) -> list[dict]:
    """Install `node`'s entries (or those whose path or repo path is in `only`) from `ref`; returns [{path, src, changed, run}]."""
    commit = git("rev-parse", f"{ref}^{{commit}}", repo=repo).strip()
    if not origin_branches(commit, repo, most=1):
        raise RuntimeError(f"{ref} ({commit[:12]}) is on no origin branch: push it first, so what runs is in a pushed commit")
    want = expected(node, commit, repo)
    skipped = [] if only else [{"path": e.path, "src": e.src, "changed": "absent", "run": []} for e in absent(node, want)]
    gone = [o for o in only for e in absent(node, want) if o in (e.path, e.src)]
    if gone:
        raise RuntimeError(f"{ref} ({commit[:12]}) lacks the source of {', '.join(gone)}")
    if only:
        picked = {p: v for p, v in want.items() if p in only or v[0] in only or v[3].path in only}
        missing = [o for o in only if not any(o in (p, v[0], v[3].path) for p, v in want.items())]
        if missing:
            raise RuntimeError(f"not in deploy.toml for {node.name}: {', '.join(missing)}")
        want = picked
    files = [{"path": p, "blob": sha, "mode": e.mode, "git_mode": mode,
              "data": base64.b64encode(subprocess.run(["git", "-C", str(repo), "cat-file", "blob", sha], capture_output=True,
                                                      check=True).stdout).decode()}
             for p, (_, sha, mode, e) in sorted(want.items())]
    if dry:
        seen = probe(node, [f["path"] for f in files], run)["files"]
        return [{"path": f["path"], "src": want[f["path"]][0], "run": [],
                 "changed": False if (seen.get(f["path"]) or {}).get("blob") == f["blob"] and f["mode"] is None else None}
                for f in files] + skipped
    req = {"files": files, "commit": commit, "ref": ref, "by": by, "record": node.record}
    r = run(node.name, ["sudo", "-n", "python3", "-c", INSTALL], json.dumps(req).encode())
    if r.returncode != 0:
        raise RuntimeError(f"{node.name}: install failed (exit {r.returncode}): {r.stderr.decode(errors='replace').strip()[-400:]}")
    changed = json.loads(r.stdout)
    now = [f["path"] for f, c in zip(files, changed) if c]
    after = probe(node, now, run) if now else {"files": {}, "procs": {}}

    def old_code(p: str) -> bool:
        got, started = after["files"].get(p) or {}, after["procs"].get(p)
        return started is not None and "mtime" in got and started < got["mtime"] - 1

    return [{"path": f["path"], "src": want[f["path"]][0], "changed": c,
             "run": (want[f["path"]][3].run or [f["path"]]) if c and old_code(f["path"]) else []}
            for f, c in zip(files, changed)] + skipped


def attic(node: Node, ref: str, by: str, paths: list[str], backups: bool, run: Runner, dry: bool = False,
          repo: Path = REPO) -> list[tuple[str, str | None]]:
    """Move strays of `node` (those in `paths`, and with `backups` every one named as a backup) into its attic; [(path, dest)]."""
    strays = set(drift(node, ref, run, repo)["strays"])
    pick = sorted({*paths, *(p for p in strays if backups and any(BACKUP.search(c) for c in Path(p).parts))})
    if bad := [p for p in pick if p not in strays]:
        raise RuntimeError(f"not a stray of {node.name} against {ref} (an entry lists it, or nothing is there): {', '.join(bad)}")
    if pick and (running := probe(node, pick, run)["procs"]):
        raise RuntimeError(f"a process runs {', '.join(sorted(running))}: stop it first")
    if dry or not pick:
        return [(p, None) for p in pick]
    req = {"paths": pick, "record": node.record, "by": by, "backup": BACKUP.pattern}
    r = run(node.name, ["sudo", "-n", "python3", "-c", ATTIC], json.dumps(req).encode())
    if r.returncode != 0:
        raise RuntimeError(f"{node.name}: attic failed (exit {r.returncode}): {r.stderr.decode(errors='replace').strip()[-400:]}")
    return list(zip(pick, json.loads(r.stdout)))


def main(argv: list[str] | None = None, run: Runner | None = None, manifest: Path = MANIFEST, repo: Path = REPO) -> int:
    ap = argparse.ArgumentParser(prog="research deploy", description=__doc__.split("\n\n")[0])
    sub = ap.add_subparsers(dest="cmd", required=True)
    d = sub.add_parser("drift", help="each node's files against REF")
    d.add_argument("--node", nargs="+", help="default: every node in deploy.toml")
    d.add_argument("--ref", default="origin/main")
    d.add_argument("--json", action="store_true")
    i = sub.add_parser("install", help="install a node's files from REF")
    i.add_argument("node")
    i.add_argument("paths", nargs="*", help="installed paths or repository paths (default: every entry for the node)")
    i.add_argument("--ref", default="origin/main")
    i.add_argument("--by", required=True, help="who installs (a lane, an agent's URL): goes into the node's record")
    i.add_argument("--dry-run", action="store_true")
    a = sub.add_parser("attic", help="move a node's strays into its attic, beside the record")
    a.add_argument("node")
    a.add_argument("paths", nargs="*", help="strays `drift` lists")
    a.add_argument("--backups", action="store_true", help="every stray named as a backup, or under a directory that is (*.bak*, *.prev*, *.orig*)")
    a.add_argument("--ref", default="origin/main")
    a.add_argument("--by", required=True, help="who moves them: goes into the node's record")
    a.add_argument("--dry-run", action="store_true")
    for p in (d, i, a):
        p.add_argument("--no-fetch", action="store_true", help="don't `git fetch origin main` first")
    ns = ap.parse_args(argv)
    if not ns.no_fetch:
        subprocess.run(["git", "-C", str(repo), "fetch", "-q", "origin", "main"], capture_output=True)
    nodes = load(manifest, manifest_at(ns.ref, repo) if manifest == MANIFEST else None)
    run = run or ssh_runner()
    if ns.cmd == "drift":
        reps, rc = {}, 0
        for name in ns.node or sorted(nodes):
            if name not in nodes:
                print(f"research deploy: no node {name!r} in {manifest}", file=sys.stderr)
                return 2
            try:
                reps[name] = drift(nodes[name], ns.ref, run, repo)
            except (RuntimeError, subprocess.CalledProcessError, ValueError) as e:
                reps[name] = {"error": str(e)}
            rc |= 0 if "error" not in reps[name] and clean(reps[name]) else 1
        if ns.json:
            print(json.dumps(reps, indent=1))
        else:
            print("\n\n".join(f"{n}: {r['error']}" if "error" in r else render(n, ns.ref, r) for n, r in reps.items()))
        return rc
    if ns.node not in nodes:
        print(f"research deploy: no node {ns.node!r} in {manifest}", file=sys.stderr)
        return 2
    if ns.cmd == "attic":
        try:
            moved = attic(nodes[ns.node], ns.ref, ns.by, ns.paths, ns.backups, run, ns.dry_run, repo)
        except (RuntimeError, ValueError) as e:
            print(f"research deploy: {e}", file=sys.stderr)
            return 1
        for p, dest in moved:
            print(f"would move  {p}" if dest is None else f"moved  {p}  -> {dest}")
        if moved and not ns.dry_run:
            print(f"restore one with `sudo mv DEST PATH`; {nodes[ns.node].record} lists every move")
        return 0
    try:
        done = install(nodes[ns.node], ns.ref, ns.by, ns.paths, run, ns.dry_run, repo)
    except (RuntimeError, ValueError) as e:
        print(f"research deploy: {e}", file=sys.stderr)
        return 1
    for f in done:
        mark = {None: "would install", True: "installed", False: "unchanged", "absent": f"skipped ({ns.ref} lacks it)"}[f["changed"]]
        print(f"{mark:13} {f['path']}  <- {f['src']}")
    runs = sorted({r for f in done for r in f["run"]})
    if runs:
        print(f"restart when safe: {', '.join(runs)} (`research deploy drift --node {ns.node}` says `restart` until then)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
