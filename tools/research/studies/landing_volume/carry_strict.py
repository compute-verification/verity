"""Lever 1's safe subset and its hold rate: of the week's carry-able re-heads (carry_net.py's `unchanged`, or no own
change), those where every PR the new head brought in had a land verdict, by the new head's first label, on a head the
new head contains; and how often anyone held a new head, carry-able or edited.

    [STRICT=1] python3 carry_strict.py REHEADS_NET_CSV LABELS_JSON REPO [COMMIT_TIMES]

COMMIT_TIMES: `git log --no-walk --stdin --format='%H %cI'` of the new heads, for the verdict wait a carry would remove.

STRICT=1 (with carry_net.py's STRICT=1 CSV): a lock regenerated by the re-head is own change, and a brought-in PR's head
with a hold on it by then doesn't count.
"""
from __future__ import annotations

import collections
import csv
import json
import os
import subprocess
import sys
from concurrent.futures import ThreadPoolExecutor
from datetime import datetime

W0, W1 = "2026-10-29T17:00:00Z", "2026-11-05T17:00:00Z"


def ts(s: str) -> float:
    return datetime.fromisoformat(s.replace("Z", "+00:00")).timestamp()


def carry(r: dict) -> bool:
    own_same = ("empty", "sync") if os.environ.get("STRICT") == "1" else ("empty", "sync", "sync+regen")
    return r["net"] == "unchanged" or (r["net"] == "" and r["kind"] in own_same)


def main(reheads_csv, labels_json, repo, commit_times=None):
    labels = json.load(open(labels_json))
    verdicts: dict[int, list[tuple[float, str]]] = collections.defaultdict(list)
    held: dict[str, float] = {}
    on_head: dict[str, list[dict]] = collections.defaultdict(list)
    for n, xs in labels.items():
        for x in xs:
            h = x["target"].split("@", 1)[1]
            on_head[h[:12]].append(x)
            if x["key"] == "reviewed" and x["value"] == "land":
                verdicts[int(n)].append((ts(x["ts"]), h))
            if x["key"] == "reviewed" and x["value"] == "hold":
                held[h] = min(held.get(h, 1e18), ts(x["ts"]))
    strict_holds = os.environ.get("STRICT") == "1"
    rows = [r for r in csv.DictReader(open(reheads_csv)) if r["new_first_label"] and ts(W0) <= ts(r["new_first_label"]) < ts(W1)]

    def anc(a: str, b: str) -> bool:
        return subprocess.run(["git", "-C", repo, "merge-base", "--is-ancestor", a, b], capture_output=True).returncode == 0

    def strict(r: dict) -> bool:
        t = ts(r["new_first_label"])
        for q in filter(None, r["carried_in"].split(";")):
            if not any(vt <= t and not (strict_holds and held.get(h, 1e18) <= t) and anc(h, r["new"])
                       for vt, h in verdicts.get(int(q), [])):
                return False
        return True

    cands = [r for r in rows if carry(r)]
    with ThreadPoolExecutor(16) as ex:
        ok = list(ex.map(strict, cands))
    after_verdict = [r for r, s in zip(cands, ok) if s and "verdict" in r["old_had"]]
    after_mark = [r for r, s in zip(cands, ok) if s and "mark" in r["old_had"]]
    print(f"re-heads labelled in the week {len(rows)}; carry-able {len(cands)}; every brought-in PR verdicted {sum(ok)}; "
          f"of those after a verdict {len(after_verdict)}, after a mark {len(after_mark)}")
    if commit_times:
        ct = {line.split()[0][:12]: ts(line.split()[1]) for line in open(commit_times)}
        wait = []
        for r in after_verdict:
            vd = [ts(x["ts"]) for x in on_head.get(r["new"][:12], []) if x["key"] == "reviewed" and x["value"] == "land"]
            if vd and r["new"][:12] in ct:
                wait.append(max(0.0, (min(vd) - ct[r["new"][:12]]) / 3600))
        wait.sort()
        if wait:
            print(f"verdict wait on those after a verdict: n={len(wait)} p50={wait[len(wait) // 2]:.2f} h "
                  f"p90={wait[int(0.9 * (len(wait) - 1))]:.2f} h sum={sum(wait):.0f} h")
    for r, s in zip(cands, ok):
        holds = [x for x in on_head.get(r["new"][:12], []) if x["key"] == "reviewed" and x["value"] == "hold"]
        if s and holds:
            print(f"  would skip a hold: #{r['pr']} {r['new'][:12]} ({r['kind']}): {str(holds[0].get('ref'))[:160]}")
    for name, sel in (("carry-able", cands), ("edit", [r for r in rows if not carry(r)])):
        held = sum(any(x["key"] == "reviewed" and x["value"] == "hold" for x in on_head.get(r["new"][:12], [])) for r in sel)
        land = sum(any(x["key"] == "reviewed" and x["value"] == "land" for x in on_head.get(r["new"][:12], [])) for r in sel)
        print(f"{name}: {len(sel)} new heads, {land} with a land verdict, {held} with a hold")


if __name__ == "__main__":
    main(*sys.argv[1:])
