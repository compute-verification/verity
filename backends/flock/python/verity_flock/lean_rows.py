"""The Lean soundness package's verified lowerings (`FlockSoundness/UnitRows.lean`): for each template in `TEMPLATES`, its
unit's gate circuit (the IR's Boolean export) in chunks, its pinned rows by region, a checkpoint at each cut, and the
kernel's checks, as `FlockSoundness/<ns>/Gates.lean`, `Pinned.lean`, `Checkpoints.lean` and `Chunks.lean`. The chunks'
checks (`UnitRows.chunkOK`) and the regions' check (`UnitRows.regionsOK`) give `<ns>.sound`
(`UnitRows.sound_of_checks`): the pinned rows compute the gate circuit. `backends/flock/tests/test_lean_rows.py` checks
that the files are what this module writes, for the netlists the templates pin.

A checkpoint is the next wire, the next AND's column, and the forms of the wires the rest of the gates or the outputs
read. Encodings, one `Nat` literal each, so that Lean elaborates the data quickly:

* a gate is ``op + 3·(a + 2^17·b)`` (op 0 AND, 1 XOR, 2 NOT with b = 0), an operand ``0`` / ``1`` for the constants 0 / 1
  and ``2 + w`` for wire ``w`` (``boolean_export.gate_list``'s ``-1`` / ``-2`` and wire numbers);
* a list of columns is its runs of consecutive columns, ``(first, length)``, each the base-2^26 digit
  ``first·8192 + length + 1``, least significant first (at most 512 runs, columns below 8192).

    python -m verity_flock.lean_rows --out backends/flock/verifier/lean/soundness/FlockSoundness [TEMPLATE ...]
"""
from __future__ import annotations

import argparse
import gzip
import importlib
import json
import tempfile
from pathlib import Path

HEAD = "/-! Generated by `python -m verity_flock.lean_rows` (`backends/flock/python/verity_flock/lean_rows.py`); do not edit. -/"
FILES = ("Gates.lean", "Pinned.lean", "Checkpoints.lean", "Chunks.lean")
#: template -> (Lean namespace under `FlockSoundness`, the subcircuit's parameters, gates per chunk)
TEMPLATES = {
    "rope-head": ("Rope", {"D": 64}, 1000),
}
WORD = 128


def _listdef(name: str, items: list[str], ty: str, per: int) -> str:
    if len(items) <= per:
        return f"def {name} : List {ty} := [{', '.join(items)}]"
    parts = [items[i:i + per] for i in range(0, len(items), per)]
    out = [f"def {name}_{k} : List {ty} := [{', '.join(q)}]" for k, q in enumerate(parts)]
    out.append(f"def {name} : List {ty} := " + " ++ ".join(f"{name}_{k}" for k in range(len(parts))))
    return "\n\n".join(out)


def _operand(w: int) -> int:
    return 0 if w == -1 else 1 if w == -2 else w + 2


def _ungate(c: int) -> tuple[int, int, int | None]:
    """`UnitRows.decGate`, in Python: the op and the operands (``-1`` / ``-2`` for the constants), NOT's second None."""
    src = lambda n: -1 if n == 0 else -2 if n == 1 else n - 2
    return c % 3, src(c // 3 % (1 << 17)), None if c % 3 == 2 else src(c // 3 // (1 << 17))


def _gate_code(op: int, a: int, b: int) -> int:
    x, y = _operand(a), _operand(b) if op != 2 else 0
    assert x < 1 << 17 and y < 1 << 17, f"an operand of ({op}, {a}, {b}) is at or above 2^17, which a gate code cannot hold"
    c = op + 3 * (x + (1 << 17) * y)
    assert _ungate(c) == (op, a, None if op == 2 else b)
    return c


def _unpack(n: int) -> list[int]:
    """`UnitRows.unpackRuns 512` then `runsList`, in Python."""
    cols: list[int] = []
    for _ in range(512):
        if n == 0:
            break
        d = n % (1 << 26) - 1
        cols.extend(range(d // 8192, d // 8192 + d % 8192))
        n >>= 26
    return cols


def _pack(cols: list[int]) -> int:
    runs: list[list[int]] = []
    for c in cols:
        if runs and c == runs[-1][0] + runs[-1][1]:
            runs[-1][1] += 1
        else:
            runs.append([c, 1])
    assert len(runs) <= 512, f"{len(runs)} runs, more than UnitRows.unpackRuns' fuel of 512"
    n = 0
    for a, length in reversed(runs):
        d = a * 8192 + length + 1
        assert a < 8192 and length < 8192 and d < 1 << 26, f"the run ({a}, {length}) does not fit a base-2^26 digit"
        n = (n << 26) + d
    assert _unpack(n) == list(cols)
    return n


def _bits(m: int) -> list[int]:
    return [i for i in range(m.bit_length()) if m >> i & 1]


def _cols(groups) -> list[int]:
    """The columns of a layout's ports, in order: each group's ports from its first word on."""
    cols: list[int] = []
    for word, words, widths in groups:
        assert sum(widths) <= words * WORD
        off = word * WORD
        for w in widths:
            cols.extend(range(off, off + w))
            off += w
    return cols


def unit(template: str) -> dict[str, str]:
    """The four files for `template`'s unit, with its netlist's sha256 under ``"sha256"``."""
    from verity_numerical.bench import lowerings, templates as TM

    from . import boolean_export as BE

    ns, params, per = TEMPLATES[template]
    mod = lowerings.registry("C-Flock").module(template)
    low = mod.lowering(TM.subcircuit(template, **params))
    pins = importlib.import_module(f"verity_flock.templates.{template.replace('-', '_')}").PINS
    assert low.sha256 == pins[next(iter(params.values()))], f"{template}: the lowering is not the pinned netlist"
    C, root = BE.trace(low.units.circuit)
    reg = BE.Registry(Path(tempfile.mkdtemp()))
    rid = reg.analyse(C, root, f"{mod.UNIT} unit", "c-flock-unit", list_root=True)
    gl = json.loads(gzip.decompress((reg.gates_dir / f"{rid}.json.gz").read_bytes()))["lists"][rid]
    g, n_in, outs = gl["gates"], gl["inputs"], gl["outputs"]
    ops, A, B = g[0::3], g[1::3], g[2::3]
    G = len(ops)
    lay = low.layout
    in_cols, out_cols = _cols(lay.in_groups), _cols(lay.out_groups)
    and_base, k = lay.counts["in_words"] * WORD, lay.const
    assert len(in_cols) == n_in and len(out_cols) == len(outs) and k == len(lay.rows_a) - 1
    codes = [_gate_code(op, a, b) for op, a, b in zip(ops, A, B)]
    # the forms `GateRows.St.steps` gives each wire, in the layout's columns
    forms: list[tuple[int, int]] = [(1 << in_cols[i], 0) for i in range(n_in)]
    ands = [0]
    for op, a, b in zip(ops, A, B):
        fa = (0, 0) if a == -1 else (0, 1) if a == -2 else forms[a]
        fb = (0, 0) if b == -1 else (0, 1) if b == -2 else forms[b]
        if op == 0:
            forms.append((1 << (and_base + ands[-1]), 0))
            ands.append(ands[-1] + 1)
        else:
            forms.append((fa[0] ^ fb[0], fa[1] ^ fb[1]) if op == 1 else (fa[0], fa[1] ^ 1))
            ands.append(ands[-1])
    n_and, out_len = ands[-1], k - and_base - ands[-1]
    assert n_and == lay.counts["ands"] and out_len >= 0
    last: dict[int, int] = {}
    for i, (op, a, b) in enumerate(zip(ops, A, B)):
        for x in ((a, b) if op != 2 else (a,)):
            if x >= 0:
                last[x] = i
    for x in outs:
        if x >= 0:
            last[x] = G
    cuts = list(range(0, G, per)) + [G]
    K = len(cuts) - 1
    row = lambda r: f"({_pack(lay.rows_a[r])}, {_pack(lay.rows_b[r])})"
    top = f"{HEAD}\n\nnamespace FlockSoundness.{ns}\n\n"
    end = f"\n\nend FlockSoundness.{ns}\n"
    gates = [f"{top}/-- The unit's inputs. -/\ndef nIn : Nat := {n_in}"]
    pinned = [top + _listdef("pinIn", [row(r) for r in range(and_base)], "(Nat × Nat)", 256)]
    cps = [f"{top}/-! Checkpoints: the next wire, the next AND's column, and `(wire, its form's runs, its constant)`\n"
           "for each wire the rest of the gates or the outputs read. -/"]
    for j, c in enumerate(cuts):
        live = [x for x in range(n_in + c) if last.get(x, -1) >= c]
        ent = [f"({x}, {_pack(_bits(forms[x][0]))}, {'true' if forms[x][1] else 'false'})" for x in live]
        cps.append(_listdef(f"cpEntries{j}", ent, "(Nat × Nat × Bool)", 256))
        cps.append(f"def cpData{j} : Nat × Nat × List (Nat × Nat × Bool) := ({n_in + c}, {and_base + ands[c]}, cpEntries{j})")
    for j in range(K):
        lo, hi = cuts[j], cuts[j + 1]
        gates.append(_listdef(f"gatesChunk{j}", [str(x) for x in codes[lo:hi]], "Nat", 500))
        pinned.append(_listdef(f"pinAnd{j}", [row(r) for r in range(and_base + ands[lo], and_base + ands[hi])],
                               "(Nat × Nat)", 256))
    gates.append("def gateCodes : List Nat :=\n  " + " ++ ".join(f"gatesChunk{j}" for j in range(K)))
    gates.append(f"def outCodes : List Nat := [{', '.join(str(_operand(w)) for w in outs)}]")
    out_base = and_base + n_and
    pinned.append(_listdef("pinOut", [row(r) for r in range(out_base, out_base + out_len)], "(Nat × Nat)", 256))
    pinned.append(f"def pinConst : Nat × Nat := {row(k)}")
    pinned.append("def pinnedCodes : List (Nat × Nat) :=\n  pinIn ++ " + " ++ ".join(f"pinAnd{j}" for j in range(K))
                  + " ++ pinOut ++ [pinConst]")
    in_col = ("fun i => i" if in_cols == list(range(n_in)) else f"fun i => [{', '.join(map(str, in_cols))}].getD i 0")
    flat = ["List.flatMap_cons", "List.flatMap_nil", "List.append_nil", "List.append_assoc"]
    chunk_list = ",\n".join(f"  (gatesChunk{j}, decCP cpData{j + 1}, pinAnd{j})" for j in range(K))
    theorems = [
        f"import FlockSoundness.UnitRows\nimport FlockSoundness.{ns}.Gates\nimport FlockSoundness.{ns}.Pinned\n"
        f"import FlockSoundness.{ns}.Checkpoints\n\n{top}open GateRows UnitRows",
        f"/-- Each input's column. -/\ndef inCol : ℕ → ℕ := {in_col}",
        f"/-- Each output's column. -/\ndef outCols : List ℕ := [{', '.join(map(str, out_cols))}]",
        "/-- The gate circuit: the unit's Boolean export. -/\ndef circ : Circ := circOf nIn gateCodes outCodes",
        "/-- The pinned rows, as the file lists their columns. -/\ndef pinned : List (List ℕ × List ℕ) := pinnedCodes.map rowOf",
        "/-- The chunks: each chunk's gates, the checkpoint it reaches, and its AND rows. -/\n"
        f"def chunks : List (List ℕ × CP × List (ℕ × ℕ)) := [\n{chunk_list}]",
    ]
    theorems += [f"theorem chunk{j} : chunkOK {k} (decCP cpData{j}) gatesChunk{j} (decCP cpData{j + 1}) pinAnd{j} = true := by\n"
                 "  decide +kernel" for j in range(K)]
    theorems += [
        f"theorem chunksOK : ChunksOKc {k} (decCP cpData0) chunks := by\n  simp only [chunks, ChunksOKc]\n"
        "  exact ⟨" + ", ".join(f"chunk{j}" for j in range(K)) + ", trivial⟩",
        "theorem lastCP_chunks :\n    lastCP (decCP cpData0) (chunks.map fun c => (c.1.map decGate, c.2.1, c.2.2.map rowMasks)) =\n"
        f"      decCP cpData{K} := rfl",
        f"theorem gates_eq : gateCodes = chunks.flatMap (·.1) := by\n  simp only [gateCodes, chunks, {', '.join(flat)}]",
        "theorem pinned_split : pinnedCodes = pinIn ++ chunks.flatMap (·.2.2) ++ pinOut ++ [pinConst] := by\n"
        f"  simp only [pinnedCodes, chunks, {', '.join(flat)}]",
        f"theorem nA_eq : (chunks.flatMap (·.2.2)).length = {n_and} := by\n  decide +kernel",
        f"theorem regions : regionsOK circ inCol outCols {and_base} {out_len} {k} {n_and} (decCP cpData0) (decCP cpData{K})\n"
        "    pinIn pinOut pinConst = true := by\n  decide +kernel",
        f"/-- **The pinned rows compute the gate circuit** (`UnitRows.Sound`). -/\ntheorem sound : Sound pinned circ inCol outCols {k} := by\n"
        "  rw [pinned, pinned_split]\n"
        f"  exact sound_of_checks nIn gateCodes outCodes inCol outCols {and_base} {out_len} {k} {n_and} pinIn pinOut pinConst\n"
        f"    (decCP cpData0) (decCP cpData{K}) chunks gates_eq chunksOK lastCP_chunks nA_eq regions",
    ]
    return {"Gates.lean": "\n\n".join(gates) + end, "Pinned.lean": "\n\n".join(pinned) + end,
            "Checkpoints.lean": "\n\n".join(cps) + end, "Chunks.lean": "\n\n".join(theorems) + end, "sha256": low.sha256}


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--out", type=Path, required=True, help="the FlockSoundness directory")
    ap.add_argument("templates", nargs="*", default=list(TEMPLATES), help="templates (default: all)")
    args = ap.parse_args()
    for t in args.templates:
        data = unit(t)
        d = args.out / TEMPLATES[t][0]
        d.mkdir(parents=True, exist_ok=True)
        for name in FILES:
            (d / name).write_text(data[name])
        print(f"{t}: wrote {', '.join(FILES)} in {d} for the netlist {data['sha256']}")


if __name__ == "__main__":
    main()
