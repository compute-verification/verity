//! Elementwise BF16 families (lane PROOF-ELEM): the registered semantics of
//! `verity_ir/registry/prims.py` `Bf16AddF2fp_v1` and `SiluMulBf16_v1` as
//! checker gates, plus the two new gate-set families that carry them and the
//! casts (`Bf16ToF32_v1`, `F2fpBf16_v1`, which are `tc.rs`'s existing
//! `bf16_to_f32` / `f32_to_bf16_hw`):
//!
//! * `veritor.elem-bf16@1` — 16-bit sources; `bf16_add_f2fp` (the fused
//!   add+RMSNorm residual add: `bf16_rn(f32(a) + f32(b))`, NaN -> `0x7FFF`),
//!   `silu_mul_bf16` (vLLM `act_and_mul_kernel<silu>`:
//!   `bf16_rn(f32(bf16_rn(silu_f32(f32(g)))) * f32(u))`, NaN -> `0x7FC0`),
//!   `bf16_to_f32` (the exact widening).
//! * `veritor.elem-f32@1` — 32-bit sources; `f32_to_bf16` (the hardware
//!   `cvt.rn.bf16.f32` / SASS `F2FP.BF16.F32`, NaN -> `0x7FFF`: byte for byte
//!   `veritor.tc-ampere-bf16@2`'s cast), for F2fpBf16 rows whose inputs are
//!   committed FP32 words.
//!
//! The IEEE binary32 add and multiply are integer arithmetic on the raw
//! encodings (round to nearest, ties to even, gradual underflow, no FTZ),
//! mirroring `verity_ir.registry.prims.f32_add_bits` / `f32_mul_bits`
//! (`numpy.float32` arithmetic).  Their gate domains are pairs of BF16 words,
//! so both gates are verified *exhaustively* over all `2^32` argument pairs
//! against the Python evaluators (`zk/bench/elem_vectors.py` writes the
//! chunked SHA-256 digest of every output; `tests/elem.rs` recomputes it).
//!
//! `silu_f32` — W4b's float64-exact stand-in for the CUDA `expf` + division
//! (total on encodings: NaN -> NaN, +inf -> +inf, -inf -> -0) — is
//! transcendental, so its 2^16-entry BF16 -> BF16 table (the composition
//! `bf16_rn_torch(silu_f32(f32(g)))`, the kernel's intermediate `s`) is
//! generated from the registered Python evaluator
//! (`zk/bench/gen_elem_silu_table.py`) and embedded in the guest
//! (`elem_silu_table.bin`, 128 KiB, little-endian u16 per BF16 encoding).
//! The table *is* the primitive semantics inside the proof — the pattern the
//! GEMM statement uses for the tensor-core step, whose semantics live in
//! `tc.rs` as code; a measured/tabled function embeds as data.

use crate::tc::{f32_to_bf16, f32_to_bf16_hw};

/// The canonical quiet NaN the reference evaluators produce for an invalid
/// operation; only ever observed through a BF16 canonicalisation, which maps
/// every NaN to one word, so the payload is immaterial.
const F32_QNAN: u32 = 0x7FC0_0000;

/// `silu_table[g]`: `bf16_rn_torch(silu_f32(f32(g)))` for every BF16 word `g`
/// (`SiluMulBf16_v1`'s intermediate), generated by
/// `zk/bench/gen_elem_silu_table.py` from the registered evaluator.
static SILU_TABLE: &[u8; 131072] = include_bytes!("elem_silu_table.bin");

/// The tabled `bf16_rn_torch(silu_f32(f32(g)))` of one BF16 word.
#[cfg_attr(feature = "attribution", inline(never))]
pub fn silu_bf16(g: u64) -> u64 {
    let index = (g as usize & 0xFFFF) * 2;
    u16::from_le_bytes([SILU_TABLE[index], SILU_TABLE[index + 1]]) as u64
}

#[inline]
fn is_nan(x: u32) -> bool {
    (x & 0x7F80_0000) == 0x7F80_0000 && (x & 0x007F_FFFF) != 0
}

#[inline]
fn is_inf(x: u32) -> bool {
    (x & 0x7FFF_FFFF) == 0x7F80_0000
}

/// Decode a finite FP32 word: `(sign, e', m')` with the hidden bit applied,
/// so the value is `(-1)^sign * m' * 2^(e' - 150)` (`e'` is the exponent
/// field, floored at 1 for subnormals; `m' = 0` only for a zero).
#[inline]
fn decode_finite(x: u32) -> (u32, i32, u32) {
    let sign = x >> 31;
    let field = ((x >> 23) & 0xFF) as i32;
    let mantissa = x & 0x007F_FFFF;
    if field == 0 {
        (sign, 1, mantissa)
    } else {
        (sign, field, mantissa | 0x0080_0000)
    }
}

/// Pack a rounded significand on the `2^(e' - 150)` grid: `sig < 2^24`; a
/// `sig` without bit 23 is a subnormal and must have `e' == 1`.
#[inline]
fn pack(sign: u32, e_prime: i32, sig: u32) -> u32 {
    debug_assert!(sig < (1 << 24));
    if sig == 0 {
        return sign << 31;
    }
    if e_prime >= 255 {
        return (sign << 31) | 0x7F80_0000;
    }
    let field = if sig & (1 << 23) != 0 {
        debug_assert!(e_prime >= 1);
        e_prime as u32
    } else {
        debug_assert!(e_prime == 1);
        0
    };
    (sign << 31) | (field << 23) | (sig & 0x007F_FFFF)
}

/// IEEE binary32 addition on encodings, round to nearest even, gradual
/// underflow, no FTZ: `verity_ir.registry.prims.f32_add_bits` (`numpy.float32`
/// `+`) up to NaN payloads (any NaN operand or `inf - inf` yields a NaN word;
/// every consumer canonicalises).  Total on 32-bit words.
pub fn f32_add_rn(a: u32, b: u32) -> u32 {
    if is_nan(a) || is_nan(b) {
        return F32_QNAN;
    }
    match (is_inf(a), is_inf(b)) {
        (true, true) => return if a == b { a } else { F32_QNAN },
        (true, false) => return a,
        (false, true) => return b,
        _ => {}
    }
    let (sa, ea, ma) = decode_finite(a);
    let (sb, eb, mb) = decode_finite(b);
    if ma == 0 && mb == 0 {
        // IEEE RN: an exact zero sum is -0 only when both addends are -0.
        return (sa & sb) << 31;
    }
    if ma == 0 {
        return b;
    }
    if mb == 0 {
        return a;
    }
    // order by magnitude: L >= S (e' first, then significand)
    let (sl, el, ml, ss, es, ms) = if (ea, ma) >= (eb, mb) {
        (sa, ea, ma, sb, eb, mb)
    } else {
        (sb, eb, mb, sa, ea, ma)
    };
    let shift = (el - es) as u64;
    // three extra bits: guard, round, sticky
    let big = (ml as u64) << 3;
    let small_full = (ms as u64) << 3;
    let small = if shift >= 64 {
        u64::from(small_full != 0)
    } else {
        let kept = small_full >> shift;
        let lost = small_full & ((1u64 << shift) - 1);
        kept | u64::from(lost != 0)
    };
    let (mut mag, sign) = if sa == sb {
        (big + small, sl)
    } else if big > small {
        (big - small, sl)
    } else if small > big {
        (small - big, ss)
    } else {
        return 0; // exact cancellation of nonzero addends: +0 under RN
    };
    let mut e = el;
    // normalize up (carry): at most one step for an add of two 27-bit terms
    while mag >= (1 << 27) {
        mag = (mag >> 1) | (mag & 1);
        e += 1;
    }
    // normalize down (cancellation), not past the subnormal grid
    while mag < (1 << 26) && e > 1 {
        mag <<= 1;
        e -= 1;
    }
    // round to nearest even on the low three bits
    let lsb = (mag >> 3) & 1;
    let round = (mag >> 2) & 1;
    let sticky = (mag & 0b11) != 0;
    let mut sig = (mag >> 3) as u32;
    if round == 1 && (sticky || lsb == 1) {
        sig += 1;
    }
    if sig >= (1 << 24) {
        sig >>= 1;
        e += 1;
    }
    pack(sign, e, sig)
}

/// IEEE binary32 multiplication on encodings, round to nearest even, gradual
/// underflow, no FTZ: `verity_ir.registry.prims.f32_mul_bits` (`numpy.float32`
/// `*`) up to NaN payloads.  Total on 32-bit words.
pub fn f32_mul_rn(a: u32, b: u32) -> u32 {
    if is_nan(a) || is_nan(b) {
        return F32_QNAN;
    }
    let sign = (a ^ b) >> 31;
    if is_inf(a) || is_inf(b) {
        let other = if is_inf(a) { b } else { a };
        if other & 0x7FFF_FFFF == 0 {
            return F32_QNAN; // inf * 0
        }
        return (sign << 31) | 0x7F80_0000;
    }
    let (_, ea, ma) = decode_finite(a);
    let (_, eb, mb) = decode_finite(b);
    if ma == 0 || mb == 0 {
        return sign << 31;
    }
    // exact product: value = p * 2^(ea + eb - 300), p < 2^48
    let p = (ma as u64) * (mb as u64);
    let bit_length = 64 - p.leading_zeros() as i32;
    // unbiased exponent of the leading bit: value = 1.xxx * 2^e_unbiased
    let e_unbiased = (ea - 127) + (eb - 127) + (bit_length - 47);
    // shift so the hidden bit lands at position 23 (plus rounding bits below)
    let mut shift_right = bit_length - 24;
    let mut e_prime = e_unbiased + 127; // tentative exponent field of a normal result
    if e_unbiased < -126 {
        // gradual underflow: the grid is fixed at e' = 1
        shift_right += -126 - e_unbiased;
        e_prime = 1;
    }
    let mut sig = if shift_right <= 0 {
        (p << (-shift_right) as u32) as u32 // exact: no rounding needed
    } else if shift_right >= 64 {
        0 // p < 2^48 is all sticky, far below half an ulp: rounds to zero
    } else {
        let kept = p >> shift_right;
        let lost = p & ((1u64 << shift_right) - 1);
        let half = 1u64 << (shift_right - 1);
        let mut s = kept as u32;
        if lost > half || (lost == half && (kept & 1) == 1) {
            s += 1;
        }
        s
    };
    if sig >= (1 << 24) {
        sig >>= 1;
        e_prime += 1;
    }
    // a subnormal that rounding carried up to 2^23 packs as the smallest
    // normal (field 1 == e_prime) by itself
    pack(sign, e_prime, sig)
}

/// `Bf16AddF2fp_v1` (`verity_ir/registry/prims.py`): the CUDA
/// `fused_add_rms_norm` residual add — `bf16_rn(f32(a) + f32(b))`, every NaN
/// to the hardware word `0x7FFF` (`F2FP.BF16.F32`).  Total on BF16 words.
pub fn bf16_add_f2fp(a: u64, b: u64) -> u64 {
    let sum = f32_add_rn((a as u32) << 16, (b as u32) << 16);
    f32_to_bf16_hw(sum as u64)
}

/// `SiluMulBf16_v1` (`verity_ir/registry/prims.py`): vLLM
/// `act_and_mul_kernel<silu>` — `bf16(f32(bf16(silu_f32(f32(g)))) * f32(u))`,
/// both roundings with the torch canonical NaN `0x7FC0`; `silu_f32` by the
/// embedded table.  Total on BF16 words.
pub fn silu_mul_bf16(g: u64, u: u64) -> u64 {
    let s = silu_bf16(g);
    let product = f32_mul_rn((s as u32) << 16, (u as u32) << 16);
    f32_to_bf16(product as u64)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn f(x: f32) -> u32 {
        x.to_bits()
    }

    #[test]
    fn add_matches_native_f32_on_widened_bf16_samples() {
        // native f32 arithmetic on the host is IEEE RN: a direct oracle here
        let words: Vec<u64> = (0..=0xFFFFu64).step_by(97).chain([0, 1, 0x80, 0x3F80, 0x7F7F, 0x7F80, 0x8000, 0xFF80, 0x0001, 0x8001, 0x7FC0, 0x7FFF]).collect();
        for &a in &words {
            for &b in &words {
                let expected = {
                    let fa = f32::from_bits((a as u32) << 16);
                    let fb = f32::from_bits((b as u32) << 16);
                    let s = fa + fb;
                    if s.is_nan() { F32_QNAN } else { s.to_bits() }
                };
                let got = f32_add_rn((a as u32) << 16, (b as u32) << 16);
                let same = if is_nan(expected) { is_nan(got) } else { got == expected };
                assert!(same, "add {a:#06x} {b:#06x}: got {got:#010x} want {expected:#010x}");
            }
        }
    }

    #[test]
    fn mul_matches_native_f32_on_widened_bf16_samples() {
        let words: Vec<u64> = (0..=0xFFFFu64).step_by(89).chain([0, 1, 0x80, 0x3F80, 0x7F7F, 0x7F80, 0x8000, 0xFF80, 0x0001, 0x8001, 0x7FC0, 0x7FFF]).collect();
        for &a in &words {
            for &b in &words {
                let expected = {
                    let fa = f32::from_bits((a as u32) << 16);
                    let fb = f32::from_bits((b as u32) << 16);
                    let p = fa * fb;
                    if p.is_nan() { F32_QNAN } else { p.to_bits() }
                };
                let got = f32_mul_rn((a as u32) << 16, (b as u32) << 16);
                let same = if is_nan(expected) { is_nan(got) } else { got == expected };
                assert!(same, "mul {a:#06x} {b:#06x}: got {got:#010x} want {expected:#010x}");
            }
        }
    }

    #[test]
    fn add_zero_signs_follow_ieee_rn() {
        assert_eq!(f32_add_rn(f(0.0), f(-0.0)), f(0.0));
        assert_eq!(f32_add_rn(f(-0.0), f(-0.0)), f(-0.0));
        assert_eq!(f32_add_rn(f(1.0), f(-1.0)), f(0.0));
        assert_eq!(f32_add_rn(f(1.0), f(0.0)), f(1.0));
        assert_eq!(f32_add_rn(f(-0.0), f(5.0)), f(5.0));
        // inf - inf is a NaN; inf + inf keeps the sign
        assert!(is_nan(f32_add_rn(f(f32::INFINITY), f(f32::NEG_INFINITY))));
        assert_eq!(f32_add_rn(f(f32::INFINITY), f(f32::INFINITY)), f(f32::INFINITY));
    }

    #[test]
    fn gate_outputs_canonicalise_nan() {
        // NaN operand -> the family's canonical BF16 NaN word
        assert_eq!(bf16_add_f2fp(0x7FC0, 0x3F80), 0x7FFF);
        assert_eq!(bf16_add_f2fp(0x7F80, 0xFF80), 0x7FFF); // inf - inf
        assert_eq!(silu_mul_bf16(0x7FC1, 0x3F80), 0x7FC0);
        // inf * 0 through the mul
        assert_eq!(silu_mul_bf16(0x7F80, 0x0000), 0x7FC0); // silu(+inf) = +inf; inf * 0
    }

    /// Exhaustive over the full gate domain (all 2^32 BF16 pairs), against
    /// the host's native f32 arithmetic (IEEE RN) composed with the `tc.rs`
    /// casts: `cargo test --release -- --ignored exhaustive`.  The same
    /// digests are produced by `zk/bench/elem_vectors.py` from the registered
    /// Python evaluators (`verity_ir.registry.prims`), which ties the guest
    /// gates to the registered semantics word for word.
    #[test]
    #[ignore = "4.3e9 evaluations per gate; run explicitly in release"]
    fn exhaustive_gate_digests_match_the_python_evaluators() {
        use sha2::{Digest, Sha256};

        // bf16_add_f2fp: oracle = native f32 add + hardware cast
        let mut add_ours = Sha256::new();
        let mut row = vec![0u8; 2 * 65536];
        for a in 0..=0xFFFFu32 {
            let fa = f32::from_bits(a << 16);
            for b in 0..=0xFFFFu32 {
                let ours = bf16_add_f2fp(a as u64, b as u64) as u16;
                let oracle = f32_to_bf16_hw(((fa + f32::from_bits(b << 16)).to_bits()) as u64) as u16;
                assert_eq!(ours, oracle, "add {a:#06x} {b:#06x}");
                row[b as usize * 2..b as usize * 2 + 2].copy_from_slice(&ours.to_le_bytes());
            }
            add_ours.update(&row);
        }
        let add_digest = format!("{:x}", add_ours.finalize());

        // silu_mul_bf16: oracle = table + native f32 mul + torch cast
        let mut mul_ours = Sha256::new();
        for g in 0..=0xFFFFu32 {
            let s = silu_bf16(g as u64) as u32;
            let fs = f32::from_bits(s << 16);
            for u in 0..=0xFFFFu32 {
                let ours = silu_mul_bf16(g as u64, u as u64) as u16;
                let oracle = f32_to_bf16(((fs * f32::from_bits(u << 16)).to_bits()) as u64) as u16;
                assert_eq!(ours, oracle, "silu_mul {g:#06x} {u:#06x}");
                row[u as usize * 2..u as usize * 2 + 2].copy_from_slice(&ours.to_le_bytes());
            }
            mul_ours.update(&row);
        }
        let mul_digest = format!("{:x}", mul_ours.finalize());

        // pinned by zk/bench/elem_vectors.py (the registered Python evaluators)
        assert_eq!(add_digest, ADD_DIGEST_PYTHON, "bf16_add_f2fp digest");
        assert_eq!(mul_digest, MUL_DIGEST_PYTHON, "silu_mul_bf16 digest");
    }

    /// `zk/bench/elem_vectors.py`: sha256 over rows `a = 0..2^16` of the
    /// 2^16 little-endian u16 outputs `Bf16AddF2fp(a, b)`, `b = 0..2^16`.
    const ADD_DIGEST_PYTHON: &str =
        "06ef9a7a6794bffaeef5e788936a206581c34b8f40e3a65f8949e64a88331b87";
    /// The same layout for `SiluMulBf16(g, u)`.
    const MUL_DIGEST_PYTHON: &str =
        "17279a99f4c4572bd7ab7b2951f64a5c2350b5c9267c2b8610217070b379f0c3";

    #[test]
    fn silu_table_spot_values() {
        // silu(0) = 0, silu(+inf) = +inf, silu(-inf) = -0, silu(NaN) = NaN(torch word)
        assert_eq!(silu_bf16(0x0000), 0x0000);
        assert_eq!(silu_bf16(0x7F80), 0x7F80);
        assert_eq!(silu_bf16(0xFF80), 0x8000);
        assert_eq!(silu_bf16(0x7FC1), 0x7FC0);
        // silu(1) = 1/(1+e^-1) = 0.7310586, bf16_rne -> 0x3F3B
        assert_eq!(silu_bf16(0x3F80), 0x3F3B);
    }
}
