"""The H200 walking skeleton: steps of the frozen MQA shape (or a small one) on the plain INT8 weights loaded once
into the device's memory (``--weights staged`` decodes them from the store into staging), every op's output committed per step,
drawn units replayed bit for bit, each subprotocol run or named, and the replay bundle and block record written to ``--out``.

    python demos/h200/run.py --out OUT [--shape tiny|small|slice|h200] [--seed test|demo|TEXT] [--batch B]
        [--steps T] [--prompt-bytes P] [--requests N --generate G --admit A] [--device cpu|cuda] [--weights resident|staged] [--micro-batch M]
        [--store generator|p2-encode|p2:PATH | --weights-file W --weights-manifest M] [--workers N] [--commit slots|reference|host|device] [--salt-keys fresh|fixture]
        [--open K] [--draw K] [--replay-step S] [--attention attn_ref|numpy] [--subcircuit MODULE:FACTORY ...]
        [--tamper OP] [--run-id ID]

Without ``--requests`` the B slots run in lockstep for T steps; with it, N requests of P prompt and G generated bytes are
served through the B slots by continuous batching (``slots.SlotKV``, at most A admitted a step), until every one finishes,
and the run keeps every step's tables and replays from them.

``--weights-file W`` serves W itself (the file network's load sink writes) through `store.FileStore`: before the first step
every tensor's sha256 is checked against the manifest ``M`` (`SW.manifest`'s), and the run refuses (exit 5) on any mismatch.

Under ``--commit slots`` (kernels' per-slot tree) a lockstep run keeps no step's tables: ``--open K`` slots drawn by a fixture coin
are replayed alone and their slot roots compared with the committed ones (`e2e_h200.opening`), then ``--draw K`` units a
family of the replayed step are replayed against the Definitions and opened against the step's root. The by-table backends
keep every step's tables and replay from them.

Exit 0 when every drawn unit replays to its committed word, every opened slot to its committed root and every subcircuit's
own check holds (a PoUW unit's z the served sums, `e2e_h200.percall`), 3 when one doesn't (``--tamper OP`` flips bit 0 of
OP's committed words at every step: replay or opening must find it), 4 when a leg's fixture check fails, 5 when
``--weights-file`` isn't its manifest's W.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import sys
import time
from pathlib import Path

import numpy as np
import torch

sys.path.insert(0, str(Path(__file__).resolve().parent))
from e2e_h200 import legs as L  # noqa: E402
from e2e_h200 import record as REC  # noqa: E402
from e2e_h200.commit import Committer, fixture_salt, fixture_secrets  # noqa: E402
from e2e_h200.driver import Driver, Params  # noqa: E402
from e2e_h200.opening import Openings, draw_slots, replay_slot  # noqa: E402
from e2e_h200.shape import SHAPES  # noqa: E402
from e2e_h200.slots import Request, SlotKV, SlotShape  # noqa: E402
from e2e_h200.store import FileStore, GeneratorStore, Mismatch, P2Store  # noqa: E402
from e2e_h200.units import Replayer, load_subcircuit  # noqa: E402
from e2e_h200.weights import Weights  # noqa: E402
from e2e_h200 import served_weights as SW  # noqa: E402

#: the weights' registration digest under the test salt key is computed for streams up to this size (about 1 s a MiB)
DIGEST_BYTES = 1 << 26


def prompts_for(run_id: str, batch: int, p: int) -> np.ndarray:
    h = hashlib.sha512(b"e2e-h200/prompts-fixture\0" + run_id.encode()).digest()
    rng = np.random.Generator(np.random.PCG64(int.from_bytes(h[:16], "big")))
    return rng.integers(32, 127, size=(batch, p), dtype=np.int64)


def make_store(a, weights: Weights, device: str):
    if a.weights_file:
        if not a.weights_manifest:
            raise SystemExit("--weights-file needs --weights-manifest, the manifest its tensors' sha256 are checked against")
        return FileStore(weights, a.weights_file, a.weights_manifest, a.workers)
    salt = bytes.fromhex(a.salt) if a.salt else hashlib.sha512(b"e2e-h200/salt-fixture\0" + a.run_id.encode()).digest()[:24]
    if a.store == "generator":
        return GeneratorStore(weights, a.workers)
    if a.store == "p2-encode":
        return P2Store.encode(weights, salt, workers=a.workers)
    if a.store.startswith("p2:"):
        return P2Store.load(weights, salt, a.store[3:], device if a.stage_lib else None, a.stage_lib)
    raise SystemExit(f"--store is generator, p2-encode or p2:PATH, not {a.store!r}")


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out", required=True)
    ap.add_argument("--shape", default="small", choices=sorted(SHAPES))
    ap.add_argument("--batch", type=int, default=4)
    ap.add_argument("--steps", type=int, default=4)
    ap.add_argument("--prompt-bytes", type=int, default=2)
    ap.add_argument("--requests", type=int, default=0, help="serve N requests through the slots (0: lockstep)")
    ap.add_argument("--generate", type=int, default=3, help="bytes each served request generates")
    ap.add_argument("--admit", type=int, default=0, help="admissions a step when serving (0: slots // steps a request)")
    ap.add_argument("--device", default="cpu")
    ap.add_argument("--weights", default="resident", choices=("resident", "staged"))
    ap.add_argument("--micro-batch", type=int, default=0, help="rows a layer's ops run on at once (0: the whole batch)")
    ap.add_argument("--store", default="generator")
    ap.add_argument("--weights-file", default="", help="W itself, checked tensor by tensor against --weights-manifest")
    ap.add_argument("--weights-manifest", default="", help="the manifest (with sha256) --weights-file is checked against")
    ap.add_argument("--salt", default="")
    ap.add_argument("--stage-lib", default="")
    ap.add_argument("--workers", type=int, default=1)
    ap.add_argument("--commit", default="slots", choices=("slots", "reference", "host", "device"))
    ap.add_argument("--salt-keys", default="fresh", choices=("fresh", "fixture"))
    ap.add_argument("--open", type=int, default=2, help="slots drawn and opened by replaying their requests (slots backend)")
    ap.add_argument("--draw", type=int, default=4, help="units drawn per family of the replayed step (per opened slot)")
    ap.add_argument("--replay-step", type=int, default=None,
                    help="default: the last step (lockstep), the first with the most distinct positions (serving)")
    ap.add_argument("--attention", default=None, choices=("attn_ref", "numpy"))
    ap.add_argument("--subcircuit", action="append", default=[], help="MODULE:FACTORY joining the integrity registration")
    ap.add_argument("--pous-reads", type=int, default=16)
    ap.add_argument("--tamper", default="")
    ap.add_argument("--run-id", default="e2e-h200-fixture")
    ap.add_argument("--seed", default="test", help="test (TEST_SEED), demo (DEMO_SEED) or a text seed")
    a = ap.parse_args(argv)
    out = Path(a.out)
    out.mkdir(parents=True, exist_ok=True)
    shape = SHAPES[a.shape]
    seed = {"test": SW.TEST_SEED, "demo": SW.DEMO_SEED}.get(a.seed, a.seed.encode())
    weights = Weights(shape, seed)
    t0 = time.perf_counter()
    try:
        store = make_store(a, weights, a.device)
    except Mismatch as e:
        print(f"refused: {e}", file=sys.stderr)
        return 5
    t_store = time.perf_counter() - t0
    ctx, key = fixture_secrets(a.run_id)
    slots = a.commit == "slots" and not a.requests
    committer = Committer(a.commit, ctx, key, shape, a.device, fixture_salt(a.run_id) if a.salt_keys == "fixture" else None)
    prompts = prompts_for(a.run_id, a.requests or a.batch, a.prompt_bytes)
    subs = [load_subcircuit(s, shape=shape, weights=weights, run_id=a.run_id) for s in a.subcircuit]
    params = Params(shape, store, a.device, a.weights == "resident")
    print(json.dumps({"params": params.describe()}), flush=True)

    def drive(salt_keys=None, p=params):
        d = Driver(shape, p, a.batch, committer, a.device, tamper=a.tamper or None, keep=not slots,
                   micro_batch=a.micro_batch or None, attention=a.attention, subcircuits=subs)
        if not a.requests:
            return d, d.run(prompts, a.steps, salt_keys)
        kv = SlotKV(SlotShape(a.batch, shape.layers, shape.context, shape.head_dim, prompt=a.prompt_bytes,
                              generate=a.generate), a.device, admit=a.admit or None)
        return d, d.serve(kv, [Request(i, bytes(prompts[i].astype(np.uint8))) for i in range(a.requests)],
                          salt_keys=salt_keys)

    driver, results = drive()
    for r in results:
        print(json.dumps({"step": r.step, "active": len(r.slots), "positions": sorted(set(r.positions.tolist())),
                          "finished": len(r.finished), "root": r.root.hex()[:32], "value_bytes": r.value_bytes,
                          "seconds": {k: round(v, 3) for k, v in r.seconds.items()}}), flush=True)
    if a.replay_step is not None:
        step = a.replay_step % len(results)
    elif a.requests:
        step = max(range(len(results)), key=lambda s: (len(set(results[s].positions.tolist())), -s))
    else:
        step = len(results) - 1
    t0 = time.perf_counter()
    opening = None
    if slots:
        opn, units, opened_docs = Openings(committer, results), [], []
        for s in draw_slots(a.batch, a.open, a.run_id.encode(), step):
            op = replay_slot(shape, params, committer, results, prompts, s, step, a.device, a.attention)
            got = Replayer(shape, weights, op.driver.steps, op.tokens, subs).draw(step, a.draw, a.run_id.encode() + b"%d" % s)
            for u in got:
                u.slot = s
                u.opened = opn.open(op, step, u)
            opened_docs.append(op.doc() | {"reference_slot_root_equal": opn.reference_equal(op, step)})
            units += got
        opening = {"slots": opened_docs, "draw": f"fixture coin, {a.open} slots of the batch (the sampling plan's live coins replace it)",
                   "mismatches": sum(not d["slot_roots_equal"] for d in opened_docs),
                   "units_opened": sum(u.opened is not None for u in units),
                   "units_unverified": sum(u.opened is not None and not u.opened["verified"] for u in units),
                   "reference_unequal": sum(not d["reference_slot_root_equal"] for d in opened_docs)}
        registration = Replayer(shape, weights, op.driver.steps, op.tokens, subs).registration(step)
    else:
        rp = Replayer(shape, weights, driver.steps, [r.tokens_in for r in results], subs)
        units = rp.draw(step, a.draw, a.run_id.encode())
        registration = rp.registration(step)
    t_replay = time.perf_counter() - t0
    REC.write_bundle(out, units, results[step].root, step, results[step].slots, results[step].positions)
    replay = REC.replay_summary(units) | {"step": step, "seconds": t_replay, "opening": opening,
                                          "draw": f"fixture coin, {a.draw} a family (the sampling plan's live coins replace it)"}
    if a.requests:
        outputs = np.array([list(f.generated) for f in sorted(driver.finished, key=lambda f: f.seq)], np.uint8)
        serving = {"requests": a.requests, "prompt": a.prompt_bytes, "generate": a.generate, "admit": driver.kv.admit,
                   "finished": len(driver.finished), "slot_reuses": len(driver.finished) - len({f.slot for f in driver.finished})}
    else:
        outputs, serving = np.stack([r.tokens_out for r in results], 1), None
    legs = {
        "integrity": L._entry("integrity", "fixture", replayed=replay["drawn"], mismatches=replay["mismatches"],
                              stands_in_for="C-Flock --zk proving the drawn units and Lean's ACCEPT"),
        "pous": L.pous_spot_reads(store, a.pous_reads, a.run_id.encode()),
        "bandwidth": L.not_run("bandwidth", "M4: memory-accounting's audit reads against the demo card's store"),
        "certifier": L.certifier(prompts, outputs),
        "wipe": L.wipe_reload(store, lambda: drive([r.salt_key for r in results],
                                                   Params(shape, store, a.device, a.weights == "resident"))[1][-1].root,
                              results[-1].root),
        "pouw": L.not_run("pouw", "per-call-noise tiles, a --subcircuit of the registration")
        if not subs else L._entry("pouw", "fixture", subcircuits={s.name: s.manifest() for s in subs},
                                  mismatches=sum(getattr(s, "mismatches", 0) for s in subs)),
    }
    store.close()
    doc = REC.write_record(
        out, run_id=a.run_id, shape=shape, batch=a.batch, device=a.device,
        weights={**weights.manifest(), **params.describe(), "registration_digest_test_key":
                 weights.registration_digest() if weights.nbytes <= DIGEST_BYTES else None},
        store={**store.describe(), "seconds": t_store,
               "stands_in_for": None if store.kind == "p2-v4" else "memory-accounting's P2-encoded store and its decode call"},
        commit={**committer.describe(), "context": "fixture"},
        results=results, prompts=prompts, outputs=outputs, replay=replay, legs=legs,
        extra={"serving": serving, "tamper": a.tamper or None, "registration": registration, "micro_batch": a.micro_batch or a.batch,
               "attention": driver.attn.kind + (" (attn_bf16's reference kernels and softmax_t)" if driver.attn.kind == "attn_ref"
                                                else " (the Definitions' numpy kernels on the CPU)"),
               "gemm": "torch._int_mm + torch epilogue" if a.device.startswith("cuda") else "exact f64 matmul + torch epilogue",
               "cuda_peak_allocated_bytes": torch.cuda.max_memory_allocated() if a.device.startswith("cuda") else None})
    print(json.dumps({"replay": {k: replay[k] for k in ("drawn", "mismatches", "families", "step")}, "serving": serving,
                      "opening": opening and {k: opening[k] for k in ("mismatches", "units_opened", "units_unverified",
                                                                      "reference_unequal")},
                      "legs": {k: v["status"] for k, v in legs.items()}}), flush=True)
    if replay["mismatches"] or legs["pouw"].get("mismatches") or (opening and (opening["mismatches"] or opening["units_unverified"]
                                             or opening["reference_unequal"])):
        return 3
    if legs["pous"].get("mismatched_blocks") or legs["wipe"].get("store_digest_equal") is False \
            or legs["wipe"].get("step_root_equal") is False:
        return 4
    return 0 if doc else 1


if __name__ == "__main__":
    sys.exit(main())
