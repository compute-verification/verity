"""The sm_120 FP8 draft target (``verity.ml.circuits.targets.target.FP8_SM120_MMA``): its family, its model-replay vectors, and its conformance
device (the RTX PRO 6000, not the arch's default anchor)."""
from __future__ import annotations

import json
from pathlib import Path

import pytest

from verity.ml.circuits.silicon.instructions import INSTRUCTIONS
from verity.ml.circuits.silicon.models import BLACKWELL_SM120_E4M3_M16N8K32
from verity_sp1.proofs.families import make_tensor_core_gate_set
from verity_sp1.proofs.programs import gemm_accumulator_fp8
from verity.ml.circuits.targets.target import FP8_ADA_MMA, FP8_SM120_MMA, TARGETS, TC_VECTORS

ROOT = next(p for p in Path(__file__).resolve().parents if (p / "uv.lock").exists())
T = FP8_SM120_MMA


def vector(name: str) -> dict:
    return json.loads((ROOT / TC_VECTORS / f"{name}.json").read_text())


def test_the_target_is_a_draft_on_the_pro_6000_over_the_one_group_26_bit_pipeline():
    assert TARGETS[T.name] is T and T.status == "draft" and T.instruction == "sm120.mma.m16n8k32.e4m3"
    assert T.anchor_device == "NVIDIA RTX PRO 6000 Blackwell Server Edition"
    assert T.dossier == "art:b3074aba4c9ddeef7f87454bfc23e73a5a3c5f73f1676260545115fe8589cc89"
    ins = INSTRUCTIONS[T.instruction]
    assert ins.status == "pinned" and ins.model is T.pipeline and ins.dossier == T.dossier
    p = T.pipeline
    assert p is BLACKWELL_SM120_E4M3_M16N8K32
    assert (p.dtype, p.operand_bits, p.groups, p.width, p.zero_exponent) == ("e4m3", 8, (32,), 26, -133)
    gate_set = make_tensor_core_gate_set(p)
    assert f"{gate_set.name}@{gate_set.version}" == T.family and gate_set.digest == T.family_digest
    assert sorted(g.name for g in gate_set) == ["in", "tc_dot32", "tc_dot32_0", "weight"]


@pytest.mark.parametrize("which", [0, 1], ids=["k32", "k1536"])
def test_each_reference_vector_replays_on_the_model(which):
    name = T.reference_vectors[which]
    rec = vector(name)
    assert rec["name"] == name and rec["target"] == T.name and rec["instruction"] == T.instruction and rec["model"] == T.pipeline.name
    assert rec["family"] == T.family and rec["family_digest"] == T.family_digest
    k = rec["k"]
    assert k == (32, 1536)[which] and rec["program_digest"] == gemm_accumulator_fp8(k).digest
    a, b = [int(x, 16) for x in rec["a"]], [int(x, 16) for x in rec["b"]]
    c = int(rec["c0"], 16)
    for s, step in enumerate(rec["steps"]):
        assert int(step["c_in"], 16) == c
        c = T.pipeline.step(c, a[32 * s:32 * s + 32], b[32 * s:32 * s + 32])
        assert c == int(step["c_out"], 16), f"{name}: step {s}"
    assert c == int(rec["y"], 16)


def test_the_vectors_share_the_ada_operands_and_give_other_words():
    """The operands are regenerated by the Ada vectors' recipe and seed; the one-group, 26-bit adder differs at every step."""
    for mine, ada in zip(T.reference_vectors, FP8_ADA_MMA.reference_vectors, strict=True):
        m, a = vector(mine), vector(ada)
        assert m["generator"] == a["generator"] and m["a"] == a["a"] and m["b"] == a["b"]
        assert all(x["c_out"] != y["c_out"] for x, y in zip(m["steps"], a["steps"], strict=True))
