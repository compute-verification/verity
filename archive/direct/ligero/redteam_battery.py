"""The 83-case BabyBear forgery battery (``fixtures/redteam/babybear-battery/v1``, ``babybear_rules.md`` section 7)
against THIS prover's constraint system.

A case is a WP2 hint tree with one or more hints mutated (a +p shadow, a re-split limb pair, a swapped zero, a
foreign hint tree, a chained ``c + p`` accumulator, an epilogue tie flip) and the output word a congruence-only
checker would be led to.  Here the case's hints are loaded into the hint rows of ``W`` exactly as a forging prover
would place them, the derived rows (products, bits, selectors) are generated by the witness program -- they are
*determined* by the constraints given the hint rows (a bit decomposition exists iff the value is in range; a one-hot
selector exists iff the key is a table row), so the honest program is the only completion a prover could commit --
and the case is **accepted iff every linear, quadratic and chain constraint holds** with the claimed output.  The
proof system on top is sound for that constraint system (the gates in ``run.py`` / ``vu.py``), so this is the
acceptance test that matters.

The 12 ``gadget``-level cases (z3 models of one embedding rule dropped) have no unit around them; they are
reported as not applicable -- the rules they test (LIMB16, LT_DIRECT, QUOT_TIGHT, NORM_MBND, V_PREMISE) are
realised here by bit decompositions plus the compile-time integer audit (PROTOCOL.md section 2), and the
step/vu classes exercise the same shadows end to end.

    python -m archive.direct.ligero.redteam_battery --device cuda --out results/babybear_battery.json
"""
from __future__ import annotations

import argparse
import json
import sys as _sys
import time
from pathlib import Path

import torch
from verity_numerical.checker.params import REAL
from verity_numerical.checker.step import gen_step, step_output
from verity_numerical.redteam.battery_babybear import Case, load_battery, run_battery

from .chain import Layout
from .compile import P, System
from .unit import compile_unit, flatten_hints, public_vectors
from .witness import Tables, build_witness, check_constraints, eval_expr, tables

STEP, STEPS = 16, 96


def _word(acc: dict) -> int:
    return (int(acc["s"]) << 31) | (int(acc["t"]) << 23) | int(acc["f"])


def check_chain(sys: System, W: torch.Tensor, lay: Layout, y16: torch.Tensor) -> list[str]:
    """The cross-column constraints of ``chain.py`` evaluated directly on W (link / start / end)."""
    ch = sys.chain
    start, link, end = lay.masks(W.device)
    bad = []
    for x, name in enumerate(("s", "t", "f")):
        c_row = W[ch["c"][x]]
        y_row = eval_expr(ch["y"][x], W)
        if ((c_row[1:] != y_row[:-1]) & link[:-1].bool()).any():
            bad.append(f"link c.{name}")
        if ((c_row != 0) & start.bool()).any():
            bad.append(f"start c.{name}")
    y16_row = eval_expr(ch["y16"], W)
    if ((y16_row != (y16.to(W.device) % P)) & end.bool()).any():
        bad.append("end y16")
    return bad


class LigeroAcceptor:
    def __init__(self, device: str):
        self.p = REAL
        self.device = device
        self.unit = compile_unit(self.p)
        self.unit_tb: Tables = tables(self.unit, device)
        self.chain = compile_unit(self.p, chain=True)
        self.chain_tb: Tables = tables(self.chain, device)
        self.last: dict[str, str] = {}

    def _hints(self, sys: System, flats: list[dict[str, int]]) -> torch.Tensor:
        names = [n for _, n in sys.hints]
        pos = {n: i for i, n in enumerate(names)}
        out = torch.zeros((len(names), len(flats)), dtype=torch.int64)
        for col, flat in enumerate(flats):
            for n, v in flat.items():
                if n in pos:
                    out[pos[n], col] = int(v) % P
        return out.to(self.device)

    def accepts_step(self, case: Case) -> tuple[bool, str]:
        x = case.inputs
        c, a, b, y = int(x["c"]), [int(v) for v in x["a"]], [int(v) for v in x["b"]], int(case.claimed["y"])
        l = 256
        cs, as_, bs, ys = [c] + [0] * (l - 1), [a] + [[0] * STEP] * (l - 1), [b] + [[0] * STEP] * (l - 1), [y] + [0] * (l - 1)
        try:
            pub = public_vectors(self.p, cs, as_, bs, ys, device=self.device)
        except ValueError as e:
            return False, f"public inputs: {e}"
        flats = [flatten_hints(self.p, case.hints)] + [flatten_hints(self.p, _trivial_hints(self.p))] * (l - 1)
        W = build_witness(self.unit, pub, self._hints(self.unit, flats), self.device)
        bad = check_constraints(self.unit, self.unit_tb, W, pub)
        return (not bad), ("accept" if not bad else "; ".join(bad[:4]))

    def accepts_vu(self, case: Case) -> tuple[bool, str]:
        x = case.inputs
        a, b = [int(v) for v in x["a"]], [int(v) for v in x["b"]]
        steps = case.hints["steps"]
        epi = case.hints["epilogue"]
        y16 = int(case.claimed["y16"])
        lay = Layout(256, 1, STEPS)
        flats = []
        for s in range(STEPS):
            if s + 1 < STEPS:
                y_s = _word(steps[s + 1]["acc"])
            else:
                y_s = (int(epi["hi"]) << 16) | int(epi["lo"])
            try:
                flat = flatten_hints(self.p, steps[s], y_s)
            except Exception as e:  # noqa: BLE001 -- a forged word the epilogue gadget cannot even decompose
                return False, f"hint layout: {type(e).__name__}"
            if s + 1 == STEPS:            # the case's own epilogue hints, not Epilogue.gen's
                for n in ("lo", "hi2", "lsb", "carry", "rem"):
                    flat[f"epi.{n}"] = int(epi[n])
                flat["epi.fhi"] = int(epi["hi"]) & (2 ** (self.p.acc_frac - 16) - 1)
            flats.append(flat)
        triv = flatten_hints(self.p, _trivial_hints(self.p), 0)
        flats += [triv] * (lay.l - STEPS)
        a_units = [a[16 * s:16 * s + 16] for s in range(STEPS)] + [[0] * STEP] * (lay.l - STEPS)
        b_units = [b[16 * s:16 * s + 16] for s in range(STEPS)] + [[0] * STEP] * (lay.l - STEPS)
        try:
            pub = public_vectors(self.p, None, a_units, b_units, None, device=self.device)
        except ValueError as e:
            return False, f"public inputs: {e}"
        W = build_witness(self.chain, pub, self._hints(self.chain, flats), self.device)
        y16v = torch.zeros(lay.l, dtype=torch.int64)
        y16v[STEPS - 1] = y16
        bad = check_constraints(self.chain, self.chain_tb, W, pub) + check_chain(self.chain, W, lay, y16v)
        return (not bad), ("accept" if not bad else "; ".join(bad[:4]))

    def __call__(self, case: Case) -> bool:
        if case.level == "step":
            ok, why = self.accepts_step(case)
        elif case.level == "vu":
            ok, why = self.accepts_vu(case)
        else:
            raise ValueError("gadget-level case: not applicable to a unit constraint system")
        self.last[case.id] = why
        return ok


_TRIV: dict = {}


def _trivial_hints(p):
    if not _TRIV:
        from verity_numerical.checker.step import gen_step
        _TRIV["h"] = gen_step(p, 0, [0] * STEP, [0] * STEP)
    return _TRIV["h"]


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--device", default="cuda" if torch.cuda.is_available() else "cpu")
    ap.add_argument("--root", default=None)
    ap.add_argument("--out", default=None)
    args = ap.parse_args(argv)
    cases = load_battery(Path(args.root) if args.root else None)
    applicable = [c for c in cases if c.level in ("step", "vu")]
    gadget = [c for c in cases if c.level == "gadget"]
    acc = LigeroAcceptor(args.device)
    t0 = time.time()
    # control: the honest hint trees of the same instances must be accepted (the battery has no honest case;
    # rebuild one from the first step case's inputs with gen_step)
    ctrl = applicable[0]
    hon = Case(id="control-honest", cls="control", level="step", params="REAL", inputs=ctrl.inputs,
               hints=gen_step(REAL, ctrl.inputs["c"], list(ctrl.inputs["a"]), list(ctrl.inputs["b"])),
               claimed={"y": step_output(REAL, ctrl.inputs["c"], list(ctrl.inputs["a"]), list(ctrl.inputs["b"]))},
               honest={}, mutation="none (control)", expected="accept")
    control_ok = acc(hon)
    report = run_battery(acc, applicable)
    print(report.render())
    # an accepted case is a forgery unless its claimed word IS the exact output of its (mutated) inputs -- the
    # zero_swap step cases claim the honest word for c = -0, which is also the true word for c = -0: the reference
    # rejects them on the hint tree's stale acc.s, a row this system has no witness for (the decode is a pin)
    true_statements = {}
    for c in applicable:
        if c.id in report.accepted and c.level == "step":
            try:
                true_statements[c.id] = step_output(REAL, c.inputs["c"], list(c.inputs["a"]), list(c.inputs["b"])) == c.claimed["y"]
            except Exception:  # noqa: BLE001
                true_statements[c.id] = False
    forgeries = [cid for cid in report.accepted if not true_statements.get(cid, False)]
    for cid in report.accepted:
        print(f"  accepted {cid}: claimed word is the exact output of the mutated inputs: {true_statements.get(cid)}")
    print(f"forgeries accepted: {len(forgeries)}")
    print(f"control (honest hints of {ctrl.id}'s inputs): {'accept' if control_ok else 'REJECT -- harness bug'}")
    print(f"gadget-level cases not applicable (no unit around a lone gadget): {len(gadget)}")
    out = {"total_cases": len(cases), "applicable": len(applicable), "gadget_not_applicable": [c.id for c in gadget],
           "accepted": report.accepted, "accepted_true_statements": true_statements, "forgeries": forgeries,
           "by_class": report.by_class, "ok": (not forgeries) and control_ok,
           "control_honest_accepted": control_ok, "seconds": time.time() - t0, "device": args.device,
           "per_case": {c.id: {"class": c.cls, "level": c.level, "verdict": acc.last.get(c.id, "?")} for c in applicable}}
    if args.out:
        Path(args.out).write_text(json.dumps(out, indent=1))
    return 0 if out["ok"] else 2


if __name__ == "__main__":
    _sys.exit(main())
